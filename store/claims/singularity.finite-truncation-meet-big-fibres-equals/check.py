"""singularity.finite-truncation-meet-big-fibres-equals: exact checks for N = |F| = 1, 2, 3 points.

Modes by Jordan-Wigner (v_j = Z x ... x Z x E_12 x 1 ...), as 2^N x 2^N rational matrices.
Big fibre B_j: the Ad(sigma_j)-fixed subalgebra (elements even in mode j), sigma_j = v_j* v_j -
v_j v_j*. Small fibre A_{x_j}^+: the even part of mode j's own factor, span{v_j* v_j, v_j v_j*}.
(1) The meet: the common kernel of Ad(sigma_j) - id over all j, computed by linear algebra over the
4^N matrix entries, has dimension 2^N and equals the joint-number-diagonal algebra.
(2) The join: the subalgebra generated by the small fibres, computed as the closure of their span
under products, has dimension 2^N and equals the meet; the 2^N monomials prod_{j in S} sigma_j are
independent and diagonal (the strings cancel in sigma_j).
(3) range(E_F) for the joint pinching E_F (composite of the mode-wise parity averages of the
premise) has dimension 2^N and equals both.
The identification with compatible evaluations of the sheaf assembly (bump functions) has no finite
computable content beyond (2) and is not checked.
"""
from fractions import Fraction as F
from itertools import combinations

import GA
import fock
from tp_premise import premise


def lower(n, k):
    return fock.to_dense(fock.ann(k, n, fock.MSB), 2 ** n)


def mm(A, B):
    D = len(A)
    out = [[F(0)] * D for _ in range(D)]
    for i in range(D):
        for t in range(D):
            a = A[i][t]
            if a:
                for j in range(D):
                    if B[t][j]:
                        out[i][j] += a * B[t][j]
    return out


def tp(A):
    return [list(r) for r in zip(*A)]


def msub(A, B):
    return [[A[i][j] - B[i][j] for j in range(len(A))] for i in range(len(A))]


def flat(M):
    return [x for r in M for x in r]


def unit(D, b, c):
    M = [[F(0)] * D for _ in range(D)]
    M[b][c] = F(1)
    return M


def ladders(n):
    out = []
    for k in range(n):
        v = lower(n, k)
        out.append((v, tp(v)))
    return out


def basis_of(mats):
    out = []
    for M in mats:
        if GA.field_rank([flat(x) for x in out + [M]]) > len(out):
            out.append(M)
    return out


def check_meet_of_big_fibres_is_joint_diagonal():
    premise("singularity.p-reduced-metric-level-reading-many")
    for n in (1, 2, 3):
        D = 2 ** n
        rows = []
        for v, vs in ladders(n):
            s = msub(mm(vs, v), mm(v, vs))
            cols = [flat(mm(mm(s, unit(D, b, c)), s)) for b in range(D) for c in range(D)]
            rows += [[cols[j][i] - (1 if i == j else 0) for j in range(D * D)] for i in range(D * D)]
        meet = GA.field_kernel(rows)
        diag = [flat(unit(D, b, b)) for b in range(D)]
        assert len(meet) == 2 ** n and GA.field_rank(meet + diag) == 2 ** n


def check_join_of_small_fibres_is_the_same_algebra():
    premise("singularity.p-reduced-metric-level-reading-many")
    for n in (1, 2, 3):
        D = 2 ** n
        small = []
        for v, vs in ladders(n):
            small += [mm(vs, v), mm(v, vs)]
        gen = basis_of(small)
        alg = list(gen)
        while True:
            new = basis_of(alg + [mm(a, b) for a in alg for b in gen])
            if len(new) == len(alg):
                break
            alg = new
        diag = [flat(unit(D, b, b)) for b in range(D)]
        assert len(alg) == 2 ** n
        assert GA.field_rank([flat(x) for x in alg] + diag) == 2 ** n
        # the monomials prod_{j in S} sigma_j: 2^N of them, independent and diagonal
        sig = [msub(mm(vs, v), mm(v, vs)) for v, vs in ladders(n)]
        monos = []
        for r in range(n + 1):
            for S in combinations(range(n), r):
                M = [[F(1) if i == j else F(0) for j in range(D)] for i in range(D)]
                for j in S:
                    M = mm(M, sig[j])
                assert all(M[i][j] == 0 for i in range(D) for j in range(D) if i != j)
                monos.append(flat(M))
        assert len(monos) == 2 ** n and GA.field_rank(monos) == 2 ** n


# Numbers of points N = |F| at which the joint descent is computed.
NS_DESCENT = (1, 2, 3)


def check_range_of_joint_descent_is_the_same_algebra():
    premise("singularity.p-reduced-metric-level-reading-many")
    for n in NS_DESCENT:
        D = 2 ** n
        sig = [msub(mm(vs, v), mm(v, vs)) for v, vs in ladders(n)]
        zero = [[F(0)] * D for _ in range(D)]
        imgs = []
        for b in range(D):
            for c in range(D):
                y = unit(D, b, c)
                for s in sig:
                    sys_ = mm(mm(s, y), s)
                    y = [[(y[i][j] + sys_[i][j]) / 2 for j in range(D)] for i in range(D)]
                # E_F is the pinching: it fixes the diagonal units and kills the off-diagonal ones
                assert y == (unit(D, b, c) if b == c else zero)
                imgs.append(flat(y))
        diag = [flat(unit(D, b, b)) for b in range(D)]
        assert GA.field_rank(imgs) == 2 ** n and GA.field_rank(imgs + diag) == 2 ** n