"""synthesis.even-slots-need-a-spectator-generator: exact checks in the tower's Clifford engine.

The composite's own floor is Cl(5,5): e_k (k < 5) square +1, f_k = generator 5 + k squares -1, and the
five rungs carry null pairs v_k = (e_k + f_k)/2, w_k = (e_k - f_k)/2 (pairs k = 0, 1, 2; slots k = 3, 4).
Conjugation by a generator multiplies each basis blade by +1 or -1, so a commutant of a set of
generators is spanned by the blades it contains; the check enumerates them.
  (A) commutant and graded commutant of the pair algebra: 16 blades each, of which 8 are even;
      the even ones close under multiplication; two CAR modes span 16 dimensions;
      hence two even CAR slots cannot lie in either; Klein-twisted odd slots v_k G_W do;
      the tower grading is conjugation by the pseudoscalar, the only blade anticommuting with all ten.
  (B) with one spectator generator g (Cl(6,5)), even slots s_k = v_k g satisfy (b)-(d).
"""
import GA
from GA import mul, add, sub, scal, sc, gen, eq, is_zero, all_blades, rank_of_vectors
from tp_premise import premise
from fractions import Fraction as F
from itertools import combinations


def ops(n_gen, n_plus):
    sq = tuple([1] * n_plus + [-1] * (n_gen - n_plus))

    def M(x, y):
        return mul(x, y, sq)
    return sq, M


def pairs(M):
    v = [scal(F(1, 2), add(gen(k), gen(5 + k))) for k in range(5)]
    w = [scal(F(1, 2), sub(gen(k), gen(5 + k))) for k in range(5)]
    return v, w


def acomm(M, x, y):
    return add(M(x, y), M(y, x))


def comm(M, x, y):
    return sub(M(x, y), M(y, x))


def blade_sign(M, bl, g):
    """+1 if the blade commutes with generator g, -1 if it anticommutes."""
    e = {bl: F(1)}
    if is_zero(comm(M, e, gen(g))):
        return 1
    assert is_zero(acomm(M, e, gen(g)))
    return -1


def car_ok(M, cre, ann):
    n = len(cre)
    for i in range(n):
        for j in range(n):
            if not is_zero(acomm(M, cre[i], cre[j])):
                return False
            if not eq(acomm(M, cre[i], ann[j]), sc(1 if i == j else 0)):
                return False
    return True


def parity(M, v, w, ks):
    g = sc(1)
    for k in ks:
        g = M(g, sub(sc(1), scal(2, M(v[k], w[k]))))
    return g


def check_even_slots_need_spectator():
    premise("tower.ladder-pairs-satisfy-car-vectors")
    premise("field-theory.no-canonical-commutation-relations-tower")
    premise("standard-model.imported-pair-systems-two-chirality-halves")
    sq, M = ops(10, 5)
    v, w = pairs(M)
    # the five rungs carry five fermionic modes, as vectors
    assert car_ok(M, v, w)
    # no pair in the floor has [a, a*] = 1: the scalar part of a commutator vanishes (the trace argument)
    xs = [add(sc(2), gen(0), M(gen(3), gen(7)), scal(3, M(gen(1), M(gen(5), gen(9))))),
          add(gen(4), scal(F(-1, 2), M(gen(2), gen(6))), M(M(gen(0), gen(1)), M(gen(8), gen(9))))]
    assert comm(M, xs[0], xs[1]).get((), F(0)) == 0 and comm(M, v[0], w[0]).get((), F(0)) == 0
    pair_gens = [0, 1, 2, 5, 6, 7]
    blades = all_blades(10)
    signs = {bl: [blade_sign(M, bl, g) for g in range(10)] for bl in blades}
    # (A1) commutant and graded commutant of the pair algebra
    com = [bl for bl in blades if all(signs[bl][g] == 1 for g in pair_gens)]
    gcom = [bl for bl in blades if all(signs[bl][g] == -1 for g in pair_gens)]
    assert len(com) == 16 and len(gcom) == 16
    com_even = [bl for bl in com if len(bl) % 2 == 0]
    gcom_even = [bl for bl in gcom if len(bl) % 2 == 0]
    assert len(com_even) == 8 and len(gcom_even) == 8
    # the even commutant is the even slot algebra, generated by blades in the slot generators 3, 4, 8, 9
    assert all(set(bl) <= {3, 4, 8, 9} for bl in com_even)
    # graded commutant even part = (even slot blades) times the pair pseudoscalar, up to sign
    assert all(set(bl) >= set(pair_gens) and len(set(bl) - set(pair_gens)) % 2 == 0 for bl in gcom_even)
    # closure: products of even commutant blades stay in its span (a subalgebra of dimension 8)
    for b1 in com_even:
        for b2 in com_even:
            assert set(M({b1: F(1)}, {b2: F(1)})) <= set(com_even)
    # (A2) two CAR modes span 16 dimensions: the 16 products t_J^* t_K of the Klein-twisted slots
    GW = parity(M, v, w, [0, 1, 2])
    assert eq(M(GW, GW), sc(1))
    t = [M(v[k], GW) for k in (3, 4)]
    ts = [M(GW, w[k]) for k in (3, 4)]
    assert car_ok(M, t, ts)
    assert all(is_zero(comm(M, x, y)) for x in t + ts for k in range(3) for y in (v[k], w[k]))
    assert all(len(bl) % 2 == 1 for x in t for bl in x)          # odd: grade 7
    prods = []
    for J in [(), (0,), (1,), (0, 1)]:
        for K in [(), (0,), (1,), (0, 1)]:
            x = sc(1)
            for j in J:
                x = M(x, t[j])
            for k in K:
                x = M(x, ts[k])
            prods.append([x.get(bl, F(0)) for bl in blades])
    assert rank_of_vectors(prods) == 16
    # so two even CAR slots would generate 16 dimensions inside an 8-dimensional subalgebra: none exist.
    # the untwisted slots anticommute with the pairs and are vectors (odd)
    assert all(is_zero(acomm(M, v[k], y)) for k in (3, 4) for j in range(3) for y in (v[j], w[j]))
    # (A3) U(2) forces slot-slot CAR: commuting two-level slots have a rotated slot with nonzero square
    G3 = parity(M, v, w, [3])
    s3, s4 = v[3], M(v[4], G3)
    assert is_zero(comm(M, s3, s4))
    su = add(scal(F(3, 5), s3), scal(F(4, 5), s4))
    assert not is_zero(M(su, su)) and eq(M(su, su), scal(F(24, 25), M(s3, s4)))
    # (A4) chirality: the only blade anticommuting with all ten generators is the pseudoscalar, which
    # is the total parity and implements the tower grading (grade involution) by conjugation
    anti = [bl for bl in blades if all(s == -1 for s in signs[bl])]
    assert anti == [tuple(range(10))]
    GT = parity(M, v, w, range(5))
    assert eq(GT, {tuple(range(10)): F(1)})
    for x in xs + t:
        assert eq(M(M(GT, x), GT), GA.grade_inv(x))
    # (A5) the Fock states: vacuum projector, 32 independent states, chirality (-1)^(j+k) relative to the
    # vacuum for odd slots, and the Klein twist changes each state only by the sign (-1)^(j k)
    P0 = sc(1)
    for k in range(5):
        P0 = M(P0, M(w[k], v[k]))
    assert eq(M(P0, P0), P0) and eq(M(GT, P0), P0)
    states = []
    for nj in range(3):
        for J in combinations((3, 4), nj):
            for nk in range(4):
                for K in combinations((0, 1, 2), nk):
                    st, stk = P0, P0
                    for k in reversed(K):
                        st = M(v[k], st)
                        stk = M(v[k], stk)
                    for k in reversed(J):
                        st = M(v[k], st)
                        stk = M(M(v[k], GW), stk)
                    assert eq(M(GT, st), scal((-1) ** (nj + nk), st))
                    assert eq(stk, scal((-1) ** (nj * nk), st))
                    states.append([st.get(bl, F(0)) for bl in blades])
    assert len(states) == 32 and rank_of_vectors(states) == 32
    # (B) one spectator generator g = generator 10, g^2 = +1: even slots s_k = v_k g satisfy (b)-(d)
    sq2 = tuple([1] * 5 + [-1] * 5 + [1])

    def N(x, y):
        return mul(x, y, sq2)
    g = gen(10)
    s = [N(v[k], g) for k in (3, 4)]
    ss = [N(g, w[k]) for k in (3, 4)]
    assert all(len(bl) % 2 == 0 for x in s for bl in x)            # even
    for i in range(2):
        for j in range(2):
            assert is_zero(add(N(s[i], s[j]), N(s[j], s[i])))
            assert eq(add(N(s[i], ss[j]), N(ss[j], s[i])), sc(1 if i == j else 0))
        for k in range(3):
            for y in (v[k], w[k]):
                assert is_zero(sub(N(s[i], y), N(y, s[i])))          # commute with the pairs
    sr = add(scal(F(3, 5), s[0]), scal(F(4, 5), s[1]))
    assert is_zero(N(sr, sr))                                          # U(2) covariant
    # with even slots the tower grading of s_J^* b_K^* is (-1)^k: the slot count drops out
    for J in [(), (0,), (0, 1)]:
        for K in [(), (0,), (0, 1), (0, 1, 2)]:
            op = sc(1)
            for j in J:
                op = N(op, ss[j])
            for k in K:
                op = N(op, w[k])
            assert op and all(len(bl) % 2 == len(K) % 2 for bl in op)
    return True
