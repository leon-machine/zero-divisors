"""state-selection.euclidean-partner-curvature-selected: exact checks.

Cl(1,3): e0^2 = +1, e1, e2, e3 square -1; sigma_r = e0 e1, I = e0e1e2e3. Half-angles Pythagorean.
(1) (I sigma_r)^2 = -1 and sigma_r^2 = +1; on the six frame bivectors the shape operator
    S(B) = -(B + 3 sigma_r B sigma_r)/2 has its eigenvalue -2 eigenspace (kernel of S + 2, computed) equal to
    span(sigma_r, I sigma_r), and eigenvalue 1 on the four-dimensional complement.
(2) R_theta = c + s I sigma_r: R R~ = 1, the composition law at 4 x 4 Pythagorean pairs, R_{2 pi} = -1,
    R_{4 pi} = +1; conjugation by R_{2 pi} fixes all 16 blades, conjugation by R_pi does not.
(3) Both flows live in the same pair: the boost rotor B_lambda = ch + sh sigma_r (ch^2 - sh^2 = 1, rational)
    and R_theta are rotors with generators in ker(S + 2); they commute; the hyperbolic one is generated by
    the member of square +1 and the elliptic one by the member of square -1.
(4) Conformal spinors, Cl(2,4) (e+ at index 4 square +1, e- at 5 square -1), E = e+ e-, I6 = I4 E:
    I6 sigma = E (I sigma) has square -1, so R^W_theta = c + s I6 sigma; with eps_pm = (1 +- E)/2,
    R^W_theta = eps_+ R_theta + eps_- R_{-theta}, and I6 eps_pm = +-I eps_pm: on the E = +1 half the
    continued boost acts as R_theta, on the E = -1 half as R_{-theta}.
On vectors R_theta fixes e0, e1 and rotates e2 into e3 (the angular plane), which is clause (3) of the
cited Euclidean-rotor proposition, checked in its own claim.
"""
from fractions import Fraction as F

import GA
from tp_premise import premise

S = GA.sig(1, 3)
SIG = GA.mul(GA.gen(0), GA.gen(1), S)
I4 = {(0, 1, 2, 3): F(1)}
ISIG = GA.mul(I4, SIG, S)
BIV = [(0, 1), (0, 2), (0, 3), (1, 2), (1, 3), (2, 3)]
ANGLES = [(F(3, 5), F(4, 5)), (F(-5, 13), F(12, 13)), (F(8, 17), F(-15, 17)), (F(0), F(1))]
BOOSTS = [(F(5, 4), F(3, 4)), (F(13, 12), F(-5, 12)), (F(17, 8), F(15, 8))]


def shape(B):
    return GA.scal(F(-1, 2), GA.add(B, GA.scal(3, GA.mul(GA.mul(SIG, B, S), SIG, S))))


def coords(B):
    return [B.get(b, F(0)) for b in BIV]


def eigenspaces():
    T = [list(c) for c in zip(*[coords(shape({b: F(1)})) for b in BIV])]
    k2 = GA.field_kernel([[T[i][j] + (2 if i == j else 0) for j in range(6)] for i in range(6)])
    k1 = GA.field_kernel([[T[i][j] - (1 if i == j else 0) for j in range(6)] for i in range(6)])
    return k2, k1


def check_pair_is_doubled_eigenplane():
    premise("singularity.curvature-gauge-field-exact-shape-decoupling")
    k2, k1 = eigenspaces()
    ok = len(k2) == 2 and len(k1) == 4
    ok = ok and GA.rank_of_vectors(k2 + [coords(SIG), coords(ISIG)]) == 2
    ok = ok and GA.eq(GA.mul(SIG, SIG, S), GA.sc(1)) and GA.eq(GA.mul(ISIG, ISIG, S), GA.sc(-1))
    ok = ok and GA.eq(shape(ISIG), GA.scal(-2, ISIG)) and GA.eq(shape(SIG), GA.scal(-2, SIG))
    _tp_rv = (ok); assert _tp_rv is not False, "check_pair_is_doubled_eigenplane"; return _tp_rv


def Rot(c, s):
    return GA.add(GA.sc(c), GA.scal(s, ISIG))


def check_elliptic_rotor_periods():
    ok = True
    for (c1, s1) in ANGLES:
        R = Rot(c1, s1)
        ok = ok and GA.eq(GA.mul(R, GA.reverse(R), S), GA.sc(1))
        for (c2, s2) in ANGLES:
            ok = ok and GA.eq(GA.mul(R, Rot(c2, s2), S), Rot(c1 * c2 - s1 * s2, s1 * c2 + c1 * s2))
    Rpi = Rot(F(0), F(1))
    R2 = GA.mul(Rpi, Rpi, S)
    ok = ok and GA.eq(R2, GA.sc(-1)) and GA.eq(GA.mul(R2, R2, S), GA.sc(1))
    blades = [{b: F(1)} for b in GA.all_blades(4)]
    ok = ok and all(GA.eq(GA.mul(GA.mul(R2, x, S), GA.reverse(R2), S), x) for x in blades)
    ok = ok and any(not GA.eq(GA.mul(GA.mul(Rpi, x, S), GA.reverse(Rpi), S), x) for x in blades)
    _tp_rv = (ok); assert _tp_rv is not False, "check_elliptic_rotor_periods"; return _tp_rv


def check_hyperbolic_and_elliptic_flows_share_the_pair():
    premise("singularity.curvature-gauge-field-exact-shape-decoupling")
    k2, _ = eigenspaces()
    ok = GA.rank_of_vectors(k2 + [coords(SIG)]) == 2 and GA.rank_of_vectors(k2 + [coords(ISIG)]) == 2
    ok = ok and GA.commutes(SIG, ISIG, S)
    for (ch, sh) in BOOSTS:
        ok = ok and ch * ch - sh * sh == 1
        B = GA.add(GA.sc(ch), GA.scal(sh, SIG))
        ok = ok and GA.eq(GA.mul(B, GA.reverse(B), S), GA.sc(1))
        for (c, s) in ANGLES:
            ok = ok and GA.eq(GA.mul(B, Rot(c, s), S), GA.mul(Rot(c, s), B, S))
        # hyperbolic: composition adds rapidities with the +1 square
        for (ch2, sh2) in BOOSTS:
            ok = ok and GA.eq(GA.mul(B, GA.add(GA.sc(ch2), GA.scal(sh2, SIG)), S),
                              GA.add(GA.sc(ch * ch2 + sh * sh2), GA.scal(sh * ch2 + ch * sh2, SIG)))
    _tp_rv = (ok); assert _tp_rv is not False, "check_hyperbolic_and_elliptic_flows_share_the_pair"; return _tp_rv


def check_chiral_halves_carry_r_theta_and_r_minus_theta():
    premise("singularity.euclidean-rotor-where-it-lies")
    S6 = (1, -1, -1, -1, 1, -1)
    E = GA.mul(GA.gen(4), GA.gen(5), S6)
    I6 = GA.mul(I4, E, S6)
    sig = GA.mul(GA.gen(0), GA.gen(1), S6)
    isig = GA.mul(I4, sig, S6)
    gen6 = GA.mul(I6, sig, S6)
    ok = GA.eq(GA.mul(E, E, S6), GA.sc(1)) and GA.eq(gen6, GA.mul(E, isig, S6))
    ok = ok and GA.eq(GA.mul(gen6, gen6, S6), GA.sc(-1))
    epp = GA.scal(F(1, 2), GA.add(GA.sc(1), E))
    epm = GA.scal(F(1, 2), GA.sub(GA.sc(1), E))
    ok = ok and GA.eq(GA.mul(I6, epp, S6), GA.mul(I4, epp, S6))
    ok = ok and GA.eq(GA.mul(I6, epm, S6), GA.neg(GA.mul(I4, epm, S6)))
    for (c, s) in ANGLES:
        RW = GA.add(GA.sc(c), GA.scal(s, gen6))
        Rp = GA.add(GA.sc(c), GA.scal(s, isig))
        Rm = GA.add(GA.sc(c), GA.scal(-s, isig))
        ok = ok and GA.eq(RW, GA.add(GA.mul(epp, Rp, S6), GA.mul(epm, Rm, S6)))
        ok = ok and GA.eq(GA.mul(RW, epp, S6), GA.mul(Rp, epp, S6))
        ok = ok and GA.eq(GA.mul(RW, epm, S6), GA.mul(Rm, epm, S6))
    _tp_rv = (ok); assert _tp_rv is not False, "check_chiral_halves_carry_r_theta_and_r_minus_theta"; return _tp_rv
