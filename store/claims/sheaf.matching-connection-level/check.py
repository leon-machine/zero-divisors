"""sheaf.matching-connection-level: exact checks in Gauge Theory Gravity.

(1) Frames. The Painleve-Gullstrand gauge field hb = 1 - beta P on Cl(1,3) (GA.py, (+,-,-,-)),
    P(a) = (a . e_t) e_r, beta = m/sqrt r, with the cometric G(a, b) = hb^T(a) . hb^T(b) on covectors
    (background vectors through the reciprocal frame: dt -> e^t, dr -> e^r = -e_r; rho = sqrt(r) dr,
    k = rho + m dt). At rational (m, sqrt r) with m^2 - r a rational square, inside the horizon (r < m^2):
    d tau = sqrt(r/(m^2 - r)) dr and theta^1 = sqrt((m^2 - r)/r) dt_S, dt_S = dt + (m/(m^2 - r)) rho;
    computed: sqrt(m^2 - r) d tau = rho and sqrt(m^2 - r) theta^1 = -sqrt(r) dt + m k/sqrt(r) exactly;
    (d tau, theta^1) is G-orthonormal; with k^ = k/sqrt(r), theta^1 = sinh(chi) dt + cosh(chi) k^ and
    d tau = -(cosh(chi) dt + sinh(chi) k^) for (sinh chi, cosh chi) = (-sqrt r, m)/sqrt(m^2 - r), unit; the
    same formula evaluated at r = 0 gives (0, 1), so theta^1 = k^ and d tau = -dt at the wall (the frames
    coincide there, future orientations matched by the sign), approached with |sinh chi| < 2 sqrt r and
    0 < cosh chi - 1 < r along a rational sequence at m = 1.
(2) Rates. Exact series in u = sqrt(r) (2M = m^2 = 1): tau sigma_1 = -1/3 - (4/15) r + ..., tau sigma_2 =
    2/3 - (2/15) r + ..., the sphere term tau/r = (2/3) u + O(u^3), and the trace rule
    tau(sigma_1 + 2 sigma_2) -> 1 with correction -(8/15) r.
(3) Matching (values level). The boundary value sum p_i B_i (p = (-1/3, 2/3, 2/3)) has total element
    B_w = sum p_i e_0 ^ e_i with B_w^2 = 1 (unit boost), and the three values p_i B_i generate a Lie algebra
    of dimension 6 = dim so(1,3). The ladder-boost sentence is carried by sheaf.matching-fibre and is not
    recomputed.
"""
