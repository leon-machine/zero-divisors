# ---- exact series of the Schwarzschild interior (2M = 1) in u = sqrt(r) ----
NS = 8


def interior_series(N=NS):
    """tau(u) = int_0^r sqrt(s/(1-s)) ds = int 2 v^2 (1 - v^2)^{-1/2} dv; returns (tau, tau sigma_1,
    tau sigma_2, R/u^2, tau/r) as coefficient lists in u, with sigma_1 = -(1/2) r^{-3/2} (1 - r)^{-1/2},
    sigma_2 = r^{-3/2} (1 - r)^{1/2}, R = (3 tau/2)^{2/3}."""
    w = GA.ps_pow_rat([F(1), F(0), F(-1)], F(-1, 2), N)
    tau = GA.ps_int(GA.ps_mul([F(0), F(0), F(2)], w, N))
    t3 = GA.ps_trunc(tau[3:], N)
    ts1 = [-c / 2 for c in GA.ps_mul(w, t3, N)]
    ts2 = GA.ps_mul(GA.ps_pow_rat([F(1), F(0), F(-1)], F(1, 2), N), t3, N)
    Ru2 = GA.ps_pow_rat([F(3, 2) * c for c in t3], F(2, 3), N)
    tau_over_r = [F(0)] + t3[:N]
    return tau, ts1, ts2, Ru2, tau_over_r


def lie_dim(gens, sq):
    """Dimension of the Lie algebra generated by bivectors under the commutator."""
    blades = [(a, b) for a in range(4) for b in range(a + 1, 4)]

    def rank(xs):
        return GA.field_rank([[x.get(bl, F(0)) for bl in blades] for x in xs]) if xs else 0
    span = [g for g in gens if g]
    while True:
        new = span + [GA.scal(F(1, 2), GA.sub(GA.mul(a, b, sq), GA.mul(b, a, sq))) for a in span for b in span]
        if rank(new) == rank(span):
            return rank(span)
        basis = []
        for x in new:
            if rank(basis + [x]) > len(basis):
                basis.append(x)
        span = basis


S13 = GA.sig(1, 3)
E = [GA.gen(i) for i in range(4)]
UP = [E[0], GA.neg(E[1]), GA.neg(E[2]), GA.neg(E[3])]
MS = [(F(1), F(3, 5)), (F(1), F(4, 5)), (F(5, 4), F(3, 4)), (F(13, 12), F(5, 12)), (F(5, 3), F(4, 3))]


def hbT(beta, b):
    return GA.sub(b, GA.scal(beta * GA.dot(b, E[1], S13), E[0]))


def G(beta, a, b):
    return GA.dot(hbT(beta, a), hbT(beta, b), S13)


ROOTS = {(F(1), F(3, 5)): F(4, 5), (F(1), F(4, 5)): F(3, 5), (F(5, 4), F(3, 4)): F(1), (F(13, 12), F(5, 12)): F(1),
         (F(5, 3), F(4, 3)): F(1)}                                   # sqrt(m^2 - r), checked by squaring


def gbiv(a, b):
    return GA.mul(GA.gen(a), GA.gen(b), S13)


def boost(m, s, root):
    """(sinh chi, cosh chi) = (-sqrt r, m)/sqrt(m^2 - r) at sqrt r = s, root = sqrt(m^2 - r)."""
    return -s / root, m / root


def check_adapted_coframe_is_exceptional():
    premise("sheaf.schwarzschild-degeneration-boundary-tame")
    ok = True
    for m, s in MS:
        r, beta = s * s, m / s
        root = ROOTS[(m, s)]
        ok = ok and root * root == m * m - r and root > 0
        dt, dr = UP[0], UP[1]
        rho = GA.scal(s, dr)
        k = GA.add(rho, GA.scal(m, dt))
        dtS = GA.add(dt, GA.scal(m / (m * m - r), rho))
        dtau = GA.scal(s / root, dr)
        th1 = GA.scal(root / s, dtS)
        ok = ok and GA.eq(GA.scal(root, dtau), rho)
        ok = ok and GA.eq(GA.scal(root, th1), GA.add(GA.scal(-s, dt), GA.scal(m / s, k)))
        ok = ok and G(beta, dtau, dtau) == 1 and G(beta, th1, th1) == -1 and G(beta, dtau, th1) == 0
        kh = GA.scal(1 / s, k)
        sh, ch = boost(m, s, root)
        ok = ok and ch * ch - sh * sh == 1 and G(beta, dt, dt) == 1 and G(beta, kh, kh) == -1 and G(beta, dt, kh) == 0
        ok = ok and GA.eq(th1, GA.add(GA.scal(sh, dt), GA.scal(ch, kh)))
        ok = ok and GA.eq(dtau, GA.neg(GA.add(GA.scal(ch, dt), GA.scal(sh, kh))))
    for mm, _ in MS:                                            # at r = 0: sqrt(m^2 - r) = m
        ok = ok and mm > 0
        sh0, ch0 = boost(mm, F(0), mm)
        # theta^1 = sh dt + ch k^ and d tau = -(ch dt + sh k^) at the wall: theta^1 = k^, d tau = -dt
        ok = ok and (sh0, ch0) == (0, 1) and [[sh0, ch0], [-ch0, -sh0]] == [[0, 1], [-1, 0]]
    for n in (10, 100, 1000):                                   # approach along m = 1, s = 2n/(n^2 + 1)
        sn, rn = F(2 * n, n * n + 1), F(n * n - 1, n * n + 1)
        ok = ok and rn * rn == 1 - sn * sn
        sh, ch = boost(F(1), sn, rn)
        ok = ok and -2 * sn < sh < 0 and 0 < ch - 1 < sn * sn
    _tp_rv = (ok); assert _tp_rv is not False, "check_adapted_coframe_is_exceptional"; return _tp_rv


def check_rates_by_exact_series():
    premise("sheaf.weighted-limit")
    tau, ts1, ts2, Ru2, tor = interior_series()
    ok = (ts1[0], ts1[2], ts2[0], ts2[2]) == (F(-1, 3), F(-4, 15), F(2, 3), F(-2, 15))
    trace = [a + 2 * b for a, b in zip(ts1, ts2)]
    ok = ok and trace[0] == 1 and trace[2] == F(-8, 15) and trace[1] == 0
    _tp_rv = (ok and tor[:2] == [0, F(2, 3)] and tor[2] == 0); assert _tp_rv is not False, "check_rates_by_exact_series"; return _tp_rv


def check_matching_values_generate_so13():
    premise("sheaf.matching-fibre")
    premise("sheaf.weighted-limit")
    tau, ts1, ts2, Ru2, tor = interior_series()
    p = (ts1[0], ts2[0], ts2[0])
    Bw = GA.add(*[GA.scal(p[i], gbiv(0, i + 1)) for i in range(3)])
