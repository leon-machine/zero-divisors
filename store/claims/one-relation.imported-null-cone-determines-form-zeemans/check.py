"""one-relation.imported-null-cone-determines-form-zeemans: exact checks.

(1) The null cone fixes the form up to scale: for all nine mixed signatures (p, q) with 1 <= p, q <= 3, an
    unknown symmetric S (n(n+1)/2 unknowns) vanishing on the listed null vectors e_i +- e_j (i positive,
    j negative), 3e_i + 4e_k +- 5e_j (i, k distinct positive, j negative) and 5e_i + 3e_j +- 4e_l (i positive,
    j, l distinct negative) is a multiple of Q: the solution space is one-dimensional and contains Q. All
    listed vectors are null. The first family alone leaves exactly the space S_ij = 0 (mixed pairs),
    S_ii = -S_jj, with the same-sign off-diagonal entries free: dimension 1 + p(p-1)/2 + q(q-1)/2, so at
    n = 2 it suffices and for n >= 3 the second and third families are needed.
(2) Null-locus criterion: every mixed signature with n <= 6 has the nonzero null vector e_1 + e_n; every
    definite one has a Gram matrix of signature (n, 0) or (0, n), so no nonzero null vector.
(3) In n = 2 the causal order in null coordinates u = t - x, v = t + x is the product order (2025 ordered
    comparable pairs on a 9 x 9 grid); the reparametrisations u -> u + a_1 u^3 + ... (a_i >= 0) preserve it on
    the grid and are not affine (for u + u^3 the second difference with step h is 6 u h^2, nonzero), and
    u^3, u^5, u^7, u^9 are independent on the grid: the causal automorphisms are not a finite-dimensional
    family generated by Lorentz maps, translations and dilations.
Zeeman's theorem for n >= 3 is literature with no finite core here; the -external entity is the
literature restatement and is not called.
"""
from fractions import Fraction as F
from itertools import combinations

import GA
from tp_premise import premise

GRID = [F(k, 2) for k in range(-4, 5)]
COEFF_SETS = [(1,), (1, 2), (F(1, 3), 1, 5), (2, 1, F(1, 2), 3)]


def null_families(p, q):
    n = p + q
    pos, neg = range(p), range(p, n)

    def v(*terms):
        out = [F(0)] * n
        for c, i in terms:
            out[i] += c
        return out
    fam1 = [v((1, i), (s, j)) for i in pos for j in neg for s in (1, -1)]
    fam2 = [v((3, i), (4, k), (5 * s, j)) for i in pos for k in pos if k != i for j in neg for s in (1, -1)]
    fam3 = [v((5, i), (3, j), (4 * s, l)) for i in pos for j in neg for l in neg if l != j for s in (1, -1)]
    return fam1, fam2, fam3


def form_rows(vectors, n):
    pairs = [(a, b) for a in range(n) for b in range(a, n)]
    rows = []
    for x in vectors:
        rows.append([x[a] * x[b] * (1 if a == b else 2) for a, b in pairs])
    return pairs, rows


def check_null_cone_determines_the_form_up_to_scale():
    ok = True
    count = 0
    for p in range(1, 4):
        for q in range(1, 4):
            n = p + q
            sq = [1] * p + [-1] * q
            f1, f2, f3 = null_families(p, q)
            ok = ok and all(sum(sq[a] * x[a] * x[a] for a in range(n)) == 0 for x in f1 + f2 + f3)
            pairs, rows = form_rows(f1 + f2 + f3, n)
            ker = GA.field_kernel(rows)
            Qvec = [F(sq[a]) if a == b else F(0) for a, b in pairs]
            ok = ok and len(ker) == 1 and GA.rank_of_vectors(ker + [Qvec]) == 1
            _, rows1 = form_rows(f1, n)
            ok = ok and len(GA.field_kernel(rows1)) == 1 + p * (p - 1) // 2 + q * (q - 1) // 2
            count += 1
    ok = ok and count == 9
    _tp_rv = (ok); assert _tp_rv is not False, "check_null_cone_determines_the_form_up_to_scale"; return _tp_rv


def check_null_vector_exists_iff_signature_mixed():
    premise("transport.existence-locus-type-n")
    ok = True
    mixed = definite = 0
    for n in range(1, 7):
        for p in range(n + 1):
            q = n - p
            gram = [[F(0)] * n for _ in range(n)]
            for a in range(n):
                gram[a][a] = F(1) if a < p else F(-1)
            if p * q != 0:
                v = [F(0)] * n
                v[0], v[n - 1] = F(1), F(1)
                ok = ok and sum(gram[a][a] * v[a] * v[a] for a in range(n)) == 0
                mixed += 1
            else:
                ok = ok and GA.congruence_signature(gram) in ((n, 0, 0), (0, n, 0))
                definite += 1
    ok = ok and mixed == 15 and definite == 12
    _tp_rv = (ok); assert _tp_rv is not False, "check_null_vector_exists_iff_signature_mixed"; return _tp_rv


def reparam(coeffs, u):
    out = u
    for k, a in enumerate(coeffs):
        out += a * u ** (2 * k + 3)
    return out


def precedes(a, b):
    """Causal order in null coordinates: the product order."""
    return a[0] <= b[0] and a[1] <= b[1]


PTS = [(u, v) for u in GRID for v in GRID]
D2_POINTS = [F(1), F(-3, 2), F(2)]
STEP = F(1, 2)
ODD_POWERS = [[u ** (2 * j + 3) for u in GRID] for j in range(4)]


def comparable_pairs(points):
    return sum(1 for a in points for b in points if precedes(a, b))


def check_two_dimensional_causal_automorphisms_are_not_conformal():
    ok = True
    # on the 9 x 9 grid the product order has 45^2 = 2025 ordered comparable pairs (45 = 9 * 10 / 2 per factor)
    ok = ok and comparable_pairs(PTS) == 2025
    for coeffs in COEFF_SETS:
        image = {P: (reparam(coeffs, P[0]), P[1]) for P in PTS}
        ok = ok and all(precedes(a, b) == precedes(image[a], image[b]) for a in PTS for b in PTS)
        ok = ok and comparable_pairs(list(image.values())) == 2025
    # not affine: for u + u^3 the second difference with step 1/2 at u is 6 u (1/2)^2 = 3u/2
    for u in D2_POINTS:
        d2 = reparam((1,), u + STEP) - 2 * reparam((1,), u) + reparam((1,), u - STEP)
        ok = ok and d2 == 6 * u * STEP * STEP
    # the maps u -> u^3, u^5, u^7, u^9 are independent functions on the grid: no finite dimension bound
    ok = ok and GA.rank_of_vectors(ODD_POWERS) == 4
    _tp_rv = (ok); assert _tp_rv is not False, "check_two_dimensional_causal_automorphisms_are_not_conformal"; return _tp_rv
