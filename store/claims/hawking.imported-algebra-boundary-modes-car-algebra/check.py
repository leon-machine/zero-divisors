"""hawking.imported-algebra-boundary-modes-car-algebra: exact checks of the finite core.

The completed limit and the CAR uniqueness are the cited theorems (tower.algebraic-limit-even-charge,
tower.car-limit-even-charge) and have no finite content here. Checked on the physical lineage, the
tower over Cl(1,3) (GA.py: ground generators first, then plane j as e_j (+1), f_j (-1),
v_j = (e_j + f_j)/2, w_j = (e_j - f_j)/2):
(1) the transport charge p - q mod 8 of every floor Cl(1+k, 3+k), k = 0..6, is 6, even;
(2) the mode operators are the adjoined null pairs: they satisfy the CAR exactly in T_k (k <= 3),
    v_j^* = w_j for the *-antiautomorphism (x* = x for x^2 = 1, x* = -x for x^2 = -1), and they
    commute with the twisted ground generators, which satisfy the Cl(1,3) relations; the mode
    algebra generated by the v_j, w_j contains e_j = v_j + w_j and f_j = v_j - w_j, and the products
    of the ordered ground words with the ordered mode words hit all 2^(4 + 2k) blades of the floor
    (k <= 3), so the floor is the ground factor tensored with the mode algebra (16 * 4^k = dim);
    at k = 1 the same is shown directly from the words in v_1, w_1 (rank 64);
(3) the Fock adjointness: the images rho(e_j) = wedge + contraction, rho(f_j) = wedge - contraction
    on Lambda W_k (orthonormal wedge monomials) satisfy the Cl(k,k) relations; extending rho to
    the Clifford element v_j (as a sum of blades) gives the wedge by v_j, and rho(x^*) is the
    transpose of rho(x) for every blade x of Cl(k,k) (k <= 2), in particular for w_j = v_j^* (k <= 3);
    the vacuum is annihilated by every rho(w_j) and by no rho(v_j).
The labelling checked is the statement's and the premise's (tower.car-limit-even-charge):
annihilation a_j = v_j^* = w_j, creation a_j^dagger = v_j.
"""
