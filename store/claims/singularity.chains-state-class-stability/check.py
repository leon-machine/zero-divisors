"""singularity.chains-state-class-stability: exact checks.

Boundary modes are qubits in the number basis; mode k has weight omega_k and Boltzmann factor
x_k = e^{-beta omega_k} = r^(2 omega_k) at the common beta (r = 3/4, weights 1 and 2 used), so the
Gibbs marginal of K_k at beta is diag(1, x_k)/(1 + x_k). Thermofield pairs on two modes of equal
weight are built from the unnormalised vector |00> + t|11>, t = r^omega (amplitudes rational, the
density matrix normalised exactly).
(1) Members of C (pairs, pairs after controlled-Z patterns, the product state) are even (P) and
every single-mode marginal is the Gibbs matrix at the common beta and satisfies the KMS identity
omega(ab) = omega(b e^{-beta K} a e^{beta K}) on all matrix units (the ungraded identity that (R)
reads, via the KMS-uniqueness premise).
(2) Dynamics permitted by (L_E): diagonal unitaries in the joint number basis (controlled-Z patterns,
phases diag(u^{m_b}) with u = (3 + 4i)/5 on the unit circle, generated by products of sigma's) keep
every member even with the same marginals, while changing the joint state. Control: a hopping
rotation (excluded by (L_E)) moves a marginal out of the class.
(3) The product member e^{-beta K_geo}/Z is in C; it is the member satisfying (G), read as
rho = e^{-beta K_geo}/Z exactly (the exact-equilibrium premise), which no other state equals. E_N-fixedness
alone does not single it out: the diagonal correlated member with populations of the product shifted by
+-1/100 (same Gibbs marginals, connected correlator nonzero) is in C and E_N-fixed, and differs from the
product; the entangled pair members are not E_N-fixed. For k = 1, 2, 3 pairs
(2k modes) the pure member has S(rho) = 0 (rho^2 = rho), 2k marginals with the same spectrum
{c^2, s^2} (binary entropy h > 0 each) and E_N(rho) equal to the k-fold product of
diag(c^2, 0, 0, s^2): so C(rho) = 2k h and the descent deficit S(E_N rho) - S(rho) = k h, unbounded
in k. (R) constrains none of these correlations: all members share the marginals.
"""
from fractions import Fraction as F

from GA import QI
import fock
from tp_premise import premise

R = F(3, 4)
U = QI(F(3, 5), F(4, 5))


def bit(b, k, n):
    return (b >> (n - 1 - k)) & 1


popcount = fock.popcount


def dm(n, amps):
    D = 2 ** n
    nrm = sum((QI(a) * QI(a).conj() for a in amps.values()), QI(0))
    rho = [[QI(0)] * D for _ in range(D)]
    for i, a in amps.items():
        for j, b in amps.items():
            rho[i][j] = rho[i][j] + QI(a) * QI(b).conj() / nrm
    return rho


def pairs_state(weights):
    """Thermofield pairs (2j, 2j+1) with t_j = R^weight_j, unnormalised amplitudes."""
    n = 2 * len(weights)
    amps = {0: F(1)}
    for j, w in enumerate(weights):
        t = R ** w
        new = {}
        for m, a in amps.items():
            new[m] = new.get(m, F(0)) + a
            m2 = m | (1 << (n - 1 - 2 * j)) | (1 << (n - 2 - 2 * j))
            new[m2] = new.get(m2, F(0)) + a * t
        amps = new
    return n, amps


def qpow(z, e):
    out = QI(1)
    for _ in range(abs(e)):
        out = out * (z if e > 0 else z.conj())
    return out


def apply_diag(amps, phase):
    return {m: a * phase(m) for m, a in amps.items()}


def marginal(rho, k, n):
    out = [[QI(0), QI(0)], [QI(0), QI(0)]]
    for b in range(2 ** n):
        for c in range(2 ** n):
            if all(bit(b, t, n) == bit(c, t, n) for t in range(n) if t != k):
                out[bit(b, k, n)][bit(c, k, n)] = out[bit(b, k, n)][bit(c, k, n)] + rho[b][c]
    return out


def gibbs(x):
    return [[QI(1 / (1 + x)), QI(0)], [QI(0), QI(x / (1 + x))]]


def is_even(rho):
    D = len(rho)
    return all(rho[b][c] == 0 for b in range(D) for c in range(D) if (popcount(b) + popcount(c)) % 2)


def in_class(rho, n, weights):
    if not is_even(rho):
        return False
    return all(marginal(rho, k, n) == gibbs(R ** (2 * weights[k // 2])) for k in range(n))


def kms_ok(m, x):
    """omega(ab) = omega(b E a E^{-1}) on all matrix units, E = diag(1, x) = e^{-beta K} up to scale."""
    E, Ei = [F(1), x], [F(1), 1 / x]
    for a in range(2):
        for b in range(2):
            for c in range(2):
                for d in range(2):
                    lhs = m[d][a] if b == c else QI(0)
                    rhs = m[b][c] * E[a] * Ei[b] if d == a else QI(0)
                    if lhs != rhs:
                        return False
    return True


CZ = lambda n, i, j: (lambda m: F(-1) if bit(m, i, n) and bit(m, j, n) else F(1))


def check_members_are_even_with_gibbs_kms_marginals():
    premise("singularity.p-univalence")
    premise("singularity.r-regularity-fixed-locus")
    premise("singularity.kms-uniqueness-factor")
    premise("singularity.rate-discharge-hypothesis-iii")
    weights = [1, 2]
    n, amps = pairs_state(weights)
    members = [dm(n, amps), dm(n, apply_diag(amps, CZ(n, 1, 3)))]
    for rho in members:
        assert in_class(rho, n, weights)
        for k in range(n):
            x = R ** (2 * weights[k // 2])
            assert kms_ok(marginal(rho, k, n), x)
            assert not kms_ok(marginal(rho, k, n), x * x)       # a wrong beta fails
    assert marginal(members[0], 0, n) == gibbs(F(9, 16)) and marginal(members[0], 2, n) == gibbs(F(81, 256))


# Dynamics permitted by (L_E), applied to the member with two weight-1 pairs (n = 4 modes).
WEIGHTS_DYN = [1, 1]


def diag_phases(n):
    """Sample joint-number-diagonal unitaries: two controlled-Z patterns and two phases built from U."""
    return [CZ(n, 1, 3), CZ(n, 0, 2),
            lambda m: qpow(U, 2 * bit(m, 0, n) - 1) * qpow(U, 1 - 2 * bit(m, 3, n)),
            lambda m: qpow(U, (2 * bit(m, 1, n) - 1) * (2 * bit(m, 2, n) - 1))]


# Control: a real hopping rotation (cos, sin) = (3/5, 4/5) between modes 1 and 2 of the weights (1, 2) member.
WEIGHTS_CTRL = [1, 2]
HOP = (1, 2, F(3, 5), F(4, 5))


def hop_rotation(amps, n, i, j, c, s):
    """|1_i 0_j> -> c |1_i 0_j> + s |0_i 1_j>, |0_i 1_j> -> c |0_i 1_j> - s |1_i 0_j>; other occupations fixed."""
    hop = {}
    for m, a in amps.items():
        bi, bj = bit(m, i, n), bit(m, j, n)
        if bi == bj:
            hop[m] = hop.get(m, F(0)) + a
            continue
        f = m ^ (1 << (n - 1 - i)) ^ (1 << (n - 1 - j))
        hop[m] = hop.get(m, F(0)) + c * a
        hop[f] = hop.get(f, F(0)) + (s if bi else -s) * a
    return hop


def check_class_invariant_under_number_diagonal_dynamics():
    premise("singularity.l-boundary-mode-locality")
    premise("singularity.number-diagonal-dynamics-models-scrambling-derived")
    weights = WEIGHTS_DYN
    n, amps = pairs_state(weights)
    rho0 = dm(n, amps)
    for ph in diag_phases(n):
        rho = dm(n, apply_diag(amps, ph))
        assert in_class(rho, n, weights) and rho != rho0
    # control: the hopping rotation on the weights (1, 2) member. Modes i, j lie in different pairs, so their
    # occupations are independent with Gibbs populations p_i, p_j; by hand the rotation gives
    # p_i' = c^2 p_i + s^2 p_j and p_j' = s^2 p_i + c^2 p_j, which leave the class as p_i != p_j
    weights = WEIGHTS_CTRL
    n, amps = pairs_state(weights)
    i, j, c, s = HOP
    rho = dm(n, hop_rotation(amps, n, i, j, c, s))
    pi, pj = [gibbs(R ** (2 * weights[k // 2]))[1][1] for k in (i, j)]
    assert marginal(rho, i, n)[1][1] == c * c * pi + s * s * pj
    assert marginal(rho, j, n)[1][1] == s * s * pi + c * c * pj
    assert is_even(rho) and not in_class(rho, n, weights)


def check_product_member_and_unbounded_correlation():
    premise("singularity.exact-equilibrium-over-determines-boundary-modes")
    premise("singularity.parity-protection")
    # the product member e^{-beta K_geo}/Z for weights (1, 2) on 2 modes; E_N-fixed, but not uniquely so
    x1, x2 = R ** 2, R ** 4
    prod = [[QI(0)] * 4 for _ in range(4)]
    Z = (1 + x1) * (1 + x2)
    for b in range(4):
        prod[b][b] = QI(x1 ** bit(b, 0, 2) * x2 ** bit(b, 1, 2) / Z)
    assert marginal(prod, 0, 2) == gibbs(x1) and marginal(prod, 1, 2) == gibbs(x2) and is_even(prod)
    pinch = lambda r: [[r[i][j] if i == j else QI(0) for j in range(len(r))] for i in range(len(r))]
    assert pinch(prod) == prod
    # a diagonal correlated member: populations shifted by +eps on |00>, |11> and -eps on |01>, |10>
    eps = F(1, 100)
    corr = [[prod[i][j] + (QI(eps if bit(i, 0, 2) == bit(i, 1, 2) else -eps) if i == j else QI(0))
             for j in range(4)] for i in range(4)]
    assert all(corr[b][b].re > 0 and corr[b][b].im == 0 for b in range(4))
    assert sum((corr[b][b] for b in range(4)), QI(0)) == QI(1)
    assert marginal(corr, 0, 2) == gibbs(x1) and marginal(corr, 1, 2) == gibbs(x2) and is_even(corr)
    assert pinch(corr) == corr and corr != prod
    conn = corr[3][3] - (corr[2][2] + corr[3][3]) * (corr[1][1] + corr[3][3])   # <n_0 n_1> - <n_0><n_1>
    assert conn == QI(eps)
    for k in (1, 2, 3):
        n, amps = pairs_state([1] * k)
        rho = dm(n, amps)
        D = 2 ** n
        nz = [t for t in range(D) if rho[t][t] != 0]
        rho2 = [[sum((rho[i][t] * rho[t][j] for t in nz), QI(0)) for j in range(D)] for i in range(D)]
        assert rho2 == rho                                   # pure: S(rho) = 0
        margs = [marginal(rho, j, n) for j in range(n)]
        assert all(m == gibbs(R ** 2) for m in margs) and len(margs) == 2 * k
        assert pinch(rho) != rho                             # not the (G) member
        # E_N(rho) is the k-fold product of diag(c^2, 0, 0, s^2): spectrum multiset of size 2^k
        c2, s2 = 1 / (1 + R ** 2), R ** 2 / (1 + R ** 2)
        diag = sorted(rho[b][b].re for b in range(D) if rho[b][b] != 0)
        want = [F(1)]
        for _ in range(k):
            want = [w * p for w in want for p in (c2, s2)]
        assert diag == sorted(want) and len(diag) == 2 ** k
        assert 0 < c2 < 1                                    # h = H(c^2) > 0 per marginal and per pair
