"""odd-extensions.are-ascents-pair-signed: exact checks.

The rung as GA's Cl(2,4): Lorentz frame e_0 (+1), e_1, e_2, e_3 (-1), and the plane orthogonal to it spanned by
e_+ = e_4 (+1), e_- = e_5 (-1). The frozen point is I = c e_+ + d e_- with Q(I) = c^2 - d^2 = Lambda/3; for
Lambda != 0 the Stelle-West vector is V = (3/Lambda)(d e_+ + c e_-), the vector of the plane orthogonal to I with
Q(V) = -3/Lambda. Samples (c, d) at module level give Lambda/3 = 3, -3, 5/4, -8/9 and 0.
(i) <I, V> = 0, Q(I) Q(V) = -1 (opposite signs), and I, V anticommute with each other and with e_0..e_3.
(ii) I^perp (exact kernel of <I, .>) is 5-dimensional and equals span{e_0..e_3, V}; the induced form has
    signature (1,4) for Lambda > 0 (V^2 < 0) and (2,3) for Lambda < 0 (V^2 > 0); the 32 products of distinct
    elements of {e_0..e_3, V} are independent, and adjoining I gives all 64 dimensions of the rung.
(iii) Lambda = 0: I^2 = 0, I is in I^perp, the induced form on I^perp has signature (1,3) with a 1-dimensional
    radical spanned by I; I anticommutes with the Lorentz frame; the algebra generated by e_0..e_3 and I has
    dimension 32 and I times it is a 16-dimensional two-sided ideal of square zero.
(iv) The Lorentz frame is orthogonal to I and V and has signature (1,3) for every sample.
"""
from fractions import Fraction as F
from itertools import combinations

import GA
from tp_premise import premise

SQ = (1, -1, -1, -1, 1, -1)
SAMPLES = [(F(2), F(1)), (F(1), F(2)), (F(3, 2), F(1)), (F(1, 3), F(1)), (F(1), F(1)), (F(-5, 2), F(-5, 2))]
FRAME = [GA.gen(i) for i in range(4)]


def vec(coords):
    return {(i,): F(x) for i, x in enumerate(coords) if x}


def coords(x):
    return [x.get((i,), F(0)) for i in range(6)]


def gram(vs):
    return [[GA.dot(a, b, SQ) for b in vs] for a in vs]


def prods(gs):
    out = []
    for k in range(len(gs) + 1):
        for idx in combinations(range(len(gs)), k):
            x = {(): F(1)}
            for t in idx:
                x = GA.mul(x, gs[t], SQ)
            out.append(x)
    return out


def rank_mv(xs):
    blades = sorted({b for x in xs for b in x})
    return GA.rank_of_vectors([[x.get(b, F(0)) for b in blades] for x in xs]) if blades else 0


def frozen(c, d):
    return vec([0, 0, 0, 0, c, d])


def stelle_west(c, d):
    lam = 3 * (c * c - d * d)
    return GA.scal(3 / lam, vec([0, 0, 0, 0, d, c]))


def perp_basis(I):
    row = [[GA.dot(I, GA.gen(i), SQ) for i in range(6)]]
    return [vec(v) for v in GA.field_kernel(row)]


def check_hyperbolic_plane_and_signed_ascent():
    premise("odd-extensions.imported-frozen-point")
    premise("odd-extensions.imported-frozen-point-degenerate-algebras")
    premise("odd-extensions.four-extensions-oriented-pair")
    ok = True
    n = 0
    for c, d in SAMPLES:
        qi = c * c - d * d
        if qi == 0:
            continue
        n += 1
        I, V = frozen(c, d), stelle_west(c, d)
        qv = GA.dot(V, V, SQ)
        ok = ok and GA.dot(I, I, SQ) == qi and GA.dot(I, V, SQ) == 0 and qi * qv == -1
        ok = ok and GA.anticommutes(I, V, SQ) and all(GA.anticommutes(x, e, SQ) for x in (I, V) for e in FRAME)
        P = perp_basis(I)
        ok = ok and len(P) == 5 and GA.rank_of_vectors([coords(x) for x in P + FRAME + [V]]) == 5
        sig = GA.congruence_signature(gram(FRAME + [V]))
        ok = ok and sig == ((1, 4, 0) if qi > 0 else (2, 3, 0))
        gen5 = prods(FRAME + [V])
        ok = ok and rank_mv(gen5) == 32 and rank_mv(prods(FRAME + [V, I])) == 64
    ok = ok and n == 4
    GA.check("I, V hyperbolic pair; Cl(I^perp) = Cl(1,4) for Lambda > 0, Cl(2,3) for Lambda < 0; with I all of Cl(2,4)", ok)
    return ok


def check_null_frozen_point_degenerate():
    premise("odd-extensions.imported-frozen-point-degenerate-algebras")
    ok = True
    n = 0
    for c, d in SAMPLES:
        if c * c != d * d:
            continue
        n += 1
        I = frozen(c, d)
        ok = ok and GA.mul(I, I, SQ) == {} and GA.dot(I, I, SQ) == 0
        P = perp_basis(I)
        ok = ok and len(P) == 5 and GA.rank_of_vectors([coords(x) for x in P + FRAME + [I]]) == 5
        ok = ok and GA.congruence_signature(gram(P)) == (1, 3, 1)
        rad = GA.field_kernel(gram(P))
        ok = ok and len(rad) == 1
        radv = GA.add(*[GA.scal(x, P[i]) for i, x in enumerate(rad[0])])
        ok = ok and GA.rank_of_vectors([coords(radv), coords(I)]) == 1
        ok = ok and all(GA.anticommutes(I, e, SQ) for e in FRAME)
        alg = prods(FRAME + [I])
        ideal = [GA.mul(I, x, SQ) for x in alg]
        ok = ok and rank_mv(alg) == 32 and rank_mv(ideal) == 16
        ok = ok and all(GA.mul(x, y, SQ) == {} for x in ideal for y in ideal)
        ok = ok and all(rank_mv(ideal + [GA.mul(x, e, SQ), GA.mul(e, x, SQ)]) == 16 for x in ideal for e in FRAME + [I])
    ok = ok and n == 2
    GA.check("Lambda = 0: I null in its own complement, Cl(1,3;1) with I nilpotent and I Cl a square-zero ideal of dim 16", ok)
    return ok


def check_lorentz_frame_signature_constant():
    premise("odd-extensions.imported-frozen-point")
    ok = True
    for c, d in SAMPLES:
        I = frozen(c, d)
        ok = ok and all(GA.dot(I, e, SQ) == 0 for e in FRAME)
        if c * c != d * d:
            V = stelle_west(c, d)
            ok = ok and all(GA.dot(V, e, SQ) == 0 for e in FRAME)
        ok = ok and GA.congruence_signature(gram(FRAME)) == (1, 3, 0)
    GA.check("the Lorentz frame {I,V}^perp has signature (1,3) for every Lambda", ok)
    return ok
