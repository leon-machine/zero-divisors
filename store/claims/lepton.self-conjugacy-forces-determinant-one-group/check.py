def in_lattice(v, gens):
    if not gens:
        return v == (0, 0)
    if len(gens) == 1:
        (a, b) = gens[0]
        if a * v[1] - b * v[0] != 0:
            return False
        c = F(v[0], a) if a else F(v[1], b)
        return c.denominator == 1
    (a, b), (c, d) = gens
    det = a * d - b * c
    if det == 0:
        g = (a, b) if (a, b) != (0, 0) else (c, d)
        # dependent generators: the lattice is spanned by a primitive multiple; test through gcd of multipliers
        for m in range(-12, 13):
            for n in range(-12, 13):
                if (m * a + n * c, m * b + n * d) == tuple(v):
                    return True
        return False
    x = F(v[0] * d - v[1] * c, det)
    y = F(a * v[1] - b * v[0], det)
    return x.denominator == 1 and y.denominator == 1


CONJ = {"1": "1", "3": "3b", "3b": "3"}


def self_dual_on(gens, ks=(0, 1, 2, 3)):
    content = [su3_content(weights(j)) for j in range(4)]
    ok = True
    for k in ks:
        found = any(content[j] == CONJ[content[k]] and in_lattice((1 - (-1), j - (-k)), gens) for j in range(4))
        ok = ok and found
    return ok


