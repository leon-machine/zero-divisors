"""synthesis.r-loc-needs-sheet-labelled-modes: exact checks.

(1) Minkowski, edge {t = x = 0}: the boost field K = x d_t + t d_x is future pointing on one sheet through the
edge and past pointing on the other (past halves and future halves alike), so the future-directed boost fields of
the two local Rindler horizons sharing an edge are chi and -chi, each of unit surface gravity, chi = -lambda k.
(2) On a two-mode window (4 x 4 matrices, diagonal H with weights 1 and 2, Boltzmann symbol q rational) the KMS
condition E^{-1} rho A E = A rho for all matrix units A, imposed for H and for -H, has only rho = 0 (no state);
for H alone the solution space is the line of the Gibbs density; for a scalar H both conditions hold at the trace.
(3) In Cl(1,3) ad of the boost e0e1 has the real eigenvalues +-2 on the bivectors e0e2 -+ e1e2, and the ideal each
generates is all six bivectors. Window side, at three sampled non-diagonal self-adjoint h (n = 2, 3, entries in
Q(i)): X -> i[h, X] -+ 2X has zero kernel on M_n, so the homomorphism condition i[h_B, h_X] = 2 h_X (mod scalars)
forces D(X+) = 0 and, by the ideal, D = 0; control: a skew-adjoint h does give the eigenvalue 2. The general
statement for every self-adjoint h is the standard fact, sampled here, not proved.
(4) The future boosts of all horizons generated by one null l (edges moved by null rotations fixing l) dilate l
with one weight, -1; null rotations and the rotation about l have weight 0; the weight vanishes on brackets
(a character of the stabiliser of [l]); the opposite sheet's boost gives l the weight +1.
(5) de Sitter, embedding R^{1,4}: the static Killing field of an observer is past pointing on the antipodal
observer's worldline and both fix the bifurcation sphere X0 = X4 = 0.
"""
from fractions import Fraction as F
import GA
from tp_premise import premise

S13 = GA.sig(1, 3)  # e0^2 = +1, e1^2 = e2^2 = e3^2 = -1


def vec(t, x, y=0, z=0):
    out = {}
    for i, c in enumerate((t, x, y, z)):
        if c != 0:
            out[(i,)] = F(c)
    return out


def half_ad(B, v):
    return GA.scal(F(1, 2), GA.sub(GA.mul(B, v, S13), GA.mul(v, B, S13)))


def bracket(A, B):
    return GA.sub(GA.mul(A, B, S13), GA.mul(B, A, S13))


BIV = [(0, 1), (0, 2), (0, 3), (1, 2), (1, 3), (2, 3)]


def biv_coords(B):
    return [B.get(b, F(0)) for b in BIV]


def blade(i, j):
    return GA.mul(GA.gen(i), GA.gen(j), S13)


def boost_field(t, x):
    """K = x d_t + t d_x, components (K^t, K^x)."""
    return (x, t)


def check_two_sheets_have_opposite_boosts():
    premise("synthesis.einstein-equations-from-c-loc-and-clausius")
    premise("synthesis.c-loc-is-a-second-placement-of-the-count")
    ok = True
    # null normals of the edge: l = (1, 1), n = (1, -1) in (t, x)
    sheets = {"l": (F(1), F(1)), "n": (F(1), F(-1))}
    orient = {}
    for name, k in sheets.items():
        for half, sgn in (("past", -1), ("future", 1)):
            for s in (F(1, 3), F(2), F(7, 5)):
                lam = sgn * s                      # affine parameter along k, 0 at the edge
                pt = (lam * k[0], lam * k[1])
                Kt, Kx = boost_field(*pt)
                # K is tangent to the generator: K = c k
                c = Kt / k[0]
                ok = ok and Kx == c * k[1] and c != 0
                # future-directed boost field chi = sign(c) K; check chi = -kappa lambda k with kappa = 1
                fut = 1 if c > 0 else -1
                chi_coeff = fut * c
                ok = ok and abs(chi_coeff) == abs(lam)   # unit surface gravity: |chi| = |lambda| |k|
                if half == "past":
                    ok = ok and chi_coeff == -lam        # Jacobson's chi = -kappa lambda k, kappa = 1
                orient[(name, half, s)] = fut
    # on the past halves the future boost is -K on the l-sheet and +K on the n-sheet; reversed on future halves
    for s in (F(1, 3), F(2), F(7, 5)):
        ok = ok and orient[("l", "past", s)] == -1 and orient[("n", "past", s)] == 1
        ok = ok and orient[("l", "future", s)] == 1 and orient[("n", "future", s)] == -1
    # the field vanishes on the edge (its fixed locus), where point-spectrum modes sit
    ok = ok and boost_field(F(0), F(0)) == (0, 0)
    GA.check("the two local horizons through one edge have future boosts chi and -chi", ok)
    return ok


def kms_rows(E, n):
    """Linear conditions on rho (n*n unknowns) for E^{-1} rho A E = A rho, all matrix units A."""
    rows = []
    for k in range(n):
        for l in range(n):
            for i in range(n):
                for j in range(n):
                    row = [F(0)] * (n * n)
                    # (E^{-1} rho E_kl E)_{ij} = E_i^{-1} rho_{ik} delta_{lj} E_l
                    if l == j:
                        row[i * n + k] += E[l] / E[i]
                    # (E_kl rho)_{ij} = delta_{ik} rho_{lj}
                    if i == k:
                        row[l * n + j] -= F(1)
                    if any(r != 0 for r in row):
                        rows.append(row)
    return rows


def nullity(rows, m):
    return m - GA.field_rank(rows)


def check_joint_kms_forces_zero_weight():
    premise("singularity.kms-uniqueness-factor")
    premise("hawking.gibbs-states-are-kms-conversely-finite")
    premise("hawking.kms-restricts-invariant-subalgebras")
    premise("singularity.rate-rigidity-temperature-not-algebra-intrinsic")
    n = 4
    q = F(1, 3)   # Boltzmann factor of one unit of weight (stands for e^{-2 pi w})
    # H = N1 + 2 N2 on the basis |00>, |10>, |01>, |11>: E = e^{-beta H}
    E = [F(1), q, q ** 2, q ** 3]
    Einv = [1 / e for e in E]
    one = nullity(kms_rows(E, n), n * n)
    both = nullity(kms_rows(E, n) + kms_rows(Einv, n), n * n)
    # the solution for H alone is the Gibbs density
    gibbs = [F(0)] * (n * n)
    for i in range(n):
        gibbs[i * n + i] = E[i]
    sat = all(sum(r[c] * gibbs[c] for c in range(n * n)) == 0 for r in kms_rows(E, n))
    # scalar H: both conditions hold, at the trace
    Es = [q, q, q, q]
    scal_both = nullity(kms_rows(Es, n) + kms_rows([1 / e for e in Es], n), n * n)
    # the completed pair read by its two sheets: occupations q/(1+q) and 1/(1+q) agree only at q = 1
    occ = (q / (1 + q), 1 / (1 + q))
    ok = one == 1 and sat and both == 0 and scal_both == 1 and occ[0] != occ[1]
    GA.check("KMS at one beta for H and for -H: no state unless H is scalar", ok)
    return ok


def ideal_rank(gens):
    span = [biv_coords(g) for g in gens]
    basis = [blade(*b) for b in BIV]
    frontier = list(gens)
    for _ in range(4):
        new = []
        for g in frontier:
            for b in basis:
                c = bracket(g, b)
                if c:
                    new.append(c)
        span += [biv_coords(c) for c in new]
        frontier = new
    return GA.field_rank(span)


def check_covariant_lifts_on_windows_are_trivial():
    premise("hawking.modular-structure-completed-pair")
    B = blade(0, 1)
    Xp = GA.sub(blade(0, 2), blade(1, 2))
    Xm = GA.add(blade(0, 2), blade(1, 2))
    # ad of a boost has the real eigenvalues +2 and -2 on the bivectors
    ok = GA.eq(bracket(B, Xp), GA.scal(F(2), Xp)) and GA.eq(bracket(B, Xm), GA.scal(F(-2), Xm))
    # the ideal generated by the eigenvector X+ is the whole Lorentz algebra (rank 6)
    ok = ok and ideal_rank([Xp]) == 6 and ideal_rank([Xm]) == 6
    # window side: for self-adjoint h on C^n, the derivation X -> i[h, X] has no real eigenvalue +-2, so the
    # map X -> i[h, X] -+ 2 X is injective on M_n(C) (its kernel over Q(i) is zero); non-diagonal samples.
    # With the homomorphism condition D([B, X+]) = 2 D(X+), i.e. i[h_B, h_X] = 2 h_X up to a scalar, this
    # forces h_X scalar (D(X+) = 0), and the ideal generated by X+ is everything, so D = 0.
    I_ = GA.qi(0, 1)

    def deriv_matrix(h, ev):
        n_ = len(h)
        cols = []
        for k in range(n_):
            for l in range(n_):
                # X = E_kl: (h X - X h)_{ij} = h_ik delta_lj - delta_ik h_lj
                col = []
                for i in range(n_):
                    for j in range(n_):
                        c = GA.qi(0, 0)
                        if l == j:
                            c = c + h[i][k]
                        if i == k:
                            c = c - h[l][j]
                        c = I_ * c
                        if (i, j) == (k, l):
                            c = c - ev
                        col.append(c)
                cols.append(col)
        return [[cols[c][r] for c in range(n_ * n_)] for r in range(n_ * n_)]

    def is_self_adjoint(h):
        return all(h[i][j] == GA.qi(h[j][i].re, -h[j][i].im) for i in range(len(h)) for j in range(len(h)))
    samples = [
        [[GA.qi(1), GA.qi(2, -1)], [GA.qi(2, 1), GA.qi(-3)]],
        [[GA.qi(0), GA.qi(1)], [GA.qi(1), GA.qi(0)]],
        [[GA.qi(F(1, 2)), GA.qi(1, 1), GA.qi(0, 2)], [GA.qi(1, -1), GA.qi(2), GA.qi(-1)],
         [GA.qi(0, -2), GA.qi(-1), GA.qi(F(-3, 2))]],
    ]
    for h in samples:
        ok = ok and is_self_adjoint(h)
        for ev in (GA.qi(2), GA.qi(-2)):
            ok = ok and len(GA.field_kernel(deriv_matrix(h, ev))) == 0
    # control: a skew-adjoint h = -i diag(2, 0) gives i[h, E_12] = 2 E_12, a real eigenvalue (kernel dimension 1)
    hskew = [[GA.qi(0, -2), GA.qi(0)], [GA.qi(0), GA.qi(0)]]
    ok = ok and not is_self_adjoint(hskew) and len(GA.field_kernel(deriv_matrix(hskew, GA.qi(2)))) == 1
    # control: the bracket is the Lorentz algebra (two boosts close on a rotation)
    ok = ok and GA.eq(bracket(blade(0, 1), blade(0, 2)), GA.scal(F(-2), blade(1, 2)))
    GA.check("ad of a boost has real eigenvalues +-2 with ideal of rank 6; i[h, .] for sampled self-adjoint h "
             "(n = 2, 3, non-diagonal) has no eigenvalue +-2, so a covariant lift kills X+, hence everything", ok)
    return ok


def null_rotor(a, j):
    """Lambda = 1 + (a/2) l e_j with l = e0 + e1, j in {2, 3}: exp of a nilpotent bivector."""
    l = vec(1, 1)
    return GA.add(GA.sc(1), GA.scal(F(a, 2), GA.mul(l, GA.gen(j), S13)))


def check_dilation_character_of_the_generator():
    premise("hawking.modular-structure-completed-pair")
    l = vec(1, 1)
    nn = vec(1, -1)
    # (1/2) ad_B with B = e0 e1 maps t e0 + x e1 to -(x e0 + t e1): it is -K, the l-sheet's future boost (past half)
    B = blade(0, 1)
    ok = GA.eq(half_ad(B, vec(3, 5)), vec(-5, -3))
    ok = ok and GA.eq(half_ad(B, l), GA.neg(l))            # weight -1 on its own generator
    ok = ok and GA.eq(half_ad(GA.neg(B), nn), GA.neg(nn))   # the n-sheet's boost -B: weight -1 on n
    ok = ok and GA.eq(half_ad(GA.neg(B), l), l)             # ... and weight +1 on l: the two sheets disagree on l
    # other edges for the same generator: conjugate B by null rotations fixing l
    for a, j in ((1, 2), (F(-3, 2), 3), (2, 2)):
        Lam = null_rotor(a, j)
        Lrev = GA.reverse(Lam)
        ok = ok and GA.eq(GA.mul(Lam, Lrev, S13), GA.sc(1))
        ok = ok and GA.eq(GA.mul(GA.mul(Lam, l, S13), Lrev, S13), l)        # fixes l
        Bp = GA.mul(GA.mul(Lam, B, S13), Lrev, S13)
        ok = ok and not GA.eq(Bp, B)                                         # a different boost (different edge)
        ok = ok and GA.eq(GA.mul(Bp, Bp, S13), GA.sc(1))                    # unit boost
        ok = ok and GA.eq(half_ad(Bp, l), GA.neg(l))                         # same weight -1 on l
        ok = ok and not GA.is_zero(half_ad(Bp, GA.gen(j)))                   # e_j is not in its edge
    # the stabiliser of [l]: B, l e2, l e3, e2 e3; weight on l is a character (vanishes on brackets)
    stab = [B, GA.mul(l, GA.gen(2), S13), GA.mul(l, GA.gen(3), S13), blade(2, 3)]
    weights = []
    for X in stab:
        img = half_ad(X, l)
        # img is a multiple of l
        c = img.get((0,), F(0))
        ok = ok and GA.eq(img, GA.scal(c, l))
        weights.append(c)
    ok = ok and weights == [F(-1), F(0), F(0), F(0)]
    for X in stab:
        for Y in stab:
            Z = bracket(X, Y)
            ok = ok and GA.is_zero(half_ad(Z, l))
    GA.check("one dilation weight for every horizon generated by l, and it is a character of the stabiliser", ok)
    return ok


def check_antipodal_de_sitter_observers():
    premise("synthesis.de-sitter-static-boost-frozen-point")
    # embedding coordinates (X0, X1, X2, X3, X4), hyperboloid -X0^2 + X1^2 + X2^2 + X3^2 + X4^2 = 1
    def on_hyperboloid(X):
        return -X[0] ** 2 + X[1] ** 2 + X[2] ** 2 + X[3] ** 2 + X[4] ** 2 == 1

    def xi(X):  # boost of the (X0, X4) plane: xi = X4 d_0 + X0 d_4
        return (X[4], F(0), F(0), F(0), X[0])

    ok = True
    # observer O at X4 > 0 and antipodal O' at X4 < 0 (rational points of their worldlines, X1=X2=X3=0)
    for (s, c) in ((F(0), F(1)), (F(3, 4), F(5, 4)), (F(-5, 12), F(13, 12))):
        O = (s, F(0), F(0), F(0), c)
        Op = (-s, F(0), F(0), F(0), -c)
        ok = ok and on_hyperboloid(O) and on_hyperboloid(Op)
        ok = ok and xi(O)[0] > 0 and xi(Op)[0] < 0
    # both flows fix the bifurcation sphere X0 = X4 = 0
    for P in ((F(0), F(1), F(0), F(0), F(0)), (F(0), F(3, 5), F(4, 5), F(0), F(0))):
        ok = ok and on_hyperboloid(P) and xi(P) == (0, 0, 0, 0, 0)
    GA.check("antipodal de Sitter observers share the bifurcation sphere with Killing fields xi and -xi", ok)
    return ok
