from tp_premise import premise

S4 = (1, -1, -1, -1)
E = [GA.gen(i) for i in range(4)]
ROOTS = ((2, -1), (3, -2))
CS = (F(2), F(6))
VECS = ((1, 2, -1, 3), (F(1, 2), 0, 5, -2), (-3, F(1, 3), 1, 1))
HVALS = (F(-7, 9), F(5, 2))
USAMPLES = (F(0), F(1, 3), F(2))
JUS = (F(1, 2), F(-1, 3), F(4))
PAIRS = ((F(1, 2), F(-1, 3), (F(0), F(0))), (F(2), F(1, 5), (F(1), F(-3))),
         (F(1, 7), F(3, 2), (F(-2), F(1, 2))), (F(-1, 2), F(4), (F(3), F(3))))


class Jet(object):
    """Truncated Taylor polynomial (degree <= 2) in several variables, exact coefficients."""

    def __init__(self, d=None):
        self.d = d or {}

    @staticmethod
    def c(a):
        return Jet({(): F(a)})

    @staticmethod
    def var(i, a):
        return Jet({(): F(a), (i,): F(1)})

    def _j(self, o):
        return o if isinstance(o, Jet) else Jet.c(o)

    def __add__(self, o):
        o = self._j(o)
        r = dict(self.d)
        for k, v in o.d.items():
            r[k] = r.get(k, F(0)) + v
        return Jet(r)

    __radd__ = __add__

    def __neg__(self):
        return Jet({k: -v for k, v in self.d.items()})

    def __sub__(self, o):
        return self + (-self._j(o))

    def __rsub__(self, o):
        return self._j(o) - self

    def __mul__(self, o):
        o = self._j(o)
        r = {}
        for k1, v1 in self.d.items():
            for k2, v2 in o.d.items():
                k = tuple(sorted(k1 + k2))
                if len(k) <= 2:
                    r[k] = r.get(k, F(0)) + v1 * v2
        return Jet(r)

    __rmul__ = __mul__

    def inv(self):
        a0 = self.d.get((), F(0))
        x = (self - a0) * (1 / a0)
        return (Jet.c(1) - x + x * x) * (1 / a0)

    def __truediv__(self, o):
        return self * self._j(o).inv()

    def __rtruediv__(self, o):
        return self._j(o) * self.inv()

    def __pow__(self, n):
        if n < 0:
            return (self ** (-n)).inv()
        r = Jet.c(1)
        for _ in range(n):
            r = r * self
        return r

    def val(self):
        return self.d.get((), F(0))

    def d1(self, i):
        return self.d.get((i,), F(0))

    def d2(self, i, j):
        v = self.d.get(tuple(sorted((i, j))), F(0))
        return v + v if i == j else v


def basis(i, u):
    r1, r2 = ROOTS[i]
    s = 1 + u
    return s ** r1, s ** r2, r1 * s ** (r1 - 1), r2 * s ** (r2 - 1)


def jacobi(i, u, up):
    """A(u,u'), A'(u,u'), K(u,u'), K'(u,u') (derivatives in u) for x'' = -h_i x."""
    f, g, fp, gp = basis(i, u)
    f0, g0, fp0, gp0 = basis(i, up)
    w = f0 * gp0 - fp0 * g0
    return ((f0 * g - f * g0) / w, (f0 * gp - fp * g0) / w,
            (gp0 * f - fp0 * g) / w, (gp0 * fp - fp0 * gp) / w)


def tidal(i, u):
    return -CS[i] / (1 + u) ** 2


def sigma(x, xp):
    u, v, a1, a2 = x
    up, vp, b1, b2 = xp
    du = u - up
    s = du * (v - vp)
    for i, (xi, xpi) in enumerate(((a1, b1), (a2, b2))):
        A, Ap, K, Kp = jacobi(i, u, up)
        w = (xi - K * xpi) / A
        s = s - du / 2 * (xi * (Kp * xpi + Ap * w) - xpi * w)
    return s


def metric(x):
    u, v, a1, a2 = x
    H = tidal(0, u) * a1 * a1 + tidal(1, u) * a2 * a2
    z = u * 0
    return [[H, z + 1, z, z], [z + 1, z, z, z], [z, z, z - 1, z], [z, z, z, z - 1]]


def metric_inverse(x):
    u, v, a1, a2 = x
    H = tidal(0, u) * a1 * a1 + tidal(1, u) * a2 * a2
    z = u * 0
    return [[z, z + 1, z, z], [z + 1, -H, z, z], [z, z, z - 1, z], [z, z, z, z - 1]]


def eikonal_residual(x, xp, second):
    """g^{mu nu} d sigma d sigma - 2 sigma, derivatives in x (second = False) or in x' (True)."""
    X = [Jet.var(i, x[i]) if not second else Jet.c(x[i]) for i in range(4)]
    XP = [Jet.var(i, xp[i]) if second else Jet.c(xp[i]) for i in range(4)]
    s = sigma(X, XP)
    gi = metric_inverse(xp if second else x)
    q = sum(gi[m][n] * s.d1(m) * s.d1(n) for m in range(4) for n in range(4))
    return q - 2 * s.val()


def det(M):
    n = len(M)
    M = [row[:] for row in M]
    d = F(1)
    for c in range(n):
        p = next((r for r in range(c, n) if M[r][c] != 0), None)
        if p is None:
            return F(0)
        if p != c:
            M[c], M[p] = M[p], M[c]
            d = -d
        d *= M[c][c]
        for r in range(c + 1, n):
            f = M[r][c] / M[c][c]
            for k in range(c, n):
                M[r][k] -= f * M[c][k]
    return d


def minv4(G):
    n = len(G)
    M = [list(G[r]) + [F(1) if c == r else F(0) for c in range(n)] for r in range(n)]
    for c in range(n):
        p = next(r for r in range(c, n) if M[r][c] != 0)
        M[c], M[p] = M[p], M[c]
        pv = M[c][c]
        M[c] = [e / pv for e in M[c]]
        for r in range(n):
            if r != c and M[r][c] != 0:
                fct = M[r][c]
                M[r] = [M[r][t] - fct * M[c][t] for t in range(2 * n)]
    return [row[n:] for row in M]


def van_vleck(x, xp):
    """Delta = -det(-d_mu d'_nu sigma)/sqrt(g g'); det g = -1 here, so sqrt(g g') = 1."""
    X = [Jet.var(i, x[i]) for i in range(4)]
    XP = [Jet.var(4 + i, xp[i]) for i in range(4)]
    s = sigma(X, XP)
    return -det([[-s.d2(m, 4 + n) for n in range(4)] for m in range(4)])


def congruence(i, u):
    A, Ap, K, Kp = jacobi(i, u, F(0))
    return K, Kp


def horizon_point(u, y):
    x = [congruence(i, u)[0] * y[i] for i in range(2)]
    P = [congruence(i, u)[1] / congruence(i, u)[0] for i in range(2)]
    return (u, (P[0] * x[0] * x[0] + P[1] * x[1] * x[1]) / 2, x[0], x[1])


def area_density(u):
    return congruence(0, u)[0] * congruence(1, u)[0]


def label_hessian(u, up, yp):
    """sigma(X(u, y' + eta), X(u', y')) = c0 + c1.eta - (1/2) eta^T M eta (exactly quadratic here)."""
    xp = horizon_point(up, yp)
    s = lambda e: sigma(horizon_point(u, (yp[0] + e[0], yp[1] + e[1])), xp)
    s0 = s((F(0), F(0)))
    lin, quad = [], []
    for i in range(2):
        e1 = [F(0), F(0)]
        e1[i] = F(1)
        em = [F(0), F(0)]
        em[i] = F(-1)
        sp, sm = s(e1), s(em)
        lin.append((sp - sm) / 2)
        quad.append(-(sp + sm - 2 * s0))
    cross = -(s((F(1), F(1))) - s0 - lin[0] - lin[1]) - quad[0] / 2 - quad[1] / 2
    return s0, lin, [[quad[0], cross], [cross, quad[1]]]


def vec(c):
    return GA.add(*[GA.scal(F(c[i]), E[i]) for i in range(4)])


def hb_inv(a, H, k):
    return GA.add(a, GA.scal(H * GA.dot(a, k, S4) / 2, k))


def hb(a, H, k):
    return GA.sub(a, GA.scal(H * GA.dot(a, k, S4) / 2, k))



# ---- non-commuting model: tidal map C/(1+u)^2 rotated off the label basis, J'(0) = B0 not commuting with C ----
ROT = ((F(3, 5), F(-4, 5)), (F(4, 5), F(3, 5)))
B0 = ((F(1, 4), F(1, 6)), (F(1, 6), F(-1, 5)))


def mm(X, Y):
    return [[X[i][0] * Y[0][j] + X[i][1] * Y[1][j] for j in range(2)] for i in range(2)]


def mv(X, y):
    return [X[i][0] * y[0] + X[i][1] * y[1] for i in range(2)]


def tp(X):
    return [[X[j][i] for j in range(2)] for i in range(2)]


def madd(X, Y):
    return [[X[i][j] + Y[i][j] for j in range(2)] for i in range(2)]


def mdet(X):
    return X[0][0] * X[1][1] - X[0][1] * X[1][0]


def minv(X):
    d = mdet(X)
    return [[X[1][1] / d, -X[0][1] / d], [-X[1][0] / d, X[0][0] / d]]


def rot_maps(u, up):
    """A, A', K, K' of x'' = -h x with h = -R diag(2, 6) R^T/(1+u)^2, as linear maps in the label basis."""
    out = []
    j0, j1 = jacobi(0, u, up), jacobi(1, u, up)
    for idx in range(4):
        out.append(mm(mm(ROT, [[j0[idx], 0], [0, j1[idx]]]), tp(ROT)))
    return out


def sigma_nc(x, xp):
    u, v, a1, a2 = x
    up, vp, b1, b2 = xp
    A, Ap, K, Kp = rot_maps(u, up)
    w = mv(minv(A), [a1 - mv(K, [b1, b2])[0], a2 - mv(K, [b1, b2])[1]])
    t = [mv(Kp, [b1, b2])[i] + mv(Ap, w)[i] for i in range(2)]
    du = u - up
    return du * (v - vp) - du / 2 * (a1 * t[0] + a2 * t[1] - b1 * w[0] - b2 * w[1])


def tidal_nc(u):
    D = [[-CS[0] / (1 + u) ** 2, 0], [0, -CS[1] / (1 + u) ** 2]]
    return mm(mm(ROT, D), tp(ROT))


def metric_inverse_nc(x):
    u, v, a1, a2 = x
    h = tidal_nc(u)
    H = a1 * (h[0][0] * a1 + h[0][1] * a2) + a2 * (h[1][0] * a1 + h[1][1] * a2)
    z = u * 0
    return [[z, z + 1, z, z], [z + 1, -H, z, z], [z, z, z - 1, z], [z, z, z, z - 1]]


def congruence_nc(u):
    A, Ap, K, Kp = rot_maps(u, F(0))
    return madd(K, mm(A, B0)), madd(Kp, mm(Ap, B0))


def horizon_point_nc(u, y):
    J, Jp = congruence_nc(u)
    x = mv(J, list(y))
    v = (y[0] * mv(mm(tp(J), Jp), list(y))[0] + y[1] * mv(mm(tp(J), Jp), list(y))[1]) / 2
    return (u, v, x[0], x[1])


def van_vleck_of(sig, x, xp):
    X = [Jet.var(i, x[i]) for i in range(4)]
    XP = [Jet.var(4 + i, xp[i]) for i in range(4)]
    s = sig(X, XP)
    return -det([[-s.d2(m, 4 + n) for n in range(4)] for m in range(4)])


def hessian_of(sig, hp, u, up, yp):
    xp = hp(up, yp)
    s = lambda e: sig(hp(u, (yp[0] + e[0], yp[1] + e[1])), xp)
    s0 = s((F(0), F(0)))
    lin = [(s((F(1), F(0))) - s((F(-1), F(0)))) / 2, (s((F(0), F(1))) - s((F(0), F(-1)))) / 2]
    h11 = s((F(1), F(0))) + s((F(-1), F(0))) - 2 * s0
    h22 = s((F(0), F(1))) + s((F(0), F(-1))) - 2 * s0
    h12 = (s((F(1), F(1))) - s((F(1), F(-1))) - s((F(-1), F(1))) + s((F(-1), F(-1)))) / 4
    cubic = s((F(2), F(3))) - (s0 + 2 * lin[0] + 3 * lin[1] + (4 * h11 + 9 * h22 + 12 * h12) / 2)
    return s0, lin, cubic, [[-h11, -h12], [-h12, -h22]]


