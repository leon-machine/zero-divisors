def check_generator_scaling_of_leading_term_and_smooth_differences():
    premise("synthesis.microlocal-condition-on-a-generator-gives-the-local-null-ground-state")
    premise("synthesis.imported-microlocal-hadamard-condition")
    ok = True
    u0 = F(1, 3)
    # square of the leading coefficient of (u - u')^-1 delta^2, from the model's own sigma and Delta:
    # canonical factor a(u) a(u') times Delta/det M, at scaled points; weight 1/2 per leg gives lambda^2
    for lam in (F(1, 10), F(1, 1000)):
        for x, y in ((F(1), F(-2)), (F(3, 4), F(1, 5))):
            uu, vv = u0 + lam * x, u0 + lam * y
            M = label_hessian(uu, vv, (F(0), F(0)))[2]
            D = van_vleck(horizon_point(uu, (F(0), F(0))), horizon_point(vv, (F(0), F(0))))
            c2 = area_density(uu) * area_density(vv) * D / (M[0][0] * M[1][1] - M[0][1] * M[1][0])
            ok &= lam ** 2 * c2 / (uu - vv) ** 2 == 1 / (x - y) ** 2
            # without the canonical factor the scaled kernel is not the flat one
            ok &= lam ** 2 * (D / (M[0][0] * M[1][1])) / (uu - vv) ** 2 != 1 / (x - y) ** 2
    # a smooth (polynomial) difference of two Hadamard kernels scales away at rate lambda
    r = lambda s, t: 3 + s * t - 2 * s ** 2 + 5 * t ** 3
    errs = [abs(F(1, 10 ** j) * r(u0 + F(1, 10 ** j) * 2, u0 - F(1, 10 ** j))) * 10 ** j for j in range(1, 7)]
    ok &= max(errs) < 4 and min(errs) > 2
    GA.check("generator scaling: the canonical leading coefficient is scale invariant at weight 1/2 (and not without the canonical factor); smooth differences vanish at rate lambda", ok)
    return ok


