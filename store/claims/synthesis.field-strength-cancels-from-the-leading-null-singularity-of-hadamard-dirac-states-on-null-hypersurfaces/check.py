"""Leading null singularity of Hadamard kernels restricted to a null hypersurface: exact checks.

Model: a plane-wave gravitational field crossed by a null hypersurface H, exact rationals.
Field (Kerr-Schild form, k = e0 + e3 null): hb^{-1}(a) = a + (1/2) H (a.k) k, so the derived metric is
g(a, b) = a.b + H (a.k)(b.k). Coordinate reading (labelled): u = x.k, v = x.m with m = (e0 - e3)/2,
x_i = -x.e_i (i = 1, 2): g = 2 du dv + H du^2 - dx1^2 - dx2^2 with H = h1(u) x1^2 + h2(u) x2^2,
h_i(u) = -c_i/(1 + u)^2, c = (2, 6). The tidal matrix along d/du is diag(h1, h2): its trace (Ricci
R(k, k)) and its trace-free (Weyl) part are both nonzero. Transverse Jacobi equation x'' = -h x has
the rational solutions (1 + u)^r, r(r - 1) = c_i: r = (2, -1) and (3, -2).
H = {v = (1/2) sum_i P_i(u) x_i^2}, P = J'/J, J the Jacobi solution with J(0) = 1, J'(0) = 0: a null
hypersurface generated by the affine null geodesics u -> X(u, y) = (u, (1/2) sum P_i J_i^2 y_i^2, J y),
with expansion and shear P(0) = 0 at x0 = 0 (a local Rindler horizon through x0 along d/du) and
nonzero away from u = 0.
Synge function (closed form, checked against the eikonal equation in both points and the coincidence
limit): sigma = du dv - (du/2) sum_i [x_i (K_i' x'_i + A_i' w_i) - x'_i w_i], w_i = (x_i - K_i x'_i)/A_i,
A the Jacobi map (A(u') = 0, A'(u') = 1), K (K(u') = 1, K'(u') = 0).
Checks: (1) the field in GTG; (2) sigma; (3) H; (4) transverse Hessian of -sigma, M = du J(u')^T A^-1 J(u), and the
Wronskian; (5) Van Vleck Delta = du^2/det A; (6) det M = Delta a(u) a(u'): curvature, expansion and
shear cancel from the coefficient Delta^(1/2)/sqrt(det M) = (a(u) a(u'))^(-1/2); (7) the canonical
projector algebra and the flux of the canonical part (GA); (8) generator scaling of the leading
term and of smooth differences.
Exact arithmetic only (Fractions, truncated first- and second-order jets).
"""
from fractions import Fraction as F

