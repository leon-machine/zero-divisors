"""transport.door-one-way: exact checks of the dimension count behind "no unital homomorphism B -> A".

A semisimple B maps unitally into A only if some Wedderburn block of B embeds in A; the check
computes the blocks of every minimal completion and compares dimensions.
(1) Rule 1, all 15 signatures with n = p + q <= 4: B = Cl(p+1, q+1). The centre of B is read from
    its central blades; B is simple (centre R, or C when omega_B^2 = -1) with one block of
    dimension 4 dim A when A is simple, and has two central idempotents eps_+- with blocks
    eps_+- B of dimension 2^(n+1) = 2 dim A when A is split (p - q = 1 mod 4, computed from A's own
    central blades). Every block exceeds dim A. The Morita form B = Mat_2(A) is confirmed for
    n <= 3: A' (generators e_i e+ e-) commutes with the matrix units of Cl(1,1) and the products
    span B.
(2) Rule 2 (p - q = 1 mod 4, n <= 5, both signs): B simple with centre R (central blades, via the
    exports of the transport.rule-2-ideal-fusion-sharp-form check), one block of dimension
    2^(n+1) = 2 dim A > dim A.
(3) The kernel step: in a simple B every nonzero two-sided ideal is B (the ideal generated by
    sample elements has full rank), so a unital theta is injective on a surviving block, and
    dim(block) > dim A is the contradiction. For split B the ideal generated by an element of
    eps_+ B is eps_+ B (half rank), the block structure the proof uses.
"""
from fractions import Fraction as F

import GA
from tp_premise import premise


def _central_blades(sq, m):
    return [b for b in GA.all_blades(m)
            if all(GA.commutes(GA.gen(i), {b: F(1)}, sq) for i in range(m))]


def _rank(elems, m):
    blades = GA.all_blades(m)
    rows = [GA.basis_vector_of(x, blades) for x in elems if x]
    return GA.rank_of_vectors(rows) if rows else 0


def _blocks(sq, m):
    """Dimensions of the Wedderburn blocks of the Clifford algebra with this (nondegenerate) sq."""
    cb = _central_blades(sq, m)
    if cb == [()]:
        return [2 ** m]
    top = tuple(range(m))
    assert cb == [(), top]
    om = {top: F(1)}
    if GA.eq(GA.mul(om, om, sq), GA.sc(-1)):
        return [2 ** m]                                     # centre C: simple
    out = []
    for s in (1, -1):
        e = GA.scal(F(1, 2), GA.add(GA.sc(1), GA.scal(s, om)))
        out.append(_rank([GA.mul(e, {b: F(1)}, sq) for b in GA.all_blades(m)], m))
    return out


def _split(p, q):
    n = p + q
    sq = GA.sig(p, q)
    cb = _central_blades(sq, n)
    if len(cb) < 2:
        return False
    om = {tuple(range(n)): F(1)}
    return GA.eq(GA.mul(om, om, sq), GA.sc(1))


def check_rule_one_blocks_exceed_dim_a():
    premise("transport.classification-real-clifford-algebras")
    premise("transport.rule-1-morita-trivial")
    ok = True
    n_split = 0
    for n in range(0, 5):
        for p in range(n + 1):
            q = n - p
            dimA = 2 ** n
            sqB = GA.sig(p, q) + (1, -1)
            blocks = _blocks(sqB, n + 2)
            if _split(p, q):
                n_split += 1
                ok = ok and blocks == [2 * dimA, 2 * dimA]
            else:
                ok = ok and blocks == [4 * dimA]
            ok = ok and all(b > dimA for b in blocks)
            if n <= 3:
                ep, em = GA.gen(n), GA.gen(n + 1)
                f = GA.mul(ep, em, sqB)
                Ap = [GA.mul(GA.gen(i), f, sqB) for i in range(n)]
                units = [GA.scal(F(1, 2), GA.add(GA.sc(1), f)), GA.scal(F(1, 2), GA.sub(GA.sc(1), f)),
                         GA.scal(F(1, 2), GA.add(ep, em)), GA.scal(F(1, 2), GA.sub(ep, em))]
                ok = ok and all(GA.commutes(a, u, sqB) for a in Ap for u in units)
                prods = []
                for b in GA.all_blades(n):
                    a = GA.sc(1)
                    for i in b:
                        a = GA.mul(a, Ap[i], sqB)
                    for u in units:
                        prods.append(GA.mul(a, u, sqB))
                ok = ok and _rank(prods, n + 2) == 4 * dimA
    ok = ok and n_split == 3                    # (1,0), (2,1), (0,3)
    GA.check("Rule 1: every block of Cl(p+1,q+1) exceeds dim Cl(p,q) (4 dim A, or 2 dim A if split), n <= 4", ok)
    return ok


def check_rule_two_block_exceeds_dim_a():
    ex = premise("transport.rule-2-ideal-fusion-sharp-form")
    fusion, central_blades = ex["fusion"], ex["central_blades"]
    ok = True
    for (p, q) in [(1, 0), (2, 1), (0, 3), (3, 2), (1, 4), (5, 0)]:
        n = p + q
        for g in (1, -1):
            sq = fusion(p, q, g)["sq"]
            ok = ok and central_blades(sq, n + 1) == [()]
            ok = ok and _blocks(sq, n + 1) == [2 * 2 ** n]
    GA.check("Rule 2: the fused algebra is one block of dimension 2 dim A", ok)
    return ok


SAMPLES = [{(): F(1), (0,): F(2)}, {(0, 1): F(1), (1,): F(-1, 2)}, {(0,): F(1), (1,): F(1)}]


# Sample signatures, simple and split (the split ones are those with _split true).
IDEAL_SIGNATURES = [(1, 1), (2, 1), (1, 2), (3, 0), (2, 2), (1, 3)]


def unit_blade(b):
    return {b: F(1)}


def check_ideals_are_blocks():
    premise("transport.classification-real-clifford-algebras")
    ok = True
    for (p, q) in IDEAL_SIGNATURES:
        m = p + q
        sq = GA.sig(p, q)
        blades = GA.all_blades(m)
        split = _split(p, q)
        om = unit_blade(tuple(range(m)))
        ep = GA.scal(F(1, 2), GA.add(GA.sc(1), om))
        if split:
            # eps_+ = (1 + omega)/2 is a central idempotent (omega central, omega^2 = 1)
            ok = ok and GA.eq(GA.mul(ep, ep, sq), ep)
            ok = ok and all(GA.commutes(om, GA.gen(i), sq) for i in range(m))
        for x in SAMPLES:
            if split:
                x = GA.mul(ep, x, sq)
            gen = [GA.mul(GA.mul(unit_blade(a), x, sq), unit_blade(b), sq) for a in blades for b in blades]
            ok = ok and _rank(gen, m) == (2 ** (m - 1) if split else 2 ** m)
    GA.check("two-sided ideals generated by samples: all of A (simple) or one block eps_+ A (split)", ok)
    return ok
