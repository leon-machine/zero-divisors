"""rule2.which-residues-obstruct-which-way: exact checks.

(1) Over every even-dimensional nondegenerate (p,q) with 2 <= p + q <= 8, type C (odd dimension,
omega central with omega^2 = +1, so (1 +- omega)/2 are nonzero central idempotents) is computed for
the spacelike extension Cl(p,q+1) and the timelike extension Cl(p+1,q). The residues d = p - q mod 8
whose spacelike extension is type C are exactly {2, 6}, whose timelike one is type C exactly {0, 4};
for every (p,q) exactly one of the two extensions is type C, the other having omega^2 = -1.
(2) The physical lineage: Rule 1 ascents (1,3) -> (2,4) -> (3,5) keep d = 6; from (1,3) the only
type-C extension is the spacelike one, Cl(1,4), at residue 5; the opposite-sign (timelike) repair
gives Cl(2,4), residue 6 again, and the null pair f = (nu + e4)/2, f* = (nu - e4)/2 of the adjoined
hyperbolic plane gives matrix units (E11 + E22 = 1, E_ij E_kl = delta_jk E_il) whose corner
ff* Cl(2,4) ff* has dimension 16 and is the image of Cl(1,3) under the injective homomorphism
a -> a ff*: Cl(2,4) = Mat_2(Cl(1,3)).
(3) The mirror residue 2, (3,1): the square -1 extension Cl(3,2) is type C at residue 1, the square +1
extension Cl(4,1) is not (omega^2 = -1, residue 3), and the opposite-sign repair Cl(4,2) =
Mat_2(Cl(3,1)) by the same corner computation, at residue 2.
"""
from fractions import Fraction as F
from itertools import combinations
import GA
from tp_premise import premise


def omega_sq(sq):
    n = len(sq)
    om = {tuple(range(n)): F(1)}
    return GA.mul(om, om, sq)[()]


def type_C(p, q):
    """Type C: odd dimension, omega central and omega^2 = +1 (nonzero central idempotents)."""
    sq = GA.sig(p, q)
    n = p + q
    if n % 2 == 0:
        return False
    om = {tuple(range(n)): F(1)}
    central = all(GA.commutes(om, GA.gen(i), sq) for i in range(n))
    if not central or omega_sq(sq) != 1:
        return False
    ep = GA.scal(F(1, 2), GA.add(GA.sc(1), om))
    return GA.eq(GA.mul(ep, ep, sq), ep) and not GA.eq(ep, GA.sc(1))


def check_even_residue_table():
    premise("rule2.where-obstruction-sits-commuting-square")
    ok = True
    space, time = set(), set()
    for n in range(2, 9, 2):
        for p in range(n + 1):
            q = n - p
            d = (p - q) % 8
            s, t = type_C(p, q + 1), type_C(p + 1, q)
            if s:
                space.add(d)
            if t:
                time.add(d)
            ok = ok and (s != t)
            ok = ok and omega_sq(GA.sig(p, q + 1) if t else GA.sig(p + 1, q)) == -1
    ok = ok and sorted(space) == [2, 6] and sorted(time) == [0, 4]
    GA.check("even residues: spacelike extension type C exactly at {2, 6}, timelike at {0, 4}; one each", ok)
    return ok


def rank(xs, n):
    bl = GA.all_blades(n)
    return GA.rank_of_vectors([[x.get(b, F(0)) for b in bl] for x in xs])


def repair_is_mat2(p, q, ext_index, nu_index):
    """In Cl(p+1,q+1) (generators ordered as GA.sig) the null pair of the plane (nu, e_ext) gives
    matrix units, and the corner ff* B ff* is the injective image of the subalgebra generated by
    the other generators, whose signature is (p,q)."""
    sq = GA.sig(p + 1, q + 1)
    N = p + q + 2
    nu, ex = GA.gen(nu_index), GA.gen(ext_index)
    f = GA.scal(F(1, 2), GA.add(nu, ex))
    fs = GA.scal(F(1, 2), GA.sub(nu, ex))
    ok = GA.is_zero(GA.mul(f, f, sq)) and GA.is_zero(GA.mul(fs, fs, sq))
    E = {(1, 1): GA.mul(f, fs, sq), (2, 2): GA.mul(fs, f, sq), (1, 2): f, (2, 1): fs}
    ok = ok and GA.eq(GA.add(E[(1, 1)], E[(2, 2)]), GA.sc(1))
    for (i, j) in E:
        for (k, l) in E:
            want = E[(i, l)] if j == k else {}
            ok = ok and GA.eq(GA.mul(E[(i, j)], E[(k, l)], sq), want)
    e = E[(1, 1)]
    corner = [GA.mul(GA.mul(e, {b: F(1)}, sq), e, sq) for b in GA.all_blades(N)]
    rc = rank(corner, N)
    others = [i for i in range(N) if i not in (nu_index, ext_index)]
    base_sq = tuple(sq[i] for i in others)
    base = []
    for k in range(len(others) + 1):
        for S in combinations(others, k):
            base.append(GA.mul({S: F(1)} if S else GA.sc(1), e, sq))
    # a -> a e is multiplicative because each other generator commutes with e
    ok = ok and all(GA.commutes(GA.gen(i), e, sq) for i in others)
    ok = ok and rc == 2 ** (N - 2) and rank(base, N) == rc and rank(base + corner, N) == rc
    return ok, base_sq


def check_physical_lineage_and_mirror():
    premise("rule2.where-obstruction-sits-commuting-square")
    premise("transport.rule-1-morita-trivial")
    ok = True
    # Rule 1 ascents of (1,3) keep the residue 6 and its omega^2 = -1 (Morita invariance is checked by the corners below)
    for k in range(3):
        p, q = 1 + k, 3 + k
        ok = ok and (p - q) % 8 == 6 and omega_sq(GA.sig(p, q)) == -1
    # from (1,3): spacelike (square -1) extension type C at residue 5, timelike not
    ok = ok and type_C(1, 4) and not type_C(2, 3) and (1 - 4) % 8 == 5 and (2 - 3) % 8 == 7
    # repair of Cl(1,4) by a timelike nu: Cl(2,4); generators e0, e1 (+1), e2..e5 (-1);
    # the plane (nu = e1, extension = e5); the rest e0, e2, e3, e4 has signature (1,3)
    good, base_sq = repair_is_mat2(1, 3, 5, 1)
    ok = ok and good and base_sq == (1, -1, -1, -1) and (2 - 4) % 8 == 6
    # mirror residue 2: (3,1)
    ok = ok and (3 - 1) % 8 == 2 and type_C(3, 2) and not type_C(4, 1) and omega_sq(GA.sig(4, 1)) == -1
    ok = ok and (3 - 2) % 8 == 1 and (4 - 1) % 8 == 3
    good, base_sq = repair_is_mat2(3, 1, 5, 3)
    ok = ok and good and sorted(base_sq) == [-1, 1, 1, 1] and (4 - 2) % 8 == 2
    GA.check("residue 6 leaves only spacelike into 5 and the opposite repair is Mat_2 of where it began; "
             "likewise the mirror residue 2", ok)
    return ok
