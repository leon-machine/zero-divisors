"""sheaf.one-sided-completion-singularity: exact checks on Schwarzschild data, 2M = m^2 (m = 1, 2), as
rational-function identities in u = sqrt(r) (GA.RF), at sample couplings and bump values.

Frame (rho, dt_PG, mu1, mu2, n_O, n_inf). G is the Gram of W from the inverse Painleve-Gullstrand block
(Theorem sheaf.schwarzschild-degeneration-boundary-tame); the trivial plane has h(n_O, n_inf) = -1,
h(n_O, n_O) = h(n_inf, n_inf) = 0; the collar coupling at the normalised transversal u = d_t/m
(k(u) = 1) puts b nu/m and b mu/m in the (dt_PG, n_O) and (dt_PG, n_inf) slots, b in [0, 1] the bump
value (b = 1 at E, b = 0 outside the horizon).
  (1) Determinant identity (Lemma sheaf.determinant-identity-blow-up-expansion): with
      s = G^-1(e, e) = (r - m^2)/(m^2 r) exactly (e evaluation at d_t/m),
      det h = det G * (-(1 + 2 mu nu b^2 s)) as a rational-function identity, for four couplings with
      mu nu < 0 and three bump values; inside the horizon s < 0, so F = 1 + 2 mu nu b^2 s >= 1, and F
      never vanishes on the sample grid (no shadow wall).
  (2) Signature: h has signature (2,4) at E (u = 0, b = 1), at interior radii with b in {1, 1/2, 1/3},
      and at the horizon and exterior radii with b = 0 (h = G + H there); the opposite sign mu nu > 0
      gives (3,3) at E.
  (3) Ladder pair exactly over E (Corollary sheaf.localised-transport): k = rho + m dt_PG and
      k* = n_O/(2 nu) satisfy c(k)c(k*) + c(k*)c(k) = 1 and c(k)^2 = c(k*)^2 = 0 on all 64 states of the
      exterior model of h at E; off E (u = 1/2, 1) c(k)^2 = h(k, k) = -r != 0. With the unnormalised
      transversal d_t the anticommutator is m instead of 1 (m = 2), the reason for the normalisation.
The statement that the subalgebra generated by W is canonically the degeneration sheaf is not computed.
"""
from fractions import Fraction as F

import GA
from tp_premise import premise

U = GA.RF.var()
R = U * U
MASSES = (F(1), F(2))
COUPLINGS = ((F(1), F(-1)), (F(1), F(-1, 2)), (F(2), F(-1, 4)), (F(-1), F(3)))   # (nu, mu), mu nu < 0
BUMPS = (F(1), F(1, 2), F(1, 3))
INSIDE = (F(1, 10), F(1, 3), F(1, 2), F(9, 10))          # u/m inside the horizon
OUTSIDE = (F(1), F(3, 2), F(2), F(5))                     # u/m at and beyond the horizon


def C(x):
    return GA.RF.const(F(x))


def gram(m):
    beta = C(m) / U
    g_tt, g_tr, g_rr = GA.RF1 - beta * beta, -beta, C(-1)
    det = g_tt * g_rr - g_tr * g_tr
    Ctt, Ctr, Crr = g_rr / det, -g_tr / det, g_tt / det
    Z = GA.RF0
    return [[R * Crr, U * Ctr, Z, Z], [U * Ctr, Ctt, Z, Z], [Z, Z, C(-1), Z], [Z, Z, Z, C(-1)]]


def hmat(G, m, nu, mu, b, norm=True):
    Z = GA.RF0
    scale = m if norm else F(1)
    cn, cm = C(b * nu / scale), C(b * mu / scale)
    return [[G[0][0], G[0][1], Z, Z, Z, Z],
            [G[1][0], G[1][1], Z, Z, cn, cm],
            [Z, Z, G[2][2], Z, Z, Z],
            [Z, Z, Z, G[3][3], Z, Z],
            [Z, cn, Z, Z, Z, C(-1)],
            [Z, cm, Z, Z, C(-1), Z]]


def at(M, u0):
    return [[e.eval(u0) for e in row] for row in M]


def check_determinant_identity_and_no_shadow_wall():
    premise("sheaf.determinant-identity-blow-up-expansion")
    premise("sheaf.schwarzschild-degeneration-boundary-tame")
    ok = True
    for m in MASSES:
        G = gram(m)
        detG = GA.rf_mat_det(G)
        ok = ok and detG.eqrf(-R)
        x = GA.rf_mat_solve(G, [GA.RF0, GA.RF1, GA.RF0, GA.RF0])
        s = C(F(1) / (m * m)) * x[1]
        ok = ok and s.eqrf((R - C(m * m)) / (C(m * m) * R))
        for nu, mu in COUPLINGS:
            for b in BUMPS:
                Fn = GA.RF1 + C(2 * nu * mu * b * b) * s
                ok = ok and GA.rf_mat_det(hmat(G, m, nu, mu, b)).eqrf(detG * (-Fn))
                for f in INSIDE:
                    u0 = m * f
                    ok = ok and s.eval(u0) < 0 and Fn.eval(u0) >= 1
    GA.check("det h = det G (-(1 + 2 mu nu b^2 s)), s = (r - m^2)/(m^2 r) < 0 inside, so F >= 1: no shadow wall", ok)
    return ok


def check_signature_two_four_on_the_whole_closure():
    premise("sheaf.schwarzschild-degeneration-boundary-tame")
    ok = True
    for m in MASSES:
        G = gram(m)
        for nu, mu in COUPLINGS:
            ok = ok and GA.congruence_signature(at(hmat(G, m, nu, mu, F(1)), F(0))) == (2, 4, 0)
            for b in BUMPS:
                for f in INSIDE:
                    ok = ok and GA.congruence_signature(at(hmat(G, m, nu, mu, b), m * f)) == (2, 4, 0)
            for f in OUTSIDE:
                ok = ok and GA.congruence_signature(at(hmat(G, m, nu, mu, F(0)), m * f)) == (2, 4, 0)
        ok = ok and GA.congruence_signature(at(hmat(G, m, F(1), F(1), F(1)), F(0))) == (3, 3, 0)
    GA.check("h has signature (2,4) at E, inside (any bump value) and outside; mu nu > 0 gives (3,3) at E", ok)
    return ok


def ext_add(*ds):
    tot = {}
    for d in ds:
        for S, c in d.items():
            tot[S] = tot.get(S, F(0)) + c
    return {S: c for S, c in tot.items() if c != 0}


def check_ladder_pair_exactly_over_the_boundary():
    premise("sheaf.localised-transport")
    ok = True
    for m in MASSES:
        G = gram(m)
        nu, mu = F(1), F(-1)
        k = [F(1), m, F(0), F(0), F(0), F(0)]
        ks = [F(0)] * 4 + [1 / (2 * nu), F(0)]
        h0 = at(hmat(G, m, nu, mu, F(1)), F(0))
        for S in GA.all_blades(6):
            st = {frozenset(S): F(1)}
            car = ext_add(GA.ext_c(k, h0, GA.ext_c(ks, h0, st)), GA.ext_c(ks, h0, GA.ext_c(k, h0, st)))
            ok = ok and GA.ext_state_eq(car, st)
            ok = ok and GA.ext_c(k, h0, GA.ext_c(k, h0, st)) == {}
            ok = ok and GA.ext_c(ks, h0, GA.ext_c(ks, h0, st)) == {}
        for u0 in (F(1, 2), F(1)):
            hu = at(hmat(G, m, nu, mu, F(1)), u0)
            vac = {frozenset(): F(1)}
            ok = ok and GA.ext_c(k, hu, GA.ext_c(k, hu, vac)) == {frozenset(): -u0 * u0}
        # unnormalised transversal: the anticommutator is m, not 1
        hraw = at(hmat(G, m, nu, mu, F(1), norm=False), F(0))
        vac = {frozenset(): F(1)}
        car = ext_add(GA.ext_c(k, hraw, GA.ext_c(ks, hraw, vac)), GA.ext_c(ks, hraw, GA.ext_c(k, hraw, vac)))
        ok = ok and car == {frozenset(): m}
    GA.check("k* = n_O/(2 nu) is a ladder partner of k on E (64 states); off E k^2 = -r; unnormalised gives m", ok)
    return ok
