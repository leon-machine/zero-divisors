"""sheaf.localised-transport: exact checks.

Collar models for (p, q) = (1, 1), (2, 1), (1, 3) (the physical case) and (2, 2): cometric G(tau) on the
covector frame (k, m_1, ..., m_(n-1)) with lambda = G(k, k) = tau + tau^2, nonzero cross terms
b(tau) = O(tau), non-orthogonal tau-dependent block; e = evaluation at u (k(u) = 1); ambient form
h = G + H + beta kappa on T = T*M + span(n0, ninf), with (mu, nu) = (2, 3). Points: the wall (tau = 0,
beta = 1), physical collar points tau = 1/5, 1/20 (beta = 1, 1/2) and an outside point (beta = 0).
(1) The subalgebra generated by T*M is A = Cl(T*M, G) at every point, the wall included: in the exterior
    model of Cl(T, h) the 2^n blades in the first n letters are independent (injectivity) and every product
    e_I e_J of them acts on the vacuum exactly as in the exterior model of Cl(T*M, G) itself.
(2) Off the wall the complement of T*M is a hyperbolic plane: the h-orthogonal complement of T*M (a computed
    kernel) is 2-dimensional with Gram signature (1, 1); det h / det G = -(1 + 2 mu nu beta^2 s) <= -1 in
    the collar and = -1 outside; h has signature (p + 1, q + 1): the Rule-1 conformal embedding.
(3) The ladder pair exactly on the wall: at tau = 0, k is null, k* = n0/(2 nu) is null and
    c(k) c(k*) + c(k*) c(k) = 1 on every basis state (so the ideal of k in C(x) is the unit ideal), while in
    A(x) itself c(k) c(e_I) c(k) = 0 for every blade (the ideal is square-zero); off the wall
    (tau = 1/5, 1/20, -1/50) c(k)^2 = lambda(tau) != 0, so no ladder relation can hold for k there.
"""
from fractions import Fraction as F

import GA
from tp_premise import premise

SIGS = [(1, 1), (2, 1), (1, 3), (2, 2)]
MU, NU = F(2), F(3)
POINTS = [(F(0), F(1)), (F(1, 5), F(1)), (F(1, 20), F(1, 2)), (F(1, 5), F(0))]


def _det(M):
    A = [list(r) for r in M]
    n = len(A)
    d = F(1)
    for c in range(n):
        piv = next((r for r in range(c, n) if A[r][c] != 0), None)
        if piv is None:
            return F(0)
        if piv != c:
            A[c], A[piv] = A[piv], A[c]
            d = -d
        d *= A[c][c]
        for r in range(c + 1, n):
            f = A[r][c] / A[c][c]
            A[r] = [a - f * b for a, b in zip(A[r], A[c])]
    return d


def collar_gram(p, q, tau):
    """Cometric G(tau) on the frame (k, m_1..m_(n-1)): lambda = tau + tau^2, b = O(tau) nonzero,
    G1(tau) nondegenerate of signature (p - 1, q) at tau = 0, non-orthogonal and tau-dependent."""
    n = p + q
    tau = F(tau)
    G = [[F(0)] * n for _ in range(n)]
    G[0][0] = tau + tau * tau
    for i in range(1, n):
        G[0][i] = G[i][0] = tau * (i % 2 + 1) - tau * tau * i
        for j in range(1, n):
            base = (F(1) if i < p else F(-1)) if i == j else (F(1, 3) if abs(i - j) == 1 else F(0))
            G[i][j] = base + tau * F((i * j) % 3, 2)
    return G


def evaluation(n):
    """e = evaluation at the transversal u, in the covector frame: k(u) = 1, tangential parts nonzero."""
    return [F(1)] + [F(1, i + 1) for i in range(1, n)]


def ambient(G, e, beta, mu, nu):
    n = len(G)
    h = [[F(0)] * (n + 2) for _ in range(n + 2)]
    for i in range(n):
        for j in range(n):
            h[i][j] = G[i][j]
        h[i][n] = h[n][i] = nu * beta * e[i]
        h[i][n + 1] = h[n + 1][i] = mu * beta * e[i]
    h[n][n + 1] = h[n + 1][n] = F(-1)
    return h


def s_of(G, e):
    x = GA.field_solve(G, e)
    return sum((a * b for a, b in zip(e, x)), F(0))


def _basis(N, i):
    return [F(1) if t == i else F(0) for t in range(N)]


def _st_add(*ds):
    out = {}
    for d in ds:
        for S, c in d.items():
            out[S] = out.get(S, F(0)) + c
    return {S: c for S, c in out.items() if c != 0}


def check_cotangent_subalgebra_is_degenerate_algebra():
    premise("sheaf.blade-basis-degenerate-forms-included")
    ok = True
    for (p, q) in SIGS:
        n = p + q
        e = evaluation(n)
        for tau, beta in POINTS:
            G = collar_gram(p, q, tau)
            h = ambient(G, e, beta, MU, NU)
            N = n + 2
            small = GA.all_blades(n)
            rows = []
            for I in small:
                st = GA.ext_sigma_blade(I, h, N)
                rows.append([st.get(frozenset(J), F(0)) for J in GA.all_blades(N)])
            ok = ok and GA.rank_of_vectors(rows) == 2 ** n
            for I in small:
                for J in small:
                    big = GA.ext_sigma_blade(J, h, N)
                    lit = GA.ext_sigma_blade(J, G, n)
                    for i in reversed(I):
                        big = GA.ext_c(_basis(N, i), h, big)
                        lit = GA.ext_c(_basis(n, i), G, lit)
                    ok = ok and GA.ext_state_eq(big, lit)
    _tp_rv = (ok); assert _tp_rv is not False, "check_cotangent_subalgebra_is_degenerate_algebra"; return _tp_rv


def check_off_wall_complement_is_hyperbolic_plane():
    premise("sheaf.determinant-identity-blow-up-expansion")
    premise("sheaf.one-sided-completion")
    ok = True
    for (p, q) in SIGS:
        n = p + q
        e = evaluation(n)
        for tau, beta in POINTS[1:]:
            G = collar_gram(p, q, tau)
            h = ambient(G, e, beta, MU, NU)
            comp = GA.field_kernel([h[i] for i in range(n)])
            ok = ok and len(comp) == 2
            gram = [[sum((x[i] * h[i][j] * y[j] for i in range(n + 2) for j in range(n + 2)), F(0)) for y in comp]
                    for x in comp]
            ok = ok and GA.congruence_signature(gram) == (1, 1, 0)
            ratio = _det(h) / _det(G)
            ok = ok and ratio == -(1 + 2 * MU * NU * beta * beta * s_of(G, e))
            ok = ok and (ratio <= -1 if beta else ratio == -1)
            ok = ok and GA.congruence_signature(h) == (p + 1, q + 1, 0)
    _tp_rv = (ok); assert _tp_rv is not False, "check_off_wall_complement_is_hyperbolic_plane"; return _tp_rv


def check_ladder_pair_exists_exactly_on_wall():
    premise("sheaf.wall-gram")
    premise("sheaf.resolution-ideal-theoretically")
    premise("sheaf.degeneration-sheaf")
    ok = True
    for (p, q) in SIGS:
        n = p + q
        N = n + 2
        e = evaluation(n)
        k = _basis(N, 0)
        G0 = collar_gram(p, q, 0)
        h = ambient(G0, e, F(1), MU, NU)
        ks = [F(0)] * n + [F(1) / (2 * NU), F(0)]
        hq = lambda x, y: sum((x[i] * h[i][j] * y[j] for i in range(N) for j in range(N)), F(0))
        ok = ok and hq(k, k) == 0 and hq(ks, ks) == 0 and 2 * hq(k, ks) == 1
        for S in GA.all_blades(N):
            st = {frozenset(S): F(1)}
            car = _st_add(GA.ext_c(k, h, GA.ext_c(ks, h, st)), GA.ext_c(ks, h, GA.ext_c(k, h, st)))
            ok = ok and GA.ext_state_eq(car, st)
        kn = _basis(n, 0)
        for I in GA.all_blades(n):
            for S in GA.all_blades(n):
                x = GA.ext_c(kn, G0, {frozenset(S): F(1)})
                for i in reversed(I):
                    x = GA.ext_c(_basis(n, i), G0, x)
                ok = ok and GA.ext_c(kn, G0, x) == {}
        for tau in (F(1, 5), F(1, 20), F(-1, 50)):
            G = collar_gram(p, q, tau)
            lam = tau + tau * tau
            ok = ok and G[0][0] == lam and lam != 0
            st = {frozenset(): F(1)}
            ok = ok and GA.ext_state_eq(GA.ext_c(kn, G, GA.ext_c(kn, G, st)), {frozenset(): lam})
    _tp_rv = (ok); assert _tp_rv is not False, "check_ladder_pair_exists_exactly_on_wall"; return _tp_rv
