"""transport.no-fourth-rule: exact checks of the corollary's three rules and their exhaustiveness.

(1) Where each type occurs, all 28 signatures with n <= 6: type C (a nontrivial central
    idempotent: omega central with omega^2 = +1) exactly at p - q = 1 mod 4; type N (a nonzero null
    vector, e_0 + e_p) exactly in the mixed signatures (definite ones have congruence signature
    (n,0) or (0,n)); a non-central idempotent (1 + b)/2 from a blade (type P) exists in every
    signature except the five whose algebra is R, R + R, C, H or H + H: (0,0), (1,0), (0,1), (0,2),
    (0,3).
(2) Exhaustiveness on a full lattice: every element with coefficients in {-1, 0, 1} of Cl(1,0),
    Cl(0,1), Cl(2,0), Cl(1,1), Cl(0,2) (8 + 8 + 3 x 80 = 256 nonzero elements) is tested; the zero
    divisors (left multiplication singular) number 4, 0, 32, 32, 0 (counted by hand from the norm
    forms x^2 - y^2 and x^2 + w^2 - y^2 - z^2, x^2 + z^2 - y^2 - w^2); for each, idempotents
    e = 1 - f, f' not in {0, 1} with a f = 0 and f' a = 0 are solved for exactly (right and left
    annihilator ideals generated by idempotents), and each zero divisor is classified: type C (killed
    by a central idempotent) for the 4 in Cl(1,0), type P otherwise, refined to type N for the 4
    null vectors of Cl(1,1). Three samples each in Cl(2,1) and Cl(1,3) likewise (predicted by hand).
(3) Each rule repairs its type: N by the hyperbolic-plane ascent (conformal model exported by the
    transport.minimality check: the null vector's transported reciprocal is the ideal point
    [v + ninf/2]); C by the one-generator ascent (the fused algebra of the
    transport.rule-2-ideal-fusion-sharp-form check exports has centre R); P by the identity
    (e e e = e for every idempotent found in (2), increment (0, 0)).
"""
from fractions import Fraction as F
from itertools import product

import GA
from tp_premise import premise

LATTICE_SIGS = [(1, 0), (0, 1), (2, 0), (1, 1), (0, 2)]
EXTRA = {(2, 1): [{(0,): F(1), (2,): F(1)}, {(): F(1), (0, 1): F(1)}, {(): F(1), (0, 1, 2): F(1)}],
         (1, 3): [{(0,): F(1), (1,): F(1)}, {(): F(1), (0, 1): F(1)}, {(): F(1), (0, 1, 2, 3): F(1)}]}


def _solve(rows, rhs):
    """A solution of the (consistent) linear system rows x = rhs, or None."""
    m = len(rows[0])
    A = [list(r) + [b] for r, b in zip(rows, rhs)]
    piv = []
    r = 0
    for c in range(m):
        p = next((i for i in range(r, len(A)) if A[i][c] != 0), None)
        if p is None:
            continue
        A[r], A[p] = A[p], A[r]
        pv = A[r][c]
        A[r] = [x / pv for x in A[r]]
        for i in range(len(A)):
            if i != r and A[i][c] != 0:
                f = A[i][c]
                A[i] = [x - f * y for x, y in zip(A[i], A[r])]
        piv.append(c)
        r += 1
    if any(all(x == 0 for x in row[:m]) and row[m] != 0 for row in A):
        return None
    x = [F(0)] * m
    for i, c in enumerate(piv):
        x[c] = A[i][m]
    return x


def _annihilator_idempotent(a, sq, n, side):
    """side 'right': f with a f = 0 generating {x : a x = 0} = f A (f x = x there).
    side 'left': h with h a = 0 generating {x : x a = 0} = A h (x h = x there)."""
    blades = GA.all_blades(n)
    cols = []
    for b in blades:
        y = GA.mul(a, {b: F(1)}, sq) if side == "right" else GA.mul({b: F(1)}, a, sq)
        cols.append(GA.basis_vector_of(y, blades))
    M = [[cols[j][i] for j in range(len(blades))] for i in range(len(blades))]
    ker = GA.field_kernel(M)
    if not ker:
        return None
    R = [{blades[i]: c for i, c in enumerate(v) if c != 0} for v in ker]
    rows, rhs = [], []
    for rj in R:
        prods = [GA.mul(rk, rj, sq) if side == "right" else GA.mul(rj, rk, sq) for rk in R]
        for bi, b in enumerate(blades):
            rows.append([pk.get(b, F(0)) for pk in prods])
            rhs.append(rj.get(b, F(0)))
    c = _solve(rows, rhs)
    if c is None:
        return False
    out = {}
    for ck, rk in zip(c, R):
        out = GA.add(out, GA.scal(ck, rk))
    return out


def _central_idempotents(p, q):
    n = p + q
    sq = GA.sig(p, q)
    if n % 2 == 0:
        return []
    om = {tuple(range(n)): F(1)}
    if not (all(GA.commutes(om, GA.gen(i), sq) for i in range(n)) and GA.eq(GA.mul(om, om, sq), GA.sc(1))):
        return []
    return [GA.scal(F(1, 2), GA.add(GA.sc(1), GA.scal(s, om))) for s in (1, -1)]


def check_type_sites_by_signature():
    premise("transport.exhaustiveness-every-zero-divisor-annihilated-idempotent")
    ok = True
    no_p = []
    for n in range(0, 7):
        for p in range(n + 1):
            q = n - p
            sq = GA.sig(p, q)
            has_c = len(_central_idempotents(p, q)) > 0
            ok = ok and has_c == ((p - q) % 4 == 1)
            G = [[F(sq[i]) if i == j else F(0) for j in range(n)] for i in range(n)]
            P, N, _ = GA.congruence_signature(G) if n else (0, 0, 0)
            has_n = P >= 1 and N >= 1
            if has_n:
                v = GA.add(GA.gen(0), GA.gen(p))
                ok = ok and GA.is_zero(GA.mul(v, v, sq))
            ok = ok and has_n == (p >= 1 and q >= 1)
            has_p = False
            for b in GA.all_blades(n):
                x = {b: F(1)}
                if b and GA.eq(GA.mul(x, x, sq), GA.sc(1)) and not all(GA.commutes(x, GA.gen(i), sq) for i in range(n)):
                    has_p = True
                    break
            if not has_p:
                no_p.append((p, q))
    ok = ok and sorted(no_p) == [(0, 0), (0, 1), (0, 2), (0, 3), (1, 0)]
    GA.check("type C exactly at p - q = 1 mod 4, type N exactly in mixed signatures, P except R, R+R, C, H, H+H", ok)
    return ok


def _classify_all(p, q, elements):
    n = p + q
    sq = GA.sig(p, q)
    cent = _central_idempotents(p, q)
    counts = {"zd": 0, "C": 0, "P": 0, "N": 0, "fail": 0}
    for a in elements:
        f = _annihilator_idempotent(a, sq, n, "right")
        if f is None:
            continue                                  # a is not a zero divisor
        counts["zd"] += 1
        h = _annihilator_idempotent(a, sq, n, "left")
        good = (f is not False and h is not False and h is not None
                and GA.eq(GA.mul(f, f, sq), f) and GA.eq(GA.mul(h, h, sq), h)
                and GA.is_zero(GA.mul(a, f, sq)) and GA.is_zero(GA.mul(h, a, sq))
                and not GA.is_zero(f) and not GA.eq(f, GA.sc(1))
                and not GA.is_zero(h) and not GA.eq(h, GA.sc(1))
                and GA.eq(GA.mul(GA.mul(f, f, sq), f, sq), f))      # the identity repair: f f f = f
        if not good:
            counts["fail"] += 1
            continue
        if any(GA.is_zero(GA.mul(e, a, sq)) for e in cent):
            counts["C"] += 1
        else:
            counts["P"] += 1
            if all(len(b) == 1 for b in a) and GA.is_zero(GA.mul(a, a, sq)):
                counts["N"] += 1
    return counts


def check_exhaustiveness_on_lattice():
    premise("transport.exhaustiveness-every-zero-divisor-annihilated-idempotent")
    premise("transport.type-p-self-repairing")
    ok = True
    expect = {(1, 0): (4, 4, 0, 0), (0, 1): (0, 0, 0, 0), (2, 0): (32, 0, 32, 0),
              (1, 1): (32, 0, 32, 4), (0, 2): (0, 0, 0, 0)}
    total = 0
    for (p, q) in LATTICE_SIGS:
        n = p + q
        blades = GA.all_blades(n)
        els = []
        for cs in product((-1, 0, 1), repeat=len(blades)):
            if any(cs):
                els.append({b: F(c) for b, c in zip(blades, cs) if c})
        total += len(els)
        c = _classify_all(p, q, els)
        ok = ok and c["fail"] == 0 and (c["zd"], c["C"], c["P"], c["N"]) == expect[(p, q)]
    ok = ok and total == 256
    # Cl(2,1): e0 + e2 null (N), 1 + e01 invertible, 1 + e012 with central omega (C);
    # Cl(1,3): e0 + e1 null (N), 1 + e01 with (e01)^2 = 1 (P), 1 + e0123 invertible (omega^2 = -1)
    extra_expect = {(2, 1): (2, 1, 1, 1), (1, 3): (2, 0, 2, 1)}
    for (p, q), els in EXTRA.items():
        c = _classify_all(p, q, els)
        ok = ok and c["fail"] == 0 and (c["zd"], c["C"], c["P"], c["N"]) == extra_expect[(p, q)]
    GA.check("every lattice zero divisor is annihilated by idempotents and is of type C, P or N", ok)
    return ok


# Sample signatures: type N cases for the (1,1) ascent, type C cases with both fusion signs g; the type P
# example algebra Cl(1,1) with its non-scalar blades.
N_SIGNATURES = [(1, 1), (1, 3), (2, 1)]
C_SIGNATURES = [(1, 0), (2, 1), (0, 3)]
FUSION_SIGNS = (1, -1)
P_SQ = GA.sig(1, 1)
P_BLADES = [(0,), (1,), (0, 1)]


def check_each_rule_repairs_its_type():
    ex = premise("transport.minimality")
    ex2 = premise("transport.rule-2-ideal-fusion-sharp-form")
    premise("transport.totality")
    premise("transport.type-p-self-repairing")
    ok = True
    for (p, q) in N_SIGNATURES:
        M = ex["conformal"](p, q)
        sq = M["sq"]
        v = GA.add(GA.gen(0), GA.gen(p))
        ok = ok and GA.is_zero(GA.mul(v, v, sq)) and not GA.is_zero(v)       # v = e_0 + e_p is null
        I = M["iota"](M["X"](v))
        ok = ok and GA.eq(I, GA.scal(-1, GA.add(v, GA.scal(F(1, 2), M["ninf"]))))
        ok = ok and GA.is_zero(GA.mul(I, I, sq)) and not GA.is_zero(I)
    for (p, q) in C_SIGNATURES:
        for g in FUSION_SIGNS:
            D = ex2["fusion"](p, q, g)
            ok = ok and ex2["central_blades"](D["sq"], p + q + 1) == [()]
            for e in _central_idempotents(p, q):
                ok = ok and not GA.commutes(e, D["nu"], D["sq"])        # no longer central
    sq = P_SQ
    p_cases = 0
    for b in P_BLADES:
        x = {b: F(1)}
        if GA.eq(GA.mul(x, x, sq), GA.sc(1)):
            p_cases += 1
            e = GA.scal(F(1, 2), GA.add(GA.sc(1), x))
            ok = ok and GA.eq(GA.mul(e, e, sq), e)
            ok = ok and not all(GA.commutes(e, GA.gen(i), sq) for i in range(len(sq)))     # non-central
    # by hand: in Cl(1,1) the blades of square +1 are e_0 and e_0 e_1
    ok = ok and p_cases == 2
    GA.check("N repaired by the (1,1) ascent, C by the one-generator ascent, P by the identity", ok)
    return ok
