def C(z):
    return (F(z[0]), F(z[1]))


def cadd(x, y): return (x[0] + y[0], x[1] + y[1])
def cmul(x, y): return (x[0] * y[0] - x[1] * y[1], x[0] * y[1] + x[1] * y[0])
def cconj(x): return (x[0], -x[1])
def csc(c, x): return (c * x[0], c * x[1])


ZERO = (F(0), F(0))


def mat(key, d):
    return [[C(d[key][i][j]) for j in range(3)] for i in range(3)]


def lin(terms):
    out = [[ZERO] * 3 for _ in range(3)]
    for c, M in terms:
        out = [[cadd(out[i][j], cmul(c, M[i][j])) for j in range(3)] for i in range(3)]
    return out


def sectors(d):
    Y, Z, f, H = mat('Y', d), mat('Z', d), mat('f', d), mat('H', d)
    wu, wd, cu, cn, cd = C(d['wu']), C(d['wd']), C(d['cu']), C(d['cn']), C(d['cd'])
    Y[2][2] = cmul(csc(F(3), wu), f[2][2])                      # Premise (EW), held exact
    one = (F(1), F(0))
    Mu = lin([(one, Y), (wu, f), (cu, H)])
    Mn = lin([(one, Y), (csc(F(-3), wu), f), (cn, H)])
    Md = lin([(one, Z), (wd, f), (cd, H)])
    return Mu, Mn, Md


def gram(M):
    return [[_dot(M[i], M[j]) for j in range(3)] for i in range(3)]


def _dot(r, s):
    out = ZERO
    for k in range(3):
        out = cadd(out, cmul(r[k], cconj(s[k])))
    return out


def charpoly(A):
    """det(t - A) for Hermitian A, as real coefficients [c0, c1, c2, 1]."""
    tr = cadd(cadd(A[0][0], A[1][1]), A[2][2])
    m2 = ZERO
    for i, j in ((0, 1), (0, 2), (1, 2)):
        m2 = cadd(m2, cadd(cmul(A[i][i], A[j][j]), csc(F(-1), cmul(A[i][j], A[j][i]))))
    det = ZERO
    for (a, b, c), s in (((0, 1, 2), 1), ((1, 2, 0), 1), ((2, 0, 1), 1),
                         ((0, 2, 1), -1), ((2, 1, 0), -1), ((1, 0, 2), -1)):
        det = cadd(det, csc(F(s), cmul(cmul(A[0][a], A[1][b]), A[2][c])))
    assert tr[1] == 0 and m2[1] == 0 and det[1] == 0               # Hermitian: real invariants
    return [-det[0], m2[0], -tr[0], F(1)]


def sturm_count_above(p, lo):
    """number of distinct real roots of p in (lo, +infinity)."""
    seq = [ptrim(list(p)), pderiv(p)]
    while seq[-1]:
        r = pdivmod(seq[-2], seq[-1])[1]
        seq.append([-c for c in r])
    seq = [s for s in seq if s]
    def changes(vals):
        v = [x for x in vals if x != 0]
        return sum(1 for a, b in zip(v, v[1:]) if (a > 0) != (b > 0))
    at_lo = changes([peval(s, lo) for s in seq])
    at_inf = changes([s[-1] for s in seq])
    return at_lo - at_inf


def top_sv_in(M, lo, hi):
    """lo < sigma_max(M) < hi, exactly: one root of the characteristic polynomial of M M^dag above
    lo^2 and none above hi^2."""
    p = charpoly(gram(M))
    return sturm_count_above(p, lo * lo) == 1 and sturm_count_above(p, hi * hi) == 0


def check_charged_heavy_values():
    """Each set gives m_t(M_I) = 92.45 and m_b(M_I) = 1.3651 GeV to the fit's precision, with (EW)
    exact: (M_nu)_33 = 0."""
    premise("standard-model.fits-record-level")
    premise("standard-model.imported-clebsch-structure-seesaw")
    for name, d in FITS.items():
        Mu, Mn, Md = sectors(d)
        assert Mn[2][2] == ZERO
        assert top_sv_in(Mu, F(9244, 100), F(9246, 100))
        assert top_sv_in(Md, F(13649, 10000), F(13652, 10000))


def check_leading_dirac_values():
    """The leading singular value of M_nu at M_I: 0.0543-0.0544, 3.160-3.161, 5.004-5.005 and
    3.122-3.123 GeV; every one differs from m_b(M_I) by more than a factor 2.2 and from m_t(M_I) by more
    than a factor 18, and the largest and smallest differ by a factor above 90."""
    premise("standard-model.fits-record-level")
    premise("standard-model.imported-clebsch-structure-seesaw")
    mt, mb = F(9245, 100), F(13651, 10000)
    BRACKETS = {      # leading singular value of M_nu at M_I, GeV
        'natural': (F(543, 10000), F(544, 10000)),
        'gj126_two10': (F(3160, 1000), F(3161, 1000)),
        'gj126_one10': (F(5004, 1000), F(5005, 1000)),
        'shared_no120': (F(3122, 1000), F(3123, 1000)),
    }
    for name, (lo, hi) in BRACKETS.items():
        Mu, Mn, Md = sectors(FITS[name])
        assert top_sv_in(Mn, lo, hi)
        assert hi * 18 < mt
        assert hi * F(22, 10) < mb or lo > mb * F(22, 10)
    los = [b[0] for b in BRACKETS.values()]
    his = [b[1] for b in BRACKETS.values()]
    assert max(los) > 90 * min(his)


