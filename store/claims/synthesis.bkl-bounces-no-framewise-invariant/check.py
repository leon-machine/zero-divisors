"""synthesis.bkl-bounces-no-framewise-invariant: exact checks.

The BKL transition law on Kasner triples, in exact rationals: it preserves sum p = 1 and sum p^2 = 1;
in the u-parametrisation it is u -> u - 1 with the bouncing axis taking p2(u - 1); the fixed-frame jump on the
bouncing axis is >= 20/21 for 1 <= u <= 2 (both summands decreasing there, polynomial derivative signs);
rational orbits end at (-1/3, 2/3, 2/3) and then (1, 0, 0), after (sum of partial quotients) bounces; the Lie
algebra generated by the limiting values -p_i B_i (GTG sign) in Cl(1,3) is six-dimensional with two or three nonzero
exponents and one-dimensional at (1, 0, 0); e3 = p1 p2 p3 is strictly increasing on [1, oo), and
e3(u) = e3(1/(u - 1)) on (1, 2) only at u^2 - u - 1 = 0.
"""
from fractions import Fraction as F
import GA
from tp_premise import premise


def p_of_u(u):
    D = 1 + u + u * u
    return (-u / D, (1 + u) / D, u * (1 + u) / D)


def bounce(p):
    a = min(range(3), key=lambda i: p[i])
    assert p[a] < 0
    d = 1 + 2 * p[a]
    return tuple((-p[i] / d) if i == a else (p[i] + 2 * p[a]) / d for i in range(3)), a


def cf_sum(u):
    s = 0
    while True:
        n = u.numerator // u.denominator
        s += n
        fr = u - n
        if fr == 0:
            return s
        u = 1 / fr


def lie_dim(gens, squares):
    """Dimension of the Lie algebra generated by bivectors gens (closure under commutators)."""
    blades = [b for b in GA.all_blades(4) if len(b) == 2]
    basis = []

    def vec(x):
        return [x.get(b, F(0)) for b in blades]
    frontier = [x for x in gens if x]
    while frontier:
        new = []
        for x in frontier:
            if GA.rank_of_vectors([vec(y) for y in basis + [x]]) > len(basis):
                basis.append(x)
                new.append(x)
        frontier = []
        for x in new:
            for y in basis:
                c = GA.sub(GA.mul(x, y, squares), GA.mul(y, x, squares))
                if c and GA.rank_of_vectors([vec(z) for z in basis + [c]]) > len(basis):
                    frontier.append(c)
    return len(basis)


def check_bkl_bounces():
    premise("interior.weighted-limit-theorem")
    premise("interior.kasner-form-interior")
    premise("sheaf.collision-census")
    premise("dark-energy.wall-counterterm")
    premise("interior.boosts-generate-exactly-levi-factor")
    us = [F(1), F(2), F(3, 2), F(7, 5), F(13, 8), F(355, 113), F(5), F(101, 7)]
    # (i) the transition law stays on the Kasner circle; (ii) it is u -> u - 1 on the bouncing axis
    for u in us:
        p = p_of_u(u)
        assert sum(p) == 1 and sum(x * x for x in p) == 1
        q, a = bounce(p)
        assert a == 0 and sum(q) == 1 and sum(x * x for x in q) == 1
        w = u - 1
        assert q == (p_of_u(w)[1], p_of_u(w)[0], p_of_u(w)[2])
        if 0 < w < 1:
            assert sorted(q) == sorted(p_of_u(1 / w))
    # Schwarzschild's exponents bounce to the flat Kasner point
    assert p_of_u(F(1)) == (F(-1, 3), F(2, 3), F(2, 3))
    assert bounce(p_of_u(F(1)))[0] == (F(1), F(0), F(0))
    # (iii) the jump on the bouncing axis, |p1(u)| + p2(u - 1) = u/(u^2+u+1) + u/(u^2-u+1), at least 20/21 on [1, 2]
    jump = lambda u: u / (u * u + u + 1) + u / (u * u - u + 1)
    assert jump(F(2)) == F(20, 21) and jump(F(1)) == F(4, 3)
    # derivatives: d/du u/(u^2+u+1) has numerator 1 - u^2; d/du u/(u^2-u+1) has numerator 1 - u^2
    for c in (1, -1):
        num = GA.padd(GA.pmul([F(1)], [F(1), F(c), F(1)]),
                      GA.pneg(GA.pmul([F(0), F(1)], GA.pderiv([F(1), F(c), F(1)]))))
        assert num == [F(1), F(0), F(-1)]
    for k in range(9):
        u = 1 + F(k, 8)
        assert jump(u) >= F(20, 21)
        q, a = bounce(p_of_u(u))
        assert q[a] - p_of_u(u)[a] == jump(u)
    # (iv)-(v) rational orbits: sum of partial quotients - 1 bounces to u = 1, then one to (1, 0, 0)
    for u in us:
        p, n, prev = p_of_u(u), 0, None
        while min(p) < 0:
            prev = p
            p, _ = bounce(p)
            n += 1
        assert sorted(p) == [0, 0, 1] and sorted(prev) == [F(-1, 3), F(2, 3), F(2, 3)]
        assert n == cf_sum(u)
    # the generated algebra: six-dimensional while two exponents are nonzero, a line at (1, 0, 0)
    sq = (-1, 1, 1, 1)
    B = [GA.mul(GA.gen(0), GA.gen(i), sq) for i in (1, 2, 3)]
    for p in (p_of_u(F(1)), p_of_u(F(7, 5)), (F(1), F(0), F(0))):
        gens = [GA.scal(-p[i], B[i]) for i in range(3)]      # displayed values -p_i B_i (GTG sign)
        dim = lie_dim(gens, sq)
        assert dim == (1 if sorted(p) == [0, 0, 1] else 6)
    # two boosts alone generate only three dimensions; the third is forced on the variety
    assert lie_dim([B[0], B[1]], sq) == 3
    for x in (F(1, 2), F(2), F(-1, 3), F(0)):
        # p = (0, x, 1 - x) on the variety needs x^2 + (1 - x)^2 = 1, i.e. x (1 - x) = 0
        assert (x * x + (1 - x) ** 2 == 1) == (x * (1 - x) == 0)
    # (vi) e3 = p1 p2 p3 = -u^2 (1+u)^2 / (1+u+u^2)^3: derivative numerator, and the golden fixed point
    num = GA.pneg(GA.pmul(GA.pmul([F(0), F(0), F(1)], [F(1), F(1)]), [F(1), F(1)]))   # -u^2 (1+u)^2
    den = GA.pmul(GA.pmul([F(1), F(1), F(1)], [F(1), F(1), F(1)]), [F(1), F(1), F(1)])
    dnum = GA.padd(GA.pmul(GA.pderiv(num), den), GA.pneg(GA.pmul(num, GA.pderiv(den))))
    # dnum = u (1+u) (1+2u) (u+2) (u-1) (u^2+u+1)^2, positive for u > 1
    fac = GA.pmul(GA.pmul([F(0), F(1)], [F(1), F(1)]), GA.pmul([F(1), F(2)], [F(2), F(1)]))
    fac = GA.pmul(fac, GA.pmul([F(-1), F(1)], GA.pmul([F(1), F(1), F(1)], [F(1), F(1), F(1)])))
    assert dnum == fac
    e3 = lambda u: GA.peval(num, u) / GA.peval(den, u)
    assert e3(F(1)) == F(-4, 27) and e3(F(2)) == F(-36, 343)
    for u in us:
        assert e3(u) == p_of_u(u)[0] * p_of_u(u)[1] * p_of_u(u)[2]
    # on (1, 2): e3(u) - e3(1/(u - 1)) vanishes only where u^2 - u - 1 = 0 (e3 injective on [1, oo))
    for k in range(1, 8):
        u = 1 + F(k, 8)
        assert e3(u) != e3(1 / (u - 1))
        assert (e3(u) - e3(1 / (u - 1)) > 0) == (u * u - u - 1 > 0)
    # rational orbits make every continuous bounce invariant constant: f(p(r)) = f(p(1)) for rational r
    for u in us:
        p = p_of_u(u)
        while sorted(p) != [F(-1, 3), F(2, 3), F(2, 3)]:
            p, _ = bounce(p)
        assert sorted(p) == sorted(p_of_u(F(1)))
    return True
