"""rungs.imported-totality-minimality-completion: exact checks of the three imported clauses.

(1) No equivariant element-level inverse of null vectors (finite core of the no-go): in Cl(V) and
    in its ascent Cl(V + H), for the mixed signatures (2,1), (1,2), (1,3), (3,1), (2,2): v null,
    w0 null with v.w0 = 1/2, u in {v, w0}^perp with Q(u) != 0. Sample pseudo-inverses
    sigma = w0 + alpha + v beta + v w0 delta (alpha, beta, delta generated by {v, w0}^perp,
    including the ascent's e+, e-) satisfy v sigma v = v. The null rotation R = 1 + v u equals
    u' u / Q(u) with u' = u + Q(u) v (a product of two invertible vectors), fixes v, and
    R sigma R^{-1} - sigma + u is annihilated by left multiplication with v while v u != 0: so
    R sigma R^{-1} != sigma, and no sigma is equivariant.
(2) The conformal model of the completion (exported by the transport.minimality check) adjoins one
    hyperbolic plane: Gram signature (p+1, q+1) with (n0, ninf) a hyperbolic pair, for all signatures
    with n <= 4. Minimality and uniqueness up to isometry are tested in transport.minimality, not here.
(3) iota[N] = [e+ N e+] is total and involutive (e+ (e+ N e+) e+ = N, nonzero null vectors to
    nonzero null vectors), equals the reciprocal on invertible x (iota X(x) = -Q(x) X(x/Q(x))),
    sends null x0 to [x0 + ninf/2], and iota X(x) = -J(x) with J(x) = Q(x) n0 + x + ninf/2 for every
    x; J is polynomial and J(x0 + h d) - J(x0) has zero constant term in h (Lagrange extrapolation to
    h = 0 through three h and through all four, sample directions d), so iota[X(x)] -> [x0 + ninf/2] along every invertible path.
"""
from fractions import Fraction as F

import GA
from tp_premise import premise

MIXED = [(2, 1), (1, 2), (1, 3), (3, 1), (2, 2)]


def _nogo_case(p, q, ascent):
    """v, w0, u and sample alpha/beta/delta in Cl(V) (ascent False) or Cl(V + H)."""
    n = p + q
    sq = GA.sig(p, q) + ((1, -1) if ascent else ())
    v = GA.add(GA.gen(0), GA.gen(p))                        # e_0 + e_p, null
    w0 = GA.scal(F(1, 4), GA.sub(GA.gen(0), GA.gen(p)))     # null, v.w0 = 1/2
    perp = [GA.gen(i) for i in range(1, n) if i != p] + ([GA.gen(n), GA.gen(n + 1)] if ascent else [])
    return sq, v, w0, perp


def _samples(perp, sq):
    a = perp[0]
    b = perp[-1]
    ab = GA.mul(a, b, sq) if len(perp) > 1 else GA.sc(3)
    alpha = GA.add(GA.sc(2), GA.scal(F(-1, 2), a), ab)
    beta = GA.add(GA.scal(5, b), GA.sc(1))
    delta = GA.add(GA.sc(F(1, 3)), GA.scal(7, ab))
    return [({}, {}, {}), (alpha, {}, {}), (alpha, beta, delta), ({}, beta, delta)]


def check_no_equivariant_pseudo_inverse_of_null_vectors():
    premise("transport.no-go-level-elements")
    ok = True
    cases = 0
    for (p, q) in MIXED:
        for ascent in (False, True):
            sq, v, w0, perp = _nogo_case(p, q, ascent)
            ok = ok and GA.is_zero(GA.mul(v, v, sq)) and GA.is_zero(GA.mul(w0, w0, sq))
            ok = ok and GA.dot(v, w0, sq) == F(1, 2)
            u = perp[0]
            Qu = GA.mul(u, u, sq).get((), F(0))
            ok = ok and Qu != 0 and GA.dot(u, v, sq) == 0 and GA.dot(u, w0, sq) == 0
            R = GA.add(GA.sc(1), GA.mul(v, u, sq))
            Rinv = GA.sub(GA.sc(1), GA.mul(v, u, sq))
            ok = ok and GA.eq(GA.mul(R, Rinv, sq), GA.sc(1))
            up = GA.add(u, GA.scal(Qu, v))
            ok = ok and GA.eq(GA.scal(1 / Qu, GA.mul(up, u, sq)), R)
            ok = ok and GA.eq(GA.mul(GA.mul(R, v, sq), Rinv, sq), v)
            vu = GA.mul(v, u, sq)
            ok = ok and not GA.is_zero(vu)
            for alpha, beta, delta in _samples(perp, sq):
                sigma = GA.add(w0, alpha, GA.mul(v, beta, sq), GA.mul(GA.mul(v, w0, sq), delta, sq))
                ok = ok and GA.eq(GA.mul(GA.mul(v, sigma, sq), v, sq), v)
                moved = GA.mul(GA.mul(R, sigma, sq), Rinv, sq)
                rest = GA.add(GA.sub(moved, sigma), u)
                ok = ok and GA.is_zero(GA.mul(v, rest, sq))
                ok = ok and not GA.eq(moved, sigma)
                cases += 1
    ok = ok and cases == 40
    GA.check("null rotations fixing v move every pseudo-inverse of v (Cl(V) and the ascent), 5 signatures", ok)
    return ok


def check_conformal_model_adjoins_one_hyperbolic_plane():
    ex = premise("transport.minimality")
    conformal = ex["conformal"]
    ok = True
    count = 0
    for n in range(0, 5):
        for p in range(n + 1):
            q = n - p
            M = conformal(p, q)
            sq = M["sq"]
            basis = [GA.gen(i) for i in range(n + 2)]
            G = [[GA.dot(a, b, sq) for b in basis] for a in basis]
            ok = ok and GA.congruence_signature(G) == (p + 1, q + 1, 0)
            plane = [[GA.dot(a, b, sq) for b in (M["n0"], M["ninf"])] for a in (M["n0"], M["ninf"])]
            ok = ok and plane == [[0, -1], [-1, 0]]
            count += 1
    ok = ok and count == 15
    GA.check("the conformal model adjoins one hyperbolic plane, increment (+1,+1), all 15 signatures n <= 4", ok)
    return ok


def _lagrange0(hs, vals):
    out = {}
    for i, hi in enumerate(hs):
        w = F(1)
        for j, hj in enumerate(hs):
            if j != i:
                w *= (0 - hj) / (hi - hj)
        out = GA.add(out, GA.scal(w, vals[i]))
    return out


def check_transported_reciprocal_total_involutive_continuous():
    ex = premise("transport.minimality")
    premise("transport.totality")
    conformal = ex["conformal"]
    ok = True
    nulls = 0
    for (p, q) in MIXED:
        M = conformal(p, q)
        n, sq, n0, ninf = M["n"], M["sq"], M["n0"], M["ninf"]
        xs = [M["vec"](c[:n]) for c in ([1, 2, -1, 3], [F(1, 2), -3, 2, 1], [2, 0, 1, 1])]
        x0s = [{}, M["vec"]([1 if i in (0, p) else 0 for i in range(n)]),
               M["vec"]([3 if i == 0 else (-3 if i == p else 0) for i in range(n)])]
        for x in xs + x0s:
            Qx = M["Q"](x)
            Xx = M["X"](x)
            I = M["iota"](Xx)
            ok = ok and GA.eq(M["iota"](I), Xx)                                  # involution
            ok = ok and GA.is_zero(GA.mul(I, I, sq)) and not GA.is_zero(I)        # total on the quadric
            J = GA.add(GA.scal(Qx, n0), x, GA.scal(F(1, 2), ninf))
            ok = ok and GA.eq(I, GA.scal(-1, J))
            if Qx != 0:
                ok = ok and GA.eq(I, GA.scal(-Qx, M["X"](GA.scal(1 / Qx, x))))    # reciprocal
            else:
                nulls += 1
                ok = ok and GA.eq(I, GA.scal(-1, GA.add(x, GA.scal(F(1, 2), ninf))))
                for d in xs:
                    hs = [F(1, 10), F(1, 100), F(-1, 7), F(1, 1000)]
                    vals = []
                    for h in hs:
                        xh = GA.add(x, GA.scal(h, d))
                        Qh = M["Q"](xh)
                        vals.append(GA.add(GA.scal(Qh, n0), xh, GA.scal(F(1, 2), ninf)))
                    ok = ok and GA.eq(_lagrange0(hs[:3], vals[:3]), J) and GA.eq(_lagrange0(hs, vals), J)
        # the ideal points: iota swaps n0 and ninf up to scale
        ok = ok and GA.eq(M["iota"](n0), GA.scal(F(-1, 2), ninf)) and GA.eq(M["iota"](ninf), GA.scal(-2, n0))
    ok = ok and nulls == 15
    GA.check("iota total, involutive, the reciprocal on invertible x, [x0 + ninf/2] at null x0 as a limit", ok)
    return ok
