"""dark-tower-matter.gauge-algebras: exact checks.

Real matrices with exact entries. The automorphisms of a hierarchy F^a (x) F^b are A (x) B with A, B in
the F-unitary groups (premises: the ladder's unitary mixings, the field of the constituents, where mass
begins, the pair counts and the third pair's unit, and H2's identification of the gauge algebra with
those automorphisms). Complex matrices act through their real 2N x 2N forms.
(i) Three-dimensional towers, R^2 (x) R^2: the Lie algebra spanned by so(2) (x) 1 and 1 (x) so(2) has
dimension 2 and is abelian (all commutators vanish). The kernel of (A, B) -> A (x) B on O(2) x O(2), over
the rational subgroup generated by the Pythagorean rotations (3/5, 4/5), (5/13, 12/13), the quarter turn
and a reflection (all 40 x 40 pairs of the 40 distinct elements), is exactly {(1,1), (-1,-1)}. The identity
component: in the exterior algebra of the four cells of weight (s, p) = (+-1, +-1) every weight has s + p
even, so q_+- = (s +- p)/2 are integers exactly on that lattice; the cell (1,1) has (q_+, q_-) = (1, 0)
and (1,-1) has (0, 1): U(1)_+ x U(1)_-.
(ii) Five-dimensional towers, C^1 (x) C^3: u(1) (x) 1 + 1 (x) u(3) spans a real Lie algebra of dimension 9;
its derived algebra has dimension 8 (su(3)) and its centre dimension 1 (u(1)): u(3). Controls: C^2 (x) C^3
gives 12 (this tower's algebra) and C^2 (x) C^2 gives 7.
"""
from fractions import Fraction as F
from itertools import combinations
import GA
from tp_premise import premise


def kron(A, B):
    return [[A[i][j] * B[k][l] for j in range(len(A[0])) for l in range(len(B[0]))]
            for i in range(len(A)) for k in range(len(B))]


def eye(n):
    return [[F(int(i == j)) for j in range(n)] for i in range(n)]


mm = GA.mat_mul                         # dense matrix product


def comm(A, B):
    X, Y = mm(A, B), mm(B, A)
    return [[X[i][j] - Y[i][j] for j in range(len(X))] for i in range(len(X))]


def flat(A):
    return [x for r in A for x in r]


def real_of_complex(Re, Im):
    n = len(Re)
    return [[(Re[i][j] if a == b else (-Im[i][j] if a == 0 else Im[i][j])) for j in range(n) for b in range(2)]
            for i in range(n) for a in range(2)]


def u_basis(m):
    Z = [[F(0)] * m for _ in range(m)]
    out = []
    for i in range(m):
        Im = [r[:] for r in Z]
        Im[i][i] = F(1)
        out.append((Z, Im))
    for i in range(m):
        for k in range(i + 1, m):
            Re = [r[:] for r in Z]
            Re[i][k], Re[k][i] = F(1), F(-1)
            out.append((Re, Z))
            Im = [r[:] for r in Z]
            Im[i][k] = Im[k][i] = F(1)
            out.append((Z, Im))
    return out


def tensor_algebra(m, k):
    gens = []
    Ik, Zk = eye(k), [[F(0)] * k for _ in range(k)]
    Im_, Zm = eye(m), [[F(0)] * m for _ in range(m)]
    for Re, Im in u_basis(m):
        gens.append(real_of_complex(kron(Re, Ik), kron(Im, Ik)))
    for Re, Im in u_basis(k):
        gens.append(real_of_complex(kron(Im_, Re), kron(Im_, Im)))
    basis = []
    for g in gens:
        if GA.rank_of_vectors([flat(b) for b in basis + [g]]) > len(basis):
            basis.append(g)
    return basis


def o2_elements():
    rots = [(F(1), F(0)), (F(0), F(1)), (F(3, 5), F(4, 5)), (F(4, 5), F(3, 5)), (F(5, 13), F(12, 13)),
            (F(12, 13), F(5, 13))]
    els = []
    for c, s in rots:
        for sc, ss in ((1, 1), (-1, 1), (1, -1), (-1, -1)):
            R = [[sc * c, -ss * s], [ss * s, sc * c]]
            for M in (R, mm(R, [[F(1), F(0)], [F(0), F(-1)]])):
                if M not in els:
                    els.append(M)
    return els


def check_three_dimensional_algebra_is_so2_plus_so2():
    premise("dark-tower-matter.where-mass-begins")
    premise("dark-tower-matter.pairs")
    premise("dark-tower-matter.constituents-field")
    premise("dark-tower-matter.ladder")
    premise("dark-tower-matter.h2-identification")
    J = [[F(0), F(-1)], [F(1), F(0)]]
    gens = [kron(J, eye(2)), kron(eye(2), J)]
    ok = GA.rank_of_vectors([flat(g) for g in gens]) == 2
    ok = ok and all(x == 0 for x in flat(comm(gens[0], gens[1])))
    els = o2_elements()
    ok = ok and len(els) == 40 and all(mm([[a[0][0], a[1][0]], [a[0][1], a[1][1]]], a) == eye(2) for a in els)
    kernel = [(A, B) for A in els for B in els if kron(A, B) == eye(4)]
    ok = ok and len(kernel) == 2 and (eye(2), eye(2)) in kernel \
        and ([[F(-1), F(0)], [F(0), F(-1)]], [[F(-1), F(0)], [F(0), F(-1)]]) in kernel
    GA.check("thm:algebras(i): so(2) + so(2), dimension 2, abelian; kernel {(1,1), (-1,-1)} on the sampled O(2) x O(2)",
             ok)
    return ok


def check_three_dimensional_global_form():
    premise("dark-tower-matter.pairs")
    cells = [(1, 1), (1, -1), (-1, 1), (-1, -1)]
    weights = set()
    for k in range(5):
        for sub in combinations(range(4), k):
            weights.add((sum(cells[i][0] for i in sub), sum(cells[i][1] for i in sub)))
    ok = all((s + p) % 2 == 0 for s, p in weights) and (1, 0) not in weights and (0, 1) not in weights
    ok = ok and all(((s + p) % 2 == 0) == (F(s + p, 2).denominator == 1 and F(s - p, 2).denominator == 1)
                    for s in range(-3, 4) for p in range(-3, 4))
    ok = ok and (F(1 + 1, 2), F(1 - 1, 2)) == (1, 0) and (F(1 - 1, 2), F(1 + 1, 2)) == (0, 1)
    ok = ok and len(weights) == 9
    GA.check("thm:algebras(i): weights on the lattice s + p even, charges q_+- = (s +- p)/2 integral there: "
             "U(1)_+ x U(1)_-", ok)
    return ok


def check_five_dimensional_algebra_is_u3():
    premise("dark-tower-matter.third-pairs-unit-five-dimensions")
    premise("dark-tower-matter.pairs")
    premise("dark-tower-matter.constituents-field")
    premise("dark-tower-matter.where-mass-begins")
    premise("dark-tower-matter.h2-identification")
    L = tensor_algebra(1, 3)
    ok = len(L) == 9
    derived = []
    for a in range(len(L)):
        for b in range(a + 1, len(L)):
            c = comm(L[a], L[b])
            if GA.rank_of_vectors([flat(x) for x in derived + [c]]) > len(derived):
                derived.append(c)
    ok = ok and len(derived) == 8
    # centre: X in span(L) commuting with all of L
    rows = []
    N = len(L[0])
    for Y in L:
        cs = [flat(comm(X, Y)) for X in L]
        for e in range(N * N):
            rows.append([cs[i][e] for i in range(len(L))])
    centre = len(L) - GA.rank_of_vectors(rows)
    ok = ok and centre == 1
    ok = ok and len(tensor_algebra(2, 3)) == 12 and len(tensor_algebra(2, 2)) == 7
    GA.check("thm:algebras(ii): C^1 (x) C^3 gives a 9-dimensional algebra with 8-dimensional derived algebra and "
             "1-dimensional centre: u(3); controls 12 and 7", ok)
    return ok
