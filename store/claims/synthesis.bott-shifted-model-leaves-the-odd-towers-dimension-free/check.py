"""Exact checks: the descent leaves the five-dimensional towers' dimension free; Premise U fixes the
three-dimensional ones.

Two models of the window-sensitive premises, identical except at residues 3 and 5:
M_L puts residues 1, 7, 3, 5 at their lowest causal members (2,1), (1,2), (4,1), (1,4) (P3's choice);
M_8 agrees with M_L except at residues 3 and 5, where it takes the Bott shifts (12,1), (1,12). Both put
residue 6 at this world (1,3), residue 2 at its reversal (3,1), and leave residues 0 and 4 to the costed
single-ideal clause. The shift itself is checked at all four odd residues (an algebra fact); at residues 1 and 7
Premise U (U3) with the stored pair count admits only the lowest causal member, checked over all causal
members up to dimension 21 (real Witt index of the conformal space from GA Gram matrices, field by residue).
The shift beta adds eight directions of the majority sign. The checks build each algebra in GA.py with
squares tuples (the representative's own generators first, then the eight added ones) and verify:
the split Cl(beta s) = A (x) B with A = <e_i w8> a copy of Cl(s), B = Cl(8,0) or Cl(0,8), [A, B] = 0,
reversion restricting to each factor; that B is the real matrix algebra of size 16 (a primitive
idempotent f with f~ = f and f B f = R f on all 256 blades); the type data every stored selector reads
(residue, causality, reversal, n mod 4, pseudoscalar square and centrality); the premises' conditions on
both models; the unit-ball ratio of each model by rational bounds on pi; and that (W) holds in M_L only.
"""
from fractions import Fraction as F
from itertools import combinations

import GA
from tp_premise import premise

PI_LO, PI_HI = F(333, 106), F(355, 113)

M_L = {6: (1, 3), 2: (3, 1), 1: (2, 1), 7: (1, 2), 3: (4, 1), 5: (1, 4)}
ODD = (1, 7, 3, 5)


def beta(s):
    p, q = s
    return (p + 8, q) if p > q else (p, q + 8)


SHIFTED = (3, 5)
M_8 = {r: (beta(s) if r in SHIFTED else s) for r, s in M_L.items()}


def squares(s, shifted):
    p, q = s
    base = tuple([1] * p + [-1] * q)
    if not shifted:
        return base
    return base + tuple([1 if p > q else -1] * 8)


def residue(s):
    return (s[0] - s[1]) % 8


def causal(s):
    return min(s) == 1


def blade(*ix):
    return {tuple(sorted(ix)): F(1)}


def top_square(sq):
    c, b = GA.blade_mul(tuple(range(len(sq))), tuple(range(len(sq))), sq)
    assert b == ()
    return c


def check_bott_shift_splits_off_a_real_matrix_factor():
    """beta s has Cl(beta s) = A (x) B: A generated by e_i w8 (i < n) obeys Cl(s), B = the eight added
    generators, every a_i commutes with every b_j, w8^2 = 1, and reversion fixes each a_i."""
    premise("tower.morita-equivalence-algebra-amplification")
    premise("dark-matter.imported-eight-towers-mod-8-clock")
    for r in ODD:
        s = M_L[r]
        n = s[0] + s[1]
        sq = squares(s, True)
        assert len(sq) == n + 8
        w8 = blade(*range(n, n + 8))
        assert GA.eq(GA.mul(w8, w8, sq), GA.sc(1))
        a = [GA.mul(GA.gen(i), w8, sq) for i in range(n)]
        for i in range(n):
            assert GA.eq(GA.mul(a[i], a[i], sq), GA.sc(squares(s, False)[i]))
            assert GA.eq(GA.reverse(a[i]), a[i])
            for j in range(i + 1, n):
                assert GA.anticommutes(a[i], a[j], sq)
            for k in range(n, n + 8):
                assert GA.commutes(a[i], GA.gen(k), sq)
        # the volume of A is the pseudoscalar of s times a power of w8: same square as Cl(s)'s
        vol = GA.sc(1)
        for x in a:
            vol = GA.mul(vol, x, sq)
        assert GA.eq(GA.mul(vol, vol, sq), GA.sc(top_square(squares(s, False))))
        GA.check(f"Cl{beta(s)} = Cl{s} (x) Cl(8 of one sign), factors commute", True)


def check_tensor_split_is_an_isomorphism():
    """The 2^n products of the a_i and the 2^8 products of the added generators multiply to 2^(n+8)
    distinct basis blades up to sign: A (x) B -> Cl(beta s) is onto, so (by dimension) an isomorphism,
    and A is a faithful copy of Cl(s)."""
    premise("tower.morita-equivalence-algebra-amplification")
    for r in (1, 3):
        s = M_L[r]
        n = s[0] + s[1]
        sq = squares(s, True)
        w8 = tuple(range(n, n + 8))
        seen = set()
        for k in range(n + 1):
            for S in combinations(range(n), k):
                aS = GA.sc(1)
                for i in S:
                    aS = GA.mul(aS, GA.mul(GA.gen(i), {w8: F(1)}, sq), sq)
                assert len(aS) == 1
                for T in GA.all_blades(8):
                    prod = GA.mul(aS, {tuple(n + j for j in T): F(1)}, sq)
                    assert len(prod) == 1
                    (b, c), = prod.items()
                    assert c in (1, -1)
                    seen.add(b)
        assert len(seen) == 2 ** (n + 8)
        GA.check(f"A (x) B spans Cl{beta(s)}: {len(seen)} blades", True)


def _primitive_idempotent(sq):
    hs = [blade(0, 1, 2, 3), blade(4, 5, 6, 7), blade(0, 1, 4, 5), blade(0, 2, 4, 6)]
    f = GA.sc(1)
    for h in hs:
        assert GA.eq(GA.mul(h, h, sq), GA.sc(1))
        f = GA.mul(f, GA.scal(F(1, 2), GA.add(GA.sc(1), h)), sq)
    for h in hs:
        for g in hs:
            assert GA.commutes(h, g, sq)
    return f


def check_eight_of_one_sign_is_real_sixteen_by_sixteen():
    """Cl(8,0) and Cl(0,8): f = prod (1 + h_k)/2 over four commuting blades of square 1 is a nonzero
    idempotent with f~ = f, f has 16 terms of scalar part 1/16, and f x f is a real multiple of f for all
    256 blades x, so f B f = R f: B is Mat(16, R) with the reversion pairing on B f symmetric."""
    premise("dark-tower-matter.imported-clifford-structure")
    for sign in (1, -1):
        sq = tuple([sign] * 8)
        f = _primitive_idempotent(sq)
        assert GA.eq(GA.mul(f, f, sq), f)
        assert GA.eq(GA.reverse(f), f)
        assert len(f) == 16 and f[()] == F(1, 16)
        mult = 0
        for b in GA.all_blades(8):
            y = GA.mul(GA.mul(f, {b: F(1)}, sq), f, sq)
            c = y.get((), F(0)) * 16
            assert GA.eq(y, GA.scal(c, f))
            if c != 0:
                mult += 1
        assert mult == 16
        GA.check(f"Cl(8 of sign {sign}) has f B f = R f, 16 blades survive", True)


def check_type_data_invariant_and_pair_count_not():
    """For each odd representative s and beta s: same residue, both causal, beta commutes with reversal,
    n mod 4 equal (so the flag bit and real chirality agree), pseudoscalar square equal, pseudoscalar
    central in both (odd n), the single time on the same sign."""
    premise("dark-matter.imported-eight-towers-mod-8-clock")
    premise("synthesis.oriented-causal-towers-mirror-pair-every-window")
    premise("synthesis.residues-zero-four-real-chirality-anomaly")
    for r in ODD:
        s, t = M_L[r], beta(M_L[r])
        assert residue(s) == residue(t) == r
        assert causal(s) and causal(t)
        assert beta((s[1], s[0])) == (t[1], t[0])
        n, m = s[0] + s[1], t[0] + t[1]
        assert m - n == 8 and n % 4 == m % 4 and n % 2 == 1
        assert top_square(squares(s, False)) == top_square(squares(t, False))
        sq = squares(t, False)
        top = {tuple(range(m)): F(1)}
        for i in range(m):
            assert GA.commutes(top, GA.gen(i), sq)
        assert (s[0] < s[1]) == (t[0] < t[1])
    # not invariant: the complex Witt index of the conformal space, floor((n+2)/2), the stored pair count
    assert [(sum(M_L[r]) + 2) // 2 for r in ODD] == [2, 2, 3, 3]
    assert [(sum(beta(M_L[r])) + 2) // 2 for r in ODD] == [6, 6, 7, 7]
    # the even residues of the two models coincide, so the orientation clause of P1 reads the same pair
    for r in (2, 6):
        assert M_L[r] == M_8[r] and sum(M_L[r]) % 4 == 0
    GA.check("type data invariant under beta on the odd residues", True)


def check_descent_premises_hold_in_both_models():
    """Each model assigns one causal signature to each populated residue with the right residue, is closed
    under reversal (P2), keeps this world (1,3) and its mirror (3,1) (P1's orientation clause, P2), and has
    no orientable odd tower (n odd); the residues present are the six of the census."""
    premise("dark-matter.imported-eight-towers-mod-8-clock")
    premise("synthesis.oriented-causal-towers-mirror-pair-every-window")
    for M in (M_L, M_8):
        assert sorted(M) == [1, 2, 3, 5, 6, 7]
        for r, s in M.items():
            assert residue(s) == r and causal(s)
            assert M[(-r) % 8] == (s[1], s[0])
            sq = squares(s, False)
            for i in range(len(sq)):
                for j in range(i + 1, len(sq)):
                    assert GA.anticommutes(GA.gen(i), GA.gen(j), sq)
        assert M[6] == (1, 3) and M[2] == (3, 1)
        assert all((M[r][0] + M[r][1]) % 2 == 1 for r in ODD)
    assert [r for r in ODD if M_L[r] != M_8[r]] == [3, 5]
    GA.check("both models satisfy the descent's conditions on representatives", True)


def _ball_share_bounds(D):
    """V_3 / V_D as an interval, V_D = pi^(D/2)/(D/2)! for even D, 2^(k+1) pi^k/(2k+1)!! for D = 2k+1."""
    lo_hi = []
    for pi in (PI_LO, PI_HI):
        if D % 2 == 0:
            k, fac = D // 2, 1
            for j in range(2, k + 1):
                fac *= j
            vd = pi ** k / fac
        else:
            k, dfac = (D - 1) // 2, 1
            for j in range(3, D + 1, 2):
                dfac *= j
            vd = F(2) ** (k + 1) * pi ** k / dfac
        lo_hi.append((F(4) * pi / 3) / vd)
    return min(lo_hi), max(lo_hi)


def check_unit_ball_ratio_differs_between_models():
    """R1 to R3 in their dimension-generic form hold in both models; the ratio 1 + sum_dark V_3/V_D is
    (11 pi + 16)/(3 pi) in M_L (in (5.36, 5.37)) and 1 + 8/3 + 1920/pi^5 in M_8 (in (9.9, 10.0))."""
    out = []
    for M in (M_L, M_8):
        lo, hi = F(0), F(0)
        for r, s in M.items():
            if r == 6:
                continue
            D = s[0] + s[1] - 1
            a, b = _ball_share_bounds(D)
            lo, hi = lo + a, hi + b
        out.append((lo, hi))
    (l1, h1), (l2, h2) = out
    assert F(536, 100) < l1 and h1 < F(537, 100)
    assert F(99, 10) < l2 and h2 < F(10)
    assert (l2 - 1 - F(8, 3), h2 - 1 - F(8, 3)) == (1920 / PI_HI ** 5, 1920 / PI_LO ** 5)
    assert h1 < l2
    # closed forms: V_3/V_2 = 4/3, V_3/V_4 = 8/(3 pi), V_3/V_10 = 160/pi^4, V_3/V_12 = 960/pi^5
    assert _ball_share_bounds(2) == (F(4, 3), F(4, 3))
    assert _ball_share_bounds(4) == (F(8, 3) / PI_HI, F(8, 3) / PI_LO)
    assert _ball_share_bounds(10) == (160 / PI_HI ** 4, 160 / PI_LO ** 4)
    assert _ball_share_bounds(12) == (960 / PI_HI ** 5, 960 / PI_LO ** 5)
    GA.check("unit-ball ratio: M_L about 5.364, M_8 about 9.94", True)


def check_w_admits_m_l_and_not_m_8():
    """(W): a causal tower is admitted iff max(p,q) <= 4 (Lambda > 0). M_L is admitted, M_8 is not: (W)
    is a selector that is not periodic along a residue, and it is not in the premise set."""
    premise("synthesis.frozen-point-complement-window-lowest-causal")
    comp = (1, 4)

    def admitted(s):
        return (s[0] <= comp[0] and s[1] <= comp[1]) or (s[1] <= comp[0] and s[0] <= comp[1])

    assert all(admitted(s) for s in M_L.values())
    assert not any(admitted(M_8[r]) for r in SHIFTED)
    allowed = sorted((p, n - p) for n in range(2, 17) for p in range(n + 1)
                     if causal((p, n - p)) and admitted((p, n - p)))
    assert allowed == [(1, 1), (1, 2), (1, 3), (1, 4), (2, 1), (3, 1), (4, 1)]
    assert sorted(residue(t) for t in allowed) == [0, 1, 2, 3, 5, 6, 7]
    assert [sum(M_8[r]) for r in ODD] == [3, 3, 13, 13]
    # the lowest causal member of each odd residue is the unique admitted causal one up to dimension 16
    for r in ODD:
        hits = [(p, n - p) for n in range(2, 17) for p in range(n + 1)
                if residue((p, n - p)) == r and causal((p, n - p)) and admitted((p, n - p))]
        assert hits == [M_L[r]]
    GA.check("(W) selects M_L and excludes M_8", True)


def field_of(s):
    """Constituent field: the division ring of Cl^0(hatV) = Cl(p+1, q), by its residue (stored rule)."""
    r = (s[0] + 1 - s[1]) % 8
    return "R" if r in (0, 1, 2) else ("C" if r in (3, 7) else "H")


def real_witt_index_of_conformal_space(s):
    p, q = s
    sq = GA.sig(p + 1, q + 1)
    gram = [[GA.dot(GA.gen(i), GA.gen(j), sq) for j in range(len(sq))] for i in range(len(sq))]
    pos, neg, zero = GA.congruence_signature(gram)
    assert zero == 0
    return min(pos, neg)


def check_premise_u_admits_the_shift_only_at_residues_three_and_five():
    """U3: every complex unit that builds a ladder pair lies in the constituent's field. With b = floor((n+2)/2)
    pairs (complex Witt index of hatV) and real Witt index 2, b - 2 pairs need a unit. The field rule
    reproduces the stored table at the lowest members (R at 1, 7; H at 3, 5) and is unchanged by beta. Over
    all causal members up to dimension 21, U3 holds at residues 1 and 7 only at (2,1) and (1,2), and at every
    member of residues 3 and 5. At (1,10) the conformal pseudoscalar is central of square -1 but odd."""
    premise("synthesis.gauge-algebra-by-tower")
    premise("dark-tower-matter.u-transposition-rule")
    premise("dark-tower-matter.constituents-field")
    premise("dark-tower-matter.residue-seven-unit")
    assert [field_of(M_L[r]) for r in (6, 2, 1, 7, 3, 5)] == ["C", "C", "R", "R", "H", "H"]
    admitted = {r: [] for r in ODD}
    for n in range(3, 22):
        for p in range(1, n):
            s = (p, n - p)
            r = residue(s)
            if r not in ODD or not causal(s):
                continue
            assert real_witt_index_of_conformal_space(s) == 2
            assert field_of(s) == field_of(M_L[r])
            b = (n + 2) // 2
            if b == 2 or field_of(s) in ("C", "H"):
                admitted[r].append(s)
    assert admitted[1] == [(2, 1)] and admitted[7] == [(1, 2)]
    assert admitted[3][0] == (4, 1) and admitted[5][0] == (1, 4)
    assert (12, 1) in admitted[3] and (1, 12) in admitted[5]
    assert len(admitted[3]) == 5 and len(admitted[5]) == 5
    # the residue-seven pseudoscalar at (1,10): conformal Cl(2,11), central, square -1, odd grade
    sq = GA.sig(2, 11)
    top = {tuple(range(13)): F(1)}
    assert GA.eq(GA.mul(top, top, sq), GA.sc(-1))
    assert all(GA.commutes(top, GA.gen(i), sq) for i in range(13))
    assert len(next(iter(top))) % 2 == 1
    GA.check("U3 admits only the lowest member at residues 1, 7 and every member at 3, 5", True)


