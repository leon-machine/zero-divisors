"""tower.matrix-amplification-structural-properties: exact checks.

Unital real algebras A are realised exactly as Clifford algebras with the blade engine:
Cl(0,1) = C, Cl(0,2) = H, Cl(1,0) = R + R, Cl(1,1) = Mat_2(R), Cl(0,3) = H + H. Matrices over A are
sparse dicts {(i, j): element}.
  (i)   Z(Mat_m(A)) is computed by exact linear algebra (kernel of the commutators with every
        E_ij 1 and every a 1_m, a a generator of A) and compared with Z(A) 1_m, for five A and
        m = 2, 3;
  (ii)  for A simple (C, H, Mat_2(R)) the two-sided ideal of Mat_2(A) generated by sample nonzero
        elements is all of Mat_2(A) (rank m^2 dim A); control: for A = R + R the ideal generated by
        eps_+ E_11 is proper;
  (iii) the block flattening Phi: Mat_m(Mat_r(D)) -> Mat_mr(D) is a bijection on bases and
        multiplicative on every pair of basis elements, for (m, r, D) = (2, 2, H), (2, 3, C),
        (3, 2, R + R), with the dimensions written out;
  (iv)  for A = A1 + A2 split by a central idempotent (Cl(0,3) = H + H, Cl(1,0) = R + R) the map
        X -> (eps_+ X, eps_- X) is multiplicative on every pair of basis elements of Mat_2(A),
        injective, and onto Mat_2(eps_+ A) + Mat_2(eps_- A), each summand of the stated dimension,
        eps_+ H-part satisfying the quaternion relations.
"""
from fractions import Fraction as F

import GA
from tp_premise import premise  # noqa: F401  (self-contained lemma: no premises)


def alg(p, q):
    sq = GA.sig(p, q)
    return sq, GA.all_blades(p + q)


def mmul(X, Y, sq):
    out = {}
    for (i, k), a in X.items():
        for (k2, j), b in Y.items():
            if k == k2:
                c = GA.mul(a, b, sq)
                if c:
                    out[(i, j)] = GA.add(out.get((i, j), {}), c)
    return {ij: c for ij, c in out.items() if c}


def msub(X, Y):
    out = dict(X)
    for ij, c in Y.items():
        out[ij] = GA.sub(out.get(ij, {}), c)
    return {ij: c for ij, c in out.items() if c}


def mcoords(X, m, blades):
    return [X.get((i, j), {}).get(b, F(0)) for i in range(m) for j in range(m) for b in blades]


def mbasis(m, blades):
    return [{(i, j): {b: F(1)}} for i in range(m) for j in range(m) for b in blades]


def ident(m, a=None):
    a = GA.sc(1) if a is None else a
    return {(i, i): a for i in range(m)}


def centre_of_matrices(m, sq, blades):
    n = len(sq)
    tests = [{(i, j): GA.sc(1)} for i in range(m) for j in range(m)]
    tests += [ident(m, GA.gen(g)) for g in range(n)]
    basis = mbasis(m, blades)
    rows = []
    for T in tests:
        cols = [mcoords(msub(mmul(T, B, sq), mmul(B, T, sq)), m, blades) for B in basis]
        rows.extend([cols[c][r] for c in range(len(basis))] for r in range(len(cols[0])))
    return GA.field_kernel(rows)


def centre_of_alg(sq, blades):
    n = len(sq)
    rows = []
    for g in range(n):
        cols = []
        for b in blades:
            c = GA.sub(GA.mul(GA.gen(g), {b: F(1)}, sq), GA.mul({b: F(1)}, GA.gen(g), sq))
            cols.append([c.get(bb, F(0)) for bb in blades])
        rows.extend([cols[c][r] for c in range(len(blades))] for r in range(len(blades)))
    if not rows:
        return [[F(1)]]
    return GA.field_kernel(rows)


def check_centre_of_matrix_algebra():
    # (p, q) of A, dim Z(A)
    algebras = [((0, 1), 2), ((0, 2), 1), ((1, 0), 2), ((1, 1), 1), ((1, 2), 2)]
    ok = True
    for (p, q), zdim in algebras:
        sq, blades = alg(p, q)
        ZA = centre_of_alg(sq, blades)
        ok = ok and len(ZA) == zdim
        for m in (2, 3):
            ZM = centre_of_matrices(m, sq, blades)
            ok = ok and len(ZM) == zdim
            # every z 1_m (z in Z(A)) is in the computed centre: span unchanged
            emb = []
            for z in ZA:
                zel = {b: c for b, c in zip(blades, z) if c != 0}
                emb.append(mcoords(ident(m, zel), m, blades))
            ok = ok and GA.field_rank(ZM + emb) == zdim
    GA.check("Z(Mat_m(A)) = Z(A) 1_m for five A and m = 2, 3", ok)
    return ok


def ideal_dim(x, m, sq, blades):
    basis = mbasis(m, blades)
    span = []
    for L in basis:
        Lx = mmul(L, x, sq)
        if not Lx:
            continue
        for R in basis:
            y = mmul(Lx, R, sq)
            if y:
                span.append(mcoords(y, m, blades))
    return GA.field_rank(span)


def sample_elements(n):
    """Three nonzero elements of Mat_2(A) of different shapes."""
    return [{(0, 0): GA.sc(1)},
            {(0, 1): GA.add(GA.sc(3), GA.gen(0)), (1, 1): GA.gen(n - 1)},
            {(1, 0): GA.scal(F(1, 2), GA.add(GA.sc(1), GA.gen(0)))}]


def check_matrix_algebra_over_simple_is_simple():
    ok = True
    m = 2
    # (p, q) of A, dim Mat_2(A)
    for (p, q), dimM in (((0, 1), 8), ((0, 2), 16), ((1, 1), 16)):
        sq, blades = alg(p, q)
        for x in sample_elements(p + q):
            ok = ok and ideal_dim(x, m, sq, blades) == dimM
    # control: A = R + R is not simple, and neither is Mat_2(A): eps_+ E_11 generates Mat_2(R)
    sq, blades = alg(1, 0)
    ep = GA.scal(F(1, 2), GA.add(GA.sc(1), GA.gen(0)))
    ok = ok and ideal_dim({(0, 0): ep}, m, sq, blades) == 4
    GA.check("Mat_2(A) simple for A = C, H, Mat_2(R); not for A = R + R", ok)
    return ok


def check_block_flattening():
    ok = True
    # (m, r, (p, q) of D, dim D, dim of Mat_mr(D))
    for m, r, (p, q), dimD, total in ((2, 2, (0, 2), 4, 64), (2, 3, (0, 1), 2, 72),
                                      (3, 2, (1, 0), 2, 72)):
        sq, blades = alg(p, q)
        ok = ok and len(blades) == dimD
        # basis of Mat_m(Mat_r(D)): (i, j, a, b, blade); Phi sends it to ((i r + a), (j r + b), blade)
        B4 = [(i, j, a, c, bl) for i in range(m) for j in range(m) for a in range(r)
              for c in range(r) for bl in blades]
        phi = {e: (e[0] * r + e[2], e[1] * r + e[3], e[4]) for e in B4}
        ok = ok and len(B4) == total and len(set(phi.values())) == total
        ok = ok and set(phi.values()) == {(I, J, bl) for I in range(m * r) for J in range(m * r)
                                         for bl in blades}
        for e in B4:
            for f in B4:
                # product in Mat_m(Mat_r(D)): E_ij(E_ab d) * E_kl(E_cd d') = delta_jk delta_bc E_il(E_ad dd')
                if e[1] == f[0] and e[3] == f[2]:
                    prod = {(e[0], f[1], e[2], f[3]): GA.mul({e[4]: F(1)}, {f[4]: F(1)}, sq)}
                else:
                    prod = {}
                lhs = {}
                for (i, j, a, c), d in prod.items():
                    for bl, co in d.items():
                        lhs[(i * r + a, j * r + c)] = GA.add(lhs.get((i * r + a, j * r + c), {}),
                                                             {bl: co})
                X = {(phi[e][0], phi[e][1]): {phi[e][2]: F(1)}}
                Y = {(phi[f][0], phi[f][1]): {phi[f][2]: F(1)}}
                rhs = mmul(X, Y, sq)
                ok = ok and {k: v for k, v in lhs.items() if v} == rhs
    GA.check("block flattening Mat_m(Mat_r(D)) -> Mat_mr(D) is a multiplicative bijection", ok)
    return ok


def check_matrices_over_direct_sum():
    ok = True
    m = 2
    for (p, q), half in (((0, 3), 4), ((1, 0), 1)):
        sq, blades = alg(p, q)
        n = p + q
        omega = {tuple(range(n)): F(1)}
        ep = GA.scal(F(1, 2), GA.add(GA.sc(1), omega))
        em = GA.scal(F(1, 2), GA.sub(GA.sc(1), omega))
        ok = ok and GA.eq(GA.mul(ep, ep, sq), ep) and GA.is_zero(GA.mul(ep, em, sq))
        ok = ok and GA.eq(GA.add(ep, em), GA.sc(1))
        ok = ok and all(GA.commutes(GA.gen(g), ep, sq) for g in range(n))
        Ep, Em = ident(m, ep), ident(m, em)
        basis = mbasis(m, blades)
        # each summand eps Mat_2(A) has dimension m^2 * dim(eps A)
        for E in (Ep, Em):
            ok = ok and GA.field_rank([mcoords(mmul(E, X, sq), m, blades) for X in basis]) == m * m * half
        # Psi(X) = (eps_+ X, eps_- X): multiplicative on basis pairs, injective
        for X in basis:
            for Y in basis:
                XY = mmul(X, Y, sq)
                for E in (Ep, Em):
                    ok = ok and mmul(E, XY, sq) == mmul(mmul(E, X, sq), mmul(E, Y, sq), sq)
        joint = [mcoords(mmul(Ep, X, sq), m, blades) + mcoords(mmul(Em, X, sq), m, blades)
                 for X in basis]
        ok = ok and GA.field_rank(joint) == len(basis) == 2 * m * m * half
        if half == 4:
            # eps_+ A is a copy of H: eps_+ e1, eps_+ e2 square to -eps_+ and anticommute
            u, v = GA.mul(ep, GA.gen(0), sq), GA.mul(ep, GA.gen(1), sq)
            ok = ok and GA.eq(GA.mul(u, u, sq), GA.neg(ep)) and GA.eq(GA.mul(v, v, sq), GA.neg(ep))
            ok = ok and GA.eq(GA.mul(u, v, sq), GA.neg(GA.mul(v, u, sq)))
    GA.check("Mat_2(A1 + A2) = Mat_2(A1) + Mat_2(A2) via the central idempotents", ok)
    return ok
