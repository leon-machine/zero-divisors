"""odd-extensions.mirror-inside-complexified-extension-absent-doubled: exact checks.

GA.py basis-blade algebra, generators e_1..e_5 = GA indices 0..4, the shadow's e_1..e_4 first and
the extension generator e_5 last. The four single extensions are tested: this world's time and
space extensions Cl(2,3) (e_5^2 = +1) and Cl(1,4) (e_5^2 = -1) of the shadow Cl(1,3), and the
mirror's Cl(4,1) and Cl(3,2) of the shadow Cl(3,1) (roles exchanged, as the last sentence says).
Isomorphism types are fixed exactly: a subalgebra generated by four pairwise anticommuting
elements with squares s is a Clifford algebra of that signature when its dimension is 16, and the
Wedderburn type Mat_k(D) is read off an idempotent whose corner f A f is the division algebra D
(R: one-dimensional; H: quaternion units). Cl(1,3) = Mat_2(H) and Cl(3,1) = Mat_4(R) are thereby
recomputed, not assumed; the claim's use of Fact
odd-extensions.imported-representatives-dimension-nearest-four-types is this non-isomorphism.
(i)-(iii) and the Cl(1,4) clauses are checked in full. (iv) and the non-embedding are checked
through their computable core: the two copies have different corner types (so no automorphism,
and no unital map from the simple Mat_4(R) onto a summand Mat_2(H) of equal dimension); the
step from that to "no automorphism / no embedding" is the proof's simplicity argument.
"""
from fractions import Fraction as F
from itertools import combinations

import GA
from tp_premise import premise

# ---------------------------------------------------------------------------
# Exact Clifford helpers on top of GA.py (elements are dicts {blade: Fraction}).
# ---------------------------------------------------------------------------


def blade_el(b, c=1):
    return {tuple(b): F(c)} if c else {}


def prod(xs, sq):
    out = GA.sc(1)
    for x in xs:
        out = GA.mul(out, x, sq)
    return out


def coords(x, n):
    return [x.get(b, F(0)) for b in GA.all_blades(n)]


def span_rank(els, n):
    els = [e for e in els if not GA.is_zero(e)]
    return GA.rank_of_vectors([coords(e, n) for e in els]) if els else 0


def words(gens, sq):
    """The ordered products of all subsets of gens: they span the generated subalgebra
    when the generators pairwise anticommute and square to nonzero scalars."""
    out = []
    for r in range(len(gens) + 1):
        for idx in combinations(range(len(gens)), r):
            out.append(prod([gens[i] for i in idx], sq))
    return out


def scalar_of(x):
    """x as a scalar if it is one, else None."""
    if GA.is_zero(x):
        return F(0)
    if set(x) == {()}:
        return x[()]
    return None


def anticommuting_with_squares(gens, sq):
    """The list of squares if the gens pairwise anticommute and square to scalars, else None."""
    out = []
    for i, g in enumerate(gens):
        s = scalar_of(GA.mul(g, g, sq))
        if s is None:
            return None
        out.append(s)
        for h in gens[i + 1:]:
            if not GA.anticommutes(g, h, sq):
                return None
    return out


def volume(n, sq):
    return prod([GA.gen(i) for i in range(n)], sq)


def is_central(x, n, sq):
    return all(GA.commutes(x, GA.gen(i), sq) for i in range(n))


def corner(f, basis, sq, n):
    """An independent spanning list of f b f, b in basis."""
    out, vecs = [], []
    for b in basis:
        y = GA.mul(GA.mul(f, b, sq), f, sq)
        if GA.is_zero(y):
            continue
        v = coords(y, n)
        if GA.rank_of_vectors(vecs + [v]) > len(vecs):
            vecs.append(v)
            out.append(y)
    return out


def corner_division_type(f, basis, sq, n):
    """'R', 'C' or 'H' when f is an idempotent whose corner f A f is that division algebra
    (exact: R = span{f}; C = f plus an element squaring to -f; H = quaternion units i, j,
    i j with i^2 = j^2 = -f, i j = -j i), else None. A division corner makes f primitive,
    so the letter is the Wedderburn division algebra of the simple algebra A."""
    if not GA.eq(GA.mul(f, f, sq), f):
        return None
    cb = corner(f, basis, sq, n)
    if len(cb) == 1:
        return "R"
    roots = []
    for b in basis:
        y = GA.mul(GA.mul(f, b, sq), f, sq)
        if not GA.is_zero(y) and GA.eq(GA.mul(y, y, sq), GA.neg(f)):
            roots.append(y)
    if len(cb) == 2 and roots:
        return "C"
    if len(cb) == 4:
        for i, a in enumerate(roots):
            for c in roots[i + 1:]:
                if GA.is_zero(GA.add(GA.mul(a, c, sq), GA.mul(c, a, sq))):
                    if span_rank([f, a, c, GA.mul(a, c, sq)], n) == 4:
                        return "H"
    return None


def idempotent_from(us, sq):
    """prod (1 + u)/2 over commuting elements u with u^2 = 1."""
    f = GA.sc(1)
    for u in us:
        f = GA.mul(f, GA.scal(F(1, 2), GA.add(GA.sc(1), u)), sq)
    return f


def simple_copy_type(gens, sq, n):
    """For a simple subalgebra spanned by words(gens): (k, D) with the subalgebra Mat_k(D),
    found from an idempotent f = prod (1 + u)/2 (u words squaring to 1, commuting) whose corner
    is a division algebra; dim = k^2 dim D is asserted. None if no such f is found."""
    basis = words(gens, sq)
    dim = span_rank(basis, n)
    units = [u for u in basis if scalar_of(u) is None and GA.eq(GA.mul(u, u, sq), GA.sc(1))]
    trials = [[]] + [[u] for u in units]
    trials += [[u, v] for i, u in enumerate(units) for v in units[i + 1:] if GA.commutes(u, v, sq)]
    for us in trials:
        f = idempotent_from(us, sq)
        if GA.is_zero(f):
            continue
        d = corner_division_type(f, basis, sq, n)
        if d is None:
            continue
        dd = {"R": 1, "C": 2, "H": 4}[d]
        k = 1
        while k * k * dd < dim:
            k += 1
        assert k * k * dd == dim
        return (k, d)
    return None

N = 5
SHADOW_THIS = (1, -1, -1, -1)
SHADOW_MIRROR = (-1, 1, 1, 1)


def setting(shadow, s5):
    sq = tuple(shadow) + (s5,)
    e = [GA.gen(i) for i in range(N)]
    return sq, e


def even_part_basis():
    return [blade_el(b) for b in GA.all_blades(N) if len(b) % 2 == 0]


def check_time_extension_of_this_world():
    premise("odd-extensions.doubling-or-complexification")
    premise("odd-extensions.imported-representatives-dimension-nearest-four-types")
    sq, e = setting(SHADOW_THIS, 1)
    ok = True
    # (i) the shadow
    shadow = e[:4]
    ok = ok and anticommuting_with_squares(shadow, sq) == [1, -1, -1, -1]
    A = words(shadow, sq)
    ok = ok and span_rank(A, N) == 16
    # (ii) the translation bivectors
    biv = [GA.mul(e[m], e[4], sq) for m in range(4)]
    ok = ok and anticommuting_with_squares(biv, sq) == [-1, 1, 1, 1]
    B = words(biv, sq)
    ok = ok and span_rank(B, N) == 16
    ok = ok and span_rank(B + even_part_basis(), N) == 16
    # types: shadow Mat_2(H) = Cl(1,3); bivector copy Mat_4(R) = Cl(3,1)
    ok = ok and simple_copy_type(shadow, sq, N) == (2, "H")
    ok = ok and simple_copy_type(biv, sq, N) == (4, "R")
    # (iii) intersection = even part of the shadow, dimension 8, a Pauli algebra Mat_2(C)
    ok = ok and span_rank(A, N) + span_rank(B, N) - span_rank(A + B, N) == 8
    ev = [x for x in A if all(len(b) % 2 == 0 for b in x)]
    ok = ok and span_rank(ev, N) == 8 and span_rank(ev + B, N) == 16
    pauli = [GA.mul(e[0], e[m], sq) for m in (1, 2, 3)]
    ok = ok and anticommuting_with_squares(pauli, sq) == [1, 1, 1]
    j = prod(pauli, sq)
    ok = ok and GA.eq(GA.mul(j, j, sq), GA.sc(-1)) and all(GA.commutes(j, p, sq) for p in pauli)
    ok = ok and span_rank(words(pauli, sq), N) == 8
    # (iii) the spanning statement Cl(2,3) = Cl(1,3) + omega Cl(1,3)
    om = volume(N, sq)
    ok = ok and GA.eq(GA.mul(om, om, sq), GA.sc(-1)) and is_central(om, N, sq)
    ok = ok and span_rank(A + [GA.mul(om, x, sq) for x in A], N) == 32
    # (iv) the Wick map e_mu -> omega e_mu: squares -e_mu^2, anticommuting, a 4-blade copy of Cl(3,1)
    wick = [GA.mul(om, x, sq) for x in shadow]
    ok = ok and anticommuting_with_squares(wick, sq) == [-1, 1, 1, 1]
    ok = ok and all(set(len(b) for b in w) == {4} for w in wick)
    ok = ok and simple_copy_type(wick, sq, N) == (4, "R")
    # complex-linear (commutes with omega) but not multiplicative: (om x)(om y) = -(xy) != om (xy)
    x, y = shadow[0], shadow[1]
    xy = GA.mul(x, y, sq)
    lhs = GA.mul(GA.mul(om, x, sq), GA.mul(om, y, sq), sq)
    ok = ok and GA.eq(lhs, GA.neg(xy)) and not GA.eq(lhs, GA.mul(om, xy, sq))
    GA.check("Cl(2,3): shadow Cl(1,3), bivectors give the even part = Cl(3,1), meet in Mat_2(C), "
             "omega spans, Wick map not an automorphism", ok)
    return ok


def check_space_extension_of_this_world():
    premise("odd-extensions.doubling-or-complexification")
    premise("odd-extensions.imported-representatives-dimension-nearest-four-types")
    sq, e = setting(SHADOW_THIS, -1)
    ok = True
    shadow = e[:4]
    biv = [GA.mul(e[m], e[4], sq) for m in range(4)]
    om = volume(N, sq)
    wick = [GA.mul(om, x, sq) for x in shadow]
    ok = ok and GA.eq(GA.mul(om, om, sq), GA.sc(1)) and is_central(om, N, sq)
    for gens in (shadow, biv, wick):
        ok = ok and anticommuting_with_squares(gens, sq) == [1, -1, -1, -1]
        ok = ok and span_rank(words(gens, sq), N) == 16
        ok = ok and simple_copy_type(gens, sq, N) == (2, "H")
    # the doubling: central idempotents (1 +- omega)/2, each ideal of dimension 16 and of type Mat_2(H)
    P = [GA.scal(F(1, 2), GA.add(GA.sc(1), om)), GA.scal(F(1, 2), GA.sub(GA.sc(1), om))]
    full = [blade_el(b) for b in GA.all_blades(N)]
    for p in P:
        ok = ok and GA.eq(GA.mul(p, p, sq), p) and is_central(p, N, sq)
        ideal = [GA.mul(p, x, sq) for x in full]
        ok = ok and span_rank(ideal, N) == 16
        ok = ok and corner_division_type(GA.mul(p, idempotent_from([e[0]], sq), sq), ideal, sq, N) == "H"
    ok = ok and GA.is_zero(GA.mul(P[0], P[1], sq))
    # each summand is Mat_2(H) (division corner H), while Cl(3,1) = Mat_4(R) (corner R, checked in
    # check_mirror_extensions): an injective unital image of the simple Mat_4(R) in a summand would be
    # all of it (16 = 16), of the wrong type
    GA.check("Cl(1,4): shadow, translation bivectors and omega e_mu all generate Cl(1,3) = Mat_2(H); "
             "omega central with square 1 splits it into two Mat_2(H)", ok)
    return ok


def check_mirror_extensions():
    premise("odd-extensions.doubling-or-complexification")
    premise("odd-extensions.imported-representatives-dimension-nearest-four-types")
    ok = True
    # mirror + time: Cl(4,1), e_5^2 = +1 in the uniform convention; complexified
    sq, e = setting(SHADOW_MIRROR, 1)
    shadow = e[:4]
    biv = [GA.mul(e[m], e[4], sq) for m in range(4)]
    om = volume(N, sq)
    ok = ok and GA.eq(GA.mul(om, om, sq), GA.sc(-1)) and is_central(om, N, sq)
    ok = ok and simple_copy_type(shadow, sq, N) == (4, "R")
    ok = ok and anticommuting_with_squares(biv, sq) == [1, -1, -1, -1]
    ok = ok and simple_copy_type(biv, sq, N) == (2, "H")
    A, B = words(shadow, sq), words(biv, sq)
    ok = ok and span_rank(A, N) + span_rank(B, N) - span_rank(A + B, N) == 8
    ok = ok and span_rank(A + [GA.mul(om, x, sq) for x in A], N) == 32
    wick = [GA.mul(om, x, sq) for x in shadow]
    ok = ok and anticommuting_with_squares(wick, sq) == [1, -1, -1, -1]
    # mirror + space: Cl(3,2), e_5^2 = -1; doubled, every copy is Cl(3,1) = Mat_4(R)
    sq, e = setting(SHADOW_MIRROR, -1)
    shadow = e[:4]
    biv = [GA.mul(e[m], e[4], sq) for m in range(4)]
    om = volume(N, sq)
    wick = [GA.mul(om, x, sq) for x in shadow]
    ok = ok and GA.eq(GA.mul(om, om, sq), GA.sc(1)) and is_central(om, N, sq)
    for gens in (shadow, biv, wick):
        ok = ok and anticommuting_with_squares(gens, sq) == [-1, 1, 1, 1]
        ok = ok and simple_copy_type(gens, sq, N) == (4, "R")
    GA.check("mirror: Cl(4,1) complexified with the bivectors a Cl(1,3); Cl(3,2) doubled with three "
             "copies of Cl(3,1)", ok)
    return ok
