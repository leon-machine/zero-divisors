"""odd-extensions.cosmological-constant-deforms-wall: exact checks.

The family of the proof: in R^{2,4} (GA.py, squares (+,+,-,-,-,-)), the frozen point
I = c e_+ + d e_- with c^2 - d^2 = Lambda/3, sampled at Lambda > 0, < 0 and = 0. For each sample
the complement I^perp is computed as an exact kernel and its signature by congruence; the ascent's
generator is J = d e_+ + c e_-, the direction of the plane orthogonal to I, and with the Lorentz
frame e_0, e_2, e_3, e_4 it spans I^perp. Checked: J^2 = -Lambda/3 (the opposite sign to Lambda)
on every sample, with J anticommuting with the frame; the volume element omega of the algebra
generated by the frame and J is central there with omega^2 = Lambda/3, so it doubles for
Lambda > 0 (central idempotents with ideals of dimension 16, at samples where Lambda/3 is a
rational square) and complexifies for Lambda < 0 (omega/r a central complex unit); at Lambda = 0,
J is proportional to I, I^2 = 0, I lies in I^perp of signature (1,3;1), anticommutes with the
frame, and I Cl(I^perp) is a sixteen-dimensional ideal of square zero.
"""
from fractions import Fraction as F
from itertools import combinations

import GA
from tp_premise import premise

# ---------------------------------------------------------------------------
# Exact Clifford helpers on top of GA.py (elements are dicts {blade: Fraction}).
# ---------------------------------------------------------------------------


def blade_el(b, c=1):
    return {tuple(b): F(c)} if c else {}


def prod(xs, sq):
    out = GA.sc(1)
    for x in xs:
        out = GA.mul(out, x, sq)
    return out


def coords(x, n):
    return [x.get(b, F(0)) for b in GA.all_blades(n)]


def span_rank(els, n):
    els = [e for e in els if not GA.is_zero(e)]
    return GA.rank_of_vectors([coords(e, n) for e in els]) if els else 0


def words(gens, sq):
    """The ordered products of all subsets of gens: they span the generated subalgebra
    when the generators pairwise anticommute and square to nonzero scalars."""
    out = []
    for r in range(len(gens) + 1):
        for idx in combinations(range(len(gens)), r):
            out.append(prod([gens[i] for i in idx], sq))
    return out


def scalar_of(x):
    """x as a scalar if it is one, else None."""
    if GA.is_zero(x):
        return F(0)
    if set(x) == {()}:
        return x[()]
    return None


def anticommuting_with_squares(gens, sq):
    """The list of squares if the gens pairwise anticommute and square to scalars, else None."""
    out = []
    for i, g in enumerate(gens):
        s = scalar_of(GA.mul(g, g, sq))
        if s is None:
            return None
        out.append(s)
        for h in gens[i + 1:]:
            if not GA.anticommutes(g, h, sq):
                return None
    return out


def volume(n, sq):
    return prod([GA.gen(i) for i in range(n)], sq)


def is_central(x, n, sq):
    return all(GA.commutes(x, GA.gen(i), sq) for i in range(n))


def corner(f, basis, sq, n):
    """An independent spanning list of f b f, b in basis."""
    out, vecs = [], []
    for b in basis:
        y = GA.mul(GA.mul(f, b, sq), f, sq)
        if GA.is_zero(y):
            continue
        v = coords(y, n)
        if GA.rank_of_vectors(vecs + [v]) > len(vecs):
            vecs.append(v)
            out.append(y)
    return out


def corner_division_type(f, basis, sq, n):
    """'R', 'C' or 'H' when f is an idempotent whose corner f A f is that division algebra
    (exact: R = span{f}; C = f plus an element squaring to -f; H = quaternion units i, j,
    i j with i^2 = j^2 = -f, i j = -j i), else None. A division corner makes f primitive,
    so the letter is the Wedderburn division algebra of the simple algebra A."""
    if not GA.eq(GA.mul(f, f, sq), f):
        return None
    cb = corner(f, basis, sq, n)
    if len(cb) == 1:
        return "R"
    roots = []
    for b in basis:
        y = GA.mul(GA.mul(f, b, sq), f, sq)
        if not GA.is_zero(y) and GA.eq(GA.mul(y, y, sq), GA.neg(f)):
            roots.append(y)
    if len(cb) == 2 and roots:
        return "C"
    if len(cb) == 4:
        for i, a in enumerate(roots):
            for c in roots[i + 1:]:
                if GA.is_zero(GA.add(GA.mul(a, c, sq), GA.mul(c, a, sq))):
                    if span_rank([f, a, c, GA.mul(a, c, sq)], n) == 4:
                        return "H"
    return None


def idempotent_from(us, sq):
    """prod (1 + u)/2 over commuting elements u with u^2 = 1."""
    f = GA.sc(1)
    for u in us:
        f = GA.mul(f, GA.scal(F(1, 2), GA.add(GA.sc(1), u)), sq)
    return f


def simple_copy_type(gens, sq, n):
    """For a simple subalgebra spanned by words(gens): (k, D) with the subalgebra Mat_k(D),
    found from an idempotent f = prod (1 + u)/2 (u words squaring to 1, commuting) whose corner
    is a division algebra; dim = k^2 dim D is asserted. None if no such f is found."""
    basis = words(gens, sq)
    dim = span_rank(basis, n)
    units = [u for u in basis if scalar_of(u) is None and GA.eq(GA.mul(u, u, sq), GA.sc(1))]
    trials = [[]] + [[u] for u in units]
    trials += [[u, v] for i, u in enumerate(units) for v in units[i + 1:] if GA.commutes(u, v, sq)]
    for us in trials:
        f = idempotent_from(us, sq)
        if GA.is_zero(f):
            continue
        d = corner_division_type(f, basis, sq, n)
        if d is None:
            continue
        dd = {"R": 1, "C": 2, "H": 4}[d]
        k = 1
        while k * k * dd < dim:
            k += 1
        assert k * k * dd == dim
        return (k, d)
    return None
# ---------------------------------------------------------------------------
# The tractor space R^{2,4} in GA.py: index 0 the Lorentz time (+1), 1 = e_+ (+1),
# 2, 3, 4 the Lorentz space (-1), 5 = e_- (-1). The Lorentz frame is 0, 2, 3, 4.
# The frozen point I = c e_+ + d e_- with c^2 - d^2 = Lambda/3, written c = (t+s)/2,
# d = (t-s)/2 so that Lambda = 3 t s; the Stelle-West vector V = (3/Lambda)(d e_+ + c e_-).
# ---------------------------------------------------------------------------
SQ6 = (1, 1, -1, -1, -1, -1)
FRAME = (0, 2, 3, 4)
EP, EM = 1, 5


def vec6(cs):
    return {(i,): F(c) for i, c in enumerate(cs) if c}


def frozen(t, s):
    t, s = F(t), F(s)
    c, d = (t + s) / 2, (t - s) / 2
    return GA.add(GA.scal(c, GA.gen(EP)), GA.scal(d, GA.gen(EM))), 3 * t * s


def stelle_west(t, s):
    t, s = F(t), F(s)
    c, d = (t + s) / 2, (t - s) / 2
    lam = 3 * t * s
    return GA.scal(3 / lam, GA.add(GA.scal(d, GA.gen(EP)), GA.scal(c, GA.gen(EM))))


def vcoords(x):
    return [x.get((i,), F(0)) for i in range(6)]


def perp_basis(vs):
    """A basis of the orthogonal complement in R^{2,4} of the vectors vs (exact kernel)."""
    rows = [[F(SQ6[i]) * vcoords(v)[i] for i in range(6)] for v in vs]
    return [vec6(k) for k in GA.field_kernel(rows)]


def gram_signature(vs):
    return GA.congruence_signature([[GA.dot(a, b, SQ6) for b in vs] for a in vs])

# (t, s) with Lambda = 3 t s; the second list has Lambda / 3 = +-r^2 with r rational
SAMPLES = [(1, 1), (2, F(1, 2)), (5, F(2, 3)), (1, F(-1, 5)), (F(3, 2), -4), (2, 0), (F(-1, 3), 0)]
SQUARES = [((4, 1), 2), ((1, 1), 1), ((1, -1), 1), ((9, -1), 3)]


def ascent_generator(t, s):
    t, s = F(t), F(s)
    c, d = (t + s) / 2, (t - s) / 2
    return GA.add(GA.scal(d, GA.gen(EP)), GA.scal(c, GA.gen(EM)))


def check_generator_square_is_minus_lambda_over_three():
    premise("odd-extensions.are-ascents-pair-signed")
    ok = True
    sigs = set()
    for t, s in SAMPLES:
        I, lam = frozen(t, s)
        J = ascent_generator(t, s)
        ok = ok and GA.dot(I, I, SQ6) == lam / 3
        ok = ok and GA.dot(I, J, SQ6) == 0
        ok = ok and GA.eq(GA.mul(J, J, SQ6), GA.sc(-lam / 3))
        ok = ok and all(GA.anticommutes(J, GA.gen(i), SQ6) for i in FRAME)
        P = perp_basis([I])
        sg = gram_signature(P)
        sigs.add((lam > 0, lam < 0, sg))
        # I^perp is spanned by the frame and J
        frame = [GA.gen(i) for i in FRAME]
        ok = ok and len(P) == 5 and span_rank(P + frame + [J], 6) == 5
        ok = ok and span_rank(frame + [J], 6) == 5
    ok = ok and sigs == {(True, False, (1, 4, 0)), (False, True, (2, 3, 0)), (False, False, (1, 3, 1))}
    GA.check("J^2 = -Lambda/3; I^perp = frame + J of signature (1,4), (2,3), (1,3;1) by the sign of Lambda", ok)
    return ok


def check_omega_square_is_lambda_over_three():
    premise("odd-extensions.are-ascents-pair-signed")
    ok = True
    for t, s in SAMPLES:
        I, lam = frozen(t, s)
        gens = [GA.gen(i) for i in FRAME] + [ascent_generator(t, s)]
        om = prod(gens, SQ6)
        ok = ok and GA.eq(GA.mul(om, om, SQ6), GA.sc(lam / 3))
        ok = ok and all(GA.commutes(om, g, SQ6) for g in gens)
    for (t, s), r in SQUARES:
        I, lam = frozen(t, s)
        gens = [GA.gen(i) for i in FRAME] + [ascent_generator(t, s)]
        alg = words(gens, SQ6)
        u = GA.scal(1 / F(r), prod(gens, SQ6))
        if lam > 0:
            for sg in (1, -1):
                pz = GA.scal(F(1, 2), GA.add(GA.sc(1), GA.scal(sg, u)))
                ok = ok and GA.eq(GA.mul(pz, pz, SQ6), pz)
                ok = ok and span_rank([GA.mul(pz, x, SQ6) for x in alg], 6) == 16
        else:
            ok = ok and GA.eq(GA.mul(u, u, SQ6), GA.sc(-1))
            ok = ok and span_rank(alg + [GA.mul(u, x, SQ6) for x in alg], 6) == 32
        ok = ok and span_rank(alg, 6) == 32
    GA.check("omega^2 = Lambda/3: doubled for Lambda > 0, complexified for Lambda < 0", ok)
    return ok


def check_lambda_zero_degenerate_algebra():
    premise("odd-extensions.are-ascents-pair-signed")
    ok = True
    for t, s in SAMPLES:
        I, lam = frozen(t, s)
        if lam != 0:
            continue
        J = ascent_generator(t, s)
        ok = ok and GA.eq(J, I) and GA.is_zero(GA.mul(I, I, SQ6))
        ok = ok and GA.dot(I, I, SQ6) == 0 and gram_signature(perp_basis([I])) == (1, 3, 1)
        ok = ok and all(GA.anticommutes(I, GA.gen(i), SQ6) for i in FRAME)
        gens = [GA.gen(i) for i in FRAME] + [I]
        alg = words(gens, SQ6)
        ok = ok and span_rank(alg, 6) == 32
        ideal = [GA.mul(I, x, SQ6) for x in alg]
        ok = ok and span_rank(ideal, 6) == 16
        ok = ok and all(GA.is_zero(GA.mul(a, b, SQ6)) for a in ideal for b in ideal)
        ok = ok and all(span_rank(ideal + [GA.mul(x, y, SQ6)], 6) == 16 for x in alg[:6] for y in ideal)
    GA.check("Lambda = 0: Cl(1,3;1) with I nilpotent and I Cl a 16-dimensional ideal of square zero", ok)
    return ok
