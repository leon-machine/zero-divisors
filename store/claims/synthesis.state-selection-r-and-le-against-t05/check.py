"""synthesis.state-selection-r-and-le-against-t05: exact checks.

Boost-flow correlators of a finite window are finite sums of exponentials; every analytic
condition reduces to an algebraic one in Q_k = e^{omega_k p} > 0, kept as a positive rational
parameter, so no exponential is evaluated. States are exact density matrices on the Fock space
in the Jordan-Wigner basis |n_1 n_2>, built from integer matrices; the (L_E) comparison runs in
GA.py's Cl(3,3), one hyperbolic atom per mode.

(i)   one mode, nonzero weight: strict periodicity of both ordered correlators forces n = 1 and
      n = 0 (no state); the gluing reading forces n = 1/(Q + 1), the Gibbs state of
      T05's (R) (KMS uniqueness); at Q = 1 (zero weight) periodicity is empty of content and
      gluing gives n = 1/2.
(ii)  two modes: gluing on the mixed correlators forces <a_1 a_2^dag> = <a_1 a_2> = 0.
(iii) counter-model A: Gibbs marginals plus a coherence c between |10> and |01>: a state
      (positive), T05's (R) holds, the note's (R) fails (<a_1 a_2^dag> = -c, nonzero).
      counter-model B: Gibbs marginals, no coherence, density correlation d: the note's (R)
      holds, <N_1 N_2> - n_1 n_2 = d, nonzero, so the state is not quasi-free (Q fails).
(iv)  (L_E): the algebra generated by sigma_1, sigma_2, sigma_3 has dimension 8, commutes with
      every N_k and contains the cross-point product sigma_1 sigma_2; hopping v_1^* v_2 and
      pairing v_1^* v_2^* lie outside it and fail to commute with N_1.
"""
from fractions import Fraction as F
import GA
import fock
from tp_premise import premise

PREMISES = (
    "singularity.kms-uniqueness-factor",
    "hawking.modular-structure-completed-pair",
    "scrambling.boundary-mode-space-matrix",
    "singularity.number-diagonal-dynamics-models-scrambling-derived",
)


def touch():
    for p in PREMISES:
        premise(p)


def kron(A, B):
    n, m = len(A), len(B)
    return [[A[i // m][j // m] * B[i % m][j % m] for j in range(n * m)] for i in range(n * m)]


mm = GA.mat_mul


def dag(A):
    return [[A[j][i] for j in range(len(A))] for i in range(len(A))]


def tr(A):
    return sum(A[i][i] for i in range(len(A)))


LOWER = [[F(0), F(1)], [F(0), F(0)]]      # |0><1| on (|0>, |1>): annihilation
Z = [[F(1), F(0)], [F(0), F(-1)]]
A1, A2 = [fock.to_dense(fock.ann(k, 2, fock.MSB), 4) for k in range(2)]   # Jordan-Wigner, A1 the leading factor


def expect(rho, X):
    return tr(mm(rho, X))


def gibbs_n(Q):
    return 1 / (Q + 1)


def check_single_mode_readings():
    touch()
    a = LOWER
    want = {F(3): F(1, 4), F(1, 5): F(5, 6), F(7, 2): F(2, 9)}
    for Q, nQ in want.items():
        assert gibbs_n(Q) == nQ
        # rho = diag(1 - n, n); <a a^dag> = 1 - n, <a^dag a> = n
        # strict periodicity: (1/Q - 1)(1 - n) = 0 and (Q - 1) n = 0
        sols = [n for n in (F(0), F(1), F(1, 2), gibbs_n(Q))
                if (1 / Q - 1) * (1 - n) == 0 and (Q - 1) * n == 0]
        assert sols == []
        # gluing: (1/Q)(1 - n) = n, a linear equation with the one root 1/(Q + 1)
        n = gibbs_n(Q)
        rho = [[1 - n, F(0)], [F(0), n]]
        assert expect(rho, mm(a, dag(a))) / Q == expect(rho, mm(dag(a), a))
        assert (1 / Q) * (1 - F(1, 2)) != F(1, 2)
        assert n == F(1, 1) / (Q + 1) and 0 < n < 1
        # the ladder correlators do not see <a>: a coherent marginal glues too, (P) removes it
        c = F(1, 20)
        rc = [[1 - n, c], [c, n]]
        assert expect(rc, mm(a, dag(a))) / Q == expect(rc, mm(dag(a), a))
        assert expect(rc, a) == c and expect(rho, a) == 0
    # zero weight: Q = 1, periodicity holds for every n, gluing forces n = 1/2
    Q = F(1)
    for n in (F(0), F(1, 3), F(1)):
        assert (1 / Q - 1) * (1 - n) == 0 and (Q - 1) * n == 0
    assert [n for n in (F(1, 3), F(1, 2), F(2, 3)) if (1 - n) / Q == n] == [F(1, 2)]
    return True


def state(n1, n2, coh, d):
    """basis |00>, |01>, |10>, |11> (first index mode 1); marginals n1, n2; density shift d; coherence."""
    p11 = n1 * n2 + d
    p10 = n1 - p11
    p01 = n2 - p11
    p00 = 1 - p10 - p01 - p11
    rho = [[F(0)] * 4 for _ in range(4)]
    rho[0][0], rho[1][1], rho[2][2], rho[3][3] = p00, p01, p10, p11
    rho[1][2] = rho[2][1] = coh
    return rho


def positive(rho):
    # block structure: diag entries 0 and 3, and the 2x2 block on |01>, |10>
    return (rho[0][0] >= 0 and rho[3][3] >= 0 and rho[1][1] >= 0 and rho[2][2] >= 0
            and rho[1][1] * rho[2][2] - rho[1][2] * rho[2][1] >= 0)


def mixed_gluing_ok(rho, Q1, Q2):
    ok = True
    for (X, Y, Qy) in ((A1, dag(A2), 1 / Q2), (A1, A2, Q2), (A2, dag(A1), 1 / Q1), (A2, A1, Q1)):
        lhs = Qy * expect(rho, mm(X, Y))           # F(t + ip) coefficient
        rhs = expect(rho, mm(Y, X))                # reversed order
        ok = ok and lhs == rhs
    return ok


def check_two_mode_counter_models():
    touch()
    assert GA.mat_eq(mm(A1, dag(A2)), [[-x for x in row] for row in mm(dag(A2), A1)])   # CAR
    Q1, Q2 = F(3), F(5)
    n1, n2 = gibbs_n(Q1), gibbs_n(Q2)
    assert (n1, n2) == (F(1, 4), F(1, 6))
    # model A: coherence c
    c = F(1, 50)
    rho = state(n1, n2, c, F(0))
    assert tr(rho) == 1 and positive(rho)
    assert rho[1][1] * rho[2][2] - c * c == F(1, 4) * F(5, 6) * F(1, 6) * F(3, 4) - F(1, 2500)
    assert [rho[i][i] for i in range(4)] == [F(5, 8), F(1, 8), F(5, 24), F(1, 24)]
    N1, N2 = mm(dag(A1), A1), mm(dag(A2), A2)
    assert expect(rho, N1) == n1 and expect(rho, N2) == n2          # T05 (R) marginals
    assert expect(rho, mm(A1, dag(A2))) == -c                        # coherence survives
    assert not mixed_gluing_ok(rho, Q1, Q2)                          # note's (R) fails
    G = kron(Z, Z)                                                   # total parity
    assert GA.mat_eq(mm(G, rho), mm(rho, G))                         # even: (P) holds too
    # the product state satisfies the mixed gluing
    assert mixed_gluing_ok(state(n1, n2, F(0), F(0)), Q1, Q2)
    # model B: density correlation d, no coherence
    d = F(1, 100)
    rhoB = state(n1, n2, F(0), d)
    assert tr(rhoB) == 1 and positive(rhoB)
    assert [rhoB[i][i] for i in range(4)] == [F(127, 200), F(23, 200), F(119, 600), F(31, 600)]
    assert expect(rhoB, N1) == n1 and expect(rhoB, N2) == n2
    assert mixed_gluing_ok(rhoB, Q1, Q2)                             # note's (R) holds
    assert expect(rhoB, mm(N1, N2)) - n1 * n2 == d                   # not quasi-free
    return True


def modes(n):
    sq = tuple([1, -1] * n)
    half = F(1, 2)
    v = [GA.scal(half, GA.add(GA.gen(2 * j), GA.gen(2 * j + 1))) for j in range(n)]
    vs = [GA.scal(half, GA.sub(GA.gen(2 * j), GA.gen(2 * j + 1))) for j in range(n)]
    return sq, v, vs


def check_le_pair_same_generators():
    touch()
    sq, v, vs = modes(3)
    sig = [GA.sub(GA.mul(vs[j], v[j], sq), GA.mul(v[j], vs[j], sq)) for j in range(3)]
    N = [GA.mul(vs[j], v[j], sq) for j in range(3)]
    elems = []
    for mask in range(8):
        x = GA.sc(1)
        for j in range(3):
            if mask >> j & 1:
                x = GA.mul(x, sig[j], sq)
        elems.append(x)
    blades = GA.all_blades(6)
    assert len(blades) == 64 and len(sq) == 6 and len(N) == 3 and len(sig) == 3

    def vec(x):
        return [x.get(b, F(0)) for b in blades]
    assert len(elems) == 2 ** 3 == 8
    assert GA.rank_of_vectors([vec(x) for x in elems]) == 8
    grades = sorted(len(next(iter(x))) for x in elems)        # each product is one blade
    assert grades == [0, 2, 2, 2, 4, 4, 4, 6]
    for x in elems:
        for k in range(3):
            assert GA.commutes(x, N[k], sq)
    for k in range(3):
        assert GA.eq(N[k], GA.scal(F(1, 2), GA.add(GA.sc(1), sig[k])))     # N = (1 + sigma)/2
    cross = GA.mul(sig[0], sig[1], sq)
    assert GA.rank_of_vectors([vec(x) for x in elems] + [vec(cross)]) == 8
    hop = GA.mul(vs[0], v[1], sq)
    pair = GA.mul(vs[0], vs[1], sq)
    for y in (hop, pair):
        assert len(y) == 4 and set(abs(c) for c in y.values()) == {F(1, 4)}
    for y in (hop, pair):
        assert GA.rank_of_vectors([vec(x) for x in elems] + [vec(y)]) == 9
        assert not GA.commutes(y, N[0], sq)
    return True
