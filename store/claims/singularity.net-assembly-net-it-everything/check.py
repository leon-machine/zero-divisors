"""singularity.net-assembly-net-it-everything: exact checks in the mode algebras Cl(N,N) (GA blade engine).

Mode y has generators e_(2y) (square +1) and e_(2y+1) (square -1), ladder v_y = (e_(2y) + e_(2y+1))/2,
v_y^* = (e_(2y) - e_(2y+1))/2 and parity section sigma_y = e_(2y) e_(2y+1) (square 1). The big fibre
B_x = Fix(Ad sigma_x) is spanned by the blades with an even number of the indices 2x, 2x+1.
(1) Ad(sigma_x) fixes v_y, v_y^* for y != x and negates them at y = x (N = 3, all x, y).
(2) J(F), the algebra generated by the big fibres, is everything for |F| >= 2: for N = 2, 3 the products of
    pairs of elements of the union of the B_x already reach all 4^N blades (rank 16, 64). Control: for
    N = 1, B_x is the 2-dimensional even part, a subalgebra, so J is not the 4-dimensional mode algebra.
(3) Isotony: F = {0, 1} in F' = {0, 1, 2}: every blade of B_x(F) commutes with sigma_x in Cl(3,3), so
    B_x(F) is in B_x(F') and J(F) in J(F'). There are no restriction maps of algebras J(F') -> J(F): Cl(3,3)
    is simple (its 64 blades have pairwise distinct commutation signs against the six generators, so only
    the scalar blade is central, and each blade squares to +-1; averaging x with e_i x e_i^{-1} then isolates
    any blade component of a nonzero element of a two-sided ideal, so the ideal contains 1, shown explicitly
    for three sample elements), so a unital homomorphism Cl(3,3) -> J(F) has zero kernel and would be
    injective, impossible as 64 > 16. No homomorphism is searched for.
(4) The algebra generated by B_x alone is B_x (closed under products, dimension 2^(2N-1)) and contains
    v_y for y != x, odd at y, and the product of the v_y over y != x, odd at every other point (N = 3).
The two-level discrepancy is not recomputed: it vanishes because J(F) is the whole algebra, which is (2).
"""
from fractions import Fraction as F

import GA


def sq(N):
    return tuple(s for _ in range(N) for s in (1, -1))


def ladder(y):
    a, b = GA.gen(2 * y), GA.gen(2 * y + 1)
    return GA.scal(F(1, 2), GA.add(a, b)), GA.scal(F(1, 2), GA.sub(a, b))


def sigma(y):
    return {(2 * y, 2 * y + 1): F(1)}


def big_fibre(x, N):
    return [b for b in GA.all_blades(2 * N) if (b.count(2 * x) + b.count(2 * x + 1)) % 2 == 0]


def conj(s, v, S):
    return GA.mul(GA.mul(s, v, S), s, S)          # sigma^-1 = sigma


def check_parity_sections_act_locally():
    ok = True
    N = 3
    S = sq(N)
    for x in range(N):
        ok = ok and GA.mul(sigma(x), sigma(x), S) == GA.sc(1)
        for y in range(N):
            for v in ladder(y):
                ok = ok and conj(sigma(x), v, S) == (GA.neg(v) if x == y else v)
    GA.check("Ad(sigma_x) fixes v_y for y != x and negates v_x", ok)
    return ok


def generated_blades(N, points):
    S = sq(N)
    union = sorted({b for x in points for b in big_fibre(x, N)})
    reached = set(union)
    for a in union:
        for b in union:
            s, c = GA.blade_mul(a, b, S)
            if s != 0:
                reached.add(c)
    return union, reached


def check_net_assembly_is_everything():
    ok = True
    sizes = []
    for N in (2, 3):
        union, reached = generated_blades(N, range(N))
        sizes.append(len(reached))
    ok = ok and sizes == [16, 64]
    union1, reached1 = generated_blades(1, [0])
    ok = ok and len(reached1) == 2 and len(union1) == 2
    GA.check("J(F) is the whole mode algebra for |F| = 2, 3; a single point gives only the even part", ok)
    return ok


def check_isotony_and_no_restriction():
    ok = True
    S3 = sq(3)
    for x in (0, 1):
        ok = ok and all(GA.commutes({b: F(1)}, sigma(x), S3) for b in big_fibre(x, 2))
    central = [b for b in GA.all_blades(6) if all(GA.commutes(GA.gen(i), {b: F(1)}, S3) for i in range(6))]
    ok = ok and central == [()]
    ok = ok and len(GA.all_blades(6)) == 64 and len(GA.all_blades(4)) == 16
    # simplicity of Cl(3,3): distinct characters, invertible blades, ideal generated by a sample contains 1
    blades = GA.all_blades(6)
    chars = {tuple(GA.commutes(GA.gen(i), {b: F(1)}, S3) for i in range(6)) for b in blades}
    ok = ok and len(chars) == 64
    ok = ok and all(GA.mul({b: F(1)}, {b: F(1)}, S3) in ({(): F(1)}, {(): F(-1)}) for b in blades)
    inv = {i: GA.scal(F(1, S3[i]), GA.gen(i)) for i in range(6)}
    samples = [{(0, 1): F(2), (2,): F(-3), (1, 3, 5): F(1, 2)},
               {(): F(1), (0, 2, 4): F(5), (1, 2, 3, 4, 5): F(-1)},
               {(3,): F(7), (0, 1, 2, 3, 4, 5): F(1, 3), (2, 5): F(4)}]
    for x in samples:
        target = max(x)                                          # one blade in the support
        y = x
        for i in range(6):                                       # keep the components with target's sign at e_i
            sgn = 1 if GA.commutes(GA.gen(i), {target: F(1)}, S3) else -1
            y = GA.scal(F(1, 2), GA.add(y, GA.scal(sgn, GA.mul(GA.mul(GA.gen(i), y, S3), inv[i], S3))))
        ok = ok and y == {target: x[target]}                     # an element of the ideal of x
        tinv = GA.scal(1 / GA.mul({target: F(1)}, {target: F(1)}, S3)[()], {target: F(1)})
        ok = ok and GA.eq(GA.scal(1 / x[target], GA.mul(y, tinv, S3)), GA.sc(1))
    GA.check("isotone: B_x(F) in B_x(F'); Cl(3,3) simple with centre R, dimension 64 > 16", ok)
    return ok


def check_stalk_contains_odd_elements():
    ok = True
    N = 3
    S = sq(N)
    for x in range(N):
        Bx = big_fibre(x, N)
        ok = ok and len(Bx) == 32
        closed = all(GA.blade_mul(a, b, S)[1] in Bx for a in Bx for b in Bx)
        ok = ok and closed
        others = [y for y in range(N) if y != x]
        prod = GA.sc(1)
        for y in others:
            v = ladder(y)[0]
            ok = ok and all(b in Bx for b in v)
            ok = ok and conj(sigma(y), v, S) == GA.neg(v)
            prod = GA.mul(prod, v, S)
        ok = ok and all(b in Bx for b in prod)
        ok = ok and all(conj(sigma(y), prod, S) == GA.neg(prod) for y in others)
    GA.check("the algebra of one big fibre is B_x (dimension 32) and holds elements odd at every other point", ok)
    return ok
