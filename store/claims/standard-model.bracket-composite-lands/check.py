"""standard-model.bracket-composite-lands: exact checks.

Model: the five-mode module (pair modes 0, 1, 2; rung modes 3, 4, the text's 4 and 5), v_i creation, w_i
annihilation, as exact sparse matrices; Y = N_R/2 - N_W/3, T3 = (N_4 - N_5)/2; the frozen point
I = a v_1 + b w_1 (a = 2, b = 3), lifted rung components c_4 = -w_4 + lam v_4 (lam = 1/7), c_5 = -w_5, the
bracket b = v_4 v_5 and b^dag = w_5 w_4. Mass forms: f(X)(psi, phi) = B(psi, X phi) on the sixteen even states,
B the top-degree pairing with the reversal sign, symmetrised; species by (rung, pair) occupation.
(i) The algebra generated by I, c_4, c_5, b, b^dag (closed under products from 1) has dimension 32; the sixteen
    ordered monomials in v_4, w_4, v_5, w_5 span Cl_R (dimension 16); Cl_R and I Cl_R together span the
    algebra and meet only in zero (16 + 16 = 32).
(ii) The commutant of su(3) (the six v_i w_j, i != j pairs) inside the algebra has dimension 16 and is Cl_R.
(iii) The odd monomials of Cl_R with ad-weights Y = -1/2 and T3 = -1/2 span a two-dimensional space, spanned by
    w_4 and w_4 N_5.
(iv) f(w_4 N_5) = (1/2) f(w_4); f(w_4) couples only (L, e^c) and (Q, d^c), with equal magnitudes 1 (the 10
    form, |y_e| = |y_d|); b^dag v_5 = -w_4 + w_4 N_5 and its form is -(1/2) f(w_4).
(v) T_GJ = w_4 (B - L) chi (B - L = 1 - (2/3) N_W, chi = -(-1)^{N_R}) has a form outside the span of the
    forms of w_4 and w_4 N_5 (rank 1 -> 2); the pair bivector sum_i v_i ^ w_i is not in the algebra
    (rank 32 -> 33).
"""
from fractions import Fraction as F
from itertools import combinations

import GA
from pyutil import get_or_set
from tp_premise import premise

# ---------------------------------------------------------------------------
# The five-mode module Lambda(W + R_2) = Lambda(C^5), exact (sparse matrices {(row, col): Fraction}).
# Modes 0, 1, 2 are the pair modes (W), modes 3, 4 the two rung (slot) modes, the text's modes 4 and 5.
# v_i = creation (wedge), w_i = annihilation (contraction), v_i w_i + w_i v_i = 1.
# ---------------------------------------------------------------------------
NM = 5
PAIRS5, RUNGS5 = (0, 1, 2), (3, 4)
STATES = [frozenset(S) for k in range(NM + 1) for S in combinations(range(NM), k)]
SIDX = {S: i for i, S in enumerate(STATES)}
DIM5 = len(STATES)


def sp_from_action(act):
    M = {}
    for S in STATES:
        for T, c in act(S).items():
            if c != 0:
                M[(SIDX[T], SIDX[S])] = M.get((SIDX[T], SIDX[S]), F(0)) + c
    return {k: v for k, v in M.items() if v != 0}


def sp_mul(A, B):
    Bc = {}
    for (i, j), b in B.items():
        get_or_set(Bc, i, []).append((j, b))
    C = {}
    for (i, k), a in A.items():
        for j, b in Bc.get(k, ()):
            C[(i, j)] = C.get((i, j), F(0)) + a * b
    return {k: v for k, v in C.items() if v != 0}


def sp_add(*Ms):
    C = {}
    for M in Ms:
        for k, v in M.items():
            C[k] = C.get(k, F(0)) + v
    return {k: v for k, v in C.items() if v != 0}


def sp_scal(c, M):
    return {k: c * v for k, v in M.items() if c * v != 0}


def sp_eq(A, B):
    return sp_add(A, sp_scal(F(-1), B)) == {}


def sp_apply(M, vec):
    out = {}
    for (i, j), a in M.items():
        if j in vec:
            out[i] = out.get(i, F(0)) + a * vec[j]
    return {k: v for k, v in out.items() if v != 0}


ID5 = {(i, i): F(1) for i in range(DIM5)}
V5 = [sp_from_action(lambda S, i=i: GA.ext_wedge(i, {S: F(1)})) for i in range(NM)]
W5 = [sp_from_action(lambda S, i=i: GA.ext_contract([F(1) if j == i else F(0) for j in range(NM)], {S: F(1)}))
      for i in range(NM)]


def num(i):
    return sp_mul(V5[i], W5[i])


RUNG4, RUNG5 = 3, 4                          # the text's rung modes 4 and 5 are modes 3 and 4 here


N_W = sp_add(*[num(i) for i in PAIRS5])
N_R = sp_add(*[num(i) for i in RUNGS5])
HYP = sp_add(sp_scal(F(1, 2), N_R), sp_scal(F(-1, 3), N_W))
T3 = sp_scal(F(1, 2), sp_add(num(3), sp_scal(F(-1), num(4))))
SU3 = [sp_mul(V5[i], W5[j]) for i in PAIRS5 for j in PAIRS5 if i != j]
SU2 = [sp_mul(V5[3], W5[4]), sp_mul(V5[4], W5[3]), T3]


def comm(A, B):
    return sp_add(sp_mul(A, B), sp_scal(F(-1), sp_mul(B, A)))


def weight(M, Q):
    """The eigenvalue of ad Q on M, or None if M is not an eigenvector."""
    c = comm(Q, M)
    if c == {}:
        return F(0)
    (i, j), a = next(iter(M.items()))
    q = c.get((i, j), F(0)) / a
    return q if sp_eq(c, sp_scal(q, M)) else None


def basis5(S):
    return {SIDX[frozenset(S)]: F(1)}

A_, B_, LAM = F(2), F(3), F(1, 7)
SIXTEEN = [S for S in STATES if len(S) % 2 == 0]
FULL5 = frozenset(range(NM))


def species(S):
    nr, nw = len(S & set(RUNGS5)), len(S & set(PAIRS5))
    return {(0, 0): "nu^c", (2, 0): "e^c", (1, 1): "Q", (1, 3): "L", (0, 2): "u^c", (2, 2): "d^c"}.get((nr, nw), "odd")


def eps_sign5(S):
    seq = sorted(S) + sorted(FULL5 - S)
    return F(-1) ** sum(1 for a in range(len(seq)) for b in range(a + 1, len(seq)) if seq[a] > seq[b])


BCOEF5 = {S: F(-1) ** (len(S) * (len(S) - 1) // 2) * eps_sign5(S) for S in STATES}


def bpair5(psi, phi):
    return sum((BCOEF5[S] * psi.get(SIDX[S], F(0)) * phi.get(SIDX[FULL5 - S], F(0)) for S in STATES), F(0))


def yukawa(T):
    mat = {}
    for S in SIXTEEN:
        for U in SIXTEEN:
            val = bpair5(basis5(S), sp_apply(T, basis5(U)))
            if val != 0:
                mat[(S, U)] = val
    return mat


def sym(mat):
    keys = set(mat) | {(b, a) for a, b in mat}
    out = {k: F(1, 2) * (mat.get(k, F(0)) + mat.get((k[1], k[0]), F(0))) for k in keys}
    return {k: v for k, v in out.items() if v != 0}


def species_blocks(f):
    out = {}
    for (S, U), v in f.items():
        get_or_set(out, tuple(sorted((species(S), species(U)))), set()).add(abs(v))
    return out


class Span:
    """Incremental row echelon over sparse dict vectors."""

    def __init__(self):
        self.rows = []

    def reduce(self, x):
        x = dict(x)
        for piv, row in self.rows:
            c = x.get(piv)
            if c:
                for k, v in row.items():
                    x[k] = x.get(k, F(0)) - c * v
                x = {k: v for k, v in x.items() if v != 0}
        return x

    def add(self, x):
        r = self.reduce(x)
        if not r:
            return False
        piv = min(r)
        c = r[piv]
        self.rows.append((piv, {k: v / c for k, v in r.items()}))
        return True

    def __len__(self):
        return len(self.rows)


def rank_of(ops):
    s = Span()
    for M in ops:
        s.add(M)
    return len(s)


def generators():
    Iop = sp_add(sp_scal(A_, V5[0]), sp_scal(B_, W5[0]))
    c4 = sp_add(sp_scal(F(-1), W5[3]), sp_scal(LAM, V5[3]))
    c5 = sp_scal(F(-1), W5[4])
    brk = sp_mul(V5[3], V5[4])
    brk_d = sp_mul(W5[4], W5[3])
    return Iop, [Iop, c4, c5, brk, brk_d]


def algebra_basis(gens):
    s = Span()
    s.add(ID5)
    basis = [ID5]
    frontier = [ID5]
    while frontier:
        new = []
        for x in frontier:
            for g in gens:
                y = sp_mul(x, g)
                if s.add(y):
                    basis.append(y)
                    new.append(y)
        frontier = new
    return basis


def rung_monomials():
    ops = [V5[3], W5[3], V5[4], W5[4]]
    out = []
    for k in range(5):
        for idx in combinations(range(4), k):
            M = ID5
            for t in idx:
                M = sp_mul(M, ops[t])
            out.append(M)
    return out


def check_algebra_is_rung_clifford_plus_frozen_point_multiple():
    premise("standard-model.hyp-s-slot-statistics")
    ok = True
    Iop, gens = generators()
    basis = algebra_basis(gens)
    ok = ok and len(basis) == 32
    clr = rung_monomials()
    ok = ok and rank_of(clr) == 16
    iclr = [sp_mul(Iop, X) for X in clr]
    ok = ok and rank_of(clr + iclr) == 32 and rank_of(basis + clr + iclr) == 32
    ok = ok and sp_eq(sp_mul(Iop, Iop), sp_scal(A_ * B_, ID5))
    _tp_rv = (ok); assert _tp_rv is not False, "check_algebra_is_rung_clifford_plus_frozen_point_multiple"; return _tp_rv


def check_colour_singlet_part_is_rung_clifford():
    premise("standard-model.hyp-s-slot-statistics")
    ok = True
    _, gens = generators()
    basis = algebra_basis(gens)
    keys = sorted({k for X in SU3 for M in basis for k in comm(X, M)})
    comms = [[comm(X, M) for M in basis] for X in SU3]
    rows = [[c.get(k, F(0)) for c in cs] for cs in comms for k in keys]
    # keep an independent set of rows (the kernel only depends on their span)
    s = Span()
    rows = [r for r in rows if s.add({i: v for i, v in enumerate(r) if v != 0})]
    ker = GA.field_kernel(rows)
    ok = ok and len(ker) == 16
    inv = [sp_add(*[sp_scal(c, M) for c, M in zip(v, basis) if c != 0]) for v in ker]
    clr = rung_monomials()
    ok = ok and rank_of(inv + clr) == 16
    _tp_rv = (ok); assert _tp_rv is not False, "check_colour_singlet_part_is_rung_clifford"; return _tp_rv


def check_doublet_direction_and_mass_forms():
    premise("standard-model.hyp-s-slot-statistics")
    ok = True
    parity = ID5
    for i in range(NM):
        parity = sp_mul(parity, sp_add(ID5, sp_scal(F(-2), num(i))))
    odd = [M for M in rung_monomials() if M and sp_add(sp_mul(parity, M), sp_mul(M, parity)) == {}]
    doublet = [M for M in odd if weight(M, HYP) == F(-1, 2) and weight(M, T3) == F(-1, 2)]
    w4 = W5[3]
    w4N5 = sp_mul(w4, num(4))
    ok = ok and rank_of(doublet) == 2 and rank_of(doublet + [w4, w4N5]) == 2
    f10, fN5 = sym(yukawa(w4)), sym(yukawa(w4N5))
    ok = ok and fN5 == {k: F(1, 2) * v for k, v in f10.items()}
    ok = ok and species_blocks(f10) == {("L", "e^c"): {F(1)}, ("Q", "d^c"): {F(1)}}
    comp = sp_mul(sp_mul(W5[4], W5[3]), V5[4])
    ok = ok and sp_eq(comp, sp_add(sp_scal(F(-1), w4), w4N5))
    ok = ok and sym(yukawa(comp)) == {k: F(-1, 2) * v for k, v in f10.items()}
    _tp_rv = (ok); assert _tp_rv is not False, "check_doublet_direction_and_mass_forms"; return _tp_rv


def check_126_direction_and_pair_bivector_outside():
    premise("standard-model.hyp-s-slot-statistics")
    ok = True
    w4 = W5[RUNG4]
    w4N5 = sp_mul(w4, num(RUNG5))
    chi = sp_scal(F(-1), sp_mul(sp_add(ID5, sp_scal(F(-2), num(RUNG4))), sp_add(ID5, sp_scal(F(-2), num(RUNG5)))))
    BmL = sp_add(ID5, sp_scal(F(-2, 3), N_W))
    # chi = -(-1)^{N_R}: an involution, -1 on the rung vacuum, anticommuting with the rung mode w_4
    empty, full = SIDX[frozenset()], SIDX[FULL5]
    ok = ok and sp_eq(sp_mul(chi, chi), ID5) and chi.get((empty, empty)) == -1
    ok = ok and sp_eq(sp_add(sp_mul(chi, w4), sp_mul(w4, chi)), {})
    # B - L = 1 - (2/3) N_W by hand: 1 with no pair mode occupied, 1 - 2 = -1 with all three occupied
    ok = ok and BmL.get((empty, empty)) == 1 and BmL.get((full, full)) == -1
    TGJ = sp_mul(w4, sp_mul(BmL, chi))
    forms = [sym(yukawa(w4)), sym(yukawa(w4N5)), sym(yukawa(TGJ))]
    keys = sorted({k for f in forms for k in f}, key=lambda k: tuple(sorted(x) for x in k))
    vecs = [[f.get(k, F()) for k in keys] for f in forms]
    ok = ok and GA.rank_of_vectors(vecs[:2]) == 1 and GA.rank_of_vectors(vecs) == 2
    _, gens = generators()
    basis = algebra_basis(gens)
    pairbiv = sp_add(*[sp_scal(F(1, 2), sp_add(sp_mul(V5[i], W5[i]), sp_scal(F(-1), sp_mul(W5[i], V5[i]))))
                       for i in PAIRS5])
    # by hand: v_i w_i - w_i v_i = 2 N_i - 1, so the pair bivector is N_W - 3/2
    ok = ok and sp_eq(pairbiv, sp_add(N_W, sp_scal(F(-3, 2), ID5)))
    ok = ok and rank_of(basis + [pairbiv]) == 33
    _tp_rv = (ok); assert _tp_rv is not False, "check_126_direction_and_pair_bivector_outside"; return _tp_rv
