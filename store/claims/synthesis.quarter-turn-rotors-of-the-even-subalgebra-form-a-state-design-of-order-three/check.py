"""synthesis.quarter-turn-rotors-of-the-even-subalgebra-form-a-state-design-of-order-three: exact checks.

Setting: Cl(p,q), p + q = 2N, with pseudoscalar I of square -1; E the even subalgebra, D = 2^(N-1). A class is a
pair {S, complement of S} of even index sets; its hermitian unit h is the one of e_S, I e_S (up to sign) of square
+1. Gamma is generated by the conjugations by 1 + I h (quarter-turn rotors, unnormalised).
(1) The group: its order in Cl(1,3) and Cl(6,0); each generator acts on the units as a signed transvection; orbits on
    classes and on ordered commuting pairs in Cl(1,3), Cl(3,1), Cl(6,0) and Cl(7,1).
(2) The two identities of a state (a rational idempotent of scalar part 1/D): sum of squares and the product rule.
(3) Averages over Gamma of degree at most three in the coordinates of a state, on a blade state and a generic one,
    against the closed values and against the permutation formula of the imported moments.
(4) The mean purity of a matrix factor against the imported value.
"""
from fractions import Fraction as F
from itertools import combinations, permutations

import GA
from tp_premise import premise

ONE = GA.sc(1)
SIGNATURES_SMALL = ((1, 3), (3, 1), (6, 0))
EXPECTED_ORDER = {(1, 3): 24, (3, 1): 24, (6, 0): 11520}


def key(x):
    return tuple(sorted((b, c) for b, c in x.items() if c != 0))


def nonzero(x):
    return {b: c for b, c in x.items() if c != 0}


class Even(object):
    """Hermitian units, generators and the signed action of the quarter-turn rotors for Cl(p,q)."""

    def __init__(self, p, q):
        self.SQ = GA.sig(p, q)
        self.n = p + q
        self.D = 2 ** (self.n // 2 - 1)
        I = ONE
        for i in range(self.n):
            I = GA.mul(I, GA.gen(i), self.SQ)
        self.I = I
        self.units = []
        seen = set()
        for r in range(0, self.n + 1, 2):
            for S in combinations(range(self.n), r):
                comp = tuple(i for i in range(self.n) if i not in S)
                if S in seen or comp in seen:
                    continue
                seen.add(S)
                seen.add(comp)
                b = ONE
                for i in S:
                    b = GA.mul(b, GA.gen(i), self.SQ)
                h = b if GA.eq(self.m(b, b), ONE) else GA.mul(I, b, self.SQ)
                self.units.append(h)
        self.nz = self.units[1:]
        self.index = {}
        for i, h in enumerate(self.nz):
            self.index[key(h)] = (i, 1)
            self.index[key(GA.neg(h))] = (i, -1)

    def m(self, *xs):
        r = xs[0]
        for x in xs[1:]:
            r = GA.mul(r, x, self.SQ)
        return r

    def rotor_action(self, c):
        """Signed permutation of the nonzero units under conjugation by 1 + I h_c."""
        k = self.m(self.I, self.nz[c])
        up, down = GA.add(ONE, k), GA.sub(ONE, k)
        return tuple(self.index[key(GA.scal(F(1, 2), self.m(up, t, down)))] for t in self.nz)

    def product_sign(self, c, d):
        """(e, eps) with h_c h_d = eps h_e for commuting distinct units, None otherwise."""
        prod = self.m(self.nz[c], self.nz[d])
        return self.index.get(key(prod))

    def group(self):
        gens = [self.rotor_action(c) for c in range(len(self.nz))]
        ident = tuple((i, 1) for i in range(len(self.nz)))
        seen = {ident}
        frontier = [ident]
        while frontier:
            new = []
            for g in frontier:
                for h in gens:
                    x = tuple((h[j][0], h[j][1] * s) for (j, s) in g)
                    if x not in seen:
                        seen.add(x)
                        new.append(x)
            frontier = new
        return gens, seen

    def coordinates(self, rho):
        return [self.D * self.m(rho, h).get((), F(0)) for h in self.nz]

    def blade_state(self):
        comm = []
        for h in self.nz:
            if all(GA.commutes(h, c, self.SQ) for c in comm):
                trial = ONE
                for c in comm + [h]:
                    trial = GA.scal(F(1, 2), self.m(trial, GA.add(ONE, c)))
                if trial.get((), F(0)) == F(1, 2 ** (len(comm) + 1)):
                    comm.append(h)
            if 2 ** len(comm) == self.D:
                break
        rho = ONE
        for c in comm:
            rho = GA.scal(F(1, 2), self.m(rho, GA.add(ONE, c)))
        return rho

    def generic_state(self):
        rho = self.blade_state()
        steps = (F(1, 2), F(2, 3), F(3, 5), F(1, 3), F(5, 7), F(2, 5))
        for j, t in enumerate(steps):
            k = self.m(self.I, self.nz[(5 * j + 1) % len(self.nz)])
            V = GA.add(ONE, GA.scal(t, k))
            Vinv = GA.scal(1 / (1 + t * t), GA.sub(ONE, GA.scal(t, k)))
            rho = self.m(V, rho, Vinv)
        return rho


def orbits(points, moves):
    left = set(points)
    out = []
    while left:
        start = next(iter(left))
        orb = {start}
        frontier = [start]
        while frontier:
            new = []
            for pnt in frontier:
                for mv in moves:
                    y = mv(pnt)
                    if y not in orb:
                        orb.add(y)
                        new.append(y)
            frontier = new
        out.append(orb)
        left -= orb
    return out


def check_group_is_finite_and_transitive_on_classes_and_commuting_pairs():
    premise("synthesis.signed-directions-and-the-integer-clifford-algebra")
    ok = True
    for sgn in SIGNATURES_SMALL + ((7, 1),):
        A = Even(*sgn)
        ok &= GA.eq(A.m(A.I, A.I), GA.sc(-1))
        ok &= len(A.nz) == A.D * A.D - 1
        ok &= all(GA.commutes(A.I, h, A.SQ) for h in A.nz)
        m = len(A.nz)
        acts = [A.rotor_action(c) for c in range(m)]
        anti = [[not GA.commutes(A.nz[c], A.nz[d], A.SQ) for d in range(m)] for c in range(m)]
        # a generator is the transvection of its class: fixed if commuting, moved to the product class otherwise
        for c in range(m):
            for d in range(m):
                image = acts[c][d][0]
                if anti[c][d]:
                    prod = A.m(A.I, A.nz[d], A.nz[c])
                    ok &= A.index[key(prod)][0] == image and image != d
                else:
                    ok &= acts[c][d] == (d, 1)
        ok &= len(orbits(range(m), [lambda x, a=a: a[x][0] for a in acts])) == 1
        pairs = [(c, d) for c in range(m) for d in range(m) if c != d and not anti[c][d]]
        if A.D > 2:
            ok &= len(orbits(pairs, [lambda pr, a=a: (a[pr[0]][0], a[pr[1]][0]) for a in acts])) == 1
            # ordered commuting pairs with a given product: D^2/2 - 2 of them
            count = sum(1 for (c, d) in pairs if A.product_sign(c, d)[0] == 0)
            ok &= 2 * count == A.D * A.D - 4
        else:
            ok &= pairs == []
        if sgn in EXPECTED_ORDER:
            ok &= len(A.group()[1]) == EXPECTED_ORDER[sgn]
    GA.check("the rotor group is finite and transitive on classes and commuting pairs", ok)
    return ok


def check_two_identities_of_a_state():
    premise("synthesis.signed-directions-and-the-integer-clifford-algebra")
    ok = True
    for sgn in SIGNATURES_SMALL:
        A = Even(*sgn)
        for rho in (A.blade_state(), A.generic_state()):
            ok &= GA.eq(nonzero(A.m(rho, rho)), nonzero(rho))
            ok &= rho.get((), F(0)) == F(1, A.D)
            x = A.coordinates(rho)
            rebuilt = GA.scal(F(1, A.D), GA.add(ONE, *[GA.scal(x[i], h) for i, h in enumerate(A.nz)]))
            ok &= GA.eq(nonzero(rebuilt), nonzero(rho))
            ok &= sum(v * v for v in x) == A.D - 1
            for u in range(len(A.nz)):
                total = F(0)
                for c in range(len(A.nz)):
                    for d in range(len(A.nz)):
                        if c != d and GA.commutes(A.nz[c], A.nz[d], A.SQ):
                            e, eps = A.product_sign(c, d)
                            if e == u:
                                total += eps * x[c] * x[d]
                ok &= total == (A.D - 2) * x[u]
    GA.check("sum of squares and product rule of a state", ok)
    return ok


def complex_trace(A, x):
    """Trace over the D-dimensional module as (real part, I part)."""
    return (A.D * x.get((), F(0)), -A.D * A.m(x, A.I).get((), F(0)))


def invariant_moment(A, hs):
    """sum over permutations of products of cycle traces, over D (D+1) ... (D+n-1): the imported formula."""
    n = len(hs)
    total = [F(0), F(0)]
    for perm in permutations(range(n)):
        seen = set()
        term = (F(1), F(0))
        for start in range(n):
            if start in seen:
                continue
            cyc = []
            j = start
            while j not in seen:
                seen.add(j)
                cyc.append(j)
                j = perm[j]
            prod = ONE
            for j in cyc:
                prod = A.m(prod, hs[j])
            tr = complex_trace(A, prod)
            term = (term[0] * tr[0] - term[1] * tr[1], term[0] * tr[1] + term[1] * tr[0])
        total[0] += term[0]
        total[1] += term[1]
    den = 1
    for l in range(n):
        den *= A.D + l
    return total[0] / den, total[1] / den


def check_moments_to_order_three_equal_the_invariant_ones():
    premise("synthesis.signed-directions-and-the-integer-clifford-algebra")
    premise("synthesis.imported-haar-moments-of-random-pure-state")
    ok = True
    for sgn in ((1, 3), (6, 0)):
        A = Even(*sgn)
        gens, group = A.group()
        G = len(group)
        m = len(A.nz)
        D = A.D
        triples = []
        for c in range(m):
            for d in range(m):
                if c != d:
                    hit = A.index.get(key(A.m(A.nz[c], A.nz[d])))
                    if hit is None:
                        hit = A.index[key(A.m(A.I, A.nz[c], A.nz[d]))]
                    triples.append((c, d, hit[0]))
        triples += [(c, c, c) for c in range(m)] + [(c, c, (c + 1) % m) for c in range(m)]
        triples += [(c, (c + 1) % m, (c + 2) % m) for c in range(m)]
        triples = sorted(set(triples))
        for rho in (A.blade_state(), A.generic_state()):
            x = A.coordinates(rho)
            first = [F(0)] * m
            second = [[F(0)] * m for _ in range(m)]
            third = dict((t, F(0)) for t in triples)
            for g in group:
                y = [g[i][1] * x[g[i][0]] for i in range(m)]
                for a in range(m):
                    ya = y[a]
                    first[a] += ya
                    if ya != 0:
                        row = second[a]
                        for b in range(m):
                            row[b] += ya * y[b]
                for t in triples:
                    third[t] += y[t[0]] * y[t[1]] * y[t[2]]
            ok &= all(v == 0 for v in first)
            for a in range(m):
                for b in range(m):
                    want = F(1, D + 1) if a == b else F(0)
                    ok &= second[a][b] / G == want
                    ok &= invariant_moment(A, [A.nz[a], A.nz[b]]) == (want, 0)
            for (c, d, e) in triples:
                closed = F(0)
                if c != d and GA.commutes(A.nz[c], A.nz[d], A.SQ):
                    hit = A.product_sign(c, d)
                    if hit[0] == e:
                        closed = F(2 * hit[1], (D + 1) * (D + 2))
                ok &= third[(c, d, e)] / G == closed
                ok &= invariant_moment(A, [A.nz[c], A.nz[d], A.nz[e]]) == (closed, 0)
    GA.check("group averages to order three equal the closed and the imported values", ok)
    return ok


def check_mean_purity_of_a_matrix_factor_is_the_imported_value():
    # the imported value is the n = 2 case of the all-moment Fact (Lubkin's mean purity)
    premise("synthesis.imported-haar-moments-of-random-pure-state")
    ok = True
    # closed form for every pair of powers of two
    for r in range(1, 7):
        for s in range(0, 7):
            m, n = 2 ** r, 2 ** s
            D = m * n
            ok &= F(1, m) * (1 + (m * m - 1) * F(1, D + 1)) == F(m + n, m * n + 1)
            ok &= (D * D - 1) * F(1, D + 1) == D - 1
            if D > 2:
                ok &= (D * D - 4) * F(2, (D + 1) * (D + 2)) == 2 * (D - 2) * F(1, D + 1)
    # Cl(6,0): a factor spanned by two anticommuting units and their product (m = n = 2)
    A = Even(6, 0)
    gens, group = A.group()
    x = A.coordinates(A.generic_state())
    c = 0
    d = next(j for j in range(len(A.nz)) if not GA.commutes(A.nz[0], A.nz[j], A.SQ))
    e = A.index[key(A.m(A.I, A.nz[c], A.nz[d]))][0]
    factor = (c, d, e)
    ok &= len(set(factor)) == 3
    ok &= all(not GA.commutes(A.nz[a], A.nz[b], A.SQ) for a in factor for b in factor if a != b)
    total = F(0)
    for g in group:
        total += F(1, 2) * (1 + sum(x[g[i][0]] ** 2 for i in factor))
    ok &= total / len(group) == F(2 + 2, 2 * 2 + 1)
    GA.check("mean purity of a matrix factor is (m + n)/(m n + 1)", ok)
    return ok


def grade_of(x):
    return max(len(b) for b, c in x.items() if c != 0)


def check_generators_are_rotors_only_for_bivector_blades():
    premise("synthesis.signed-directions-and-the-integer-clifford-algebra")
    ok = True
    expected = {(6, 0): [15], (7, 1): [7, 21, 35], (10, 0): [45, 210]}
    grade_counts = {(6, 0): {2: 15}, (7, 1): {2: 21, 4: 35, 6: 7}, (10, 0): {2: 45, 6: 210}}
    for sgn in sorted(expected):
        A = Even(*sgn)
        m = len(A.nz)
        ks = [A.m(A.I, h) for h in A.nz]
        counts = {}
        for k in ks:
            counts[grade_of(k)] = counts.get(grade_of(k), 0) + 1
        ok &= counts == grade_counts[sgn]
        for k in ks:
            R = GA.add(ONE, k)
            norm = nonzero(A.m(R, GA.reverse(R)))
            if grade_of(k) == 4:
                ok &= GA.eq(norm, nonzero(GA.scal(F(2), k)))
            else:
                ok &= GA.eq(norm, GA.sc(2))
        bivector = [c for c in range(m) if grade_of(ks[c]) == 2]
        acts = [A.rotor_action(c) for c in bivector]
        sizes = sorted(len(o) for o in orbits(range(m), [lambda x, a=a: a[x][0] for a in acts]))
        ok &= sizes == expected[sgn]
    GA.check("bivector generators are rotors and alone are transitive only up to six generators", ok)
    return ok


def check_invariant_mixtures_and_the_parity_sector_corollary():
    premise("synthesis.signed-directions-and-the-integer-clifford-algebra")
    ok = True
    # closed form of the corollary: d_A d_B = 2 D
    for a in range(1, 7):
        for b in range(1, 7):
            dA, dB = 2 ** a, 2 ** b
            D = F(dA * dB, 2)
            ok &= F(1, dA) * (1 + (F(dA * dA, 2) - 1) / (D + 1)) == F(dA + dB, dA * dB + 2)
    for sgn, modes, want in (((1, 3), (1, 2), F(2, 3)), ((6, 0), (0, 1), F(3, 5)), ((6, 0), (0, 1, 2, 3), F(3, 5))):
        A = Even(*sgn)
        gens, group = A.group()
        G = len(group)
        dA = 2 ** (len(modes) // 2)
        inside = []
        for r in range(2, len(modes) + 1, 2):
            for S in combinations(modes, r):
                b = ONE
                for i in S:
                    b = GA.mul(b, GA.gen(i), A.SQ)
                hit = A.index.get(key(b))
                if hit is None:
                    hit = A.index[key(A.m(A.I, b))]
                inside.append(hit[0])
        ok &= len(set(inside)) == dA * dA // 2 - 1
        states = (A.blade_state(), A.generic_state())
        means = []
        for rho in states:
            x = A.coordinates(rho)
            total = F(0)
            for g in group:
                total += F(1, dA) * (1 + sum(x[g[i][0]] ** 2 for i in inside))
            means.append(total / G)
        ok &= means == [want, want]
        ok &= want == F(dA + 2 * A.D // dA, 2 * A.D + 2)
        # a Gamma-invariant measure: the mixture of two orbits with weights 1/3 and 2/3 has the same second moment
        xs = [A.coordinates(rho) for rho in states]
        c = inside[0]
        mix = F(0)
        for weight, x in ((F(1, 3), xs[0]), (F(2, 3), xs[1])):
            mix += weight * sum(x[g[c][0]] ** 2 for g in group) / G
        ok &= mix == F(1, A.D + 1)
    GA.check("parity-sector purity (d_A + d_B)/(d_A d_B + 2) and invariant mixtures", ok)
    return ok
