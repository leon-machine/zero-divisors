"""synthesis.tower-charge-sector-label-temperature-not: exact checks.

Window: two boundary modes per tower (this tower: modes 0, 1; the mirror: modes 2, 3), realised
as a_j = (e_j + f_j)/2 in Cl(4,4) (e_j^2 = +1, f_j^2 = -1), so the CAR relations hold over the
rationals; the scalar part is the normalised trace of Cl(4,4) = Mat(16, R). Observables of the
pair are the elements invariant under each tower's charge rotation (the tower charge is
superselected); they are generated by the bilinears a_i^* a_j with i, j in one tower. A Gibbs
factor exp(-beta w N) is 1 + (x - 1) N with x = exp(-beta w) an exact rational.
"""
from fractions import Fraction as F
from itertools import product
import GA
from GA import mul, add, sub, scal, sc, gen
from tp_premise import premise

NM = 4
SQ = tuple([1] * NM + [-1] * NM)
TOWERS = ((0, 1), (2, 3))


def a(j):
    return scal(F(1, 2), add(gen(j), gen(NM + j)))


def ad(j):
    return scal(F(1, 2), sub(gen(j), gen(NM + j)))


def m(*xs):
    out = sc(1)
    for x in xs:
        out = mul(out, x, SQ)
    return out


def num(j):
    return m(ad(j), a(j))


def tr(x):
    return x.get((), F(0))


def one_minus(x):
    return sub(sc(1), x)


def charge_projections(t):
    """Spectral projections of the tower charge N_i + N_j on charge 0, 1, 2."""
    i, j = TOWERS[t]
    Ni, Nj = num(i), num(j)
    return [m(one_minus(Ni), one_minus(Nj)),
            add(m(Ni, one_minus(Nj)), m(one_minus(Ni), Nj)),
            m(Ni, Nj)]


def bilinears():
    return [m(ad(i), a(j)) for t in TOWERS for i in t for j in t]


def gibbs(xs):
    rho = sc(1)
    for j, xj in enumerate(xs):
        rho = mul(rho, add(sc(1), scal(xj - 1, num(j))), SQ)
    return rho


def expval(rho, X):
    return tr(mul(rho, X, SQ)) / tr(rho)


def reduce(x, pivots):
    """Reduce the multivector x against an echelon basis {pivot blade: row}."""
    x = dict(x)
    for b, row in pivots.items():
        c = x.get(b, F(0))
        if c != 0:
            x = sub(x, scal(c, row))
    return x


def generated_dimension(gens):
    """Dimension of the unital algebra generated by gens: close {1} under left multiplication by
    the generators, keeping an exact echelon basis of the span."""
    pivots = {}
    frontier = []

    def insert(y):
        r = reduce(y, pivots)
        if not r:
            return False
        b = min(r)
        r = scal(1 / r[b], r)
        for k in list(pivots):
            c = pivots[k].get(b, F(0))
            if c != 0:
                pivots[k] = sub(pivots[k], scal(c, r))
        pivots[b] = r
        return True
    insert(sc(1))
    frontier = [sc(1)]
    while frontier:
        new = []
        for x in frontier:
            for g in gens:
                y = mul(g, x, SQ)
                if insert(y):
                    new.append(y)
        frontier = new
    return len(pivots)


def check_car_window():
    premise("synthesis.imported-powers-stormer-takesaki-disjointness")
    premise("hawking.imported-quasi-free-states-car-algebra")
    for i, j in product(range(NM), range(NM)):
        anti = add(m(a(i), ad(j)), m(ad(j), a(i)))
        assert anti == (sc(1) if i == j else {})
        assert add(m(a(i), a(j)), m(a(j), a(i))) == {}


def check_charge_is_sector_label():
    """Charge projections are central in the observable window algebra, sum to one, and the
    observable algebra is the direct sum of full matrix algebras over the joint charge sectors:
    dimension sum over (q, q') of (d_q d_q')^2 = (1 + 4 + 1)^2 = 36."""
    premise("synthesis.imported-powers-stormer-takesaki-disjointness")
    premise("dark-matter.superselected-hence-dark-exactly-stable")
    premise("dark-matter.stored-asymmetry-charge-not-number")
    premise("dark-matter.mirror-tower-copy-one")
    gens = bilinears()
    for t in range(2):
        P = charge_projections(t)
        assert add(*P) == sc(1)
        for q, Pq in enumerate(P):
            assert m(Pq, Pq) == Pq and Pq != {} and Pq != sc(1)
            assert all(GA.commutes(Pq, g, SQ) for g in gens)
            assert tr(Pq) * 4 == [1, 2, 1][q]
    assert generated_dimension(gens) == 36
    # states of different charge are separated by a central projection
    P, Pp = charge_projections(0), charge_projections(1)
    sec = m(P[1], Pp[1])
    rho1 = m(gibbs([F(1, 2), F(1, 3), F(1, 2), F(1, 3)]), sec)
    rho2 = m(gibbs([F(1, 2), F(1, 3), F(1, 2), F(1, 3)]), m(P[2], Pp[1]))
    assert expval(rho1, sec) == 1 and expval(rho2, sec) == 0


def check_temperature_not_sector_label():
    """Gibbs states of the pair at two clocks (x for this tower, x' for the mirror) give positive
    weight to every joint charge sector and are invertible, so no central projection of the
    observable window algebra separates two temperatures; the mirror's occupation differs."""
    premise("synthesis.imported-powers-stormer-takesaki-disjointness")
    premise("hawking.i-state")
    premise("synthesis.cold-mirror-needs-non-equilibrium-descent")
    premise("synthesis.mirror-asymmetry-route-one")
    x = F(1, 3)
    for xp in (F(1, 3), F(1, 50), F(2, 7)):
        xs = [x, x * x, xp, xp * xp]
        rho = gibbs(xs)
        inv = gibbs([1 / y for y in xs])
        assert m(rho, inv) == sc(1)
        P, Pp = charge_projections(0), charge_projections(1)
        w = [expval(rho, m(P[q], Pp[qq])) for q in range(3) for qq in range(3)]
        assert all(v > 0 for v in w) and sum(w) == 1
        nmir = expval(rho, num(2))
        assert nmir == xp / (1 + xp)
        assert (nmir == F(1, 4)) == (xp == x)


def affinity_sq_lt_one(n, k):
    """a^2 < 1 for a = sqrt(n k) + sqrt((1-n)(1-k)), as the rational inequality
    4 n k (1-n)(1-k) < (n + k - 2 n k)^2 (both sides of 2 sqrt(X) < 1 - nk - (1-n)(1-k) >= 0)."""
    lhs = 4 * n * k * (1 - n) * (1 - k)
    rhs = (n + k - 2 * n * k) ** 2
    return lhs < rhs, lhs == rhs


def one_minus_a_le_gap(n, k):
    """1 - a <= |n - k|, as a rational inequality: a^2 >= (1 - d)^2 with d = |n - k|."""
    d = abs(n - k)
    base = n * k + (1 - n) * (1 - k)
    need = (1 - d) ** 2 - base
    if need <= 0:
        return True
    return 4 * n * k * (1 - n) * (1 - k) >= need * need


def check_mode_affinity():
    """Per mode, Fermi-Dirac occupations n = x/(1+x) at x = exp(-beta w): the Hellinger affinity
    is < 1 exactly when the clocks differ, and 1 - a <= |n - n'|."""
    premise("synthesis.imported-powers-stormer-takesaki-disjointness")
    premise("hawking.i-state")
    premise("hawking.imported-quasi-free-states-car-algebra")
    xs = [F(1, 2), F(1, 3), F(2, 9), F(1, 50), F(7, 8), F(3), F(1, 1000)]
    for x, y in product(xs, xs):
        n, k = x / (1 + x), y / (1 + y)
        lt, eq = affinity_sq_lt_one(n, k)
        assert lt == (x != y) and eq == (x == y)
        assert one_minus_a_le_gap(n, k)
    # a band of K modes at one frequency: the Powers-Stormer sum is K (1 - a), and (1 - a) has a
    # positive rational lower bound, (1 - a^2)/2 <= 1 - a, with 1 - a^2 > 0 rational-bounded below
    n, k = F(1, 3), F(1, 4)
    lt, _ = affinity_sq_lt_one(n, k)
    assert lt
    gap = (n + k - 2 * n * k) ** 2 - 4 * n * k * (1 - n) * (1 - k)
    assert gap == F(1, 144) and gap > 0


