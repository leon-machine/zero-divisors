"""interior.boosts-generate-exactly-levi-factor: exact checks.

Cl(2,4) in GA.py with the squares (e_0, e_1, e_2, e_3, e_+, e_-) = (+1, -1, -1, -1, +1, -1), so
W = span(e_0..e_3) has signature (1,3) and the null pair n_inf = e_+ + e_-, n_0 = (e_+ - e_-)/2 spans its
orthogonal complement. Bivectors are the grade-2 part; the bracket is the commutator product
A x B = (AB - BA)/2, under which Lambda^2 V = so(2,4). Boosts B_i = e_0 ^ e_i, rotations R_ij = e_i ^ e_j.
(1) The bracket rule [u ^ v, v ^ w] = Q(v) u ^ w for orthogonal frame vectors, and brackets of wedges
    sharing no factor vanish, on all pairs of frame bivectors; [B_1, B_2] = -R_12, [B_2, B_3] = -R_23,
    [B_3, B_1] = -R_31.
(2) The Lie algebra generated by {B_1, B_2, B_3}, computed by iterated brackets until the span is
    stable, has dimension 6 and equals span{e_a ^ e_b : a < b <= 3} = Lambda^2 W (rank of the union 6),
    contains R_12, R_13, R_23, and every element of it has zero coefficient on every blade containing
    e_+ or e_-, i.e. no component along n_inf ^ W, n_0 ^ W or n_inf ^ n_0 (these 9 directions span
    exactly the blades with an e_+ or e_- letter, rank 9).
"""
from fractions import Fraction as F
from itertools import combinations

import GA

SQ = (1, -1, -1, -1, 1, -1)
PAIRS = [(a, b) for a in range(6) for b in range(a + 1, 6)]


def w(a, b):
    x, y = GA.gen(a), GA.gen(b)
    return GA.scal(F(1, 2), GA.sub(GA.mul(x, y, SQ), GA.mul(y, x, SQ)))


def br(A, B):
    return GA.scal(F(1, 2), GA.sub(GA.mul(A, B, SQ), GA.mul(B, A, SQ)))


def coords(B):
    return [B.get(p, F(0)) for p in PAIRS]


def check_bracket_rule_and_boost_brackets():
    for (a, b) in PAIRS:
        for (c, d) in PAIRS:
            got = br(w(a, b), w(c, d))
            shared = set((a, b)) & set((c, d))
            if not shared:
                assert GA.is_zero(got)
            elif len(shared) == 1 and b == c:
                assert GA.eq(got, GA.scal(F(SQ[b]), w(a, d)))
    B = {i: w(0, i) for i in (1, 2, 3)}
    assert GA.eq(br(B[1], B[2]), GA.neg(w(1, 2)))
    assert GA.eq(br(B[2], B[3]), GA.neg(w(2, 3)))
    assert GA.eq(br(B[3], B[1]), GA.neg(w(3, 1)))
    return True


def check_boosts_generate_exactly_lambda2_w():
    span = [w(0, i) for i in (1, 2, 3)]
    while True:
        new = [br(x, y) for x in span for y in span]
        cand = span[:]
        for z in new:
            if GA.rank_of_vectors([coords(t) for t in cand + [z]]) > len(cand):
                cand.append(z)
        if len(cand) == len(span):
            break
        span = cand
    assert len(span) == 6
    l2w = [w(a, b) for a, b in combinations(range(4), 2)]
    assert GA.rank_of_vectors([coords(t) for t in span + l2w]) == 6
    for R in (w(1, 2), w(1, 3), w(2, 3)):
        assert GA.rank_of_vectors([coords(t) for t in span + [R]]) == 6
    for x in span:
        assert all(4 not in blade and 5 not in blade for blade in x)
    ninf = GA.add(GA.gen(4), GA.gen(5))
    n0 = GA.scal(F(1, 2), GA.sub(GA.gen(4), GA.gen(5)))
    assert GA.dot(ninf, n0, SQ) == 1 and GA.dot(ninf, ninf, SQ) == 0 and GA.dot(n0, n0, SQ) == 0
    outside = [br(ninf, GA.gen(a)) for a in range(4)] + [br(n0, GA.gen(a)) for a in range(4)] + [br(ninf, n0)]
    assert GA.rank_of_vectors([coords(t) for t in outside]) == 9
    assert GA.rank_of_vectors([coords(t) for t in outside + l2w]) == 15
    return True
