"""singularity.modular-structure-completed-pair: exact checks.

Completed pairs (v, v*) satisfying the CAR, in the blade engine: the hyperbolic atom of Cl(1,1)
(v = (e0 + e1)/2, v* = (e0 - e1)/2), its rescalings (lambda v, v*/lambda), and the pair
((e1 + e3)/2, (e1 - e3)/2) in Cl(2,2); and the Fock (defining) representation v = E_12, v* = E_21.
sigma := v* v - v v*.
(1) sigma^2 = 1 in every realisation, and sigma = e0 e1 exactly in the atom.
(2) R_lambda = exp(lambda sigma/2) = c + s sigma with (c, s) = (cosh, sinh)(lambda/2) at rational
points c^2 - s^2 = 1 (both signs of lambda): R v R^{-1} = (c - s)^2 v = e^{-lambda} v and
R v* R^{-1} = (c + s)^2 v* = e^{+lambda} v*, with (c - s)^2 (c + s)^2 = 1.
(3) (1 + sigma)/2 = v* v and (1 - sigma)/2 = v v*, the descent projectors P, 1 - P of the premise.
(4) Fock: sigma = 2N - 1 with N = v* v = diag(0, 1), so K = sigma/2 = N - 1/2.
(5) Cl(1,1): the even subalgebra is span{1, e0 e1} (dimension 2) and its bivector space is
one-dimensional (the rotor group has two components: -1 is a rotor outside the exponential branch), so every one-parameter real rotor flow is generated by a multiple of sigma, and the
rotors a + b sigma satisfy R R~ = a^2 - b^2. The mode algebra Mat_2(C) has a 3-dimensional real space
of traceless Hermitian generators (computed as a kernel), the three-parameter family of the scope
sentence.
"""
from fractions import Fraction as F

import GA
from GA import QI
from tp_premise import premise

RAPIDITIES = [(F(5, 3), F(4, 3)), (F(5, 4), F(3, 4)), (F(13, 12), F(5, 12)), (F(5, 3), F(-4, 3)),
              (F(17, 15), F(8, 15))]
SCALES = [F(1), F(2), F(-3, 7)]


def pairs():
    out = []
    sq = GA.sig(1, 1)
    e0, e1 = GA.gen(0), GA.gen(1)
    for lam in SCALES:
        out.append((GA.scal(lam / 2, GA.add(e0, e1)), GA.scal(1 / (2 * lam), GA.sub(e0, e1)), sq))
    sq22 = GA.sig(2, 2)
    f1, f3 = GA.gen(1), GA.gen(3)
    out.append((GA.scal(F(1, 2), GA.add(f1, f3)), GA.scal(F(1, 2), GA.sub(f1, f3)), sq22))
    return out


def car(v, vs, sq):
    return (GA.is_zero(GA.mul(v, v, sq)) and GA.is_zero(GA.mul(vs, vs, sq))
            and GA.eq(GA.add(GA.mul(v, vs, sq), GA.mul(vs, v, sq)), GA.sc(1)))


def sigma_of(v, vs, sq):
    return GA.sub(GA.mul(vs, v, sq), GA.mul(v, vs, sq))


def check_sigma_is_unit_boost_bivector():
    premise("singularity.pseudo-inverse-identities-hyperbolic-atom")
    for v, vs, sq in pairs():
        assert car(v, vs, sq)
        s = sigma_of(v, vs, sq)
        assert GA.eq(GA.mul(s, s, sq), GA.sc(1)) and not GA.eq(s, GA.sc(1))
    v, vs, sq = pairs()[0]
    assert sigma_of(v, vs, sq) == {(0, 1): F(1)}
    assert GA.eq(sigma_of(v, vs, sq), GA.mul(GA.gen(0), GA.gen(1), sq))


def check_rotor_flow_opposite_weights():
    premise("std-algebra.bivector-exponential")
    count = 0
    # the series collapses: sigma^(2k) = 1 and sigma^(2k+1) = sigma
    for v, vs, sq in pairs():
        s = sigma_of(v, vs, sq)
        pw = GA.sc(1)
        for k in range(1, 7):
            pw = GA.mul(pw, s, sq)
            assert GA.eq(pw, s if k % 2 else GA.sc(1))
    for v, vs, sq in pairs():
        s = sigma_of(v, vs, sq)
        for c, sh in RAPIDITIES:
            assert c * c - sh * sh == 1
            R = GA.add(GA.sc(c), GA.scal(sh, s))
            Ri = GA.sub(GA.sc(c), GA.scal(sh, s))
            assert GA.eq(GA.mul(R, Ri, sq), GA.sc(1))
            em, ep = (c - sh) ** 2, (c + sh) ** 2
            assert em * ep == 1
            assert GA.eq(GA.mul(GA.mul(R, v, sq), Ri, sq), GA.scal(em, v))
            assert GA.eq(GA.mul(GA.mul(R, vs, sq), Ri, sq), GA.scal(ep, vs))
            count += 1
    assert count == 20
    # at (cosh, sinh)(lambda/2) = (5/3, 4/3): e^{-lambda} = 1/9
    v, vs, sq = pairs()[0]
    s = sigma_of(v, vs, sq)
    R = GA.add(GA.sc(F(5, 3)), GA.scal(F(4, 3), s))
    Ri = GA.sub(GA.sc(F(5, 3)), GA.scal(F(4, 3), s))
    assert GA.eq(GA.mul(GA.mul(R, v, sq), Ri, sq), GA.scal(F(1, 9), v))


def check_spectral_projectors_are_descent_projectors():
    premise("singularity.descent-what-it-erases")
    for v, vs, sq in pairs():
        s = sigma_of(v, vs, sq)
        P = GA.mul(vs, v, sq)
        assert GA.eq(GA.scal(F(1, 2), GA.add(GA.sc(1), s)), P)
        assert GA.eq(GA.scal(F(1, 2), GA.sub(GA.sc(1), s)), GA.mul(v, vs, sq))
        assert GA.eq(GA.mul(P, P, sq), P)
    # Fock representation: sigma = 2N - 1 = diag(-1, 1), K = N - 1/2
    V = [[F(0), F(1)], [F(0), F(0)]]
    VS = [[F(0), F(0)], [F(1), F(0)]]
    mm = lambda A, B: [[sum(A[i][t] * B[t][j] for t in range(2)) for j in range(2)] for i in range(2)]
    N = mm(VS, V)
    sig = [[mm(VS, V)[i][j] - mm(V, VS)[i][j] for j in range(2)] for i in range(2)]
    assert N == [[0, 0], [0, 1]]
    assert sig == [[2 * N[i][j] - (1 if i == j else 0) for j in range(2)] for i in range(2)]
    assert [[sig[i][j] / 2 for j in range(2)] for i in range(2)] == [[F(-1, 2), 0], [0, F(1, 2)]]


def check_rotor_flow_unique_within_real_rotors():
    premise("std-algebra.bivector-exponential")
    blades = GA.all_blades(2)
    assert len([b for b in blades if len(b) == 2]) == 1
    assert len([b for b in blades if len(b) % 2 == 0]) == 2
    sq = GA.sig(1, 1)
    s = GA.mul(GA.gen(0), GA.gen(1), sq)
    for a, b in ((F(5, 3), F(4, 3)), (F(2), F(1))):
        R = GA.add(GA.sc(a), GA.scal(b, s))
        assert GA.mul(R, GA.reverse(R), sq) == {(): a * a - b * b}
    # two components: -1 = e0(-e0) is a rotor with scalar part -1, while every exp(l sigma/2) =
    # cosh + sigma sinh lies on the branch c > 0 of c^2 - s^2 = 1 (c = 1 at l = 0, c never 0 on the
    # hyperbola, so by continuity c > 0), hence c >= 1
    e0 = GA.gen(0)
    m1 = GA.mul(e0, GA.neg(e0), sq)
    a1 = m1.get((), F(0))
    assert GA.eq(GA.mul(m1, GA.reverse(m1), sq), GA.sc(1))
    assert a1 * a1 - m1.get((0, 1), F(0)) ** 2 == 1 and a1 <= -1
    for c, sh in RAPIDITIES:
        assert c * c - sh * sh == 1 and c > 0
        assert c >= 1 and a1 < c
        R = GA.add(GA.sc(c), GA.scal(sh, s))
        assert not GA.eq(R, m1) and GA.eq(GA.mul(R, GA.reverse(R), sq), GA.sc(1))
    # Mat_2(C): real dimension of {H = H^dagger, tr H = 0}; unknowns (Re, Im) of the 4 entries
    rows = []
    for i in range(2):
        for j in range(2):
            # H_ij - conj(H_ji) = 0: real and imaginary parts
            re = [F(0)] * 8
            im = [F(0)] * 8
            re[2 * (2 * i + j)] += 1
            re[2 * (2 * j + i)] -= 1
            im[2 * (2 * i + j) + 1] += 1
            im[2 * (2 * j + i) + 1] += 1
            rows += [re, im]
    trr = [F(0)] * 8
    tri = [F(0)] * 8
    trr[0] = trr[6] = F(1)
    tri[1] = tri[7] = F(1)
    rows += [trr, tri]
    assert len(GA.field_kernel(rows)) == 3
