"""hawking.modular-structure-completed-pair: exact checks.

The hyperbolic atom Cl(1,1) (e0^2 = 1, e1^2 = -1), v = (e0 + e1)/2, v* = (e0 - e1)/2, and, for the
CAR-only clauses, two further completed pairs: the rescaled atom (2v, v*/2) and ((e1 + e3)/2,
(e1 - e3)/2) in Cl(2,2). sigma := v* v - v v*.
(1) sigma^2 = 1; in the atom sigma = e0 e1; relabelling the pair (v <-> v*) gives -sigma.
(2) R_lambda = cosh(lambda/2) + sinh(lambda/2) sigma at rational points (c, s), c^2 - s^2 = 1:
R v R^{-1} = (c - s)^2 v = e^{-lambda} v and R v* R^{-1} = (c + s)^2 v* = e^{+lambda} v*; sigma v =
-v, v sigma = v, sigma v* = v*, v* sigma = -v* (weights -1, +1).
(3) (1 + sigma)/2 = v* v and (1 - sigma)/2 = v v*.
(4) Fock representation (v = E_12, v* = E_21, N = v* v): sigma/2 = N - 1/2.
(5) The bivector space of Cl(1,1) is one-dimensional, computed as the span of the products e_i e_j,
i < j. A rotor flow generated by k sigma (k rational, both signs) is R_lambda at parameter k lambda:
its conjugation multiplies v by (c_k - s_k)^2 = ((c - s)^2)^k at the sample points, the same orbit
reparametrised, reversed for k < 0. The algebra fixes the orbits but not the speed: two different
k give different scale factors at the same parameter.
"""
from fractions import Fraction as F

import GA

SQ = GA.sig(1, 1)
RAPIDITIES = [(F(5, 3), F(4, 3)), (F(5, 4), F(3, 4)), (F(13, 12), F(-5, 12))]


def atom():
    e0, e1 = GA.gen(0), GA.gen(1)
    return GA.scal(F(1, 2), GA.add(e0, e1)), GA.scal(F(1, 2), GA.sub(e0, e1))


def other_pairs():
    v, vs = atom()
    sq22 = GA.sig(2, 2)
    f1, f3 = GA.gen(1), GA.gen(3)
    return [(GA.scal(2, v), GA.scal(F(1, 2), vs), SQ),
            (GA.scal(F(1, 2), GA.add(f1, f3)), GA.scal(F(1, 2), GA.sub(f1, f3)), sq22)]


def sig_of(v, vs, sq):
    return GA.sub(GA.mul(vs, v, sq), GA.mul(v, vs, sq))


def conj(R, x, Ri, sq):
    return GA.mul(GA.mul(R, x, sq), Ri, sq)


def check_sigma_square_and_boost_bivector():
    v, vs = atom()
    s = sig_of(v, vs, SQ)
    assert s == {(0, 1): F(1)}
    assert GA.eq(GA.mul(s, s, SQ), GA.sc(1))
    assert GA.eq(sig_of(vs, v, SQ), GA.neg(s))           # relabelling reverses the orientation
    for w, ws, sq in other_pairs():
        t = sig_of(w, ws, sq)
        assert GA.eq(GA.mul(t, t, sq), GA.sc(1))


def check_boost_weights_and_rotor_flow():
    v, vs = atom()
    s = sig_of(v, vs, SQ)
    assert GA.eq(GA.mul(s, v, SQ), GA.neg(v)) and GA.eq(GA.mul(v, s, SQ), v)
    assert GA.eq(GA.mul(s, vs, SQ), vs) and GA.eq(GA.mul(vs, s, SQ), GA.neg(vs))
    for w, ws, sq in [(v, vs, SQ)] + other_pairs():
        t = sig_of(w, ws, sq)
        for c, sh in RAPIDITIES:
            assert c * c - sh * sh == 1
            R = GA.add(GA.sc(c), GA.scal(sh, t))
            Ri = GA.sub(GA.sc(c), GA.scal(sh, t))
            assert GA.eq(conj(R, w, Ri, sq), GA.scal((c - sh) ** 2, w))
            assert GA.eq(conj(R, ws, Ri, sq), GA.scal((c + sh) ** 2, ws))
    R = GA.add(GA.sc(F(5, 3)), GA.scal(F(4, 3), s))
    Ri = GA.sub(GA.sc(F(5, 3)), GA.scal(F(4, 3), s))
    assert GA.eq(conj(R, v, Ri, SQ), GA.scal(F(1, 9), v)) and GA.eq(conj(R, vs, Ri, SQ), GA.scal(9, vs))


def check_projectors_and_fock_number():
    for w, ws, sq in [atom() + (SQ,)] + other_pairs():
        t = sig_of(w, ws, sq)
        assert GA.eq(GA.scal(F(1, 2), GA.add(GA.sc(1), t)), GA.mul(ws, w, sq))
        assert GA.eq(GA.scal(F(1, 2), GA.sub(GA.sc(1), t)), GA.mul(w, ws, sq))
    V = [[F(0), F(1)], [F(0), F(0)]]
    W = [[F(0), F(0)], [F(1), F(0)]]
    mm = lambda A, B: [[sum(A[i][k] * B[k][j] for k in range(2)) for j in range(2)] for i in range(2)]
    N = mm(W, V)
    half_sigma = [[(mm(W, V)[i][j] - mm(V, W)[i][j]) / 2 for j in range(2)] for i in range(2)]
    assert N == [[0, 0], [0, 1]]
    assert half_sigma == [[N[i][j] - (F(1, 2) if i == j else 0) for j in range(2)] for i in range(2)]


def check_unique_flow_up_to_reparametrisation():
    sq = SQ
    bivs = []
    for i in range(2):
        for j in range(i + 1, 2):
            bivs.append(GA.mul(GA.gen(i), GA.gen(j), sq))
    blades = GA.all_blades(2)
    assert GA.rank_of_vectors([[x.get(b, F(0)) for b in blades] for x in bivs]) == 1
    v, vs = atom()
    s = sig_of(v, vs, sq)
    # generator k sigma: R = cosh(k lambda/2) + sinh(k lambda/2) sigma. At k = 2 and k = -1 with the
    # half-rapidity point (c, s) = (5/4, 3/4) (e^{-lambda} = 1/4): double angle (c^2 + s^2, 2 c s).
    c, sh = F(5, 4), F(3, 4)
    for k, (ck, sk) in ((1, (c, sh)), (2, (c * c + sh * sh, 2 * c * sh)), (-1, (c, -sh))):
        R = GA.add(GA.sc(ck), GA.scal(sk, s))
        Ri = GA.sub(GA.sc(ck), GA.scal(sk, s))
        assert ck * ck - sk * sk == 1
        assert GA.eq(conj(R, v, Ri, sq), GA.scal(F(1, 4) ** k, v))
