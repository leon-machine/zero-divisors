"""conformal.nilpotent-ideal-becomes-unit-ideal: exact checks.

(1) In Cl(p,q,r) (GA, radical letters rho_1..rho_r of square 0) for every (p,q,r) with p + q <= 2,
    1 <= r <= 3, plus PGA (3,0,1): the two-sided ideal J generated by the rho_i (span of all blade products
    a rho_i b) has dimension 2^m - 2^(m-r); the powers J^k (spans of products) are nonzero for k <= r and
    J^(r+1) = 0; hence J^2 = 0 exactly when r = 1.
(2) The model completion Cl(p+r,q+r), rho_j -> a_j + b_j (a_j^2 = 1, b_j^2 = -1): with phi_j = (a_j - b_j)/4,
    rho_j phi_j + phi_j rho_j = 1, so the ideal generated by the image of any rho_j contains 1, and
    span(rho_j, phi_j) has Gram signature (1,1) (a hyperbolic plane).
(3) Any completion (non-diagonal, sample extensions [[B, X], [X^T, Y]] by r vectors, nondegenerate): for each
    radical vector rho a partner phi with B(rho, phi) = 1/2 is found among the added vectors, the pair has Gram
    signature (1,1), and in the exterior model of the completion's Clifford algebra (arbitrary Gram, GA.ext_c)
    rho phi + phi rho acts as the identity on every basis state: the unit ideal.
"""
from fractions import Fraction as F

import GA
from tp_premise import premise

IDEAL_CASES = [(p, s - p, r) for s in range(0, 3) for p in range(s + 1) for r in (1, 2, 3)] + [(3, 0, 1)]


def span_basis(elems, blades):
    """A basis (as multivectors) of the span of elems."""
    basis, piv = [], {}                       # piv: pivot column -> reduced row
    for x in elems:
        v = [x.get(b, F(0)) for b in blades]
        for c, row in piv.items():
            if v[c] != 0:
                f = v[c]
                v = [a - f * b for a, b in zip(v, row)]
        nz = next((c for c, a in enumerate(v) if a != 0), None)
        if nz is not None:
            v = [a / v[nz] for a in v]
            for c in piv:
                row = piv[c]
                if row[nz] != 0:
                    f = row[nz]
                    piv[c] = [a - f * b for a, b in zip(row, v)]
            piv[nz] = v
            basis.append(x)
    return basis


def ideal_and_powers(p, q, r):
    m = p + q + r
    S = GA.sig(p, q, r)
    blades = GA.all_blades(m)
    rhos = [GA.gen(p + q + j) for j in range(r)]
    gens = []
    for a in blades:
        for rho in rhos:
            x = GA.mul({a: F(1)}, rho, S)
            if not GA.is_zero(x):
                gens.append(x)
    # two-sided: rho_j commute or anticommute with blades, so a rho b = +- (a b') rho; left span suffices,
    # but take right multiples too
    gens2 = [GA.mul(x, {b: F(1)}, S) for x in gens[:len(blades)] for b in blades[:4]]
    J = span_basis(gens + [g for g in gens2 if not GA.is_zero(g)], blades)
    dims = [len(J)]
    Jk = J
    while Jk:
        prods = [GA.mul(x, y, S) for x in Jk for y in J]
        Jk = span_basis([z for z in prods if not GA.is_zero(z)], blades)
        dims.append(len(Jk))
    return m, dims


def check_radical_ideal_dimension_and_nilpotency():
    premise("conformal.blade-basis-persists-under-degeneracy")
    ok = len(IDEAL_CASES) == 19
    for (p, q, r) in IDEAL_CASES:
        m, dims = ideal_and_powers(p, q, r)
        ok = ok and dims[0] == 2 ** m - 2 ** (m - r)
        ok = ok and len(dims) == r + 1 and dims[r] == 0 and all(dims[k] > 0 for k in range(r))
        ok = ok and ((len(dims) == 2) == (r == 1))
    _tp_rv = (ok); assert _tp_rv is not False, "check_radical_ideal_dimension_and_nilpotency"; return _tp_rv


def check_model_completion_unit_ideal():
    ok = True
    for (p, q, r) in IDEAL_CASES:
        S = GA.sig(p + r, q + r)
        for j in range(r):
            a, b = GA.gen(p + j), GA.gen(p + r + q + j)
            rho = GA.add(a, b)
            phi = GA.scal(F(1, 4), GA.sub(a, b))
            ok = ok and GA.is_zero(GA.mul(rho, rho, S))
            ok = ok and GA.eq(GA.add(GA.mul(rho, phi, S), GA.mul(phi, rho, S)), GA.sc(1))
            gram = [[GA.dot(rho, rho, S), GA.dot(rho, phi, S)], [GA.dot(phi, rho, S), GA.dot(phi, phi, S)]]
            ok = ok and gram[0][1] == F(1, 2) and GA.congruence_signature(gram) == (1, 1, 0)
    _tp_rv = (ok); assert _tp_rv is not False, "check_model_completion_unit_ideal"; return _tp_rv


def lcg(seed):
    x = seed
    while True:
        x = (1103515245 * x + 12345) % (2 ** 31)
        yield F((x >> 8) % 7 - 3, 1 + (x >> 4) % 3)


def completion_samples(p, q, r, seed, count):
    m = p + q + r
    B = [[F(0)] * m for _ in range(m)]
    for i in range(p):
        B[i][i] = F(1)
    for i in range(p, p + q):
        B[i][i] = F(-1)
    g = lcg(seed)
    out = []
    while len(out) < count:
        X = [[next(g) for _ in range(r)] for _ in range(m)]
        Y = [[F(0)] * r for _ in range(r)]
        for a in range(r):
            for b in range(a, r):
                Y[a][b] = Y[b][a] = next(g)
        G = [B[i][:] + X[i][:] for i in range(m)] + [[X[i][a] for i in range(m)] + Y[a][:] for a in range(r)]
        if GA.mat_rank(G) == m + r:
            out.append(G)
    return out


def check_any_completion_unit_ideal_hyperbolic_partner():
    premise("conformal.blade-basis-persists-under-degeneracy")
    ok = True
    n_states = 0
    for (p, q, r) in [(1, 0, 1), (0, 1, 1), (1, 1, 1), (2, 0, 2), (0, 1, 2), (1, 0, 3)]:
        m = p + q + r
        for G in completion_samples(p, q, r, 3 * m + r, 2):
            N = m + r

            def bil(x, y):
                return sum(x[i] * G[i][j] * y[j] for i in range(N) for j in range(N) if x[i] and y[j])

            for j in range(r):
                rho = [F(1) if t == p + q + j else F(0) for t in range(N)]
                ok = ok and bil(rho, rho) == 0
                t0 = next(t for t in range(m, N) if G[p + q + j][t] != 0)
                phi = [F(0)] * N
                phi[t0] = 1 / (2 * G[p + q + j][t0])
                ok = ok and bil(rho, phi) == F(1, 2)
                gram = [[bil(rho, rho), bil(rho, phi)], [bil(phi, rho), bil(phi, phi)]]
                ok = ok and GA.congruence_signature(gram) == (1, 1, 0)
                for k in range(2 ** N):
                    s = {frozenset(i for i in range(N) if k >> i & 1): F(1)}
                    lhs = GA.ext_c(rho, G, GA.ext_c(phi, G, s))
                    lhs2 = GA.ext_c(phi, G, GA.ext_c(rho, G, s))
                    tot = {key: lhs.get(key, F(0)) + lhs2.get(key, F(0)) for key in set(lhs) | set(lhs2)}
                    ok = ok and GA.ext_state_eq(tot, s)
                    n_states += 1
    _tp_rv = (ok and n_states == 2 * (8 + 8 + 16 + 2 * 64 + 2 * 32 + 3 * 128)); assert _tp_rv is not False, "check_any_completion_unit_ideal_hyperbolic_partner"; return _tp_rv
