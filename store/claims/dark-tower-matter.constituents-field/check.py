"""dark-tower-matter.constituents-field: exact checks.

For each of the eight towers (both representatives of r = 4) and its conformal ambient (p+1, q+1), in
GA.py: a primitive idempotent f of the even subalgebra Cl^0 is built greedily from commuting even blades
of square +1, the ideal (T at the conformal level, S at the tower level) is Cl^0 f with an exact basis,
and the field is identified twice:
- as the corner f Cl^0 f (Schur, premise: the imported Clifford structure (iii)), whose type is read
  from the signature of its regular trace form ((1,0) R, (1,1) C, (1,3) H, else not a division algebra);
- directly, as the commutant of the left action of Cl^0 (generated by the bivectors e_0 e_a) on the
  ideal, solved as a linear system for every tower-level ideal S and for the conformal ideals T of the
  three- and four-dimensional towers; its type from the trace form tr(XY) on the commutant.
Checked: the table of fields (C, C, R, R, H, H, R, H, H at r = 6, 2, 1, 7, 3, 5, 0, 4, 4) at both levels,
the dimensions dim T, dim S, and the field being D(r + 1) (the residue of Cl^0(p,q) = Cl(p, q-1),
premise (i)); the conformal pseudoscalar's square Q(omega) = -1 at (2,4), (4,2), (2,3), (5,2) and +1 at
(3,2), (2,5), (3,3), (5,1), (1,5), so r = 7 (field R) and r = 3 (field H) share Q(omega) = -1.
"""
from fractions import Fraction as F
import GA
from tp_premise import premise

TOWERS = [(6, (1, 3)), (2, (3, 1)), (1, (2, 1)), (7, (1, 2)), (3, (4, 1)), (5, (1, 4)), (0, (2, 2)),
          (4, (4, 0)), (4, (0, 4))]
TYPE_OF_SIG = {(1, 0, 0): "R", (1, 1, 0): "C", (1, 3, 0): "H"}


def even_ideal(p, q):
    sq = GA.sig(p, q)
    n = p + q
    ev = [b for b in GA.all_blades(n) if len(b) % 2 == 0]

    def co(x):
        return [x.get(b, F(0)) for b in ev]

    def dim_left(f):
        return GA.rank_of_vectors([co(GA.mul({b: F(1)}, f, sq)) for b in ev])
    f, d, chosen = GA.sc(1), len(ev), []
    for b in ev:
        if b and GA.mul({b: F(1)}, {b: F(1)}, sq) == {(): F(1)} and \
                all(GA.commutes({b: F(1)}, {c: F(1)}, sq) for c in chosen):
            f2 = GA.mul(f, GA.scal(F(1, 2), GA.add(GA.sc(1), {b: F(1)})), sq)
            d2 = dim_left(f2)
            if 0 < d2 < d:
                f, d, chosen = f2, d2, chosen + [b]
    rows, basis = [], []
    for b in ev:
        x = GA.mul({b: F(1)}, f, sq)
        if x and GA.rank_of_vectors(rows + [co(x)]) > len(rows):
            rows.append(co(x))
            basis.append(x)
    crow, corner = [], []
    for b in ev:
        y = GA.mul(GA.mul(f, {b: F(1)}, sq), f, sq)
        if y and GA.rank_of_vectors(crow + [co(y)]) > len(crow):
            crow.append(co(y))
            corner.append(y)
    return sq, n, ev, f, basis, rows, corner, crow, co


def solver(rows):
    """Coordinates in the span of independent rows, through an invertible square submatrix."""
    d = len(rows)
    cols, sub = [], []
    for k in range(len(rows[0])):
        cand = sub + [[rows[i][k] for i in range(d)]]
        if GA.rank_of_vectors(cand) > len(sub):
            sub, cols = cand, cols + [k]
        if len(cols) == d:
            break
    M = [[sub[j][i] for j in range(d)] for i in range(d)]  # M[i][j] = rows[i][cols[j]]
    Mt = [[M[i][j] for i in range(d)] for j in range(d)]

    def coords(v):
        c = GA.field_solve(Mt, [v[k] for k in cols])
        assert all(sum(c[i] * rows[i][k] for i in range(d)) == v[k] for k in range(len(v)))
        return c
    return coords


def corner_type(p, q):
    sq, n, ev, f, basis, rows, corner, crow, co = even_ideal(p, q)
    cc = solver(crow)
    d = len(corner)
    T = [[sum(cc(co(GA.mul(GA.mul(corner[i], corner[j], sq), corner[k], sq)))[k] for k in range(d))
          for j in range(d)] for i in range(d)]
    return TYPE_OF_SIG.get(tuple(GA.congruence_signature(T))), len(basis)


def commutant_type(p, q):
    sq, n, ev, f, basis, rows, corner, crow, co = even_ideal(p, q)
    cs = solver(rows)
    N = len(basis)
    gens = [GA.mul(GA.gen(0), GA.gen(a), sq) for a in range(1, n)]
    mats = []
    for g in gens:
        cols = [cs(co(GA.mul(g, x, sq))) for x in basis]
        mats.append([[cols[j][i] for j in range(N)] for i in range(N)])
    eqs = []
    for G in mats:
        for i in range(N):
            for j in range(N):
                row = [F(0)] * (N * N)
                for k in range(N):
                    row[i * N + k] += G[k][j]
                    row[k * N + j] -= G[i][k]
                eqs.append(row)
    ker = GA.field_kernel(eqs)
    Xs = [[[v[i * N + j] for j in range(N)] for i in range(N)] for v in ker]
    tr = lambda A, B: sum(A[i][k] * B[k][i] for i in range(N) for k in range(N))
    G = [[tr(A, B) for B in Xs] for A in Xs]
    return TYPE_OF_SIG.get(tuple(GA.congruence_signature(G))), N


def residue_field(r):
    return {0: "R", 1: "R", 2: "R", 3: "C", 7: "C", 4: "H", 5: "H", 6: "H"}[r % 8]


def check_fields_by_corner_at_both_levels():
    premise("dark-tower-matter.imported-clifford-structure")
    want = {6: "C", 2: "C", 1: "R", 7: "R", 3: "H", 5: "H", 0: "R", 4: "H"}
    dims = {6: (8, 4), 2: (8, 4), 1: (4, 2), 7: (4, 2), 3: (16, 8), 5: (16, 8), 0: (4, 2), 4: (8, 4)}
    ok = True
    for r, (p, q) in TOWERS:
        fT, dT = corner_type(p + 1, q + 1)
        fS, dS = corner_type(p, q)
        ok = ok and fT == fS == want[r] == residue_field(r + 1) and (dT, dS) == dims[r]
    GA.check("thm:fields: F(T) = F(S) = D(r + 1) for all eight towers (corner f Cl^0 f), with the stated dim T, dim S",
             ok)
    return ok


def check_fields_by_direct_commutant():
    premise("dark-tower-matter.imported-clifford-structure")
    want = {6: "C", 2: "C", 1: "R", 7: "R", 3: "H", 5: "H", 0: "R", 4: "H"}
    ok = True
    count = 0
    for r, (p, q) in TOWERS:
        fS, dS = commutant_type(p, q)
        ok = ok and fS == want[r]
        if p + q <= 4:
            fT, dT = commutant_type(p + 1, q + 1)
            ok = ok and fT == want[r]
            count += 1
    ok = ok and count == 7
    GA.check("thm:fields: the commutant of the spin action, solved directly, is the same field at tower level "
             "(all nine) and conformal level (the seven of dimension at most four)", ok)
    return ok


def check_field_is_not_a_function_of_omega_squared():
    neg = [(2, 4), (4, 2), (2, 3), (5, 2)]
    pos = [(3, 2), (2, 5), (3, 3), (5, 1), (1, 5)]
    ok = True
    q_omega = {}
    for p, q in neg + pos:
        n = p + q
        sq = GA.sig(p, q)
        om = {tuple(range(n)): F(1)}
        q_omega[(p, q)] = GA.mul(om, om, sq)[()]
        ok = ok and all(GA.commutes(om, GA.gen(a), sq) for a in range(n)) == (n % 2 == 1)
    ok = ok and all(q_omega[s] == -1 for s in neg) and all(q_omega[s] == 1 for s in pos)
    f7, _ = corner_type(1, 2)
    f3, _ = corner_type(4, 1)
    f5, _ = corner_type(1, 4)
    ok = ok and (f7, q_omega[(2, 3)]) == ("R", -1) and (f3, q_omega[(5, 2)]) == ("H", -1) \
        and (f5, q_omega[(2, 5)]) == ("H", 1)
    GA.check("thm:fields: Q(omega) = -1 at (2,4), (4,2), (2,3), (5,2), +1 at the others; r = 7 (R) and r = 3 (H) "
             "share Q(omega) = -1", ok)
    return ok
