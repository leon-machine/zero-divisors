"""sheaf.resolution-ideal-theoretically: exact checks.

Degenerate wall fibres (T*_x M, G_x): corank one, for every signature (p, q) of the nondegenerate part with
p + q <= 3, in a general frame G_x = P^T diag(0, ...) P with radical k = P^-1 e_0. Each is embedded as a
subspace with the restricted form into nondegenerate quadratic spaces (W, Q) of dimension n + 1 and n + 2
with non-orthogonal off-diagonal blocks (Q = [[G_x, B], [B^T, C]], nondegeneracy checked by exact rank).
(1) In every such (W, Q): k is null but not radical; v = e_j / (2 Q(k, e_j)) for a basis vector with
    Q(k, e_j) != 0 has Q(k, v) = 1/2; k* = v - Q(v, v) k is null with Q(k, k*) = 1/2; and in the exterior
    model of Cl(W, Q) (faithful, arbitrary Gram) c(k) c(k*) + c(k*) c(k) = 1 on every basis state, so the
    two-sided ideal generated by k contains 1.
(2) The identity behind the construction, Q(v - Q(v,v) k) = Q(v, v)(1 - 2 Q(k, v)), at unnormalised v
    (a control: without Q(k, v) = 1/2 the candidate partner is not null).
(3) Contrast in the degenerate fibre itself (exterior model of Cl(T*_x M, G_x)): c(k) c(e_I) c(k) = 0 for
    every blade e_I, so the ideal A k A is square-zero there and does not contain 1.
"""
from fractions import Fraction as F

import GA
from tp_premise import premise  # noqa: F401  (self-contained proposition: no premises)

SIGS = [(1, 0), (0, 1), (1, 1), (2, 0), (0, 2), (2, 1), (1, 2), (3, 0), (0, 3)]
EXT_B = [[F(1), F(-2), F(0), F(3)], [F(1, 2), F(1), F(-1), F(0)]]
EXT_C = [[F(1), F(2)], [F(2), F(-3)]]


def _mm(A, B):
    return [[sum((A[i][t] * B[t][j] for t in range(len(B))), F(0)) for j in range(len(B[0]))]
            for i in range(len(A))]


def _frame(n):
    U = [[F(1) if i == j else (F((i + 2 * j) % 3 - 1) if j > i else F(0)) for j in range(n)] for i in range(n)]
    L = [[F(1) if i == j else (F((2 * i + j) % 3 - 1) if j < i else F(0)) for j in range(n)] for i in range(n)]
    return _mm(U, L)


def _q(Q, a, b):
    return sum((a[i] * Q[i][j] * b[j] for i in range(len(a)) for j in range(len(b))), F(0))


def fibre(p, q):
    n = p + q + 1
    D = [[F(0)] * n for _ in range(n)]
    for i in range(1, n):
        D[i][i] = F(1) if i <= p else F(-1)
    P = _frame(n)
    G = _mm([list(r) for r in zip(*P)], _mm(D, P))
    k = GA.field_solve(P, [F(1)] + [F(0)] * (n - 1))
    return G, k


def embeddings(G):
    """Nondegenerate (W, Q) containing (T*_x M, G) with the restricted form, of dimension n + 1 and n + 2."""
    n = len(G)
    out = []
    for extra in (1, 2):
        for shift in range(6):
            Q = [[F(0)] * (n + extra) for _ in range(n + extra)]
            for i in range(n):
                for j in range(n):
                    Q[i][j] = G[i][j]
            for a in range(extra):
                for i in range(n):
                    Q[i][n + a] = Q[n + a][i] = EXT_B[a][i % 4] + shift
                for b in range(extra):
                    Q[n + a][n + b] = EXT_C[a][b]
            if GA.rank_of_vectors(Q) == n + extra:
                out.append(Q)
                break
    return out


def _st_add(*ds):
    out = {}
    for d in ds:
        for S, c in d.items():
            out[S] = out.get(S, F(0)) + c
    return {S: c for S, c in out.items() if c != 0}


def check_partner_makes_unit_ideal():
    ok = True
    spaces = 0
    for (p, q) in SIGS:
        G, k0 = fibre(p, q)
        n = len(G)
        ok = ok and GA.rank_of_vectors(G) == n - 1 and all(_q(G, k0, e) == 0 for e in GA.field_kernel([[F(0)] * n]))
        for Q in embeddings(G):
            N = len(Q)
            k = list(k0) + [F(0)] * (N - n)
            ok = ok and _q(Q, k, k) == 0
            j = next(j for j in range(N) if Q[j] and _q(Q, k, [F(1) if i == j else F(0) for i in range(N)]) != 0)
            ej = [F(1) if i == j else F(0) for i in range(N)]
            v = [x / (2 * _q(Q, k, ej)) for x in ej]
            ok = ok and _q(Q, k, v) == F(1, 2)
            ks = [v[i] - _q(Q, v, v) * k[i] for i in range(N)]
            ok = ok and _q(Q, ks, ks) == 0 and _q(Q, k, ks) == F(1, 2)
            for S in GA.all_blades(N):
                st = {frozenset(S): F(1)}
                anti = _st_add(GA.ext_c(k, Q, GA.ext_c(ks, Q, st)), GA.ext_c(ks, Q, GA.ext_c(k, Q, st)))
                ok = ok and GA.ext_state_eq(anti, st)
            spaces += 1
    _tp_rv = (ok and spaces == 2 * len(SIGS)); assert _tp_rv is not False, "check_partner_makes_unit_ideal"; return _tp_rv


def unnormalised_vectors(N):
    """Two sample (unnormalised) vectors v in W of dimension N."""
    return ([F(i + 1) for i in range(N)], [F((-1) ** i) for i in range(N)])


def check_null_partner_needs_the_normalisation():
    ok = True
    for (p, q) in SIGS:
        G, k0 = fibre(p, q)
        for Q in embeddings(G):
            N = len(Q)
            k = list(k0) + [F(0)] * (N - len(G))
            fires = False
            for v in unnormalised_vectors(N):
                ks = [v[i] - _q(Q, v, v) * k[i] for i in range(N)]
                ok = ok and _q(Q, ks, ks) == _q(Q, v, v) * (1 - 2 * _q(Q, k, v))
                fires = fires or bool(_q(Q, ks, ks))
            # the control is not vacuous: in every space some unnormalised candidate partner is not null
            # (the old guarded assert ks non-null when Q(k, v) != 1/2 and Q(v) != 0 is implied by the identity)
            ok = ok and fires
    _tp_rv = (ok); assert _tp_rv is not False, "check_null_partner_needs_the_normalisation"; return _tp_rv


def check_degenerate_fibre_ideal_square_zero():
    ok = True
    for (p, q) in SIGS:
        G, k = fibre(p, q)
        n = len(G)
        for I in GA.all_blades(n):
            for S in GA.all_blades(n):
                st = {frozenset(S): F(1)}
                x = GA.ext_c(k, G, st)
                for i in reversed(I):
                    x = GA.ext_c([F(1) if t == i else F(0) for t in range(n)], G, x)
                ok = ok and GA.ext_c(k, G, x) == {}
        # k itself is nonzero in the fibre: c(k) moves the vacuum
        ok = ok and GA.ext_c(k, G, {frozenset(): F(1)}) != {}
        # By hand: the fibre has corank one (rank n - 1) and k spans its radical (G k = 0), so c(k) anticommutes
        # with every c(e_i), c(k)^2 = G(k, k) = 0, and A k A = k A = k ^ (complement of k) has dimension 2^(n-1),
        # half of the 2^n-dimensional algebra.
        ok = ok and GA.field_rank(G) == n - 1
        ok = ok and all(sum((k[i] * G[i][j] for i in range(n)), F(0)) == 0 for j in range(n))
        states = [frozenset(S) for S in GA.all_blades(n)]
        rows = []
        for I in GA.all_blades(n):
            row = []
            for S in states:
                x = {S: F(1)}
                for i in reversed(I):
                    x = GA.ext_c([F(1) if t == i else F(0) for t in range(n)], G, x)
                x = GA.ext_c(k, G, x)
                row.extend(x.get(T, F(0)) for T in states)
            rows.append(row)
        ok = ok and len(rows) == 2 ** n and GA.field_rank(rows) == 2 ** (n - 1)
    _tp_rv = (ok); assert _tp_rv is not False, "check_degenerate_fibre_ideal_square_zero"; return _tp_rv
