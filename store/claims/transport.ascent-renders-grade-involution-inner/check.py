"""transport.ascent-renders-grade-involution-inner: exact checks.

B_gamma = Cl(p,q) + Cl(p,q) nu, nu orthogonal to V with nu^2 = gamma = +-1 (so nu^{-1} = gamma nu).
(1) For every (p,q) with 1 <= n <= 6 and both gamma: nu a nu^{-1} = a^ on every blade of A (the grade
    involution, computed independently by GA.grade_inv), and nu nu^{-1} = 1.
(2) For every type-C base with n <= 7 (omega central, omega^2 = +1, i.e. n odd and p - q = 1 mod 4):
    eps_pm = (1 +- omega)/2 are central idempotents of A, nu omega nu^{-1} = -omega,
    nu eps_+ nu^{-1} = eps_-, and eps_+ + nu eps_+ nu^{-1} = 1.
(3) The ideals, by rank: for the type-C bases with n <= 3, the two-sided ideal of A generated by eps_+ has
    dimension 2^(n-1) (a proper ideal), while the two-sided ideal of B_gamma generated by eps_+ is all of
    B_gamma (dimension 2^(n+1)), for both gamma.
"""
from fractions import Fraction as F

import GA
from tp_premise import premise

SIGS = [(p, n - p) for n in range(1, 7) for p in range(n + 1)]
TYPE_C = [(p, n - p) for n in (1, 3, 5, 7) for p in range(n + 1) if (2 * p - n) % 4 == 1]


def blade(b):
    return {b: F(1)}


def omega(n):
    return {tuple(range(n)): F(1)}


def check_ad_nu_is_grade_involution():
    premise("transport.decomposition-commutation")
    ok = True
    cases = 0
    for (p, q) in SIGS:
        n = p + q
        for gamma in (1, -1):
            S = GA.sig(p, q) + (gamma,)
            nu = GA.gen(n)
            nu_inv = GA.scal(gamma, nu)
            ok = ok and GA.eq(GA.mul(nu, nu_inv, S), GA.sc(1))
            for b in GA.all_blades(n):
                conj = GA.mul(GA.mul(nu, blade(b), S), nu_inv, S)
                ok = ok and GA.eq(conj, GA.grade_inv(blade(b)))
                ok = ok and conj[b] == (-1) ** len(b)
            cases += 1
    _tp_rv = (ok and cases == 54); assert _tp_rv is not False, "check_ad_nu_is_grade_involution"; return _tp_rv


def check_projectors_exchanged_and_sum_to_one():
    ok = len(TYPE_C) == 10         # (1,0); (2,1),(0,3); (5,0),(3,2),(1,4); (6,1),(4,3),(2,5),(0,7)
    for (p, q) in TYPE_C:
        n = p + q
        w = omega(n)
        SA = GA.sig(p, q)
        ok = ok and GA.eq(GA.mul(w, w, SA), GA.sc(1))
        ok = ok and all(GA.commutes(w, GA.gen(i), SA) for i in range(n))
        epp = GA.scal(F(1, 2), GA.add(GA.sc(1), w))
        epm = GA.scal(F(1, 2), GA.sub(GA.sc(1), w))
        ok = ok and GA.eq(GA.mul(epp, epp, SA), epp) and GA.is_zero(GA.mul(epp, epm, SA))
        for gamma in (1, -1):
            S = SA + (gamma,)
            nu = GA.gen(n)
            nu_inv = GA.scal(gamma, nu)
            ok = ok and GA.eq(GA.mul(GA.mul(nu, w, S), nu_inv, S), GA.scal(-1, w))
            conj = GA.mul(GA.mul(nu, epp, S), nu_inv, S)
            ok = ok and GA.eq(conj, epm)
            ok = ok and GA.eq(GA.add(epp, conj), GA.sc(1))
            ok = ok and not GA.commutes(epp, nu, S)      # no longer central in B
    _tp_rv = (ok); assert _tp_rv is not False, "check_projectors_exchanged_and_sum_to_one"; return _tp_rv


def ideal_dim(gen_elt, n_total, S):
    """Dimension of the two-sided ideal generated by gen_elt: span of b1 gen b2 over all blades."""
    blades = GA.all_blades(n_total)
    vecs = []
    for b1 in blades:
        left = GA.mul(blade(b1), gen_elt, S)
        for b2 in blades:
            prod = GA.mul(left, blade(b2), S)
            vecs.append([prod.get(b, F(0)) for b in blades])
    return GA.rank_of_vectors(vecs)


def check_ideal_of_projector_is_unit_ideal():
    premise("transport.decomposition-commutation")
    ok = True
    for (p, q) in [s for s in TYPE_C if s[0] + s[1] <= 3]:
        n = p + q
        epp = GA.scal(F(1, 2), GA.add(GA.sc(1), omega(n)))
        ok = ok and ideal_dim(epp, n, GA.sig(p, q)) == 2 ** (n - 1)
        for gamma in (1, -1):
            ok = ok and ideal_dim(epp, n + 1, GA.sig(p, q) + (gamma,)) == 2 ** (n + 1)
    _tp_rv = (ok); assert _tp_rv is not False, "check_ideal_of_projector_is_unit_ideal"; return _tp_rv
