from fractions import Fraction as F
from itertools import combinations

import GA
import stdalg as S
from tp_premise import premise

SIGS = [(0, 1, 0), (2, 0, 0), (0, 0, 1), (1, 0, 1)]


def mmul(X, Y, sq):
    m = len(X)
    return [[GA.add(*[GA.mul(X[i][k], Y[k][j], sq) for k in range(m)]) for j in range(m)] for i in range(m)]


def unit(i, j, c, m=2):
    return [[c if (a, b) == (i, j) else {} for b in range(m)] for a in range(m)]


def flat(X, n):
    out = []
    for row in X:
        for x in row:
            out += S.coords(x, n)
    return out


def centre_dim_M2(sq):
    """Dimension of the centre of M_2(A): kernel of commutators with E_12, E_21 and diag(e_k)."""
    n = len(sq)
    bl = GA.all_blades(n)
    basis = [unit(i, j, {b: F(1)}) for i in range(2) for j in range(2) for b in bl]
    gens = [unit(0, 1, GA.sc(1)), unit(1, 0, GA.sc(1))]
    gens += [[[GA.gen(k), {}], [{}, GA.gen(k)]] for k in range(n)]
    rows = []
    for g in gens:
        cols = []
        for X in basis:
            C = mmul(g, X, sq)
            D = mmul(X, g, sq)
            cols.append([a - b for a, b in zip(flat(C, n), flat(D, n))])
        rows += [[cols[j][i] for j in range(len(basis))] for i in range(len(cols[0]))]
    return len(S.nullspace(rows))


def ideal_dim(X, sq):
    n = len(sq)
    bl = GA.all_blades(n)
    basis = [unit(i, j, {b: F(1)}) for i in range(2) for j in range(2) for b in bl]
    span = [flat(mmul(mmul(P, X, sq), Q, sq), n) for P in basis for Q in basis]
    return GA.rank_of_vectors(span)


def check_centre_and_ideals_of_the_amplification():
    premise("std-algebra.matrix-units")
    ok = True
    zA, zM = [], []
    for p, q, r in SIGS:
        sq = GA.sig(p, q, r)
        zA.append(len(S.centre_basis(sq)))
        zM.append(centre_dim_M2(sq))
    ok = ok and zA == zM and zA == [2, 1, 2, 1]
    # ideals: in M_2(Cl(0,0,1)) the ideal generated by diag(e, 0) is M_2(eA), of dimension 4;
    # the ideal generated by diag(1, 0) is everything, of dimension 8
    sq = GA.sig(0, 0, 1)
    ok = ok and ideal_dim(unit(0, 0, GA.gen(0)), sq) == 4
    ok = ok and ideal_dim(unit(0, 0, GA.sc(1)), sq) == 8
    # corner E_11 M_2(A) E_11 has the dimension of A
    for p, q, r in SIGS:
        sq = GA.sig(p, q, r)
        n = len(sq)
        bl = GA.all_blades(n)
        E11 = unit(0, 0, GA.sc(1))
        corner = [flat(mmul(mmul(E11, unit(i, j, {b: F(1)}), sq), E11, sq), n)
                  for i in range(2) for j in range(2) for b in bl]
        ok = ok and GA.rank_of_vectors(corner) == 2 ** n
    GA.check("Z(M_2(A)) = Z(A); ideals M_2(I); corner of M_2(A) is A (four algebras A)", ok)
    return ok
