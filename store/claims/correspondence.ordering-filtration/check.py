"""correspondence.ordering-filtration: exact checks in the palatial algebra (formal hbar, Fractions).

P is generated by Z^1..Z^4 and Zbar_1..Zbar_4 with the Z's commuting, the Zbar's commuting and
[Z^a, Zbar_b] = hbar delta_ab. Words are brought to normal order (Z's left of Zbar's) by the rule
Zbar_b Z^a = Z^a Zbar_b - hbar delta_ab; an element is {(hbar power, Z exponents, Zbar exponents): coeff}.
(1) For all 45 multisets of degree <= 2 (1 + 8 + 36), every ordering differs from the sorted one by
    hbar times a scalar; exactly 4 (the Z^a Zbar_a) have a nonzero discrepancy, -hbar or +hbar.
(2) Degree 3 (120 multisets): discrepancies are hbar times linear terms; exactly 32 multisets (those
    containing some Z^a and Zbar_a) have one.
(3) Degree 4 (330 multisets): discrepancies are hbar (quadratic) + hbar^2 (scalar) with no hbar^0 part; for
    the 100 balanced multisets the hbar-quadratic part is mixed (only Z^a Zbar_b terms) and equals q(M) up to a
    central hbar term, M read off its coefficients; exactly 58 of
    them have a nonzero discrepancy (42 have disjoint Z and Zbar indices); some balanced discrepancy has a
    nonzero mixed quadratic part, so degree 4 is the first with a gl-valued ambiguity.
(4) For sample rational M, N in gl(4): q(M) q(N) - q(N) q(M) = hbar q([M, N]), with
    q(M) = (1/2) sum M^b_a (Z^a Zbar_b + Zbar_b Z^a) (Lemma correspondence.symmetrised-quadratics-palatial-algebra).
"""
from fractions import Fraction as F
from itertools import combinations_with_replacement, permutations

import GA
from tp_premise import premise

LETTERS = [("Z", a) for a in range(4)] + [("B", a) for a in range(4)]
M_SAMPLE = [[F(1), F(2), F(0), F(-1)], [F(0), F(1, 2), F(3), F(0)], [F(-2), F(0), F(1), F(1)], [F(1, 3), F(1), F(0), F(-1)]]
N_SAMPLE = [[F(0), F(1), F(-1), F(0)], [F(2), F(0), F(0), F(1, 2)], [F(0), F(-3), F(1), F(0)], [F(1), F(0), F(2), F(-2)]]
_MEMO = {}


def normal(word):
    """Normal form of a word (tuple of letters) as {(h, zexp, bexp): coeff}."""
    if word in _MEMO:
        return _MEMO[word]
    for i in range(len(word) - 1):
        (t1, a1), (t2, a2) = word[i], word[i + 1]
        if t1 == "B" and t2 == "Z":
            swapped = word[:i] + (word[i + 1], word[i]) + word[i + 2:]
            out = dict(normal(swapped))
            if a1 == a2:
                for (h, z, b), c in normal(word[:i] + word[i + 2:]).items():
                    out[(h + 1, z, b)] = out.get((h + 1, z, b), F(0)) - c
            out = {k: v for k, v in out.items() if v != 0}
            _MEMO[word] = out
            return out
    z = [0] * 4
    b = [0] * 4
    for t, a in word:
        (z if t == "Z" else b)[a] += 1
    out = {(0, tuple(z), tuple(b)): F(1)}
    _MEMO[word] = out
    return out


def add(x, y, s=1):
    out = dict(x)
    for k, v in y.items():
        out[k] = out.get(k, F(0)) + s * v
    return {k: v for k, v in out.items() if v != 0}


def mul(x, y):
    out = {}
    for (h1, z1, b1), c1 in x.items():
        w1 = tuple([("Z", a) for a in range(4) for _ in range(z1[a])] + [("B", a) for a in range(4) for _ in range(b1[a])])
        for (h2, z2, b2), c2 in y.items():
            w2 = tuple([("Z", a) for a in range(4) for _ in range(z2[a])] + [("B", a) for a in range(4) for _ in range(b2[a])])
            for (h, z, b), c in normal(w1 + w2).items():
                key = (h + h1 + h2, z, b)
                out[key] = out.get(key, F(0)) + c * c1 * c2
    return {k: v for k, v in out.items() if v != 0}


def discrepancies(ms):
    base = normal(tuple(ms))
    return [add(normal(w), base, -1) for w in set(permutations(ms))]


def degree(key):
    h, z, b = key
    return sum(z) + sum(b)


def check_quadratic_ambiguities_are_central():
    ok = True
    total, nonzero = 0, 0
    for d in (0, 1, 2):
        for ms in combinations_with_replacement(LETTERS, d):
            total += 1
            ds = [x for x in discrepancies(ms) if x]
            ok = ok and all(h == 1 and degree((h, z, b)) == 0 for x in ds for (h, z, b) in x)
            if ds:
                nonzero += 1
                ok = ok and all(list(x.values()) in ([F(1)], [F(-1)]) for x in ds)
    ok = ok and total == 45 and nonzero == 4
    GA.check("(1) degree <= 2: ordering discrepancies are hbar times scalars; 4 multisets have one", ok)
    return ok


def check_cubic_ambiguities_are_linear():
    ok = True
    total, nonzero = 0, 0
    for ms in combinations_with_replacement(LETTERS, 3):
        total += 1
        ds = [x for x in discrepancies(ms) if x]
        ok = ok and all(h == 1 and degree((h, z, b)) == 1 for x in ds for (h, z, b) in x)
        nonzero += 1 if ds else 0
    ok = ok and total == 120 and nonzero == 32
    GA.check("(2) degree 3: discrepancies are hbar times linear terms; 32 multisets have one", ok)
    return ok


def check_quartic_ambiguities_and_balanced_mixed():
    premise("correspondence.symmetrised-quadratics-palatial-algebra")
    ok = True
    total, balanced, bal_nonzero, mixed_seen = 0, 0, 0, False
    for ms in combinations_with_replacement(LETTERS, 4):
        total += 1
        ds = [x for x in discrepancies(ms) if x]
        for x in ds:
            for (h, z, b) in x:
                ok = ok and ((h == 1 and degree((h, z, b)) == 2) or (h == 2 and degree((h, z, b)) == 0))
        nz = sum(1 for t, a in ms if t == "Z")
        if nz == 2:
            balanced += 1
            bal_nonzero += 1 if ds else 0
            for x in ds:
                quad = [(z, b) for (h, z, b) in x if h == 1]
                ok = ok and all(sum(z) == 1 and sum(b) == 1 for z, b in quad)
                mixed_seen = mixed_seen or bool(quad)
                M = [[F(0)] * 4 for _ in range(4)]
                for (h, z, b), c in x.items():
                    if h == 1:
                        M[b.index(1)][z.index(1)] += c
                rest = add({(h - 1, z, b): c for (h, z, b), c in x.items() if h == 1}, q(M), -1)
                ok = ok and all(degree(k) == 0 and k[0] == 1 for k in rest)
    ok = ok and total == 330 and balanced == 100 and bal_nonzero == 58 and mixed_seen
    GA.check("(3) degree 4: hbar quadratic + hbar^2 scalar; balanced ones mixed (58 of 100 nonzero)", ok)
    return ok


def q(M):
    out = {}
    for a in range(4):
        for b in range(4):
            if M[b][a] == 0:
                continue
            w1 = normal((("Z", a), ("B", b)))
            w2 = normal((("B", b), ("Z", a)))
            out = add(out, {k: M[b][a] * v * F(1, 2) for k, v in add(w1, w2).items()})
    return out


def check_balanced_discrepancy_is_q_of_commutator():
    premise("correspondence.symmetrised-quadratics-palatial-algebra")
    ok = True
    M, N = M_SAMPLE, N_SAMPLE
    MN = [[sum(M[i][k] * N[k][j] for k in range(4)) - sum(N[i][k] * M[k][j] for k in range(4))
           for j in range(4)] for i in range(4)]
    lhs = add(mul(q(M), q(N)), mul(q(N), q(M)), -1)
    rhs = {(h + 1, z, b): v for (h, z, b), v in q(MN).items()}
    ok = ok and lhs == rhs and lhs != {}
    one = [[F(1) if i == j else F(0) for j in range(4)] for i in range(4)]
    ok = ok and q(one).get((1, (0,) * 4, (0,) * 4)) == -2
    GA.check("(4) [q(M), q(N)] = hbar q([M, N]); q(id) has central shift -2 hbar", ok)
    return ok
