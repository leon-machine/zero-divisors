"""dark-energy.imported-walls-sphere-theorem: exact checks of the finite content of the imported Fact.

(1) Wall, radical and pole: on model tame walls (the Schwarzschild wall Gram in t = r, m = 2, and a
non-adapted polynomial family) the cometric has a one-dimensional radical at t = 0; the inverse has a
simple pole, lim t G^-1 = k (x) k / delta(k (x) k) != 0, and with the defining function tau = 2t the
residue doubles while delta halves: the pairing L (x) L -> N*Sigma is the nonzero scalar delta.
(2) The Clifford sheaf continues across the wall: along G = diag(h, t) the GA algebra has the
2^n blades as a basis for every t (degenerate t = 0 included, GA.sig(p, q, 1)); at the wall k^2 = 0,
k x k = 0 for every blade x, so the ideal A k A is square-zero, and A k has dimension 2^(n-1).
(3) Witt partner: in the completion (a hyperbolic pair adjoined) k = e_+ + e_- and k* = (e_+ - e_-)/4
are null with k k* + k* k = 1 (<k, k*> = 1/2); rescaling k* to <k, k*> = 1 spans the same subalgebra;
the ideal generated by k contains 1. Off the wall k_t^2 = t != 0 and k_t is invertible (k_t^-1 = k_t/t).
(4) Sphere: for n = 2..5 boundary modes the bilinears E_ij = a_i^dagger a_j on the 2^n-dimensional
Fock space satisfy the gl(n) relations and restrict to the matrix units on the one-particle space;
the principal sl(2) (J_3 = diag(j, ..., -j), J_+ with entries (j - m)(j + m + 1), J_- with ones) is
carried by the bilinears, J(X) = sum X_ij E_ij being a Lie homomorphism on the Fock space; on the
one-particle space the Casimir is j(j+1) with j = (n-1)/2 and J_+^(n-1) != 0 (irreducible), while a
block (non-principal) embedding 2 + 2 has J_+^2 = 0. The selection of the principal embedding rests on
the Indifference premise and is not checked.
"""
from fractions import Fraction as F
from itertools import combinations

import GA
from tp_premise import premise

RF, RF0, RF1 = GA.RF, GA.RF0, GA.RF1
T = RF.var()


def c(x):
    return RF.const(x)


M_SCH = 2
SCHW = [[c(M_SCH * M_SCH) - T, c(-M_SCH), RF0, RF0], [c(-M_SCH), RF1, RF0, RF0],
        [RF0, RF0, c(-1), RF0], [RF0, RF0, RF0, c(-1)]]
FAM = [[c(1) + T, T, RF0], [T, c(-1) + T * T, T], [RF0, T, c(2) * T]]


def ev(A, t):
    return [[x.eval(t) for x in row] for row in A]


def gk(G, k):
    acc = RF0
    for i in range(len(k)):
        for j in range(len(k)):
            acc = acc + c(k[i]) * G[i][j] * c(k[j])
    return acc


def check_radical_and_simple_pole():
    premise("sheaf.tameness")
    premise("sheaf.metrics-residue-square-root-twist")
    ok = True
    for G in (SCHW, FAM):
        n = len(G)
        G0 = ev(G, F(0))
        ker = GA.field_kernel([[F(x) for x in row] for row in G0])
        ok = ok and len(ker) == 1 and GA.mat_rank(G0) == n - 1
        k = ker[0]
        delta = gk(G, k).deriv().eval(F(0))
        ok = ok and delta != 0
        inv = GA.rf_mat_inverse(G)
        O = [[(T * x).eval(F(0)) for x in row] for row in inv]
        ok = ok and O == [[k[i] * k[j] / delta for j in range(n)] for i in range(n)]
        O2 = [[(c(2) * T * x).eval(F(0)) for x in row] for row in inv]
        ok = ok and O2 == [[2 * x for x in row] for row in O]
        # without the factor t the inverse blows up: some entry has a pole at the wall
        ok = ok and any(x.den != [F(1)] and x.den[0] == 0 for row in inv for x in row)
    # Schwarzschild by hand: k = (1, 2, 0, 0) up to scale, delta = -1 for that k
    k = GA.field_kernel([[F(x) for x in row] for row in ev(SCHW, F(0))])[0]
    k = [x / k[0] for x in k]
    ok = ok and k == [1, 2, 0, 0] and gk(SCHW, k).eqrf(-T)
    GA.check("walls: one-dimensional radical, simple pole with residue k (x) k / delta, delta != 0", ok)
    return ok


H_FORMS = ((1, 2), (1, 1), (0, 2))


def check_clifford_algebra_continues_with_square_zero_ideal():
    premise("sheaf.degeneration-sheaf")
    ok = True
    for p, q in H_FORMS:
        n = p + q + 1
        for t in (F(-1), F(0), F(1, 2)):
            sq = [F(1)] * p + [F(-1)] * q + [t]
            blades = GA.all_blades(n)
            ok = ok and len(blades) == 2 ** n
            k = GA.gen(n - 1)
            ok = ok and GA.eq(GA.mul(k, k, sq), GA.sc(t))
            if t == 0:
                ok = ok and all(GA.is_zero(GA.mul(GA.mul(k, {b: F(1)}, sq), k, sq)) for b in blades)
                Ak = [GA.mul({b: F(1)}, k, sq) for b in blades]
                support = [[x.get(b, F(0)) for b in blades] for x in Ak]
                ok = ok and GA.mat_rank(support) == 2 ** (n - 1)
    GA.check("walls: the Clifford algebra keeps its 2^n blades across the wall; the radical ideal is square-zero", ok)
    return ok


def check_witt_partner_exactly_at_the_wall():
    premise("sheaf.localised-transport")
    ok = True
    sq = [F(1), F(-1), F(-1), F(1), F(-1)]           # wall fibre e_0, e_1, e_2 and the pair e_+, e_-
    ep, em = GA.gen(3), GA.gen(4)
    k = GA.add(ep, em)
    ks = GA.scal(F(1, 4), GA.sub(ep, em))
    ok = ok and GA.is_zero(GA.mul(k, k, sq)) and GA.is_zero(GA.mul(ks, ks, sq))
    ok = ok and GA.eq(GA.add(GA.mul(k, ks, sq), GA.mul(ks, k, sq)), GA.sc(1)) and GA.dot(k, ks, sq) == F(1, 2)
    blades = GA.all_blades(5)

    def span_rank(xs):
        return GA.mat_rank([[x.get(b, F(0)) for b in blades] for x in xs])
    ks2 = GA.scal(2, ks)
    ok = ok and GA.dot(k, ks2, sq) == 1
    sub1 = [GA.sc(1), k, ks, GA.mul(k, ks, sq)]
    sub2 = [GA.sc(1), k, ks2, GA.mul(k, ks2, sq)]
    ok = ok and span_rank(sub1) == span_rank(sub2) == span_rank(sub1 + sub2) == 4
    # off the wall the dying covector is invertible: k_t = e_n with square t, inverse k_t / t
    for t in (F(1, 3), F(-2)):
        sqt = [F(1), F(-1), t]
        kt = GA.gen(2)
        ok = ok and GA.eq(GA.mul(kt, GA.scal(1 / t, kt), sqt), GA.sc(1))
    GA.check("walls: the Witt partner k* with k k* + k* k = 1 exists in the completion; off the wall k is a unit", ok)
    return ok


def fock(n):
    states = [frozenset(cmb) for r in range(n + 1) for cmb in combinations(range(n), r)]
    return states


def E_op(i, j, st):
    """a_i^dagger a_j on a state dict."""
    out = {}
    for S, a in st.items():
        if j not in S:
            continue
        s1 = -1 if sum(1 for x in S if x < j) % 2 else 1
        S2 = S - {j}
        if i in S2:
            continue
        s2 = -1 if sum(1 for x in S2 if x < i) % 2 else 1
        T2 = S2 | {i}
        out[T2] = out.get(T2, F(0)) + s1 * s2 * a
    return {k: v for k, v in out.items() if v != 0}


def J_op(X, st):
    out = {}
    n = len(X)
    for i in range(n):
        for j in range(n):
            if X[i][j] != 0:
                for k, v in E_op(i, j, st).items():
                    out[k] = out.get(k, F(0)) + X[i][j] * v
    return {k: v for k, v in out.items() if v != 0}


def principal(n):
    j = F(n - 1, 2)
    m = [j - i for i in range(n)]
    J3 = [[m[a] if a == b else F(0) for b in range(n)] for a in range(n)]
    Jp = [[(j - m[b]) * (j + m[b] + 1) if a == b - 1 else F(0) for b in range(n)] for a in range(n)]
    Jm = [[F(1) if a == b + 1 else F(0) for b in range(n)] for a in range(n)]
    return J3, Jp, Jm


def mcomm(A, B):
    AB, BA = GA.mat_mul(A, B), GA.mat_mul(B, A)
    return [[AB[i][k] - BA[i][k] for k in range(len(A))] for i in range(len(A))]


MODE_COUNTS = (2, 3, 4, 5)


def check_principal_su2_carried_by_boundary_bilinears():
    premise("scrambling.boundary-mode-space-matrix")
    premise("scrambling.principality-indifference-sphere")
    ok = True
    for n in MODE_COUNTS:
        states = fock(n)
        ok = ok and len(states) == 2 ** n
        # gl(n) relations and matrix units on the one-particle space
        for i in range(n):
            for j in range(n):
                for k in range(n):
                    for l in range(n):
                        for S in states:
                            lhs = E_op(i, j, E_op(k, l, {S: F(1)}))
                            rhs = E_op(k, l, E_op(i, j, {S: F(1)}))
                            want = {}
                            if j == k:
                                for x, v in E_op(i, l, {S: F(1)}).items():
                                    want[x] = want.get(x, F(0)) + v
                            if l == i:
                                for x, v in E_op(k, j, {S: F(1)}).items():
                                    want[x] = want.get(x, F(0)) - v
                            diff = dict(lhs)
                            for x, v in rhs.items():
                                diff[x] = diff.get(x, F(0)) - v
                            ok = ok and {x: v for x, v in diff.items() if v != 0} == \
                                {x: v for x, v in want.items() if v != 0}
                ok = ok and all(E_op(i, j, {frozenset({b}): F(1)}) == ({frozenset({i}): F(1)} if b == j else {})
                                for b in range(n))
        J3, Jp, Jm = principal(n)
        ok = ok and mcomm(J3, Jp) == Jp and mcomm(J3, Jm) == [[-x for x in r] for r in Jm]
        ok = ok and mcomm(Jp, Jm) == [[2 * x for x in r] for r in J3]
        # J is a Lie homomorphism on the Fock space
        for X, Y in ((J3, Jp), (J3, Jm), (Jp, Jm)):
            Z = mcomm(X, Y)
            for S in states:
                a = J_op(X, J_op(Y, {S: F(1)}))
                b = J_op(Y, J_op(X, {S: F(1)}))
                d = dict(a)
                for x, v in b.items():
                    d[x] = d.get(x, F(0)) - v
                ok = ok and {x: v for x, v in d.items() if v != 0} == J_op(Z, {S: F(1)})
        # one-particle space: Casimir j(j+1), and J_+^(n-1) != 0 (one irreducible block)
        j = F(n - 1, 2)
        cas = [[GA.mat_mul(J3, J3)[a][b] + (GA.mat_mul(Jp, Jm)[a][b] + GA.mat_mul(Jm, Jp)[a][b]) / 2
                for b in range(n)] for a in range(n)]
        ok = ok and cas == [[j * (j + 1) if a == b else F(0) for b in range(n)] for a in range(n)]
        P = Jp
        for _ in range(n - 2):
            P = GA.mat_mul(P, Jp)
        ok = ok and any(x != 0 for r in P for x in r)
    # a block embedding 2 + 2 of sl(2) in gl(4) is not principal: J_+^2 = 0
    blk = [[F(1) if (a, b) in ((0, 1), (2, 3)) else F(0) for b in range(4)] for a in range(4)]
    ok = ok and all(x == 0 for r in GA.mat_mul(blk, blk) for x in r)
    GA.check("walls: the principal su(2) acts through boundary-mode bilinears; Casimir j(j+1) on one particle", ok)
    return ok
