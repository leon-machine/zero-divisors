"""synthesis.bkl-bounce-invariant-holonomy-and-bound: exact checks.

Kasner exponents as rational functions of the BKL parameter u (GA.RF):
p1 = -u/(1+u+u^2), p2 = (1+u)/(1+u+u^2), p3 = u(1+u)/(1+u+u^2).
Checked exactly: the circle identities, the lower bound |p_i| >= 2/7 on 1 <= u <= 2 (the arc holding
the last epoch of every era) with equality only at u = 2, and the Lie algebra generated by the
weighted boosts -p_i B_i (the displayed values, GTG sign) in Cl(1,3): dimension 6 at points of the arc, with controls of dimension 3 (two
boosts) and 1 (the Taub point). The bounce map itself is the companion result's and is not rechecked.
"""
from fractions import Fraction as F
import GA
from GA import RF, gen, mul, sub, scal, rank_of_vectors, all_blades
from tp_premise import premise

SQ = (1, -1, -1, -1)
BL = [b for b in all_blades(4) if len(b) == 2]


def setup():
    premise("interior.weighted-limit-theorem")
    premise("interior.boosts-generate-exactly-levi-factor")
    premise("interior.transport-level-convergence-along-tangential-curves")


def kasner_rf():
    u = RF.var()
    one = RF.const(1)
    den = one + u + u * u
    return u, [-(u / den), (one + u) / den, (u * (one + u)) / den]


def p_at(u):
    den = 1 + u + u * u
    return (-u / den, (1 + u) / den, u * (1 + u) / den)


def comm(a, b):
    return sub(mul(a, b, SQ), mul(b, a, SQ))


def vec(x):
    return [x.get(b, F(0)) for b in BL]


def generated_dim(elems):
    """Dimension of the Lie algebra generated by bivectors elems (closure under commutators)."""
    basis = []
    def add_if_new(x):
        if not any(v != 0 for v in vec(x)):
            return False
        if rank_of_vectors([vec(y) for y in basis] + [vec(x)]) > len(basis):
            basis.append(x)
            return True
        return False
    for e in elems:
        add_if_new(e)
    grew = True
    while grew:
        grew = False
        for a in list(basis):
            for b in list(basis):
                if add_if_new(comm(a, b)):
                    grew = True
    return len(basis)


def check_circle_and_era_end():
    setup()
    u, p = kasner_rf()
    one = RF.const(1)
    assert (p[0] + p[1] + p[2]).eqrf(one)
    assert (p[0] * p[0] + p[1] * p[1] + p[2] * p[2]).eqrf(one)
    # every era ends in an epoch with 1 <= u <= 2, where |p_i| >= 2/7: p1 is decreasing in |.| towards u = 2
    # (|p1| = u/(1+u+u^2) has derivative (1 - u^2)/(...)^2 <= 0 on u >= 1) and p2, p3 lie in [3/7, 6/7]
    absp1 = u / (one + u + u * u)
    d = absp1.deriv()
    for t in (F(1), F(5, 4), F(3, 2), F(7, 4), F(2)):
        assert d.eval(t) <= 0
        a = p_at(t)
        assert min(abs(x) for x in a) >= F(2, 7)
    # p2 decreasing and p3 increasing on u >= 1: derivatives -u(2+u)/D^2 and (1+2u)/D^2
    d2, d3 = p[1].deriv(), p[2].deriv()
    for t in (F(1), F(5, 4), F(3, 2), F(2)):
        D = 1 + t + t * t
        assert d2.eval(t) == -t * (2 + t) / D ** 2 and d3.eval(t) == (1 + 2 * t) / D ** 2
    # equality in min |p_i| >= 2/7 only at u = 2 on the arc
    for t in (F(1), F(5, 4), F(3, 2), F(7, 4), F(199, 100)):
        assert min(abs(x) for x in p_at(t)) > F(2, 7)
    assert p_at(F(2)) == (F(-2, 7), F(3, 7), F(6, 7))
    assert p_at(F(1)) == (F(-1, 3), F(2, 3), F(2, 3))     # Schwarzschild exponents at u = 1
    return True


def check_generated_algebra():
    setup()
    B = [mul(gen(0), gen(i), SQ) for i in (1, 2, 3)]
    for t in (F(1), F(2), F(3, 2), F(11, 4)):
        p = p_at(t)
        assert all(x != 0 for x in p)
        # the displayed limiting values -p_i B_i (GTG sign of the Definition's Omega)
        assert generated_dim([scal(-p[i], B[i]) for i in range(3)]) == 6
    # Taub point (0, 0, 1): only one boost survives
    assert generated_dim([scal(F(0), B[0]), scal(F(0), B[1]), scal(F(1), B[2])]) == 1
    # two exponents nonzero and one zero (not on the circle, a control): three-dimensional so(1,2)
    assert generated_dim([B[0], B[1]]) == 3
    return True


def check_bound_epoch_independent():
    setup()
    # the Gronwall constant uses only ||sum u_i p_i B_i|| <= 1, by Cauchy-Schwarz with sum p^2 = 1:
    # check (sum |u_i p_i|)^2 <= 1 for rational unit u at Kasner points of several epochs
    units = [(F(3, 5), F(4, 5), F(0)), (F(2, 3), F(1, 3), F(2, 3)), (F(2, 7), F(6, 7), F(3, 7))]
    for t in (F(1), F(2), F(3), F(11, 4), F(29, 7)):
        p = p_at(t)
        for v in units:
            assert sum(x * x for x in v) == 1
            assert sum(abs(v[i] * p[i]) for i in range(3)) ** 2 <= 1
    return True
