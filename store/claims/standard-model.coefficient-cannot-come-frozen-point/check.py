"""standard-model.coefficient-cannot-come-frozen-point: exact checks of the computable sentences.

(1) However many rungs (R = 2, 3, 4), in GA's Cl over 3 pair modes and R rung modes (each mode an orthonormal
    pair e_{2m}^2 = +1, e_{2m+1}^2 = -1, v_m = (e_{2m} - e_{2m+1})/2, w_m = (e_{2m} + e_{2m+1})/2): the frozen
    point I = a v_1 + b w_1 and every rung vector pairwise anticommute with scalar squares, so the algebra they
    generate is spanned by the 2 * 4^R products of distinct generators (rank computed); no blade of it carries
    an index of pair modes 2 or 3, so the pair-sector bivector sum_i v_i ^ w_i is not in it (rank rises by one).
    Every polynomial in the frozen point and any lifts (whose rung components are rung vectors) lies in this
    algebra.
(2) On the module (R = 2, EXPORTS of families.doublet-direction-module-georgi-jarlskog-clebsch): the algebra
    generated by I and all four rung mode operators is 32-dimensional; its colour-singlet part (an exact kernel)
    is the 16-dimensional rung Clifford algebra; the symmetric doublet forms of its odd singlet elements with
    Y = -1/2, T_3 = -1/2 span one dimension, the 10 form; the space of all such forms (EXPORTS of
    standard-model.space-symmetric-doublet-mass-forms-two) is two-dimensional, and the extra direction is
    T_GJ's, which is outside the frozen-point algebra (consistent with standard-model.no-go-frozen-point-lifts-do).
(3) The closed form: every blade of T_GJ in Cl(5,5) contains exactly one pair-mode bivector e_{2i} e_{2i+1}
    (i = 1, 2, 3), and sum_i v_i ^ w_i = -3/2 (B - L): the pair sector enters T_GJ through the B - L generator.
The last two sentences of the statement (the bracket's B - L structure is "the right kind"; whether a neutral
composite reaches T_GJ) are a reading and an open computation, not checked here.
"""
from fractions import Fraction as F
from itertools import combinations

import GA
from tp_premise import premise

AB = (F(2), F(-3))       # sample frozen point coefficients (ab != 0)
RUNGS = (2, 3, 4)


def _module():
    return premise("families.doublet-direction-module-georgi-jarlskog-clebsch")["module"]


def big_algebra(R, a, b):
    sq = tuple([1, -1] * (3 + R))
    I = {(0,): (a + b) / 2, (1,): (b - a) / 2}
    rung = [{(i,): F(1)} for i in range(6, 6 + 2 * R)]
    gs = [I] + rung
    prods = []
    for k in range(len(gs) + 1):
        for idx in combinations(range(len(gs)), k):
            x = {(): F(1)}
            for t in idx:
                x = GA.mul(x, gs[t], sq)
            prods.append(x)
    return sq, gs, prods


def check_no_rung_count_reaches_pair_bivector():
    M = _module()
    premise("standard-model.no-go-frozen-point-lifts-do")
    ok = True
    pairbiv = GA.add(*[M["gwedge2"](M["gv"](i), M["gw"](i)) for i in M["PAIRS"]])
    for R in RUNGS:
        sq, gs, prods = big_algebra(R, *AB)
        ok = ok and all(GA.anticommutes(x, y, sq) for x, y in combinations(gs, 2))
        ok = ok and all(set(GA.mul(x, x, sq)) == {()} for x in gs)
        ok = ok and M["rank"](prods) == 2 * 4 ** R
        used = {i for x in prods for bl in x for i in bl}
        ok = ok and used == {0, 1} | set(range(6, 6 + 2 * R))
        ok = ok and M["rank"](prods + [pairbiv]) == 2 * 4 ** R + 1
    GA.check("frozen point plus rung vectors, for 2, 3, 4 rungs: dimension 2*4^R, no pair-mode 2, 3 index, no B-L", ok)
    return ok


def check_frozen_point_forms_are_the_ten():
    M = _module()
    premise("standard-model.no-go-frozen-point-lifts-do")
    sym_forms = premise("standard-model.space-symmetric-doublet-mass-forms-two")["doublet_forms"]
    mm, madd, msc, rank, kernel = M["mm"], M["madd"], M["msc"], M["rank"], M["kernel"]
    a, b = AB
    I = madd(msc(a, M["V"][0]), msc(b, M["W"][0]))
    rmons = []
    for S in (s for k in range(3) for s in combinations((3, 4), k)):
        for T in (t for k in range(3) for t in combinations((3, 4), k)):
            rmons.append(mm(M["ONE"], *([M["V"][m] for m in S] + [M["W"][m] for m in T])))
    alg = rmons + [mm(I, X) for X in rmons]
    ok = rank(rmons) == 16 and rank(alg) == 32
    imgs = []
    for X in alg:
        out = {}
        for gi, g in enumerate(M["SU3"]):
            for k, x in M["comm"](g, X).items():
                out[(gi,) + k] = x
        imgs.append(out)
    _, ker = kernel(imgs)
    singlets = [madd(*[msc(x, alg[i]) for i, x in c.items()]) for c in ker]
    ok = ok and len(singlets) == 16 and rank(singlets + rmons) == 16
    dbl = [X for X in rmons if X and M["op_weight"](M["HYP"], X) == F(-1, 2)
           and M["op_weight"](M["T3"], X) == F(-1, 2)]
    fdbl = [M["sym"](M["form"](X)) for X in dbl]
    f10 = M["sym"](M["form"](M["W"][3]))
    fGJ = M["sym"](M["form"](M["T_GJ"]()))
    ok = ok and len(dbl) == 2 and rank(fdbl) == 1 and rank(fdbl + [f10]) == 1
    _, _, allforms = sym_forms(M)
    ok = ok and rank(allforms) == 2 and rank(fdbl + [fGJ]) == 2 and rank(allforms + [f10, fGJ]) == 2
    ok = ok and rank(alg + [M["T_GJ"]()]) == 33
    GA.check("I with all rung operators: 32-dim, colour singlets = rung Clifford algebra, doublet forms = the 10 only", ok)
    return ok


def check_t_gj_needs_the_pair_bivector():
    M = _module()
    premise("families.doublet-direction-module-georgi-jarlskog-clebsch")
    t = M["ga_TGJ"]()
    pairs = [(2 * i, 2 * i + 1) for i in M["PAIRS"]]
    ok = len(t) == 6
    ok = ok and all(sum(1 for p in pairs if set(p) <= set(bl)) == 1 for bl in t)
    ok = ok and all(len(set(bl) & set(range(6))) == 2 for bl in t)
    pairbiv = GA.add(*[M["gwedge2"](M["gv"](i), M["gw"](i)) for i in M["PAIRS"]])
    ok = ok and GA.eq(pairbiv, GA.scal(F(-3, 2), M["ga_BL"]()))
    GA.check("each blade of T_GJ carries one pair-mode bivector; sum v_i^w_i = -3/2 (B - L)", ok)
    return ok
