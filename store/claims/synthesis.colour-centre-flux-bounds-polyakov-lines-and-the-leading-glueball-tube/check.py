E9 = GA.sig(9, 0)
IDX = tuple(range(3, 9))
EVEN = [b for k in (0, 2, 4, 6) for b in combinations(IDX, k)]
POS = {b: i for i, b in enumerate(EVEN)}
TAB = []
for _a in EVEN:
    _row = []
    for _b in EVEN:
        _s, _c = GA.blade_mul(_a, _b, E9)
        _row.append((int(_s), POS[_c]))
    TAB.append(_row)


def m(x, y):
    out = [F(0)] * 32
    for i, a in enumerate(x):
        if a:
            row = TAB[i]
            for j, b in enumerate(y):
                if b:
                    s, k = row[j]
                    out[k] = out[k] + s * a * b
    return tuple(out)


def arr(mv):
    a = [F(0)] * 32
    for b, c in mv.items():
        a[POS[b]] += c
    return tuple(a)


def mvec(x):
    return {EVEN[i]: c for i, c in enumerate(x) if c}


def rev(x):
    return tuple(c if len(EVEN[i]) % 4 == 0 else -c for i, c in enumerate(x))


def add(*xs):
    return tuple(sum(c, F(0)) for c in zip(*xs))


def sca(c, x):
    return tuple(c * v for v in x)


def blade(*ix):
    r = GA.sc(1)
    for i in ix:
        r = GA.mul(r, GA.gen(i), E9)
    return r


ONE = arr(GA.sc(1))
I6 = arr(blade(*IDX))
P34, P56, P78 = arr(blade(3, 4)), arr(blade(5, 6)), arr(blade(7, 8))
JB = add(P34, P56, P78)
HALF = F(1, 2)
E = ONE
for _p in (P34, P56, P78):
    E = m(E, sca(HALF, add(ONE, m(I6, _p))))
JMV = mvec(JB)
RE_OM = GA.add(blade(3, 5, 7), GA.scal(-1, blade(3, 6, 8)), GA.scal(-1, blade(4, 5, 8)), GA.scal(-1, blade(4, 6, 7)))
IM_OM = GA.add(blade(4, 5, 7), blade(3, 6, 7), blade(3, 5, 8), GA.scal(-1, blade(4, 6, 8)))


def gcomm(x, y):
    return GA.sub(GA.mul(x, y, E9), GA.mul(y, x, E9))


def su3_basis():
    so6 = [blade(i, j) for i, j in combinations(IDX, 2)]
    rows = sorted({b for x in so6 for b in gcomm(x, JMV)})
    M = [[gcomm(x, JMV).get(r, F(0)) for x in so6] for r in rows]
    u3 = [GA.add(*[GA.scal(v[i], so6[i]) for i in range(len(so6)) if v[i] != 0]) for v in GA.field_kernel(M)]
    jj = GA.mul(JMV, JMV, E9).get((), F(0))
    out = []
    for x in u3:
        y = GA.sub(x, GA.scal(GA.mul(x, JMV, E9).get((), F(0)) / jj, JMV))
        trial = out + [y]
        keys = sorted({b for z in trial for b in z})
        if y and GA.field_rank([[z.get(k, F(0)) for k in keys] for z in trial]) == len(trial):
            out.append(y)
    return out


def sandwich(R, v):
    return GA.mul(GA.mul(mvec(R), v, E9), mvec(rev(R)), E9)


def vec_action(R):
    """integer matrix M[a][b] = e_a . f_R(e_b)"""
    cols = []
    for k in IDX:
        y = sandwich(R, GA.gen(k))
        assert all(len(b) == 1 for b in y)
        cols.append([y.get((t,), F(0)) for t in IDX])
    return tuple(tuple(int(cols[b][a]) for b in range(6)) for a in range(6))


def jmat():
    out = [[0] * 6 for _ in range(6)]
    for b, k in enumerate(IDX):
        y = GA.mul(GA.gen(k), JMV, E9)
        for a, t in enumerate(IDX):
            out[a][b] = int(y.get((t,), F(0)))
    return out


def lift(R):
    RE = m(R, E)
    return R if RE == E else sca(-1, R)


def pair_rotor(a, b, c, d):
    x = GA.sub(GA.gen(a), GA.gen(b))
    y = GA.sub(GA.gen(c), GA.gen(d))
    return arr(GA.scal(HALF, GA.mul(x, y, E9)))


GENS = [lift(sca(HALF, m(add(ONE, sca(-1, P34)), add(ONE, P56)))),
        lift(sca(HALF, m(add(ONE, sca(-1, P56)), add(ONE, P78)))),
        lift(m(pair_rotor(5, 7, 6, 8), pair_rotor(3, 5, 4, 6))),
        lift(m(pair_rotor(3, 5, 4, 6), P78))]


def closure(gens):
    elems = {ONE: None}
    frontier = [ONE]
    while frontier:
        new = []
        for x in frontier:
            for g in gens:
                y = m(x, g)
                if y not in elems:
                    elems[y] = None
                    new.append(y)
        frontier = new
    return list(elems)


G = closure(GENS)
_CACHE = {}


def table():
    if 'mul' not in _CACHE:
        idx = {R: i for i, R in enumerate(G)}
        _CACHE['mul'] = [[idx[m(a, b)] for b in G] for a in G]
        _CACHE['inv'] = [idx[rev(a)] for a in G]
        _CACHE['id'] = idx[ONE]
    return _CACHE['mul'], _CACHE['inv'], _CACHE['id']


def chi(R):
    """fundamental character as (Re, Im): 4(<R>_0 + <R>_6) - 1 with I standing for i"""
    return (4 * R[0] - 1, 4 * R[POS[IDX]])


def w(R):
    return (4 * R[0] - 1) / 3


def cm(a, b):
    return (a[0] * b[0] - a[1] * b[1], a[0] * b[1] + a[1] * b[0])


def cbar(a):
    return (a[0], -a[1])


def avg(vals):
    vals = list(vals)
    return (sum((v[0] for v in vals), F(0)) / len(vals), sum((v[1] for v in vals), F(0)) / len(vals))


def tensor_of(T):
    """totally antisymmetric 6x6x6 array of a trivector"""
    out = {}
    for b, c in T.items():
        for perm in __import__('itertools').permutations(range(3)):
            sgn = 1
            p = list(perm)
            for i in range(3):
                for j in range(i + 1, 3):
                    if p[i] > p[j]:
                        sgn = -sgn
            out[tuple(IDX.index(b[q]) for q in perm)] = sgn * int(c)
    return out


def outer3(M, T):
    """outermorphism of the vector map M on a trivector T"""
    out = {}
    for b, c in T.items():
        vs = [{(IDX[a],): F(M[a][IDX.index(k)]) for a in range(6) if M[a][IDX.index(k)]} for k in b]
        x = GA.mul(GA.mul(vs[0], vs[1], E9), vs[2], E9)
        x = {bb: cc for bb, cc in x.items() if len(bb) == 3}
        out = GA.add(out, GA.scal(c, x))
    return out


class Q3(object):
    """exact a + b sqrt(3), a, b rational"""

    def __init__(self, a, b=0):
        self.a, self.b = F(a), F(b)

    def _c(self, o):
        return o if isinstance(o, Q3) else Q3(o)

    def __add__(self, o):
        o = self._c(o)
        return Q3(self.a + o.a, self.b + o.b)
    __radd__ = __add__

    def __neg__(self):
        return Q3(-self.a, -self.b)

    def __sub__(self, o):
        return self + (-self._c(o))

    def __mul__(self, o):
        o = self._c(o)
        return Q3(self.a * o.a + 3 * self.b * o.b, self.a * o.b + self.b * o.a)
    __rmul__ = __mul__

    def __eq__(self, o):
        o = self._c(o)
        return self.a == o.a and self.b == o.b

    def __hash__(self):
        return hash((self.a, self.b))

    def __bool__(self):
        return self.a != 0 or self.b != 0


