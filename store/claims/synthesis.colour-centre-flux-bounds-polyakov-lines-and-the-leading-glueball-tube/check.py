"""synthesis.colour-centre-flux-bounds-polyakov-lines-and-the-leading-glueball-tube: exact checks.

The colour factor su(3) as the eight traceless bivectors of the block e3..e8 of Cl(9,0) commuting with
J = e34 + e56 + e78 (the realisation of the stored field-level BRST result). I = e345678, P_k = e34, e56, e78,
the pure-spinor idempotent E = prod_k (1 + I P_k)/2, and the trivectors Re Omega = e357 - e368 - e458 - e467,
Im Omega = e457 + e367 + e358 - e468 (the J-complex volume form on the frame e3, e5, e7 with J-partners
e4, e6, e8; the complex structure on vectors is v -> v.J, e3 -> e4). A colour rotor is a rotor R of
the block (even, R rev(R) = 1, R v rev(R) a vector for every vector v) with R E = E; f_R(v) = R v rev(R) is its vector action.
Products in the 32-dimensional even subalgebra of the block use a blade table built from GA.blade_mul and are
checked against GA.mul on all basis pairs. The finite group G (order 96) is generated by four rational
rotors (two quarter-turn tori and two J-commuting signed permutations), each with the sign fixed by R E = E.
Haar averages on SU(3) are not imported: for a compact group the average of a representation is the
orthogonal projector onto its invariants, and the checks show that the G-invariants of the vector action in
degrees 1, 2, 3 (and of left multiplication on the even subalgebra) are spanned by tensors that every colour
rotor fixes, so G-averages equal Haar averages there (the argument is in the proof).
The centre rotor needs sqrt(3): it is computed in Q(sqrt 3) with a two-component exact number class.
Lattice integrals: tree gauge with the multiplication table of G, and, independently, closed-surface tensor
contraction with the degree-2 moment int f_ab f_cd = (delta delta + J J)/6.
"""
from fractions import Fraction as F
