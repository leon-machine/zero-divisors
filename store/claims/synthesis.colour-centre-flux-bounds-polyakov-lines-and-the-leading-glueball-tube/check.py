def check_colour_block_pure_spinor_and_det_one():
    premise("standard-model.gauge-algebra-minimal-massive-composite")
    premise("synthesis.field-level-brst-differential-of-the-derived-gauge-fields-is-nilpotent")
    for a in EVEN:
        for b in EVEN:
            assert arr(GA.mul({a: F(1)}, {b: F(1)}, E9)) == m(arr({a: F(1)}), arr({b: F(1)}))
    su3 = su3_basis()
    assert len(su3) == 8
    # E: Hermitian idempotent with scalar part 1/4; P_k E = -I E; J E = -3 I E
    assert m(E, E) == E and rev(E) == E and E[0] == F(1, 4)
    for p in (P34, P56, P78):
        assert m(p, E) == sca(-1, m(I6, E))
    assert m(JB, E) == sca(-3, m(I6, E))
    # the bivectors annihilating E are exactly su(3)
    so6 = [arr(blade(i, j)) for i, j in combinations(IDX, 2)]
    rows = sorted({k for x in so6 for k, c in enumerate(m(x, E)) if c})
    ker = GA.field_kernel([[m(x, E)[r] for x in so6] for r in rows])
    assert len(ker) == 8
    kers = [add(*[sca(v[i], so6[i]) for i in range(15)]) for v in ker]
    allv = [list(arr(b)) for b in su3] + [list(k) for k in kers]
    assert GA.field_rank(allv) == 8
    # su(3) fixes J and both parts of Omega; J itself turns Omega
    for b in su3:
        assert not gcomm(b, JMV) and not gcomm(b, RE_OM) and not gcomm(b, IM_OM)
    assert GA.eq(gcomm(JMV, RE_OM), GA.scal(-6, IM_OM)) and GA.eq(gcomm(JMV, IM_OM), GA.scal(6, RE_OM))
    # the four generators: rotors, R E = E, commute with J, fix Re Omega and Im Omega
    for R in GENS:
        assert m(R, rev(R)) == ONE and m(R, E) == E and m(R, JB) == m(JB, R)
        assert GA.eq(sandwich(R, RE_OM), RE_OM) and GA.eq(sandwich(R, IM_OM), IM_OM)
    # R R~ = 1 and R E = E do not make a rotor: R = exp(-3 phi I/2) exp(-phi J/2), cos(phi/2) = 3/5
    c, s = F(3, 5), F(4, 5)
    half_turn = ONE
    for p in (P34, P56, P78):
        half_turn = m(half_turn, add(sca(c, ONE), sca(-s, p)))
    c3, s3 = 4 * c ** 3 - 3 * c, 3 * s - 4 * s ** 3
    bad = m(add(sca(c3, ONE), sca(-s3, I6)), half_turn)
    assert (c3, s3) == (F(-117, 125), F(44, 125))
    assert m(bad, rev(bad)) == ONE and m(bad, E) == E
    img = sandwich(bad, GA.gen(3))
    assert sorted({len(b) for b in img}) == [1, 5]
    # the rotor condition excludes it, and every element of G satisfies it
    assert all(all(len(b) == 1 for b in sandwich(R, GA.gen(k))) for R in GENS for k in IDX)
    # the J quarter turn (det = -i): Re Omega -> -Im Omega, so U(3) does not fix it
    K = tuple(tuple(row) for row in jmat())
    assert GA.eq(outer3(K, RE_OM), GA.scal(-1, IM_OM)) and GA.eq(outer3(K, IM_OM), RE_OM)


def check_finite_colour_group_reproduces_haar_through_degree_three():
    premise("synthesis.field-level-brst-differential-of-the-derived-gauge-fields-is-nilpotent")
    assert len(G) == 96 and sca(-1, ONE) not in G
    assert all(m(R, E) == E for R in G)
    Ms = [vec_action(R) for R in G]
    Jm = jmat()
    tr = [sum(M[i][i] for i in range(6)) for M in Ms]
    # dimension of the G-invariants in degree k: average of tr^k
    dims = [F(sum(x ** k for x in tr), len(G)) for k in (1, 2, 3)]
    assert dims == [0, 2, 2]
    # degree 1: average zero
    for a in range(6):
        for b in range(6):
            assert sum(M[a][b] for M in Ms) == 0
    # degree 2: (delta delta + J J)/6
    for i, a, j, b in product(range(6), repeat=4):
        s = sum(M[i][a] * M[j][b] for M in Ms)
        assert F(s, 96) == F(int(i == j) * int(a == b) + Jm[i][j] * Jm[a][b], 6)
    # degree 3: (Re Omega Re Omega + Im Omega Im Omega)/24, totally antisymmetric
    TR, TI = tensor_of(RE_OM), tensor_of(IM_OM)
    assert sum(v * v for v in TR.values()) == 24
    for i, j, k in product(range(6), repeat=3):
        rows = [(M[i], M[j], M[k]) for M in Ms]
        for a, b, c in product(range(6), repeat=3):
            s = sum(r0[a] * r1[b] * r2[c] for r0, r1, r2 in rows)
            assert F(s, 96) == F(TR.get((i, j, k), 0) * TR.get((a, b, c), 0) + TI.get((i, j, k), 0) * TI.get((a, b, c), 0), 24)
    # the same in wedge form, on all twenty basis trivectors: int f(T) = (<T ~ReO> ReO + <T ~ImO> ImO)/4
    for b in combinations(IDX, 3):
        T = {b: F(1)}
        acc = {}
        for M in Ms:
            acc = GA.add(acc, outer3(M, T))
        rhs = GA.add(GA.scal(GA.mul(T, GA.reverse(RE_OM), E9).get((), F(0)), RE_OM),
                     GA.scal(GA.mul(T, GA.reverse(IM_OM), E9).get((), F(0)), IM_OM))
        assert GA.eq(GA.scal(F(1, 96), acc), GA.scal(F(1, 4), rhs))
    # rotor average: left multiplication on the even subalgebra has 8 invariant dimensions (the right ideal E Cl+)
    assert sum(32 * R[0] for R in G) / 96 == 8
    ideal = [list(m(E, arr({b: F(1)}))) for b in EVEN]
    assert GA.field_rank(ideal) == 8
    assert tuple(sum((R[i] for R in G), F(0)) / 96 for i in range(32)) == E
    # the vector actions span the 18-dimensional J-commuting matrices (Burnside), used for completeness
    assert GA.field_rank([[M[i][j] for i in range(6) for j in range(6)] for M in Ms]) == 18


def check_character_from_scalar_and_pseudoscalar_parts():
    premise("synthesis.field-level-brst-differential-of-the-derived-gauge-fields-is-nilpotent")
    Jm = jmat()
    tests = list(G)
    # rational torus rotors with theta_1 + theta_2 + theta_3 = 0, conjugated by elements of G
    c1 = add(sca(F(3, 5), ONE), sca(F(-4, 5), P34))
    c2 = add(sca(F(3, 5), ONE), sca(F(4, 5), P56))
    c3 = add(sca(F(5, 13), ONE), sca(F(-12, 13), P56))
    c4 = add(sca(F(5, 13), ONE), sca(F(12, 13), P78))
    for T in (m(c1, c2), m(c3, c4), m(m(c1, c2), m(c3, c4))):
        assert m(T, E) == E
        for g in G[:12]:
            tests.append(m(m(g, T), rev(g)))
    for R in tests:
        M = [[GA.mul(GA.gen(IDX[a]), sandwich(R, GA.gen(IDX[b])), E9).get((), F(0)) for b in range(6)] for a in range(6)]
        re = HALF * sum(M[i][i] for i in range(6))
        im = -HALF * sum(Jm[i][k] * M[k][i] for i in range(6) for k in range(6))
        assert chi(R) == (re, im)
    # the plaquette weight: 1 - w(U) = (4/3)(1 - <U>_0)
    for R in tests[:40]:
        assert 1 - w(R) == F(4, 3) * (1 - R[0])
    # U(3) contrast: the J quarter turn (vector level) averages Re Omega to zero over its cyclic group
    K = tuple(tuple(row) for row in jmat())
    acc, T = {}, RE_OM
    for _ in range(4):
        acc = GA.add(acc, T)
        T = outer3(K, T)
    assert acc == {} and GA.eq(T, RE_OM)


