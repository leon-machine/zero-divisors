def surface_integral(faces):
    """int prod_f w(U_f) over all links, each link in exactly two faces, by int f_ab f_cd = (dd + JJ)/6."""
    occ = {}
    for f, face in enumerate(faces):
        L = len(face)
        for k, (l, d) in enumerate(face):
            occ.setdefault(l, []).append(((f, k), (f, (k + 1) % L)) if d > 0 else ((f, (k + 1) % L), (f, k)))
    links = sorted(occ)
    adj = {}
    for li, l in enumerate(links):
        assert len(occ[l]) == 2
        (r1, c1), (r2, c2) = occ[l]
        for a, b in ((r1, r2), (c1, c2)):
            adj.setdefault(a, []).append((b, li, 1))
            adj.setdefault(b, []).append((a, li, -1))
    used, cycles, seen = set(), [], set()
    for start in adj:
        if start in seen:
            continue
        cyc, node = [], start
        while True:
            seen.add(node)
            for e in adj[node]:
                key = (min(node, e[0]), max(node, e[0]), e[1])
                if key not in used:
                    used.add(key)
                    cyc.append((e[1], e[2]))
                    node = e[0]
                    break
            if node == start:
                break
        cycles.append(cyc)
    total = F(0)
    for sig in product((0, 1), repeat=len(links)):
        val = 1
        for cyc in cycles:
            k, sgn = 0, 1
            for li, d in cyc:
                if sig[li]:
                    k += 1
                    sgn = -sgn if d < 0 else sgn
            if k % 2:
                val = 0
                break
            val *= sgn * (6 if k % 4 == 0 else -6)
        total += val
    return total / F(6) ** len(links) / F(6) ** len(faces)


def _link(a, b):
    return ((a, b) if a < b else (b, a)), (1 if a < b else -1)


def _loop(cs):
    return [_link(a, b) for a, b in zip(cs, cs[1:] + cs[:1])]


def disc_faces(R, T):
    faces = [_loop([(x, y), (x + 1, y), (x + 1, y + 1), (x, y + 1)]) for x in range(R) for y in range(T)]
    bd = [(x, 0) for x in range(R + 1)] + [(R, y) for y in range(1, T + 1)]
    bd += [(x, T) for x in range(R - 1, -1, -1)] + [(0, y) for y in range(T - 1, 0, -1)]
    return faces + [_loop(bd)]


def tube_faces(t):
    sq = [(0, 0), (1, 0), (1, 1), (0, 1)]
    faces = [_loop([(x, y, 0) for x, y in sq]), _loop([(x, y, t) for x, y in sq])]
    for tau in range(t):
        for (x, y), (x2, y2) in zip(sq, sq[1:] + sq[:1]):
            faces.append(_loop([(x, y, tau), (x2, y2, tau), (x2, y2, tau + 1), (x, y, tau + 1)]))
    return faces


