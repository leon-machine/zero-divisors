"""standard-model.pair-mixing-not-colour: exact checks.

The conformal spinor's Fock space Lambda(W), W = span(v_1, v_2, v_3), is built as 8 x 8 matrices over
Q(i) (GA.QI) in the occupation basis; v_a creates, w_a = v_a^dagger contracts. A real form so(2,4) is
generated by six Clifford generators of signature (2,4): v_1 + w_1, v_2 + w_2 (square +1, Hermitian)
and v_1 - w_1, v_2 - w_2, v_3 - w_3, i(v_3 + w_3) (square -1, anti-Hermitian); its 15 bivectors
(1/2) g_m g_n span the conformal algebra. u(3) is spanned over R by i E_aa, E_ab - E_ba,
i(E_ab + E_ba) with E_ab = v_a w_b.
(i) The traceless parts of v_a w_b lie in the complex span of the 15 bivectors (inside so(6,C));
u(3) is anti-Hermitian of real dimension 9; the compact part of so(2,4) (its anti-Hermitian
elements) has real dimension 7 = dim so(2) + so(4); u(3) mod scalars is not in the real span of
so(2,4). With the imported maximal-compact Fact this gives (i).
(ii) The commutant of the 15 bivectors in M_8(C) is computed by exact elimination: dimension 2,
spanned by the projections onto Lambda^even W and Lambda^odd W; every one of the nine u(3) generators
fails to commute with some bivector.
(iii) On Fock (x) C^3 (the label copy carried by the hierarchy bundle), the conformal bivectors act as
X (x) 1 and the colour generators as 1 (x) T: they commute, while the pair mixing on the Fock factor
does not. The remaining sentences of (iii) are readings and are not checked.
"""
from fractions import Fraction as F
from itertools import combinations

import GA
from tp_premise import premise

QI = GA.QI
STATES = [frozenset(c) for r in range(4) for c in combinations((1, 2, 3), r)]
IDX = {S: i for i, S in enumerate(STATES)}
DIM = 8


def zeros(n=DIM):
    return [[QI(0)] * n for _ in range(n)]


def mode(kind, a):
    M = zeros()
    for S in STATES:
        if kind == "v" and a not in S:
            T = S | {a}
        elif kind == "w" and a in S:
            T = S - {a}
        else:
            continue
        sign = -1 if sum(1 for j in S if j < a) % 2 else 1
        M[IDX[T]][IDX[S]] = QI(sign)
    return M


def mm(A, B):
    return [[sum((A[i][k] * B[k][j] for k in range(len(B))), QI(0)) for j in range(len(B[0]))] for i in range(len(A))]


def lin(*terms):
    n = len(terms[0][1])
    return [[sum((QI(0) + c * M[i][j] for c, M in terms), QI(0)) for j in range(n)] for i in range(n)]


def dag(A):
    return [[A[j][i].conj() for j in range(len(A))] for i in range(len(A))]


def comm(A, B):
    return lin((QI(1), mm(A, B)), (QI(-1), mm(B, A)))


def is_zero(A):
    return all(x == 0 for row in A for x in row)


def ident(n=DIM):
    return [[QI(1) if i == j else QI(0) for j in range(n)] for i in range(n)]


V = {a: mode("v", a) for a in (1, 2, 3)}
W = {a: mode("w", a) for a in (1, 2, 3)}
I_ = QI(0, 1)
GENS = [lin((QI(1), V[1]), (QI(1), W[1])), lin((QI(1), V[2]), (QI(1), W[2])),
        lin((QI(1), V[1]), (QI(-1), W[1])), lin((QI(1), V[2]), (QI(-1), W[2])),
        lin((QI(1), V[3]), (QI(-1), W[3])), lin((I_, V[3]), (I_, W[3]))]
BIV = [lin((QI(F(1, 2)), mm(GENS[m], GENS[n]))) for m, n in combinations(range(6), 2)]
E = {(a, b): mm(V[a], W[b]) for a in (1, 2, 3) for b in (1, 2, 3)}
U3 = ([lin((I_, E[(a, a)])) for a in (1, 2, 3)]
      + [lin((QI(1), E[(a, b)]), (QI(-1), E[(b, a)])) for a, b in combinations((1, 2, 3), 2)]
      + [lin((I_, E[(a, b)]), (I_, E[(b, a)])) for a, b in combinations((1, 2, 3), 2)])


def flat_c(A):
    return [x for row in A for x in row]


def flat_r(A):
    return [y for x in flat_c(A) for y in (x.re, x.im)]


def traceless(A):
    t = sum((A[i][i] for i in range(DIM)), QI(0)) / DIM
    return lin((QI(1), A), (-t, ident()))


def check_pair_mixing_is_compact_and_outside_the_real_form():
    premise("standard-model.imported-maximal-compact-subgroups")
    ok = True
    # the six generators have the stated squares: signature (2, 4)
    squares = [mm(g, g)[0][0] for g in GENS]
    ok = ok and squares == [1, 1, -1, -1, -1, -1]
    ok = ok and (len(GENS) == len(squares) and all(mm(g, g) == lin((sq, ident())) for g, sq in zip(GENS, squares)))
    # traceless parts of v_a w_b lie in the complex span of the 15 bivectors
    base = [flat_c(X) for X in BIV]
    ok = ok and GA.field_rank(base) == 15
    ok = ok and all(GA.field_rank(base + [flat_c(traceless(E[k]))]) == 15 for k in E)
    # u(3): anti-Hermitian, real dimension 9
    ok = ok and all(dag(X) == lin((QI(-1), X)) for X in U3)
    ok = ok and GA.mat_rank([flat_r(X) for X in U3]) == 9
    # compact part of so(2,4): every bivector is Hermitian or anti-Hermitian; 7 anti-Hermitian
    herm = [X for X in BIV if dag(X) == X]
    anti = [X for X in BIV if dag(X) == lin((QI(-1), X))]
    ok = ok and len(herm) + len(anti) == 15 and len(anti) == 7
    # u(3) mod scalars is not inside the real span of so(2,4)
    real_so = [flat_r(X) for X in BIV]
    ok = ok and GA.mat_rank(real_so) == 15
    ok = ok and GA.mat_rank(real_so + [flat_r(traceless(X)) for X in U3]) > 15
    ok = ok and 9 > len(anti)
    GA.check("pair mixing (i): u(3) compact of dimension 9 > 7, inside so(6,C) but not in so(2,4)", ok)
    return ok


def check_commutant_is_two_dimensional():
    ok = True
    # unknown M (64 entries); equations (M X - X M)_ij = 0 for the 15 bivectors
    rows = []
    for X in BIV:
        for i in range(DIM):
            for j in range(DIM):
                row = [QI(0)] * (DIM * DIM)
                for k in range(DIM):
                    row[i * DIM + k] = row[i * DIM + k] + X[k][j]
                    row[k * DIM + j] = row[k * DIM + j] - X[i][k]
                rows.append(row)
    ok = ok and DIM * DIM - GA.field_rank(rows) == 2
    even = [[QI(1) if i == j and len(STATES[i]) % 2 == 0 else QI(0) for j in range(DIM)] for i in range(DIM)]
    odd = lin((QI(1), ident()), (QI(-1), even))
    ok = ok and all(is_zero(comm(P, X)) for P in (even, odd) for X in BIV)
    ok = ok and sum(1 for i in range(DIM) if even[i][i] == 1) == 4
    # every u(3) generator fails to commute with some bivector
    ok = ok and all(any(not is_zero(comm(Uk, X)) for X in BIV) for Uk in U3)
    GA.check("pair mixing (ii): the commutant of so(2,4) on Lambda(W) is C + C; u(3) is not internal", ok)
    return ok


def skron(A, B):
    """Sparse Kronecker product {(row, col): value}."""
    m = len(B)
    out = {}
    for i, row in enumerate(A):
        for j, x in enumerate(row):
            if x != 0:
                for k, brow in enumerate(B):
                    for l, y in enumerate(brow):
                        if y != 0:
                            out[(i * m + k, j * m + l)] = x * y
    return out


def smm(A, B):
    out = {}
    for (i, k), x in A.items():
        for (k2, j), y in B.items():
            if k == k2:
                out[(i, j)] = out.get((i, j), QI(0)) + x * y
    return {k: v for k, v in out.items() if v != 0}


def scomm_zero(A, B):
    AB, BA = smm(A, B), smm(B, A)
    keys = set(AB) | set(BA)
    return all(AB.get(k, QI(0)) == BA.get(k, QI(0)) for k in keys)


def unit3(a, b):
    M = [[QI(0)] * 3 for _ in range(3)]
    M[a][b] = QI(1)
    return M


# colour su(3) on the label C^3
COLOUR = ([lin((QI(1), unit3(a, b)), (QI(-1), unit3(b, a))) for a, b in combinations(range(3), 2)]
          + [lin((I_, unit3(a, b)), (I_, unit3(b, a))) for a, b in combinations(range(3), 2)]
          + [lin((I_, unit3(0, 0)), (-I_, unit3(1, 1))), lin((I_, unit3(1, 1)), (-I_, unit3(2, 2)))])


def check_colour_on_the_label_copy_commutes():
    premise("standard-model.connection-forced")
    one3, one8 = ident(3), ident()
    conf = [skron(X, one3) for X in BIV]
    col = [skron(one8, T) for T in COLOUR]
    ok = len(COLOUR) == 8 and len(conf) == 15
    # su(3) is 8-dimensional over R: the colour generators are independent
    ok = ok and GA.mat_rank([flat_r(T) for T in COLOUR]) == 8
    ok = ok and all(scomm_zero(A, B) for A in conf for B in col)
    # the pair mixing on the Fock factor does not commute with the conformal generators
    ok = ok and all(any(not scomm_zero(skron(Uk, one3), A) for A in conf) for Uk in U3)
    GA.check("pair mixing (iii): colour on the label copy commutes with the conformal action", ok)
    return ok
