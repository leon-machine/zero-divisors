"""synthesis.central-label-carries-mass-at-zero-weight: exact checks.

pi and ln 2 enter as rational enclosures (or as free rational stand-ins where an identity holds
for every value); occupations at weight omega are written with q = e^{-x} as a rational parameter.
Mode algebras are built in GA.py's Cl(m, m), one hyperbolic atom per mode.

(i)   tension, both orderings: for rational q in (0,1), s - x n = ln(1 + q) > 0 (normal order) and
      n - 1/2 = (q - 1)/(2(1 + q)) < 0 (symmetric order); at x = 2 pi the enclosures give
      x n < s and x (n - 1/2) < 0 < s; at zero weight both energies vanish.
(ii)  the model: m zero-weight pairs; the Fock module has dimension 2^m (m = 1, 2, 3, counted as
      the rank of the left ideal generated by the vacuum projector), the Killing generator with
      zero weights is 0, and the central label commutes with every mode operator.
      Along the family 4 pi mu(m)^2 = m ln 2 the identities S = 4 pi M^2, (dS/dM) T = 1 with
      T = 1/(8 pi M), and 2 T S = M hold for rational stand-ins of pi.
(iii) no Gibbs state: for m = k^2, mu(m) <= k/4 (since ln 2/(4 pi) < 1/16), so
      m ln 2 - beta mu(m) >= k^2 ln 2 - beta k/4 grows without bound.
(v)   at x = 2 pi, (x n)/s lies in (0.8625, 0.8627): moved modes still carry less than TS.
"""
from fractions import Fraction as F
import GA
import series
from tp_premise import premise

PREMISES = (
    "synthesis.quarter-from-temperature",
    "synthesis.residue-from-mode-entropy",
    "synthesis.boundary-mode-thermal-entropy",
    "hawking.modular-structure-completed-pair",
    "scrambling.boundary-mode-space-matrix",
)


def touch():
    for p in PREMISES:
        premise(p)


PI_LO, PI_HI = F(314159265358979, 10 ** 14), F(314159265358980, 10 ** 14)


exp_bounds = series.exp_bounds          # rational bounds for e^x, x >= 0


def ln1p_bounds(y):
    return series.log_bounds(1 + y)


def ln2_bounds():
    return series.ln_bounds(2)


def at_2pi():
    xl, xh = 2 * PI_LO, 2 * PI_HI
    el, _ = exp_bounds(xl)
    _, eh = exp_bounds(xh)
    ql, qh = 1 / eh, 1 / el
    a_lo, _ = ln1p_bounds(ql)
    _, a_hi = ln1p_bounds(qh)
    n_lo, n_hi = ql / (1 + ql), qh / (1 + qh)
    xn_lo, xn_hi = xl * n_lo, xh * n_hi
    return (a_lo + xn_lo, a_hi + xn_hi), (xn_lo, xn_hi), (n_lo, n_hi)


def check_tension_both_orderings():
    touch()
    for q in (F(1, 2), F(1, 7), F(9, 10), F(1, 1000)):
        n = q / (1 + q)                      # occupancy 1/(e^x + 1) with q = e^{-x}
        assert 1 + q > 1                     # s - x n = ln(1 + q) > 0
        assert n - F(1, 2) == (q - 1) / (2 * (1 + q)) and n - F(1, 2) < 0
    table = {F(1, 2): F(-1, 6), F(1, 7): F(-3, 8), F(9, 10): F(-1, 38), F(1, 1000): F(-999, 2002)}
    for q, want in table.items():
        assert q / (1 + q) - F(1, 2) == want
    (s_lo, s_hi), (xn_lo, xn_hi), (n_lo, n_hi) = at_2pi()
    assert xn_hi < s_lo                      # normal order: beta E < s
    assert n_hi < F(1, 2)                    # symmetric order: beta E < 0 < s
    assert F(13577, 10 ** 6) < s_lo and s_hi < F(13578, 10 ** 6)
    # zero weight: x = 0 gives n = 1/2 and both energies x n, x (n - 1/2) vanish
    x, n = F(0), F(1, 2)
    assert x * n == 0 and x * (n - F(1, 2)) == 0
    return True


def fock_dimension(m):
    sq = tuple([1, -1] * m)
    half = F(1, 2)
    v = [GA.scal(half, GA.add(GA.gen(2 * j), GA.gen(2 * j + 1))) for j in range(m)]
    vs = [GA.scal(half, GA.sub(GA.gen(2 * j), GA.gen(2 * j + 1))) for j in range(m)]
    vac = GA.sc(1)
    for j in range(m):
        vac = GA.mul(vac, GA.mul(v[j], vs[j], sq), sq)          # product of v_j v_j^*
    for j in range(m):
        assert GA.is_zero(GA.mul(v[j], vac, sq))               # annihilated by every v_j
    states = [vac]
    for j in range(m):
        states = states + [GA.mul(vs[j], s, sq) for s in states]
    blades = GA.all_blades(2 * m)
    vecs = [[s.get(b, F(0)) for b in blades] for s in states]
    return GA.rank_of_vectors(vecs), sq, v, vs


def check_central_label_model():
    touch()
    for m in (1, 2, 3):
        dim, sq, v, vs = fock_dimension(m)
        assert dim == 2 ** m
        # zero weights: the Killing generator sum_j 0 * K_j is zero and moves nothing
        X = {}
        for j in range(m):
            X = GA.add(X, GA.scal(0, GA.mul(vs[j], v[j], sq)))
        assert GA.is_zero(X)
        # the central label is a scalar on each sector: it commutes with every mode operator
        label = GA.sc(m)
        for j in range(m):
            assert GA.commutes(label, v[j], sq) and GA.commutes(label, vs[j], sq)
    # thermodynamics along the family, for rational stand-ins of pi and M
    for P in (F(314159, 100000), F(22, 7), F(3)):
        for M in (F(1, 3), F(1), F(5, 2)):
            S = 4 * P * M * M                     # 4 pi M^2 = A/4 with A = 16 pi M^2
            assert S == 16 * P * M * M / 4
            dSdM = 8 * P * M
            T = 1 / (8 * P * M)
            assert dSdM * T == 1                  # Clausius dS = dM / T
            assert 2 * T * S == M                 # Smarr in the series' variables
            assert T * S == M / 2                 # the bound of the tension
            # each added zero-weight mode: dS = ln 2, so dM = T ln 2 (Landauer cost)
    return True


def check_no_gibbs_state():
    touch()
    llo, lhi = ln2_bounds()
    assert lhi / (4 * PI_LO) < F(1, 16)           # mu(m)^2 = m ln2/(4 pi) < m/16
    assert 5 < 8 * llo and 8 * lhi < 6            # the minimum over k sits between beta/6 and beta/5
    # exponent of 2^m e^{-beta mu(m)} at m = k^2 is at least k^2 ln2 - beta k/4
    want = {F(1): (2, F(2272, 1000), F(2273, 1000)), F(10): (11, F(5637, 100), F(5638, 100))}
    for beta, (k0, lo, hi) in want.items():
        assert k0 == int(beta) + 1
        val = k0 * k0 * llo - beta * F(k0, 4)
        assert lo < val < hi
        nxt = (k0 + 1) * (k0 + 1) * llo - beta * F(k0 + 1, 4)
        assert nxt - val > F(k0, 1)                 # increments grow: unbounded
    # negative heat capacity: dM/dT = -8 pi M^2 from T = 1/(8 pi M), exact finite difference
    P, M, h = F(22, 7), F(1, 2), F(1, 1000)
    dT = 1 / (8 * P * (M + h)) - 1 / (8 * P * M)
    assert dT * (8 * P * M * (M + h)) == -h
    assert dT == F(-7, 44088)
    return True


def check_moved_mode_ratio():
    touch()
    (s_lo, s_hi), (xn_lo, xn_hi), _ = at_2pi()
    assert F(8625, 10 ** 4) < xn_lo / s_hi and xn_hi / s_lo < F(8627, 10 ** 4)
    return True
