"""Z-adapted Witt flags of R^{2,4}: conformal energy sign of the pure spinor against the family. Exact.

Frame of the store (synthesis.positive-conformal-energy-gives-positive-null-translations): e0^2 = nu^2 = 1,
e1^2 = e2^2 = e3^2 = e-^2 = -1; here the generators are ordered e0, e1, e2, e3, nu, e- so that
I4 = e0 e1 e2 e3, E = nu e-, I6 = I4 E (the store's I6, conventions). Z = e0 nu. The conformal spinors'
unit is right multiplication by I6, which commutes with every left multiplication. The planes are
(e0, nu), (e1, e2), (e3, e-); for signs s = (s0, s1, s2) the flag W_s is given on the module by the three
operators w_a = L_{x_a} - s_a L_{y_a} R_{I6} ((x_a, y_a) the planes in order), the module form of the
isotropic vectors x_a - s_a y_a (unit). Its pure spinors are the elements of Cl(2,4) killed by all three.

(1) The w_a are nilpotent and pairwise anticommute (W_s isotropic); the pure spinors form an 8-dimensional
    real space K_s, generated by any nonzero element under right multiplication by Cl+(2,4); on K_s,
    v psi = (J_s v) psi I6 for every frame vector v, J_s x_a = s_a y_a, J_s y_a = -s_a x_a.
(2) On K_s, Z psi = -s0 psi I6 (Z is minus s0 times the unit), and the real part of h(psi, psi) = <psi, unit Z psi>
    is s0 <psi, psi> for the positive form <x, y> = <x^dagger y>_0 (frame vectors of square +1 self-adjoint,
    of square -1 anti-self-adjoint): s0 = +1 puts the pure spinor in the positive plane of the twistor form.
(3) On K_s, I6 psi = eps psi I6 with eps = -s0 s1 s2 (for the store's I6 = I4 E; the opposite orientation of I6
    relabels every flag by -s), and K_s is even (in the half CS) exactly when eps = +1;
    the conjugate flag -s has the other family; each pair (energy sign, family) occurs for exactly two of the
    eight flags; the orientation of J_s on the plane of Z is s0 and on the four-space orthogonal to Z is s1 s2.
Exact arithmetic only.
"""
from fractions import Fraction as F
from itertools import product
import GA
from tp_premise import premise

SQ = (1, -1, -1, -1, 1, -1)
E0, E1, E2, E3, NU, EM = [GA.gen(i) for i in range(6)]
BL = GA.all_blades(6)
PLANES = [(E0, NU), (E1, E2), (E3, EM)]
SIGNS = list(product((1, -1), repeat=3))


def _m(*xs):
    r = GA.sc(1)
    for x in xs:
        r = GA.mul(r, x, SQ)
    return r


I4 = _m(E0, E1, E2, E3)
I6 = _m(I4, NU, EM)
Z = _m(E0, NU)


def _bl(b):
    return {tuple(b): F(1)}


def _w(a, s, x):
    xa, ya = PLANES[a]
    return GA.sub(_m(xa, x), GA.scal(F(s[a]), _m(ya, x, I6)))


def _kernel(s):
    cols = []
    for b in BL:
        img = []
        for a in range(3):
            y = _w(a, s, _bl(b))
            img += [y.get(c, F(0)) for c in BL]
        cols.append(img)
    M = [[cols[j][i] for j in range(len(BL))] for i in range(len(cols[0]))]
    return [{b: c for b, c in zip(BL, v) if c != 0} for v in GA.field_kernel(M)]


def _J(s, v):
    out = {}
    for a, (xa, ya) in enumerate(PLANES):
        ca = GA.dot(v, xa, SQ) / GA.dot(xa, xa, SQ)
        cb = GA.dot(v, ya, SQ) / GA.dot(ya, ya, SQ)
        out = GA.add(out, GA.scal(ca * s[a], ya), GA.scal(-cb * s[a], xa))
    return out


def _dagger(x):
    out = {}
    for b, c in x.items():
        g = len(b)
        sign = (-1) ** (g * (g - 1) // 2)
        for i in b:
            if SQ[i] == -1:
                sign = -sign
        out[b] = sign * c
    return out


def _form(x, y):
    return _m(_dagger(x), y).get((), F(0))


def _even(x):
    return all(len(b) % 2 == 0 for b in x)


def _odd(x):
    return all(len(b) % 2 == 1 for b in x)


KER = {s: _kernel(s) for s in SIGNS}


def check_the_flag_operators_are_isotropic_with_an_eight_dimensional_kernel():
    premise("dark-matter.two-families-are-two-chiralities")
    ok_iso = ok_dim = ok_gen = ok_j = True
    for s in SIGNS:
        for a in range(3):
            for b in range(3):
                for bb in BL[::5]:
                    x = _bl(bb)
                    ok_iso = ok_iso and GA.is_zero(GA.add(_w(a, s, _w(b, s, x)), _w(b, s, _w(a, s, x))))
        K = KER[s]
        ok_dim = ok_dim and len(K) == 8
        evens = [b for b in BL if len(b) % 2 == 0]
        span = [[(_m(K[0], _bl(c))).get(b, F(0)) for b in BL] for c in evens]
        ok_gen = ok_gen and GA.rank_of_vectors(span) == 8
        for psi in K:
            for v in (E0, E1, E2, E3, NU, EM):
                ok_j = ok_j and GA.eq(_m(v, psi), _m(_J(s, v), psi, I6))
    GA.check("(1) w_a w_b + w_b w_a = 0 (nilpotent, isotropic) on sampled blades", ok_iso)
    GA.check("(1) the pure spinors of each flag span 8 real dimensions", ok_dim)
    GA.check("(1) one pure spinor generates them under right multiplication by Cl+(2,4)", ok_gen)
    GA.check("(1) v psi = (J_s v) psi I6 for every frame vector", ok_j)
    GA.check("(1) Q(I6) = -1 and I6 = I4 E", GA.eq(_m(I6, I6), GA.sc(-1)) and GA.eq(I6, _m(I4, NU, EM)))


def check_the_conformal_energy_is_minus_s0_times_the_unit():
    premise("synthesis.positive-conformal-energy-gives-positive-null-translations")
    ninf = GA.add(NU, EM)
    nO = GA.scal(F(1, 2), GA.sub(NU, EM))
    GA.check("(2) Z = P_e0 + e0 n0 with P_a = a ninf / 2, and Q(Z) = -1",
             GA.eq(Z, GA.add(GA.scal(F(1, 2), _m(E0, ninf)), _m(E0, nO))) and GA.eq(_m(Z, Z), GA.sc(-1)))
    ok_z = ok_h = True
    for s in SIGNS:
        for psi in KER[s]:
            ok_z = ok_z and GA.eq(_m(Z, psi), GA.scal(F(-s[0]), _m(psi, I6)))
            n = _form(psi, psi)
            ok_h = ok_h and n > 0 and _form(psi, _m(_m(Z, psi), I6)) == s[0] * n
    GA.check("(2) Z psi = -s0 psi I6 on every pure spinor of the eight flags", ok_z)
    GA.check("(2) <psi, (Z psi) I6> = s0 <psi, psi>, <psi, psi> > 0", ok_h)


def check_the_family_is_fixed_by_s0_s1_s2_and_independent_of_the_energy_sign():
    premise("dark-matter.two-families-are-two-chiralities")
    ok_fam = ok_par = ok_conj = True
    table = {}
    for s in SIGNS:
        eps = -s[0] * s[1] * s[2]
        for psi in KER[s]:
            ok_fam = ok_fam and GA.eq(_m(I6, psi), GA.scal(F(eps), _m(psi, I6)))
            ok_par = ok_par and (_even(psi) if eps == 1 else _odd(psi))
        neg = tuple(-x for x in s)
        ok_conj = ok_conj and _m(I6, KER[neg][0]) == GA.scal(F(-eps), _m(KER[neg][0], I6))
        table[(s[0], eps)] = table.get((s[0], eps), 0) + 1
    GA.check("(3) I6 psi = -s0 s1 s2 psi I6 on the pure spinors (store sign I6 = I4 E)", ok_fam)
    GA.check("(3) family +1 exactly when the pure spinors are even (the half CS)", ok_par)
    GA.check("(3) the conjugate flag -s is in the other family", ok_conj)
    GA.check("(3) each (energy sign, family) pair occurs for exactly two flags",
             sorted(table.items()) == [((-1, -1), 2), ((-1, 1), 2), ((1, -1), 2), ((1, 1), 2)])
    ok_or = True
    for s in SIGNS:
        zplane = GA.scal(F(1, 2), GA.sub(_m(E0, _J(s, E0)), _m(_J(s, E0), E0)))
        four = _m(E1, _J(s, E1), E3, _J(s, E3))
        ok_or = ok_or and GA.eq(zplane, GA.scal(F(s[0]), Z))
        ok_or = ok_or and GA.eq(four, GA.scal(F(s[1] * s[2]), _m(E1, E2, E3, EM)))
    GA.check("(3) J_s has orientation s0 on the plane of Z and s1 s2 on the four-space orthogonal to Z", ok_or)
