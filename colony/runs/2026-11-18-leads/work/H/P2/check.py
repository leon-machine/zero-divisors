def einstein_and_scalar(h, p):
    def riem(Bv):
        return scal(F(-1, 2), wedge(p, h(GA.neg(vdotB(p, Bv)))))

    def ric(a):
        out = {}
        for b in range(4):
            out = add(out, vdotB(REC[b], riem(wedge(E[b], a))))
        return out
    R = comp(ric)
    sc_ = tr_low(R)
    G = [[R[m][n] - F(1, 2) * (ETA[m] if m == n else 0) * sc_ for n in range(4)] for m in range(4)]
    return G, sc_


