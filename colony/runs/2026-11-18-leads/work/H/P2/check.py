def check_pair_sources_have_rotation_weights_zero_one_and_two():
    premise("synthesis.gravitational-pair-production-from-the-operator-source-at-first-order")
    premise("synthesis.electron-positron-to-muon-pairs-in-the-spacetime-algebra-lsz-tree-cross-section-and-one-loop-unitarity")
    premise("synthesis.imported-maxwell-stress-spacetime-algebra")
    ok = True
    p1, p2 = vec([1, 0, 0, 1]), vec([1, 0, 0, -1])
    s = d(add(p1, p2), add(p1, p2))
    ok = ok and s == SVAL
    # scalar: weight 0, trace (1 - 6 xi) s, trace-free norm s^2/6 at every coupling
    for xi in XIS:
        C = scalar_source(p1, p2, xi)
        ok = ok and is_zero(lie(C)) and tr_low(C) == (1 - 6 * xi) * s
        ok = ok and con(tf(C), tf(C)) == NORM_OVER_S2['s'] * s * s
        ok = ok and all(d(lin(C)(K), E[m]) == 0 for m in range(4))
    # chiral pair: the spin sum 2 <p2 w p1 w>_0 is (j1.w)^2 + (j2.w)^2 on real vectors w
    Cs, (j1, j2) = fermion_sources(p1, p2, FRAME0)
    for wv in [(1, 2, 3, 4), (0, 1, 0, 0), (2, -1, 5, 1), (1, 0, 0, 1), (3, 1, -2, 0)]:
        w = vec(wv)
        ok = ok and 2 * s0(mul(mul(mul(p2, w, S), p1, S), w, S)) == d(j1, w) ** 2 + d(j2, w) ** 2
    ok = ok and d(j1, j1) == d(j2, j2) == -s and d(j1, j2) == 0 and d(j1, p1) == d(j1, p2) == d(j2, p1) == d(j2, p2) == 0
    ok = ok and cross(BIV, j1) == j2 and cross(BIV, j2) == GA.neg(j1)        # the pair rotates as a weight-one pair
    T1, T2 = Cs
    ok = ok and lie(T1) == T2 and lie(T2) == mscal(-1, T1)                   # so L L T_n = -T_n: weight one, no weight zero
    for C in Cs:
        ok = ok and tr_low(C) == 0 and con(C, PROJ) == 0
        ok = ok and all(d(lin(C)(K), E[m]) == 0 for m in range(4))
        ok = ok and lie(lie(C)) == mscal(-1, C)
    ok = ok and con(T1, T2) == 0 and con(T1, T1) + con(T2, T2) == NORM_OVER_S2['w'] * s * s
    # vector pairs: trace-free, conserved; combinations of weight 0 and weight 2; summed norm 2 s^2
    V = vector_sources(p1, p2, FRAME0)
    ok = ok and all(tr_low(C) == 0 for C in V)
    ok = ok and all(d(lin(C)(K), E[m]) == 0 for C in V for m in range(4))
    ok = ok and sum(con(C, C) for C in V) == NORM_OVER_S2['v'] * s * s
    plus, minus = madd(V[0], V[3]), madd(V[0], V[3], -1)
    cross_p, cross_m = madd(V[1], V[2]), madd(V[1], V[2], -1)
    ok = ok and is_zero(plus) and is_zero(cross_m)                           # the two weight-zero combinations carry no source
    ok = ok and lie(lie(minus)) == mscal(-4, minus) and lie(lie(cross_p)) == mscal(-4, cross_p)
    ok = ok and not is_zero(minus) and not is_zero(cross_p) and lie(minus) == mscal(2, cross_p)
    ok = ok and all(lie(lie(C)) == mscal(-4, C) for C in V)
    # the scalar <F1 F2>_0, the two-quantum element of the square of the field bivector, lives on the
    # weight-zero combination only (where the source vanishes)
    f = [[s0(mul(wedge(p1, a1), wedge(p2, a2), S)) for a2 in FRAME0] for a1 in FRAME0]
    ok = ok and f[0][0] + f[1][1] != 0 and f[0][0] - f[1][1] == 0 and f[0][1] == 0 and f[1][0] == 0
    # the weights c = 12 sigma N / s^2
    for kind in 'swv':
        ok = ok and 12 * SIGMA[kind] * NORM_OVER_S2[kind] == WEIGHT_C[kind]
    GA.check("scalar pair weight 0 (norm s^2/6, trace (1 - 6 xi) s); chiral pair weight one only, trace-free, "
             "norm s^2/4; vector pairs weight two only, trace-free, norm 2 s^2; 12 sigma N/s^2 = 1, 3, 12", ok)
    return ok


# ---- (3) direct integration against the orthogonality formula -------------------------------------------
def poly_integral(vals):
    """Integral over [-1, 1] of the polynomial of degree len(vals) - 1 through the exact points; also returns
    the coefficients."""
    n = len(vals)
    M = [[c ** k for k in range(n)] for c, _ in vals]
    rhs = [v for _, v in vals]
    for i in range(n):
        piv = next(r for r in range(i, n) if M[r][i] != 0)
        M[i], M[piv] = M[piv], M[i]
        rhs[i], rhs[piv] = rhs[piv], rhs[i]
        for r in range(n):
            if r != i and M[r][i] != 0:
                f = M[r][i] / M[i][i]
                M[r] = [a - f * b for a, b in zip(M[r], M[i])]
                rhs[r] -= f * rhs[i]
    co = [rhs[i] / M[i][i] for i in range(n)]
    return co, sum(co[k] * F(2, k + 1) for k in range(0, n, 2))


def check_channel_weights_follow_from_norms_and_traces():
    premise("synthesis.gravitational-pair-production-from-the-operator-source-at-first-order")
    ok = True
    s = F(SVAL)
    for a in 'swv':
        for b in 'swv':
            for xa, xb in ((F(0), F(0)), (F(1, 6), F(153, 100))):
                vals = []
                for (c, s_) in ANGLES:
                    p1, p2, p3, p4, fr = kin(c, s_)
                    A, Bs = sources(a, p1, p2, xa), sources(b, p3, p4, xb, fr)
                    vals.append((c, sum(bracket(X, Y) ** 2 for X in A for Y in Bs) / s ** 4))
                co, integ = poly_integral(vals)
                ok = ok and co[5] == 0 and co[6] == 0
                W = integ * 2 * SIGMA[a] * SIGMA[b]                      # over pi
                Na, Nb = NORM_OVER_S2[a], NORM_OVER_S2[b]
                ta = (1 - 6 * xa) ** 2 if a == 's' else F(0)               # theta / s^2
                tb = (1 - 6 * xb) ** 2 if b == 's' else F(0)
                pred = 4 * SIGMA[a] * SIGMA[b] * (Na * Nb / 5 + ta * tb / 36)
                ok = ok and W == pred
                ok = ok and W == F(WEIGHT_C[a] * WEIGHT_C[b], 180) + F(5, 180) * ta * tb
    # the summed square does not depend on the azimuth of the second pair
    for (c, s_) in ANGLES[:3]:
        for a in 'swv':
            for b in 'wv':
                ref = None
                for az in AZIMUTHS:
                    p1, p2, p3, p4, fr = kin(c, s_, az)
                    v = sum(bracket(X, Y) ** 2 for X in sources(a, p1, p2) for Y in sources(b, p3, p4, F(0), fr))
                    ref = v if ref is None else ref
                    ok = ok and v == ref
    # fermion to fermion: the mixed product B11 B22 - B12 B21 integrates to zero
    vals = []
    for (c, s_) in ANGLES:
        p1, p2, p3, p4, fr = kin(c, s_)
        A, Bs = sources('w', p1, p2), sources('w', p3, p4, F(0), fr)
        vals.append((c, bracket(A[0], Bs[0]) * bracket(A[1], Bs[1]) - bracket(A[0], Bs[1]) * bracket(A[1], Bs[0])))
    co, integ = poly_integral(vals)
    ok = ok and integ == 0 and any(v != 0 for _, v in vals)
    GA.check("nine channel weights by integration equal 4 sigma_i sigma_j (N_i N_j/5 + theta_i theta_j/36)/s^4 "
             "= (c_i c_j + 5 tau_i tau_j)/180 times pi; the fermion mixed product integrates to zero", ok)
    return ok


