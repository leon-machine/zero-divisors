"""Rotation weights of pair sources at a timelike momentum: exact checks.

Spacetime algebra Cl(1,3), signature (+,-,-,-). Momentum k = p1 + p2 = 2 e0 (s = Q(k) = 4), pair axis e3.
A conserved source at k is a symmetric map T with T(k) = 0, held by its lower components T_mn = e_m . T(e_n).
Rotations about the axis are generated by the bivector e1 e2 through (L T)(a) = B x T(a) - T(B x a), with
B x a the commutator product; a source has weight m when L L T = -m^2 T.

(1) The conserved sources at k (dimension 6) split as the line of P (P(a) = a - (a.k) k / Q(k), trace 3) and
    the five trace-free ones; the invariant tensors of the rotation algebra in the tensor square of the
    trace-free space span one line (the pairing), and no trace-free source is invariant. This is the input of
    the orthogonality relation: the mean over rotations of <A, gB><A', gB'> is <A, A'><B, B'>/5.
(2) Pair sources: scalar pair weight 0 with trace-free norm s^2/6 and trace (1 - 6 xi) s; chiral pair two
    real components of weight one (L L T = -T), trace-free, orthogonal to P and to each other, summed norm
    s^2/4, fixed by the stored spin sum; vector pairs trace-free, weight two only (the two combinations of
    weight zero carry no source; the scalar <F1 F2>_0 lives on them), summed norm 2 s^2.
    12 x (identical factor) x norm / s^2 = 1, 3, 12.
(3) The nine channel weights by direct integration over the sphere agree with (4 pi/s^4) sigma_i sigma_j
    (N_i N_j/5 + theta_i theta_j/36), and the mixed product of the two fermion components integrates to zero
    (both relative helicities have one weight).
(4) A term mu ((a.k) k - Q(k) a) R[h] added to the first-order field equation (the form of a vacuum stress
    whose trace is a multiple of the d'Alembertian of the scalar curvature): its solution for a conserved
    source changes only the P-part, by 1/(1 + 3 mu Q(k)), so the bilinear becomes
    <T1_tf, T2_tf> - tr T1 tr T2 / (6 (1 + 3 mu Q(k))) and is unchanged when one source is trace-free.
"""
from fractions import Fraction as F

import GA
from GA import add, dot, gen, mul, scal, sub
from tp_premise import premise

S = GA.sig(1, 3)
ETA = [1, -1, -1, -1]
E = [gen(i) for i in range(4)]
REC = [E[0]] + [GA.neg(x) for x in E[1:]]
BIV = mul(E[1], E[2], S)                      # generator of rotations about e3

SVAL = 4                                      # s = Q(k) at k = 2 e0
XIS = [F(0), F(1, 6), F(153, 100), F(-1, 3), F(2, 7)]
ANGLES = [(F(3, 5), F(4, 5)), (F(5, 13), F(12, 13)), (F(-7, 25), F(24, 25)), (F(-8, 17), F(15, 17)),
          (F(20, 29), F(21, 29)), (F(-12, 37), F(35, 37)), (F(9, 41), F(40, 41))]
AZIMUTHS = [(F(1), F(0)), (F(3, 5), F(4, 5)), (F(-5, 13), F(12, 13))]
MUS = [F(0), F(1, 7), F(-2, 5), F(3)]
# samples of the scalar-curvature check: reference pair, two couplings, one angle, one component; and the
# values it must reproduce: gamma = 1/(1 + 3 mu s) and the modified bilinear of the two scalar sources
REF_PAIR = ((1, 0, 0, 1), (1, 0, 0, -1))
CURV_XI_A, CURV_XI_B = F(2, 7), F(-1, 3)
CURV_ANGLE = (F(5, 13), F(12, 13))
CURV_COMPONENT = 0
CURV_GAMMAS = [F(1), F(7, 19), F(-5, 19), F(1, 37)]
CURV_INTERACTIONS = [F(17648, 3549), F(13136, 9633), F(-151408, 67431), F(-77104, 131313)]
WEIGHT_C = {'s': 1, 'w': 3, 'v': 12}
SIGMA = {'s': F(1, 2), 'w': F(1), 'v': F(1, 2)}
NORM_OVER_S2 = {'s': F(1, 6), 'w': F(1, 4), 'v': F(2)}


def vec(c):
    return {(i,): F(x) for i, x in enumerate(c) if x}


def d(a, b):
    return dot(a, b, S)


def s0(x):
    return x.get((), F(0))


def grade1(x):
    return {b: c for b, c in x.items() if len(b) == 1}


def wedge(a, b):
    return scal(F(1, 2), sub(mul(a, b, S), mul(b, a, S)))


def cross(B, a):
    """Commutator product B x a of a bivector with a vector."""
    return grade1(scal(F(1, 2), sub(mul(B, a, S), mul(a, B, S))))


def vdotB(a, B):
    return grade1(scal(F(1, 2), sub(mul(a, B, S), mul(B, a, S))))


def comp(T):
    return [[d(E[m], T(E[n])) for n in range(4)] for m in range(4)]


def lin(C):
    """The map with lower components C: T(a) = sum_mn e^m C_mn (e^n . a)."""
    def T(a):
        out = {}
        for m in range(4):
            for n in range(4):
                if C[m][n]:
                    out = add(out, scal(C[m][n] * d(REC[n], a), REC[m]))
        return out
    return T


def tr_low(C):
    return sum(ETA[m] * C[m][m] for m in range(4))


def con(A, B):
    return sum(ETA[m] * ETA[n] * A[m][n] * B[m][n] for m in range(4) for n in range(4))


def bracket(C1, C2):
    return con(C1, C2) - F(1, 2) * tr_low(C1) * tr_low(C2)


def lie(C):
    """Lower components of L T, (L T)(a) = B x T(a) - T(B x a), B = e1 e2."""
    T = lin(C)
    return comp(lambda a: sub(cross(BIV, T(a)), T(cross(BIV, a))))


def madd(A, B, c=1):
    return [[A[m][n] + c * B[m][n] for n in range(4)] for m in range(4)]


def mscal(c, A):
    return [[c * A[m][n] for n in range(4)] for m in range(4)]


def madd_many(Cs, xs):
    out = [[F(0)] * 4 for _ in range(4)]
    for C, x in zip(Cs, xs):
        out = madd(out, C, x)
    return out


def is_zero(A):
    return all(A[m][n] == 0 for m in range(4) for n in range(4))


K = vec((2, 0, 0, 0))
PROJ = comp(lambda a: sub(a, scal(d(a, K) / d(K, K), K)))       # P, lower components


def tf(C):
    """Trace-free part of a conserved source at K: C - (tr C / 3) P."""
    return madd(C, PROJ, -tr_low(C) / 3)


# ---- pair sources -------------------------------------------------------------------------------------
def scalar_source(p, q, xi):
    k = add(p, q)
    k2 = d(k, k)
    return comp(lambda a: add(scal(-d(a, q), p), scal(-d(a, p), q), scal(d(p, q), a),
                              scal(2 * xi * d(a, k), k), scal(-2 * xi * k2, a)))


def vector_sources(p, q, frame):
    """The four sources -1/2 (F1 a F2 + F2 a F1) for two real transverse polarisations of each quantum."""
    pol = frame
    assert all(d(n, p) == 0 and d(n, q) == 0 and d(n, n) == -1 for n in pol) and d(pol[0], pol[1]) == 0
    out = []
    for a1 in pol:
        for a2 in pol:
            F1, F2 = wedge(p, a1), wedge(q, a2)
            out.append(comp(lambda a, F1=F1, F2=F2: scal(F(-1, 2), grade1(add(mul(mul(F1, a, S), F2, S),
                                                                                 mul(mul(F2, a, S), F1, S))))))
    return out


def fermion_sources(p, q, frame):
    """Two real components T_n(a) = 1/4 (j_n (a.d) + d (a.j_n)), d = p - q, with j_1, j_2 an orthogonal pair
    of transverse vectors of square -Q(p + q): the two real components of the pair's transition current."""
    j1 = scal(2, frame[0])
    j2 = scal(2, frame[1])
    dd = sub(p, q)
    return [comp(lambda a, j=j: scal(F(1, 4), add(scal(d(a, dd), j), scal(d(a, j), dd)))) for j in (j1, j2)], (j1, j2)


FRAME0 = (E[1], E[2])


def kin(c, s_, az=(F(1), F(0))):
    """Momenta of the two pairs at s = 4 and the transverse frame of the second pair (polar angle with
    cosine c and sine s_, azimuth az)."""
    ca, sa = az
    frame = (vec([0, c * ca, c * sa, -s_]), vec([0, -sa, ca, 0]))
    return (vec([1, 0, 0, 1]), vec([1, 0, 0, -1]),
            vec([1, s_ * ca, s_ * sa, c]), vec([1, -s_ * ca, -s_ * sa, -c]), frame)


def sources(kind, p, q, xi=F(0), frame=FRAME0):
    if kind == 's':
        return [scalar_source(p, q, xi)]
    if kind == 'v':
        return vector_sources(p, q, frame)
    return fermion_sources(p, q, frame)[0]


# ---- (1) the decomposition and the invariants -----------------------------------------------------------
def spatial_sym_basis():
    out = []
    for m in range(1, 4):
        for n in range(m, 4):
            C = [[F(0)] * 4 for _ in range(4)]
            C[m][n] = F(1)
            C[n][m] = F(1)
            out.append(C)
    return out


def rot_generators():
    """Lie action on lower components of the three rotation bivectors of the space orthogonal to K."""
    gens = []
    for (i, j) in ((1, 2), (2, 3), (3, 1)):
        Bv = mul(E[i], E[j], S)

        def L(C, Bv=Bv):
            T = lin(C)
            return comp(lambda a: sub(cross(Bv, T(a)), T(cross(Bv, a))))
        gens.append(L)
    return gens


def coords(C, basis):
    """Coordinates of a spatial symmetric C in the basis of unit symmetric matrices."""
    out = []
    for Bm in basis:
        idx = [(m, n) for m in range(4) for n in range(m, 4) if Bm[m][n] != 0][0]
        out.append(C[idx[0]][idx[1]])
    return out


def check_conserved_sources_split_and_rotation_invariants_are_one_line():
    premise("synthesis.weyl-flat-variations-carry-only-the-stress-trace-and-the-whole-stress-clause-is-the-trace-free-channel")
    ok = True
    basis = spatial_sym_basis()
    ok = ok and len(basis) == 6
    # conserved: every spatial symmetric map annihilates K, and P has trace 3 and <P, P> = 3
    for C in basis:
        ok = ok and all(d(lin(C)(K), E[m]) == 0 for m in range(4))
    ok = ok and tr_low(PROJ) == 3 and con(PROJ, PROJ) == 3
    # trace-free basis (five) in coordinates
    tfb = [tf(C) for C in basis]
    rows = [coords(C, basis) for C in tfb]
    ok = ok and GA.mat_rank(rows) == 5
    # pick five independent trace-free sources
    five = [madd(basis[0], basis[3], -1), madd(basis[0], basis[5], -1), basis[1], basis[2], basis[4]]
    ok = ok and all(tr_low(C) == 0 for C in five) and GA.mat_rank([coords(C, basis) for C in five]) == 5
    gens = rot_generators()
    # generators preserve the trace-free space and kill P; matrices of the generators on the five
    Ls = []
    for L in gens:
        ok = ok and is_zero(L(PROJ))
        M = []
        for C in five:
            img = L(C)
            ok = ok and tr_low(img) == 0
            # solve img = sum x_i five_i
            sol = [-img[2][2], -img[3][3], img[1][2], img[1][3], img[2][3]]
            ok = ok and img[1][1] == sol[0] + sol[1] and img == madd_many(five, sol)
            M.append(sol)
        Ls.append([[M[c][r] for c in range(5)] for r in range(5)])       # column c = image of five[c]
    # no invariant vector: common kernel of the three generators on the five is zero
    stacked = [row for Lm in Ls for row in Lm]
    ok = ok and GA.mat_rank(stacked) == 5
    # invariants in the tensor square: X (5 x 5) with L X + X L^T = 0 for the three generators
    eqs = []
    for Lm in Ls:
        for a in range(5):
            for b in range(5):
                row = [F(0)] * 25
                for c in range(5):
                    row[c * 5 + b] += Lm[a][c]
                    row[a * 5 + c] += Lm[b][c]
                eqs.append(row)
    ok = ok and GA.mat_rank(eqs) == 24
    # the surviving line is the inverse Gram matrix of the pairing (the pairing is invariant)
    gram = [[con(five[a], five[b]) for b in range(5)] for a in range(5)]
    for L in gens:
        for a in range(5):
            for b in range(5):
                ok = ok and con(L(five[a]), five[b]) + con(five[a], L(five[b])) == 0
    ok = ok and GA.mat_rank(gram) == 5
    GA.check("conserved sources at k = 2 e0: line of P plus five trace-free; rotation algebra has no invariant "
             "trace-free source and one line of invariants in the tensor square (rank 24 of 25)", ok)
    return ok


