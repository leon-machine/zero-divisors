"""synthesis.frozen-point-datum-is-h: exact checks.

Cl(2,4) over Q with e0 (+1), e1 e2 e3 (-1), e4 (+1), e5 (-1); n0 = (e4 + e5)/2, ninf = e4 - e5, so that
n0 . ninf = 1 (the frame of the de Sitter scale lemma). I = ninf + (L/6) n0, W = ninf - (L/6) n0, B = e0 W,
d = L/3.

A quadratic extension K = Q(sqrt delta) is realised inside GA with no imaginary unit: append two generators
f1, f2 with squares +1 and -delta; u = f1 f2 is even and disjoint from e0..e5, so it commutes with every blade
of Cl(2,4) and u^2 = -(1)(-delta) = delta. The K-multivectors are the elements of span{1, u} times the blades
of Cl(2,4), multiplied by GA.mul; the K-valued square of a K-vector v is v^2, an element of span{1, u}.
"""
from fractions import Fraction as F
from itertools import product

import GA
from GA import mul, add, sub, scal, sc, gen, eq
from tp_premise import premise

P_SCALE = "mass.de-sitter-scale-frozen-point"
P_BOOST = "synthesis.de-sitter-static-boost-frozen-point"

SQ6 = (1, -1, -1, -1, 1, -1)


def ext(delta):
    """Squares for Cl(2,4) with the two generators of span{1, u}, u^2 = delta."""
    return SQ6 + (1, -F(delta))


U = {(6, 7): F(1)}          # u = f1 f2


def kel(a, b=0):
    """The element a + b u of K = span{1, u}."""
    return add(sc(a), scal(b, U))


def isqrt(n):
    if n < 0:
        return None
    y = 1
    while y * y <= n:
        y *= 2
    lo, hi = 0, y
    while lo < hi:                       # largest x with x^2 <= n
        mid = (lo + hi + 1) // 2
        if mid * mid <= n:
            lo = mid
        else:
            hi = mid - 1
    return lo


def is_square_Q(q):
    q = F(q)
    if q < 0:
        return False
    a, b = isqrt(q.numerator), isqrt(q.denominator)
    return a * a == q.numerator and b * b == q.denominator


def is_square_K(q, delta):
    """A rational q is a square in Q(sqrt delta) (delta not a rational square) iff q or q/delta is a rational square:
    (a + b u)^2 = a^2 + delta b^2 + 2ab u is rational only for a = 0 or b = 0."""
    return is_square_Q(q) or is_square_Q(F(q) / F(delta))


def dot(a, b, sq):
    return add(mul(a, b, sq), mul(b, a, sq)).get((), F(0)) / 2


def frame(L):
    n0 = scal(F(1, 2), add(gen(4), gen(5)))
    ninf = sub(gen(4), gen(5))
    I = add(ninf, scal(F(L) / 6, n0))
    W = sub(ninf, scal(F(L) / 6, n0))
    return n0, ninf, I, W


def lift(x, sq):
    n0, ninf, _, _ = frame(0)
    Qx = dot(x, x, sq) if x else F(0)
    return add(n0, x, scal(-Qx / 2, ninf)), Qx


def half_ad(B, x, sq):
    return scal(F(1, 2), sub(mul(B, x, sq), mul(x, B, sq)))


def wedge_all(vs, sq):
    out = sc(1)
    for v in vs:
        out = mul(out, v, sq)
    return out


def centre_dimension(basis_vectors, sq):
    """Dimension of the centre of the algebra generated by orthogonal vectors (exact linear algebra over Q).
    x is central iff it commutes with every generator; solve on the 2^n products of the generators."""
    n = len(basis_vectors)
    monos = []
    for k in range(1 << n):
        m = sc(1)
        for i in range(n):
            if k >> i & 1:
                m = mul(m, basis_vectors[i], sq)
        monos.append(m)
    blades = sorted({b for m in monos for b in m} | {b for g in basis_vectors for m in monos for b in mul(g, m, sq)})
    rows = []
    for g in basis_vectors:
        comms = [sub(mul(g, m, sq), mul(m, g, sq)) for m in monos]
        for bl in blades:
            rows.append([c.get(bl, F(0)) for c in comms])
    return len(monos) - GA.field_rank(rows), monos


LAMS_ALL = [F(3), F(12), F(27, 4), F(1), F(6), F(9), F(7, 3), F(2, 3), F(-3), F(-1), F(-12, 5)]
HS = [F(1), F(1, 2), F(3, 7), F(5, 3), F(-2)]


def check_identities_hold_for_every_lambda():
    premise(P_SCALE)
    premise(P_BOOST)
    sq = SQ6
    e0, e1, e2, e3 = gen(0), gen(1), gen(2), gen(3)
    for L in LAMS_ALL:
        d = L / 3
        n0, ninf, I, W = frame(L)
        assert dot(n0, ninf, sq) == 1 and dot(n0, n0, sq) == 0 and dot(ninf, ninf, sq) == 0
        assert dot(I, I, sq) == d and dot(W, W, sq) == -d and dot(W, I, sq) == 0
        B = mul(e0, W, sq)
        assert eq(mul(B, B, sq), sc(d))
        assert GA.commutes(B, I, sq)
        # I-perp: e0, e1, e2, e3, W, mutually orthogonal, orthogonal to I, squares <1, -1, -1, -1, -d>
        basis = [e0, e1, e2, e3, W]
        gram = [[dot(a, b, sq) for b in basis] for a in basis]
        assert gram == [[F(1) if i == j == 0 else (F(-1) if i == j < 4 else (-d if i == j == 4 else F(0)))
                         for j in range(5)] for i in range(5)]
        assert all(dot(v, I, sq) == 0 for v in basis)
        # the six vectors span the ambient space (rank 6)
        vecs = basis + [I]
        assert GA.field_rank([[v.get((i,), F(0)) for i in range(6)] for v in vecs]) == 6
        # half ad_B on the plane span{e0, W}: e0 -> -W, W -> -d e0; it kills e1, e2, e3 and I
        assert eq(half_ad(B, e0, sq), scal(-1, W))
        assert eq(half_ad(B, W, sq), scal(-d, e0))
        assert all(half_ad(B, v, sq) == {} for v in (e1, e2, e3, I))
        # the scale sigma = <X(x), I> = 1 - L Q(x)/12, and on the slice x = r e1 the sphere condition is r^2 = 4/d
        for xs in ((F(1, 2), F(0), F(2), F(-1)), (F(0), F(3), F(0), F(0)), (F(2, 5), F(1), F(1, 3), F(1))):
            x = add(*[scal(c, gen(i)) for i, c in enumerate(xs) if c])
            X, Qx = lift(x, sq)
            assert dot(X, X, sq) == 0 and dot(X, I, sq) == 1 - L * Qx / 12
        r = F(5, 4)
        x = scal(r, e1)
        assert dot(x, x, sq) == -r * r
        # pseudoscalar of I-perp is central there, squares to d; the reversed form's squares to -d
        om = wedge_all(basis, sq)
        assert eq(mul(om, om, sq), sc(d))
        assert all(GA.commutes(om, v, sq) for v in basis)
        rev = tuple(-s for s in sq)
        omr = wedge_all(basis, rev)
        assert eq(mul(omr, omr, rev), sc(-d))
    return True


def check_with_h_every_construction_is_over_the_base_field():
    premise(P_SCALE)
    premise(P_BOOST)
    sq = SQ6
    e0, e1 = gen(0), gen(1)
    std = [gen(0), gen(1), gen(2), gen(3)]
    for H in HS:
        L = 3 * H * H
        d = L / 3
        assert d == H * H
        n0, ninf, I, W = frame(L)
        B = mul(e0, W, sq)
        eW = scal(1 / H, W)
        assert dot(eW, eW, sq) == -1
        u = scal(1 / H, B)
        assert eq(mul(u, u, sq), sc(1)) and eq(B, scal(H, mul(e0, eW, sq)))
        v = scal(F(1, 2), add(e0, eW))
        vs = scal(F(1, 2), sub(e0, eW))
        assert dot(v, v, sq) == 0 and dot(vs, vs, sq) == 0 and v != {} and vs != {}
        assert eq(add(mul(v, vs, sq), mul(vs, v, sq)), sc(1))
        assert eq(sub(mul(vs, v, sq), mul(v, vs, sq)), u)
        # eigen-directions of half ad_B: v -> -H v, v* -> +H v*
        assert eq(half_ad(B, v, sq), scal(-H, v)) and eq(half_ad(B, vs, sq), scal(H, vs))
        # horizon radius and surface gravity: R_h = 1/H, kappa = H
        Rh, kap = 1 / H, H
        assert Rh * Rh == 3 / L and kap * kap == L / 3
        # the horizon point of the slice x = r e1: r = 2/H, sigma = 2, areal radius r/sigma = R_h
        r = 2 / H
        x = scal(r, e1)
        X, Qx = lift(x, sq)
        assert Qx == -12 / L
        sigma = dot(X, I, sq)
        assert sigma == 2 and r / sigma == Rh
        # I-perp is the standard (1,4) space: the basis e0, e1, e2, e3, e_W has squares <1, -1, -1, -1, -1>
        basis = std + [eW]
        assert [[dot(a, b, sq) for b in basis] for a in basis] == \
            [[F(1) if i == j == 0 else (F(-1) if i == j else F(0)) for j in range(5)] for i in range(5)]
        # doubled: omega/H is a central unit of square 1, (1 +- omega/H)/2 central idempotents
        om = wedge_all(std + [W], sq)
        w1 = scal(1 / H, om)
        assert eq(mul(w1, w1, sq), sc(1))
        idem = scal(F(1, 2), add(sc(1), w1))
        assert eq(mul(idem, idem, sq), idem) and all(GA.commutes(idem, g, sq) for g in basis)
        # mirror (form reversed): omega'/H squares to -1, the central unit of Cl(4,1)
        rev = tuple(-s for s in sq)
        omr = scal(1 / H, wedge_all(std + [W], rev))
        assert eq(mul(omr, omr, rev), sc(-1))
        assert eq(mul(wedge_all(std + [gen(5)], rev), wedge_all(std + [gen(5)], rev), rev), sc(-1))
    return True


def check_lambda_over_three_must_be_a_square():
    """For L with d = L/3 not a rational square, each construction is reduced to a square root of d."""
    premise(P_SCALE)
    premise(P_BOOST)
    sq = SQ6
    e0 = gen(0)
    nonsq = [L for L in LAMS_ALL if not is_square_Q(L / 3)]
    assert nonsq == [F(1), F(6), F(9), F(7, 3), F(2, 3), F(-3), F(-1), F(-12, 5)]
    for L in nonsq:
        d = L / 3
        n0, ninf, I, W = frame(L)
        B = mul(e0, W, sq)
        # null vector a e0 + b W: Q = a^2 - d b^2 (the Gram of the plane), so a nonzero null vector gives d = (a/b)^2
        for a, b in product((F(1), F(-2), F(3, 5)), (F(1), F(7, 4), F(-1, 3))):
            z = add(scal(a, e0), scal(b, W))
            assert dot(z, z, sq) == a * a - d * b * b
        # unit boost c B: (cB)^2 = c^2 d; unit W: Q(cW) = -c^2 d; horizon radius R^2 = 1/d; slice point r^2 = 4/d
        for c in (F(1), F(2, 3), F(-5, 7)):
            assert eq(mul(scal(c, B), scal(c, B), sq), sc(c * c * d))
            assert dot(scal(c, W), scal(c, W), sq) == -c * c * d
        # characteristic polynomial of half ad_B on the plane: x^2 - d (matrix [[0, -d], [-1, 0]])
        M = [[F(0), -d], [F(-1), F(0)]]
        assert M[0][0] + M[1][1] == 0 and M[0][0] * M[1][1] - M[0][1] * M[1][0] == -d
        assert not is_square_Q(d) and not is_square_Q(1 / d) and not is_square_Q(4 / d)
        # the centre of Cl(I-perp) is span{1, omega}, omega^2 = d: a field when d is not a square
        if L in (F(6), F(7, 3)):
            dim, _ = centre_dimension([gen(0), gen(1), gen(2), gen(3), W], sq)
            assert dim == 2
    return True


def check_the_quadratic_extension_supplies_what_is_missing():
    """Over K = Q(sqrt delta) = span{1, u}, delta in the square class of d, the constructions exist."""
    premise(P_SCALE)
    premise(P_BOOST)
    for L, delta, h in ((F(6), F(2), (F(0), F(1))),          # d = 2, H = u
                        (F(7, 3), F(7), (F(0), F(1, 3))),     # d = 7/9, H = u/3
                        (F(1), F(3), (F(0), F(1, 3))),        # d = 1/3, H = u/3
                        (F(2, 3), F(2), (F(0), F(1, 3)))):    # d = 2/9, H = u/3
        sq = ext(delta)
        d = L / 3
        Hk = kel(*h)
        assert eq(mul(Hk, Hk, sq), sc(d))
        Hinv = scal(1 / (h[1] * h[1] * delta), Hk)          # (b u)^{-1} = u / (b delta)
        assert eq(mul(Hk, Hinv, sq), sc(1))
        n0, ninf, I, W = frame(L)
        e0 = gen(0)
        eW = mul(Hinv, W, sq)
        assert eq(mul(eW, eW, sq), sc(-1))
        B = mul(e0, W, sq)
        u = mul(Hinv, B, sq)
        assert eq(mul(u, u, sq), sc(1))
        v = scal(F(1, 2), add(e0, eW))
        assert mul(v, v, sq) == {} and v != {}
        assert eq(half_ad(B, v, sq), scal(-1, mul(Hk, v, sq)))
        # horizon point on the slice: r = 2/H, r^2 = 4/d
        r = scal(2, Hinv)
        assert eq(mul(r, r, sq), sc(4 / d))
    return True


def check_lambda_seven_thirds_sphere_has_no_rational_point():
    premise(P_BOOST)
    L = F(7, 3)
    d = L / 3
    assert d == F(7, 9) and 12 / L == F(36, 7) == 4 / d
    # x on the sphere (x1^2 + x2^2 + x3^2 = 36/7) iff y = 7x/6 has y1^2 + y2^2 + y3^2 = 7
    assert F(7, 6) ** 2 * F(36, 7) == 7
    # 7 is not a sum of three rational squares: A^2 + B^2 + C^2 = 7 D^2 with gcd 1.
    # mod 8 a sum of three squares is never 7 (so D is even) ...
    sums8 = {(a * a + b * b + c * c) % 8 for a, b, c in product(range(8), repeat=3)}
    assert sums8 == {0, 1, 2, 3, 4, 5, 6}
    # ... and then A^2 + B^2 + C^2 = 0 mod 4 forces A, B, C even, against gcd 1
    zero4 = [(a, b, c) for a, b, c in product(range(4), repeat=3) if (a * a + b * b + c * c) % 4 == 0]
    assert all(a % 2 == b % 2 == c % 2 == 0 for a, b, c in zero4) and len(zero4) == 8
    # a direct search agrees: no solution with |A|, |B|, |C| <= 40, 1 <= D <= 15
    sqs = {k * k: k for k in range(0, 41)}
    found = [(a, b, D) for D in range(1, 16) for a in range(0, 41) for b in range(0, 41)
             if 7 * D * D - a * a - b * b in sqs]
    assert found == []
    # for comparison, Lambda = 6 (d = 2): x = e1 + e2 lies on the sphere Q(x) = -4/d = -2
    sq = SQ6
    x = add(gen(1), gen(2))
    assert dot(x, x, sq) == -12 / F(6) == F(-2)
    return True


def check_lambda_six_centres_are_other_quadratic_fields():
    premise(P_SCALE)
    sq = SQ6
    rev = tuple(-s for s in sq)
    L = F(6)
    n0, ninf, I, W = frame(L)
    basis = [gen(0), gen(1), gen(2), gen(3), W]
    om, omr = wedge_all(basis, sq), wedge_all(basis, rev)
    assert eq(mul(om, om, sq), sc(2)) and eq(mul(omr, omr, rev), sc(-2))
    dim, _ = centre_dimension(basis, rev)
    assert dim == 2
    # the centre of Cl(4,1): om1 = product of the reversed e0, e1, e2, e3, e5, om1^2 = -1
    om1 = wedge_all([gen(0), gen(1), gen(2), gen(3), gen(5)], rev)
    s1 = mul(om1, om1, rev).get((), F(0))
    s2 = mul(omr, omr, rev).get((), F(0))
    s0 = mul(om, om, sq).get((), F(0))
    assert (s0, s2, s1) == (F(2), F(-2), F(-1))
    # discriminants of the quadratic algebras span{1, w}, w^2 = s: 4 s
    assert (4 * s0, 4 * s2, 4 * s1) == (8, -8, -4)
    # an isomorphism span{1, om'} -> span{1, om1} sends om1 to a + b om' with (a + b om')^2 = -1; the square is
    # a^2 + s2 b^2 + 2ab om', read off from (a, b) = (1, 0), (0, 1), (1, 1):
    sqr = lambda a, b: mul(add(sc(a), scal(b, omr)), add(sc(a), scal(b, omr)), rev)
    c_aa, c_bb = sqr(1, 0).get((), F(0)), sqr(0, 1).get((), F(0))
    c_ab = sub(sqr(1, 1), add(sqr(1, 0), sqr(0, 1)))
    assert (c_aa, c_bb) == (F(1), F(-2)) and eq(c_ab, scal(2, omr))
    # so ab = 0 and either a^2 = s1 = -1 or b^2 = s1 / s2 = 1/2: neither is a rational square
    assert s1 / s2 == F(1, 2) and not is_square_Q(s1) and not is_square_Q(s1 / s2)
    # ours, span{1, om} with om^2 = 2, is a field: no idempotent (2 is not a square)
    assert not is_square_Q(s0) and is_square_Q(s0 * 2)
    return True


def check_similar_to_the_standard_form_iff_sum_of_two_squares():
    premise(P_SCALE)
    sq = SQ6
    stdsq = (1, -1, -1, -1, -1)
    f = [gen(i) for i in range(5)]
    for (a, b) in ((F(1), F(1)), (F(2), F(1)), (F(1), F(0)), (F(5, 2), F(0)), (F(2, 3), F(1, 3)), (F(3), F(4))):
        d = a * a + b * b
        L = 3 * d
        n0, ninf, I, W = frame(L)
        src = [gen(0), gen(1), gen(2), gen(3), W]
        T = [add(scal((1 + d) / 2, f[0]), scal((1 - d) / 2, f[1])),
             add(scal((1 - d) / 2, f[0]), scal((1 + d) / 2, f[1])),
             add(scal(a, f[2]), scal(b, f[3])),
             add(scal(-b, f[2]), scal(a, f[3])),
             scal(d, f[4])]
        G1 = [[dot(x, y, sq) for y in src] for x in src]
        G2 = [[dot(x, y, stdsq) for y in T] for x in T]
        assert G2 == [[d * g for g in row] for row in G1]
        # pseudoscalars: (T e0 ... T w)^2 = det(T)^2 (f0...f4)^2 = d^5 * d, a square
        detT = ((1 + d) * (1 + d) - (1 - d) * (1 - d)) / 4 * (a * a + b * b) * d
        assert eq(wedge_all(T, stdsq), scal(detT, wedge_all(f, stdsq)))
        assert detT * detT == d ** 6
    # converse, d = 3 (Lambda = 9): a^2 + b^2 = 3 c^2 with gcd 1 is impossible, since a^2 + b^2 = 0 mod 3 forces 3 | a, b
    zero3 = [(x, y) for x, y in product(range(3), repeat=2) if (x * x + y * y) % 3 == 0]
    assert zero3 == [(0, 0)]
    assert [(x, y, c) for c in range(1, 25) for x in range(0, 43) for y in range(0, 43)
            if x * x + y * y == 3 * c * c] == []
    # the discriminant step: for a similarity of factor c, c^5 d is a square, so c = d mod squares
    for c, d in ((F(3), F(3)), (F(12), F(3)), (F(2), F(2))):
        assert is_square_Q(c ** 5 * d)
    assert not is_square_Q(F(1) ** 5 * F(3))
    # Witt cancellation by a reflection: if Q(z) = Q(y) = c != 0, the versor n = z - y (or z + y) carries z to y (or -y)
    for z, y in ((add(gen(0), gen(1), gen(2)), gen(1)),
                 (add(scal(3, gen(0)), scal(2, gen(1)), scal(2, gen(2))), gen(0)),
                 (add(scal(2, gen(0)), gen(1), gen(4)), add(scal(2, gen(0)), gen(1), gen(4)))):
        assert dot(z, z, stdsq) == dot(y, y, stdsq) != 0
        for s, n in ((1, sub(z, y)), (-1, add(z, y))):
            Qn = dot(n, n, stdsq)
            if Qn == 0:
                continue
            ninv = scal(1 / Qn, n)
            img = scal(-1, mul(mul(n, z, stdsq), ninv, stdsq))
            assert eq(img, scal(s, y))
            break
        else:
            assert False
    return True


def check_the_mirror_needs_minus_one_not_a_square():
    premise(P_SCALE)
    # over K = span{1, u}, u^2 = -1, with H rational: the mirror's central unit omega'/H (square -1) times u
    # squares to +1, so (1 + u omega'/H)/2 is a central idempotent: the complexified reading collapses
    sq = ext(-1)
    rev = tuple(-s for s in SQ6) + (1, 1)
    assert eq(mul(U, U, rev), sc(-1))
    for H in (F(1), F(2, 3)):
        L = 3 * H * H
        n0, ninf, I, W = frame(L)
        basis = [gen(0), gen(1), gen(2), gen(3), W]
        omr = scal(1 / H, wedge_all(basis, rev))
        assert eq(mul(omr, omr, rev), sc(-1))
        j = mul(U, omr, rev)
        assert eq(mul(j, j, rev), sc(1))
        e = scal(F(1, 2), add(sc(1), j))
        assert eq(mul(e, e, rev), e) and all(GA.commutes(e, g, rev) for g in basis)
    assert sq[7] == 1
    return True


def check_rescaling_by_root_lambda_needs_root_three():
    premise(P_SCALE)
    sq = SQ6
    std = [gen(0), gen(1), gen(2), gen(3)]
    # the rescaling w = W / sqrt|L| needs |L| a square; then w^2 = -sign(L)/3
    for L, target in ((F(-1), F(1)), (F(1), F(-1)), (F(-4), F(1)), (F(4), F(-1)), (F(-9, 4), F(1))):
        n0, ninf, I, W = frame(L)
        k = abs(L)
        assert is_square_Q(k) and not is_square_Q(k / 3)
        rt = F(isqrt(k.numerator), isqrt(k.denominator))
        w = scal(1 / rt, W)
        assert dot(w, w, sq) == -L / (3 * k) == target / 3
        om = wedge_all(std + [w], sq)
        assert eq(mul(om, om, sq), sc(-target / 3))
        # the target algebra Cl(2,3) (target +1) or Cl(1,4) (target -1) has omega^2 = -target
        g4 = gen(4) if target == 1 else gen(5)
        omt = wedge_all(std + [g4], sq)
        assert eq(mul(omt, omt, sq), sc(-target))
        # target +1: centres span{1, om}, om^2 = -1/3, and span{1, omt}, omt^2 = -1, both fields over Q, isomorphic
        # iff (-1/3)/(-1) = 1/3 is a square; target -1: omt^2 = 1 splits, om^2 = 1/3 does not. No isomorphism over Q;
        # over span{1, u}, u^2 = 3, the vector u w has square target, the form becomes the standard one
        assert not is_square_Q(F(1, 3)) and is_square_K(F(1, 3), F(3))
        assert not is_square_Q(F(-1)) and not is_square_Q(F(-1, 3)) and is_square_Q(F(1))
        sq3 = ext(3)
        uw = mul(U, w, sq3)
        assert eq(mul(uw, uw, sq3), sc(target))
    # normalising by H = sqrt(|L|/3) instead (L = 3H^2, or L = -3H'^2) gives the unit square with no root of 3
    for L, target in ((F(-3), F(1)), (F(3), F(-1)), (F(-12), F(1)), (F(12), F(-1)), (F(27, 4), F(-1))):
        n0, ninf, I, W = frame(L)
        h2 = abs(L) / 3
        assert is_square_Q(h2) and not is_square_Q(abs(L))
        h = F(isqrt(h2.numerator), isqrt(h2.denominator))
        wh = scal(1 / h, W)
        assert dot(wh, wh, sq) == target
        om = wedge_all(std + [wh], sq)
        assert eq(mul(om, om, sq), sc(-target))
    return True


def check_anti_de_sitter_datum():
    premise(P_SCALE)
    premise(P_BOOST)
    sq = SQ6
    e0 = gen(0)
    for Hp in (F(1), F(2, 5)):
        L = -3 * Hp * Hp
        n0, ninf, I, W = frame(L)
        B = mul(e0, W, sq)
        u = scal(1 / Hp, B)
        assert eq(mul(u, u, sq), sc(-1))
        eW = scal(1 / Hp, W)
        assert dot(eW, eW, sq) == 1
        basis = [gen(0), gen(1), gen(2), gen(3), eW]
        om = wedge_all(basis, sq)
        assert eq(mul(om, om, sq), sc(-1))
        # the plane span{e0, W} is definite: Q(a e0 + b W) = a^2 + Hp^2 b^2
        for a, b in product((F(1), F(-3, 2)), (F(1), F(2, 7))):
            z = add(scal(a, e0), scal(b, W))
            assert dot(z, z, sq) == a * a + Hp * Hp * b * b > 0
    # Lambda = -1: -d = 1/3 is not a square, no unit rotation c B over Q ((cB)^2 = -c^2/3)
    assert not is_square_Q(F(1, 3))
    return True


def check_operator_join_scale_needs_root_two():
    """lambda = Lambda/6; the matched scale s^2 with lambda s^4 = 1 is 1/sqrt(lambda)."""
    for H in (F(1), F(2), F(3, 5)):
        lam = 3 * H * H / 6
        assert lam == H * H / 2 and not is_square_Q(lam)
        # over span{1, u}, u^2 = 2: s^2 = u/H, lambda (s^2)^2 = 1
        sq = ext(2)
        s2 = scal(1 / H, U)
        assert eq(scal(lam, mul(s2, s2, sq)), sc(1))
    # the sample points of the stored check, Lambda = 6 and 3/2: sqrt(lambda) rational, H irrational
    for L, rl in ((F(6), F(1)), (F(3, 2), F(1, 2))):
        assert rl * rl == L / 6 and not is_square_Q(L / 3)
    return True
