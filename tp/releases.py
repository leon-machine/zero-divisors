"""Release notes: what changed in the Physics Graph between two releases.

  python -m tp release-notes vX.Y.Z [--store store] [--since TAG] [--date YYYY-MM-DD]

writes releases/vX.Y.Z.md, a draft for the maintainer to finish: a line on the main changes goes
where the comment says, and the rest is generated by comparing the store with the accepted state
(store/.tp-lock.json) at the previous release tag:

  - results added;
  - corrections and restatements, each with the defect it fixed and who made it (from the
    `amendments` and `credit` entries of the versions in between);
  - other revisions (a new version with no amendment entry: the maintainer's own passes);
  - results retired, with the reason from tombstones.yaml;
  - everyone credited for the first time in this release.

The first release has no previous tag: its notes give the counts instead of a list. The same file
is pasted as the GitHub release's notes, so Zenodo carries it too, and the site shows every file in
releases/ (RELEASING.md).

The same command brings the Zenodo record's contributors up to date: every person named in a
result's credit list, other than the record's creators, is added to `contributors` in
.zenodo.json (type Researcher, with the ORCID iD when the credit entry gives one). AI models are
left out, since Zenodo's creator and contributor fields are for people and organisations; they stay
named in the results' credit lists and in the release notes. A credit entry is read as an AI model
when it says `kind: ai`, or, with no `kind`, when its name is one of a known model family
(MODEL_RE). Entries already in the file are kept, so a hand-written entry stands and nobody is
dropped when a result is retired.
"""
import argparse
import datetime
import json
import os
import re
import subprocess

from .model import load_store

RELEASES = "releases"
ZENODO = ".zenodo.json"
# model families, matched at the start of a credit name: "Claude Opus 5.5", "GPT-5", "o3", ...;
# a person who shares a name with one (a Claude who is not a model) is marked kind: person
MODEL_RE = re.compile(r"^(claude(\s+(opus|sonnet|haiku|fable|mythos|instant|code|[0-9])\b|\s*\(|$)|"
                      r"(chatgpt|gpt|gemini|bard|llama|mistral|mixtral|codestral|deepseek|grok|qwen|"
                      r"copilot|kimi|glm)\b|o[1-9]\b|phi-?[0-9]|command[ -]r\b)", re.I)
TAG_RE = re.compile(r"^v(\d+)\.(\d+)\.(\d+)$")


def tag_key(tag):
    m = TAG_RE.match(tag or "")
    return tuple(int(x) for x in m.groups()) if m else (-1, -1, -1)


def _git(lab, *args):
    r = subprocess.run(["git", "-C", lab, *args], capture_output=True, text=True, timeout=60)
    return r.stdout if r.returncode == 0 else None


def previous_tag(lab, before=None):
    """The newest release tag (below `before`, when given)."""
    tags = [t for t in (_git(lab, "tag", "--list", "v*") or "").split() if TAG_RE.match(t)]
    if before:
        tags = [t for t in tags if tag_key(t) < tag_key(before)]
    return max(tags, key=tag_key) if tags else None


def lock_at(lab, tag, store_rel="store"):
    text = _git(lab, "show", f"{tag}:{store_rel}/.tp-lock.json")
    return json.loads(text) if text else None


def _tombstones(store_dir):
    import yaml
    p = os.path.join(store_dir, "tombstones.yaml")
    if not os.path.exists(p):
        return {}
    with open(p, encoding="utf-8") as fh:
        rows = yaml.safe_load(fh) or []
    return {t["id"]: t for t in rows if isinstance(t, dict) and t.get("id")}


def changes(old_lock, store, tombstones=None):
    """Compare the accepted state at the last release (a lock) with the store now."""
    tombstones = tombstones or {}
    out = {"added": [], "corrected": [], "restated": [], "revised": [], "retired": [],
           "contributors": []}
    old_names = {c[0] for v in old_lock.values() for c in (v.get("credit") or [])}
    new_names = []
    for eid, e in sorted(store.entities.items()):
        old = old_lock.get(eid)
        credit = [c for c in (e.meta.get("credit") or []) if isinstance(c, dict)]
        if old is None:
            out["added"].append(eid)
            new_names += [c.get("name") for c in credit]
            continue
        was = int(old.get("version") or 0)
        if e.version <= was:
            continue
        span = range(was + 1, e.version + 1)
        amended = [a for a in (e.meta.get("amendments") or [])
                   if isinstance(a, dict) and a.get("version") in span]
        for a in sorted(amended, key=lambda a: a["version"]):
            by = [c.get("name") for c in credit if c.get("version") == a["version"]]
            new_names += by
            row = {"id": eid, "version": a["version"], "defect": a.get("defect", ""), "by": by}
            out["restated" if a.get("kind") == "restatement" else "corrected"].append(row)
        if not amended:
            out["revised"].append({"id": eid, "from": was, "to": e.version})
    for eid in sorted(set(old_lock) - set(store.entities)):
        t = tombstones.get(eid) or {}
        out["retired"].append({"id": eid, "replaced_by": t.get("replaced_by"),
                               "reason": t.get("reason", "")})
    seen = set()
    for n in new_names:
        if n and n not in old_names and n not in seen:
            seen.add(n)
            out["contributors"].append(n)
    return out


def _title(store, eid):
    e = store.entities.get(eid)
    return (e.title if e else eid).strip()


def notes(tag, date, store, ch=None, since=None):
    """The release notes as Markdown. ch is None for the first release."""
    lines = [f"# {tag} ({date})", "",
             "<!-- a line or two on the main changes; everything below is generated -->", ""]
    if ch is None:
        n = len(store.entities)
        proofs = sum(1 for e in store.entities.values() if e.proofs)
        lines += [f"The first release of the Physics Graph: {n} results, {proofs} of them with "
                  "proofs, each with its premises, evidence and credit.", ""]
        return "\n".join(lines).rstrip() + "\n"
    lines += [f"Changes since {since}.", ""]
    if not any(ch.values()):
        lines += ["No results were added, corrected or retired.", ""]

    def section(head, rows):
        if rows:
            lines.extend([f"## {head}", "", *rows, ""])

    section("Results added", [f"- `{i}`: {_title(store, i)}" for i in ch["added"]])
    section("Corrections", [f"- `{r['id']}` v{r['version']}: {r['defect']}"
                            + (f" (by {', '.join(r['by'])})" if r["by"] else "")
                            for r in ch["corrected"]])
    section("Restatements", [f"- `{r['id']}` v{r['version']}: {r['defect']}"
                             + (f" (by {', '.join(r['by'])})" if r["by"] else "")
                             for r in ch["restated"]])
    section("Other revisions", [f"- `{r['id']}`: version {r['from']} to {r['to']}"
                                for r in ch["revised"]])
    section("Results retired", [f"- `{r['id']}`"
                                + (f", replaced by `{r['replaced_by']}`" if r["replaced_by"] else "")
                                + (f": {r['reason']}" if r["reason"] and not r["replaced_by"] else "")
                                for r in ch["retired"]])
    section("Credited for the first time", [f"- {n}" for n in ch["contributors"]])
    return "\n".join(lines).rstrip() + "\n"


def draft(lab, store_dir, tag, since=None, date=None):
    store = load_store(store_dir)
    since = since or previous_tag(lab, before=tag)
    date = date or datetime.date.today().isoformat()
    store_rel = os.path.relpath(os.path.abspath(store_dir), os.path.abspath(lab))
    old = lock_at(lab, since, store_rel) if since else None
    ch = changes(old, store, _tombstones(store_dir)) if old is not None else None
    return notes(tag, date, store, ch, since)


def unreleased(lab, store_dir, store=None):
    """Changes since the newest release, for a preview built ahead of it; None before the first
    release or when nothing has changed."""
    since = previous_tag(lab)
    if not since:
        return None
    store_rel = os.path.relpath(os.path.abspath(store_dir), os.path.abspath(lab))
    old = lock_at(lab, since, store_rel)
    if old is None:
        return None
    store = store or load_store(store_dir)
    ch = changes(old, store, _tombstones(store_dir))
    if not any(ch.values()):
        return None
    md = notes("Unreleased", "not yet released", store, ch, since)
    return md.replace("<!-- a line or two on the main changes; everything below is generated -->\n\n", "")


def published(lab):
    """Every file in releases/, newest first: [{tag, md}]."""
    d = os.path.join(lab, RELEASES)
    out = []
    if os.path.isdir(d):
        for f in os.listdir(d):
            tag = f[:-3] if f.endswith(".md") else ""
            if TAG_RE.match(tag):
                with open(os.path.join(d, f), encoding="utf-8") as fh:
                    out.append({"tag": tag, "md": fh.read()})
    return sorted(out, key=lambda r: tag_key(r["tag"]), reverse=True)


def is_model(entry):
    kind = entry.get("kind")
    if kind in ("person", "ai"):
        return kind == "ai"
    return bool(MODEL_RE.match(str(entry.get("name", "")).strip()))


def zenodo_name(name):
    """Zenodo's "Family, Given" form for a plain two-word name; anything else as written."""
    parts = name.split()
    if "," in name or len(parts) != 2:
        return name.strip()
    return f"{parts[1]}, {parts[0]}"


def _person_key(name):
    return frozenset(w.strip(",").lower() for w in name.split())


def people(store):
    """Every person credited in the store, first appearance first: [{name, orcid?}]."""
    out, seen = [], {}
    for _, e in sorted(store.entities.items()):
        for c in e.meta.get("credit") or []:
            if not isinstance(c, dict) or not c.get("name") or is_model(c):
                continue
            k = _person_key(c["name"])
            if k not in seen:
                seen[k] = {"name": c["name"]}
                out.append(seen[k])
            if c.get("orcid") and not seen[k].get("orcid"):
                seen[k]["orcid"] = c["orcid"]
    return out


def update_zenodo(lab, store):
    """Add the store's credited people to .zenodo.json's contributors. Returns the names added
    (or given an ORCID iD), or None when the file is missing."""
    path = os.path.join(lab, ZENODO)
    if not os.path.exists(path):
        return None
    with open(path, encoding="utf-8") as fh:
        meta = json.load(fh)
    creators = {_person_key(c.get("name", "")) for c in meta.get("creators") or []}
    contributors = meta.get("contributors") or []
    by_key = {_person_key(c.get("name", "")): c for c in contributors}
    changed = []
    for p in people(store):
        k = _person_key(p["name"])
        if k in creators:
            continue
        row = by_key.get(k)
        if row is None:
            row = {"name": zenodo_name(p["name"]), "type": "Researcher"}
            if p.get("orcid"):
                row["orcid"] = p["orcid"]
            contributors.append(row)
            by_key[k] = row
            changed.append(row["name"])
        elif p.get("orcid") and not row.get("orcid"):
            row["orcid"] = p["orcid"]
            changed.append(row["name"])
    if changed:
        meta["contributors"] = contributors
        with open(path, "w", encoding="utf-8") as fh:
            json.dump(meta, fh, indent=2, ensure_ascii=False)
            fh.write("\n")
    return changed


def main(argv=None):
    ap = argparse.ArgumentParser(prog="tp release-notes")
    ap.add_argument("cmd")
    ap.add_argument("tag")
    ap.add_argument("--store", default="store")
    ap.add_argument("--since", help="the previous release tag (default: the newest below TAG)")
    ap.add_argument("--date")
    a = ap.parse_args(argv)
    if not TAG_RE.match(a.tag):
        print(f"{a.tag!r} is not a release tag (vMAJOR.MINOR.PATCH)")
        return 1
    lab = os.path.dirname(os.path.abspath(a.store)) or "."
    path = os.path.join(lab, RELEASES, a.tag + ".md")
    if os.path.exists(path):
        print(f"{path} exists; edit it, or delete it to draft again")
        return 1
    os.makedirs(os.path.dirname(path), exist_ok=True)
    with open(path, "w", encoding="utf-8") as fh:
        fh.write(draft(lab, a.store, a.tag, a.since, a.date))
    print(f"drafted {path}: add a line on the main changes where the comment says, then commit it")
    added = update_zenodo(lab, load_store(a.store))
    if added:
        print(f"{ZENODO}: contributors added or given an ORCID iD: {', '.join(added)}; "
              "check them and commit the file with the notes")
    elif added is None:
        print(f"no {ZENODO} found, so the Zenodo contributors were not updated")
    return 0
