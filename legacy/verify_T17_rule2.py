def fusion_checks(sq_base, n, nu_sq, reflect_index):
    """In B = Cl(base + <nu>) with nu = e_n, nu^2 = nu_sq: matrix units from
    eps_pm and nu; Ad_nu = grade involution on the base; Ad_{nu e_k} = the
    reflection along e_k on the base; (nu e_k)^2."""
    sqB = sq_base + (nu_sq,)
    wB = volume(n)                       # base volume element, now inside B
    ep = g.scal(F(1, 2), g.add(ONE, wB))
    em = g.scal(F(1, 2), g.sub(ONE, wB))
    nu = g.gen(n)
    nu_inv = g.scal(nu_sq, nu)
    E = {(1, 1): ep, (2, 2): em, (1, 2): g.mul(ep, nu, sqB),
         (2, 1): g.scal(nu_sq, g.mul(em, nu, sqB))}
    units = all(g.eq(g.mul(E[(i, j)], E[(k, l)], sqB),
                     (E[(i, l)] if j == k else {}))
                for i in (1, 2) for j in (1, 2) for k in (1, 2) for l in (1, 2))
    units &= g.eq(g.add(E[(1, 1)], E[(2, 2)]), ONE)
    inner_grade = all(g.eq(ad(nu, nu_inv, g.gen(i), sqB), g.neg(g.gen(i))) for i in range(n))
    ek = g.gen(reflect_index)
    u = g.mul(nu, ek, sqB)
    u2 = g.mul(u, u, sqB)
    u_inv = g.mul(u, {(): u2[()]}, sqB) if u2 in (g.sc(1), g.sc(-1)) else None
    inner_parity = all(
        g.eq(ad(u, u_inv, g.gen(i), sqB),
             g.neg(g.gen(i)) if i == reflect_index else g.gen(i))
        for i in range(n))
    # the whole algebra B has trivial centre: its volume element anticommutes
    # with every generator (n+1 even)
    wtot = volume(n + 1)
    simple_centre = all(g.anticommutes(wtot, g.gen(i), sqB) for i in range(n + 1))
    # eps_pm are no longer central in B
    non_central = not is_central(ep, sqB)
    return units, inner_grade, inner_parity, u2, simple_centre, non_central

