def vec(c):
    """Vector from coefficient list [a0,a1,a2,a3]."""
    out = {}
    for i, x in enumerate(c):
        if x != 0:
            out[(i,)] = F(x)
    return out


def Pmap(a):
    """P(a) = (a . e_t) e_r with e_t = gamma_0, e_r = gamma_1."""
    return g.scal(g.dot(a, e0, SQ), e1)


def unip(s):
    """The map 1 + s P, acting on vectors."""
    return lambda a: g.add(a, g.scal(s, Pmap(a)))


