def is_G_antisym(M):
    return all(sum(M[k][i] * G6t[k][j] for k in range(6)) +
               sum(G6t[i][k] * M[k][j] for k in range(6)) == 0
               for i in range(6) for j in range(6))


g.check("Lem 4.2(i): the algebraic part of eq (3) is G-antisymmetric (metric preserved), all four directions",
      all(is_G_antisym(tract_conn(a, Psym)) for a in range(4)))

def tract_conn_badsign(a_idx, P):
    """Same display with the rho-slot Schouten sign flipped: not metric."""
    M = tract_conn(a_idx, P)
    for b in range(4):
        M[5][1 + b] = -M[5][1 + b]
    return M


