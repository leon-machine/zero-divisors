N = 12  # truncation order in rho


def tau_series(c_lambda):
    """tau(rho) for A-factor 1 - rho^2 + c rho^6, as a series in rho."""
    fac = [F(1), F(0), F(-1), F(0), F(0), F(0), F(c_lambda)]
    half = g.ps_pow_rat(fac, F(-1, 2), N)
    integrand = g.ps_mul([F(0), F(0), F(2)], half, N)  # 2 rho^2 * (...)
    return g.ps_int(integrand)[:N + 1]


