# basis order: n0, ninf, w0, w1, w2, w3;  <n0,ninf> = 1, W Minkowski
G6 = [[F(0)] * 6 for _ in range(6)]
G6[0][1] = G6[1][0] = F(1)
G6[2][2] = F(1)
G6[3][3] = G6[4][4] = G6[5][5] = F(-1)


def ip6(u, v):
    return sum(u[i] * G6[i][j] * v[j] for i in range(6) for j in range(6))


def basis6(i):
    return [F(1) if j == i else F(0) for j in range(6)]


N0, NINF = basis6(0), basis6(1)
Wb = [basis6(2 + i) for i in range(4)]


def wedge6(u, v):
    """(u ^ v)(w) = <v,w> u - <u,w> v as a 6x6 matrix."""
    M = [[F(0)] * 6 for _ in range(6)]
    Gu = [sum(G6[i][j] * u[j] for j in range(6)) for i in range(6)]
    Gv = [sum(G6[i][j] * v[j] for j in range(6)) for i in range(6)]
    for col in range(6):
        for row in range(6):
            M[row][col] = Gv[col] * u[row] - Gu[col] * v[row]
    return M


def mat_apply(M, v):
    return [sum(M[i][j] * v[j] for j in range(6)) for i in range(6)]


def mat_add(A, B):
    return [[A[i][j] + B[i][j] for j in range(6)] for i in range(6)]


def mat_scal(c, A):
    return [[c * A[i][j] for j in range(6)] for i in range(6)]


def mat_comm(A, B):
    return [[sum(A[i][k] * B[k][j] - B[i][k] * A[k][j] for k in range(6))
             for j in range(6)] for i in range(6)]


ETA = [F(1), F(-1), F(-1), F(-1)]


def Xpt(x):
    """Point tractor X(x) = n0 + sum x^a w_a - (eta(x,x)/2) ninf."""
    q = sum(ETA[i] * x[i] * x[i] for i in range(4))
    v = [F(0)] * 6
    v[0] = F(1)
    v[1] = -q / 2
    for i in range(4):
        v[2 + i] = x[i]
    return v


x1 = [F(2), F(1, 3), F(-1), F(4)]
y1 = [F(-1, 2), F(5), F(0), F(1)]
x2 = [F(-7, 3), F(0), F(11, 5), F(-1, 2)]
ok = True
for xa, xb in ((x1, y1), (x1, x2), (y1, x2)):
    d1 = [xa[i] - xb[i] for i in range(4)]
    qd = sum(ETA[i] * d1[i] * d1[i] for i in range(4))
    ok = ok and ip6(Xpt(xa), Xpt(xa)) == 0 and ip6(Xpt(xb), Xpt(xb)) == 0 and \
         ip6(Xpt(xa), Xpt(xb)) == -qd / 2
g.check("Prop 4.3 setup: X(x) is null and <X(x),X(y)> = -eta(x-y,x-y)/2, three pairs", ok)

