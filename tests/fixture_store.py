def build(root):
    os.makedirs(root, exist_ok=True)
    with open(os.path.join(root, "subjects.yaml"), "w") as fh:
        yaml.safe_dump(SUBJECTS, fh)
    with open(os.path.join(root, "config.yaml"), "w") as fh:
        yaml.safe_dump(CONFIG, fh)
    with open(os.path.join(root, "notation.yaml"), "w") as fh:
        yaml.safe_dump(NOTATION, fh)
    with open(os.path.join(root, "tombstones.yaml"), "w") as fh:
        yaml.safe_dump(["fx.retired.old-claim"], fh)
    for meta, levels, check, proof in ENTITIES:
        meta = dict(meta, subject="thermal" if meta["id"] in THERMAL else "algebra")
        folder = os.path.join(root, DIRS[meta["kind"]], meta["id"])
        os.makedirs(folder, exist_ok=True)
        with open(os.path.join(folder, "entity.md"), "w") as fh:
            fh.write(dump_entity(meta, levels))
        if check:
            with open(os.path.join(folder, "check.py"), "w") as fh:
                fh.write(check)
        for d in meta.get("derivations") or []:
            if d.get("proof"):
                with open(os.path.join(folder, d["proof"]), "w") as fh:
                    fh.write(proof or "")
    return root
